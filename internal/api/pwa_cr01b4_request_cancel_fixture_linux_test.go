//go:build linux

package api

// CR-01b4: test-only bounded ResponseWriter that preserves the authentic
// Gin authentication/SQL handler and exposes true net/http Request.Context
// cancellation. It does NOT replace the handler with a fake API response.
import (
	"errors"
	"net/http"
	"sync/atomic"
	"time"
)

type pwaCR01b4ReadProbe struct {
	started       atomic.Bool
	cancelled     atomic.Bool
	handlerExited atomic.Bool
}
type pwaCR01b4PacedWriter struct {
	http.ResponseWriter
	request *http.Request
	probe   *pwaCR01b4ReadProbe
	once    atomic.Bool
}

func (w *pwaCR01b4PacedWriter) Flush() {
	if flusher, ok := w.ResponseWriter.(http.Flusher); ok {
		flusher.Flush()
	}
}
func (w *pwaCR01b4PacedWriter) Write(body []byte) (int, error) {
	if !w.once.CompareAndSwap(false, true) {
		return w.ResponseWriter.Write(body)
	}
	if len(body) == 0 {
		return 0, errors.New("empty real Gin body")
	}
	// Send a genuine prefix generated by the production Gin endpoint.
	length := len(body)
	if length > 128 {
		length = 128
	}
	n, err := w.ResponseWriter.Write(body[:length])
	if err != nil {
		return n, err
	}
	w.Flush()
	w.probe.started.Store(true)
	select {
	case <-w.request.Context().Done():
		w.probe.cancelled.Store(true)
		return n, w.request.Context().Err()
	case <-time.After(25 * time.Second):
		return n, errors.New("test-only paced read was not cancelled")
	}
}
