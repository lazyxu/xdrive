'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('iOS BGProcessing registration is explicit and matches App Info', () => {
  const id = 'com.lazyxu.xdrive.ios.photos.incremental'
  const swift = read('ios/XDriveIOS/BackgroundPhotosTask.swift')
  const project = read('ios/project.yml')
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  assert.ok(swift.includes('static let identifier = "' + id + '"'))
  assert.match(project, /UIBackgroundModes:\s*\n\s*-\s*processing/)
  assert.ok(project.includes(id))
  assert.match(project, /BGTaskSchedulerPermittedIdentifiers:/)
  assert.match(app, /XDriveIOSBackgroundPhotoTaskRegistration\.registerAtLaunch\(\)/)
  assert.match(swift, /BGTaskScheduler\.shared\.register\(/)
  assert.match(swift, /BGProcessingTaskRequest\(/)
  assert.match(swift, /requiresNetworkConnectivity = true/)
  assert.match(swift, /task\.expirationHandler/)
  assert.match(swift, /task\.setTaskCompleted\(success: successful\)/)
})

test('system-launched task cannot use ambient web cookies or identity-only Device rights', () => {
  const swift = read('ios/XDriveIOS/BackgroundPhotosTask.swift')
  const bridge = read('ios/XDriveIOS/IOSPhotoHostBridge.swift')
  const scheduler = read('web/src/iosForegroundAutoScheduler.ts')
  assert.match(swift, /private struct EphemeralAuthorization/)
  assert.match(swift, /accessToken: String/)
  assert.match(swift, /XDriveNativeOwnerRootVerifier\(/)
  assert.match(swift, /try Task\.checkCancellation\(\)/)
  assert.match(swift, /XDriveIOSPhotoRunGate\.shared\.acquire\(\)/)
  assert.match(swift, /let sameOwnerScope = authorization\.map/)
  assert.match(swift, /running\?\.cancel\(\)/)
  assert.match(swift, /XDriveIOSForegroundPhotoBackupMVP\(/)
  assert.match(swift, /reserveDue\(owner: current\)/)
  assert.match(swift, /recordResult\(/)
  assert.match(swift, /self\.authorization = nil/)
  assert.doesNotMatch(swift, /kSecValueData|Set-Cookie|httpCookieStore|WKWebsiteDataStore|registerClientDevice|AuthService\.refresh/)
  assert.doesNotMatch(swift, /URLSessionConfiguration\.background\(/)
  assert.match(bridge, /case "photos\.auto\.disarm":/)
  assert.match(scheduler, /host\.disarmBackground\(\)/)
})

test('offline emergency stop revokes every local automatic schedule without requiring Server', () => {
  const store = read('ios/XDriveIOS/PhotoAutoScheduleStore.swift')
  const bridge = read('ios/XDriveIOS/IOSPhotoHostBridge.swift')
  const ui = read('ui/shared/src/mui/IOSPhotoBackupSettings.tsx')
  const login = read('web/src/App.tsx')
  assert.match(store, /func disableAllOnThisDevice\(\) -> Int/)
  assert.match(store, /\.filter\s*\{\s*\$0\.hasPrefix\(Self\.prefix\)\s*\}/)
  assert.match(bridge, /case "photos\.auto\.disableAllLocal":/)
  assert.match(bridge, /XDriveIOSBackgroundPhotos\.shared\.disarm\(\)/)
  assert.match(ui, /data-xdrive-ios-auto-stop-all-local/)
  assert.match(login, /data-xdrive-ios-emergency-stop-autobackup/)
})
