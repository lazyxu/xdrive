'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('one canonical BGProcessing identifier registers exactly once and matches Xcode Info', () => {
  const id = 'com.lazyxu.xdrive.ios.photos.backup'
  const registration = read('ios/XDriveIOS/BackgroundPhotoTask.swift')
  const executor = read('ios/XDriveIOS/BackgroundPhotosTask.swift')
  const project = read('ios/project.yml')
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  assert.ok(registration.includes('static let identifier = "' + id + '"'))
  assert.match(project, /UIBackgroundModes:\s*\n\s*-\s*processing/)
  assert.match(project, /BGTaskSchedulerPermittedIdentifiers:/)
  assert.ok(project.includes(id))
  assert.doesNotMatch(project, /com\.lazyxu\.xdrive\.ios\.photos\.incremental/)
  assert.match(app, /XDriveIOSBackgroundPhotoTask\.registerAtLaunch\(\)/)
  assert.equal((app.match(/registerAtLaunch\(\)/g) || []).length, 1)
  assert.match(registration, /BGTaskScheduler\.shared\.register\(/)
  assert.match(registration, /XDriveIOSBackgroundPhotos\.shared\.handle\(work\)/)
  assert.match(registration, /task\.setTaskCompleted\(success: false\)/)
  assert.doesNotMatch(executor, /BGTaskScheduler\.shared\.register\(/)
  assert.doesNotMatch(executor, /XDriveIOSBackgroundPhotoTaskRegistration/)
  assert.match(executor, /BGProcessingTaskRequest\(/)
  assert.match(executor, /XDriveIOSBackgroundPhotoTask\.identifier/)
  assert.match(executor, /requiresNetworkConnectivity = true/)
  assert.match(executor, /task\.expirationHandler/)
  assert.match(executor, /task\.setTaskCompleted\(success: successful\)/)
})

