  assert.match(router, /authed\.POST\("\/nodes\/:id\/shares", s\.createFileShare\)/)
  assert.match(router, /authed\.GET\("\/nodes\/:id\/shares", s\.listFileShares\)/)
  assert.match(router, /authed\.DELETE\("\/shares\/:id", s\.revokeShare\)/)
  assert.match(server, /func \(s \*Server\) createFileShare\(c \*gin\.Context\)/)
  assert.match(server, /func \(s \*Server\) listFileShares\(c \*gin\.Context\)/)
  assert.match(server, /func \(s \*Server\) revokeShare\(c \*gin\.Context\)/)
  assert.match(share, /\/api\/v1\/nodes\/\\\(node\.id\)\/shares/)
  assert.match(share, /\/api\/v1\/shares\/\\\(id\)/)
  assert.match(share, /expecting: 201/)
  assert.match(share, /expecting: 204, maximumBytes: 0/)
