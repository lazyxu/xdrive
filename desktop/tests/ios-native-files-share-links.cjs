test('native existing-link edit preserves opaque URL, validates current record and PATCH response', () => {
  assert.match(router, /authed\.PATCH\("\/shares\/:id", s\.updateShare\)/)
  assert.match(server, /func \(s \*Server\) updateShare\(c \*gin\.Context\)/)
  assert.match(server, /validateShareUploadSettings\(access, node\.Type\)/)
  assert.match(server, /"expires_at": req\.ExpiresAt/)
  assert.match(share, /case update\(original: XDriveIOSNativeFilesShareRecord, access: String, expiryDays: Int\)/)
  assert.match(share, /case \.update\(let original, let access, let expiryDays\):/)
  assert.match(share, /original\.node_id == node\.id/)
  assert.match(share, /original\.status == "active"/)
  assert.match(share, /validAccess\(\s*access, isDirectory: node\.isDirectory/)
  assert.match(share, /list\(node\.id, session: client\)\.contains\(original\)/)
  assert.match(share, /XDriveIOSNativeFilesSharePolicyUpdateBody\(/)
  assert.match(share, /method: "PATCH", body: body,\s*expecting: 200/)
  assert.match(share, /changed\.id == original\.id, changed\.node_id == node\.id/)
  assert.match(share, /changed\.access == access, changed\.status == "active"/)
  assert.match(share, /rows\.contains\(updated\)/)
  assert.match(share, /records\.contains\(original\), original\.status == "active"/)
  assert.match(share, /notice = "服务器已确认修改。原分享链接地址不变。"/)
  assert.match(share, /修改结果未能确认。请刷新已有链接核对，不要盲目重复提交。/)
  assert.doesNotMatch(share, /URLSession\.shared|WKWebView|\/api\/v1\/uploads/)
})

