'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const share = read('ios/XDriveIOS/NativeFilesShareLink.swift')
const policy = read('ios/XDriveIOS/NativeFilesShareLinkPolicy.swift')
const router = read('internal/api/router.go')
const server = read('internal/api/shares.go')
const browserAdapter = read('web/src/fileDialogAdapters.ts')

test('native Files can create and manage Server share links for files and folders', () => {
  assert.match(panel, /@State private var shareNode: XDriveIOSNativeFilesNode\?/)
  assert.match(panel, /native-ios-files-share-file/)
  assert.match(panel, /native-ios-files-share-folder/)
  assert.match(panel, /XDriveIOSNativeFilesShareScreen\(\s*login: login, expectedOwner: expectedOwner, node: selected/)
  assert.match(panel, /\.sheet\(item: \$shareNode\)/)
  assert.match(panel, /shareNode = nil/)
  assert.match(share, /struct XDriveIOSNativeFilesShareScreen: View/)
  assert.match(share, /ShareLink\(item: link\.url\)/)
  assert.match(share, /UIPasteboard\.general\.url = link\.url/)
  assert.match(share, /Button\("确认撤销", role: \.destructive\)/)
  assert.match(share, /native-ios-files-share-create/)
  assert.match(share, /native-ios-files-share-copy-link/)
})

test('only authorized Server capability API is used; no WebView or implicit download', () => {
  assert.match(router, /authed\.POST\("\/nodes\/:id\/shares", s\.createFileShare\)/)
  assert.match(router, /authed\.GET\("\/nodes\/:id\/shares", s\.listFileShares\)/)
  assert.match(router, /authed\.DELETE\("\/shares\/:id", s\.revokeShare\)/)
  assert.match(server, /func \(s \*Server\) createFileShare\(c \*gin\.Context\)/)
  assert.match(server, /func \(s \*Server\) listFileShares\(c \*gin\.Context\)/)
  assert.match(server, /func \(s \*Server\) revokeShare\(c \*gin\.Context\)/)
  assert.match(share, /\/api\/v1\/nodes\/\\\(node\.id\)\/shares/)
  assert.match(share, /\/api\/v1\/shares\/\\\(id\)/)
  assert.match(share, /expecting: 201/)
  assert.match(share, /expecting: 204, maximumBytes: 0/)
  assert.match(share, /URLSessionConfiguration\.ephemeral/)
  assert.match(share, /completionHandler\(nil\)/)
  assert.doesNotMatch(share, /WKWebView|import WebKit|URLSession\.shared|UserDefaults|@AppStorage|\/api\/v1\/uploads/)
})

test('permission, expiry, token and browser route match canonical Server/Web contracts', () => {
  assert.match(policy, /value == "read_only" \|\| \(isDirectory && value == "view_upload"\)/)
  assert.match(policy, /allowedExpiryDays: Set<Int> = \[0, 1, 7, 30\]/)
  assert.match(policy, /scalars\.count == 43/)
  assert.match(policy, /components\.scheme == "https"/)
  assert.match(policy, /components\.fragment = "\/s\/\\\(token\)"/)
  assert.match(browserAdapter, /\/#\/s\/\$\{created\.token\}/)
  assert.match(server, /shareAccessReadOnly\s+= "read_only"/)
  assert.match(server, /shareAccessViewUpload = "view_upload"/)
  assert.match(share, /dateEncodingStrategy = \.iso8601/)
  assert.match(share, /Text\("查看并上传"\)\.tag\("view_upload"\)/)
  assert.match(share, /Text\("永久"\)\.tag\(0\)/)
})

test('auth, exact Node proof, server readback, and Owner epoch fence prevent stale shares', () => {
  assert.match(share, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(share, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(share, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expectedOwner\)/)
  assert.match(share, /JSONDecoder\(\)\.decode\(XDriveIOSNativeFilesNode\.self, from: snapshot\) == node/)
  assert.match(share, /rows\.contains\(where: \{ \$0\.id == created\.id && \$0\.status == "active" \}\)/)
  assert.match(share, /records = result\.records/)
  assert.match(share, /\.onDisappear \{ model\.invalidate\(\) \}/)
  assert.match(share, /\.onChange\(of: login\.owner\)/)
  assert.match(share, /创建结果未能确认。请刷新已有链接核对，避免重复创建。/)
  assert.match(share, /撤销结果未能确认。请刷新已有链接核对，不要重复操作。/)
})
