'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const map = fs.readFileSync(path.resolve(__dirname,'../../ios/XDriveIOS/NativeLocalPhotoMap.swift'),'utf8')
const cloud = fs.readFileSync(path.resolve(__dirname,'../../ios/XDriveIOS/NativeOwnerPhotoMapGallery.swift'),'utf8')
test('viewport-filtered PhotoKit GPS cells lose MapKit and VoiceOver activation before SwiftUI repaint', () => {
  assert.match(map, /var cameraBoundCells = false/)
  assert.match(map, /cameraBoundCells: globalViewport != nil/)
  assert.match(map, /context\.coordinator\.cameraBoundCells = cameraBoundCells/)
  const coordinator = map.slice(map.indexOf('final class Coordinator: NSObject, MKMapViewDelegate'))
  const onWill = coordinator.slice(coordinator.indexOf('func mapView(_ mapView: MKMapView, regionWillChangeAnimated animated: Bool)'), coordinator.indexOf('func mapView(_ mapView: MKMapView, regionDidChangeAnimated animated: Bool)'))
  assert.match(onWill, /if cameraBoundCells \{/)
  assert.match(onWill, /canSelectCells = false/)
  assert.match(onWill, /for annotation in mapView\.annotations/)
  assert.match(onWill, /mapView\.view\(for: annotation\) as\? XDriveIOSMapPhotoCover/)
  assert.match(onWill, /cover\.isEnabled = false/)
  assert.match(onWill, /cover\.isAccessibilityElement = false/)
  assert.match(onWill, /cover\.accessibilityElementsHidden = true/)
  assert.match(onWill, /cover\.accessibilityTraits = \[\]/)
  assert.ok(onWill.indexOf('canSelectCells = false') < onWill.indexOf('onCameraWillChange?()'))
  assert.match(onWill, /onCameraWillChange\?\(\)/)
  assert.match(coordinator, /guard canSelectCells else \{ return \}/)
  assert.doesNotMatch(map, /performSelector|DispatchQueue\.main\.asyncAfter/)
})
test('settled currently-scanned region restores valid covers; normal page and world overview stay interactive', () => {
  assert.match(map, /context\.coordinator\.canSelectCells = canSelectCells/)
  assert.match(map, /cover\.isEnabled = canSelectCells/)
  assert.match(map, /cover\.isAccessibilityElement = canSelectCells/)
  assert.match(map, /cover\.accessibilityElementsHidden = !canSelectCells/)
  assert.match(map, /cover\.accessibilityTraits = canSelectCells \? \.button : \[\]/)
  assert.match(map, /view\?\.isEnabled = canSelectCells/)
  assert.match(map, /view\?\.isAccessibilityElement = canSelectCells/)
  assert.match(map, /view\?\.accessibilityTraits = canSelectCells \? \.button : \[\]/)
  assert.match(map, /canSelectCells: refinedViewportIsCurrent/)
  assert.match(map, /guard !globalCameraMoving, let current = globalCamera/)
  assert.match(map, /XDriveIOSNativeLocalMapSpatialPolicy\.containsViewport\(/)
  assert.match(map, /if globalViewport != nil \{ globalCameraMoving = true \}/)
  assert.match(map, /onCamera: \{ current in[\s\S]*?globalCameraMoving = false[\s\S]*?scheduleAutomaticRefinement\(current\)/)
  assert.match(map, /items: page\.items, revision: mapRevision, mapType: mapType, cameraReturn: cameraReturn/)
  assert.match(map, /singleViewer = candidate/)
  assert.match(map, /singleViewer = only/)
  assert.match(map, /currentPage\.items\.map\(\\\.candidate\)/)
  assert.match(cloud, /markersEnabled = false\s*refreshVisibleCovers\(mapView\)/)
  // The map may fetch only a bounded PhotoKit thumbnail rendition from
  // iCloud; this must never become an original-resource export or upload.
  assert.match(map, /options\.isNetworkAccessAllowed = true/)
  assert.match(map, /targetSize: CGSize\(width: 128, height: 128\)/)
  assert.doesNotMatch(map, /UploadSession|UserDefaults\.set\(|PHAssetResourceManager|requestData\(/)
})

test('local PhotoKit map pin matches the complete current scanned Cell snapshot before Viewer admission', () => {
  const mapTap = map.slice(map.indexOf('onCells: { cells, _ in'), map.indexOf('onCamera: { current in'))
  assert.ok(mapTap.length > 0)
  assert.match(mapTap, /XDriveIOSNativeLocalMapSpatialPolicy\.acceptsCellSelection\(/)
  assert.match(mapTap, /XDriveIOSNativeLocalMapSpatialPolicy\.matchesCurrentCell\(\s*cell, current: trusted,\s*representativeID: \{ \$0\.id \}/)
  const spatial = fs.readFileSync(path.resolve(__dirname,'../../ios/XDriveIOS/NativeLocalPhotoMapSpatialPolicy.swift'),'utf8')
  const begin = spatial.indexOf('static func matchesCurrentCell<Payload>(')
  const end = spatial.indexOf('    struct Key: Hashable', begin)
  assert.ok(begin > -1 && end > begin)
  const guard = spatial.slice(begin, end)
  for (const field of ['key', 'count', 'firstSeen', 'latitude', 'longitude']) {
    assert.match(guard, new RegExp('chosen\\.' + field + ' == current\\.' + field))
  }
  assert.match(guard, /chosenID == currentID/)
  assert.match(guard, /!chosenID\.isEmpty, !currentID\.isEmpty/)
  assert.match(guard, /key\(latitude: chosen\.latitude, longitude: chosen\.longitude/)
  assert.match(guard, /key\(latitude: current\.latitude, longitude: current\.longitude/)
})
