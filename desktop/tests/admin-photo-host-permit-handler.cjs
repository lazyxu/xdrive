const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname, '..', '..', name), 'utf8')

test('nine private model endpoints have dormant and fail-closed test verifier', () => {
  const model = read('services/photo-face-analyzer/analyzer.py')
  const guard = read('services/photo-face-analyzer/model_permit_guard.py')
  const tests = read('services/photo-face-analyzer/tests/test_model_permit_guard.py')
  const router = read('internal/api/router.go')
  const face = read('internal/photointelligence/face_unix.go')
  const semantic = read('internal/photointelligence/semantic_unix.go')
  assert.equal((model.match(/self\._require_model_permit\(/g) || []).length, 5)
  assert.ok(model.includes('self.model_permit_verifier = None'))
  assert.ok(model.includes('getattr(self.server.state, "model_permit_verifier", None)'))
  assert.ok(model.includes('if allowed is not True:'))
  assert.ok(model.includes('raise RequestError(403, "model permit not authorized")'))
  assert.ok(model.includes('duplicate model permit header'))
  assert.ok(model.includes('self._require_model_permit(method, target, payload, headers)'))
  assert.match(guard, /class OfflineModelPermitGuard:/)
  assert.match(guard, /object_pairs_hook=unique_object/)
  assert.match(guard, /admission_permit\.verify_v1\(/)
  assert.match(tests, /test_all_nine_model_routes_deny_without_injected_permit/)
  assert.match(tests, /test_fixed_canary_accept_once_then_deny_replay_and_tampering/)
  assert.match(tests, /test_post_exact_body_and_replay_before_semantic_inference/)
  assert.match(tests, /test_legacy_no_verifier_preserves_existing_model_bearer/)
  for (const source of [router, face, semantic]) {
    assert.doesNotMatch(source, /model_permit_verifier|x-xdrive-model-permit/i)
  }
  assert.doesNotMatch(model, /import admission_permit|from admission_permit import/)
  assert.doesNotMatch(router, /admin\.(?:POST|PUT|DELETE)\(".*photo-intelligence\/host\/(?:stop|restart|freeze|disable)/)
})
