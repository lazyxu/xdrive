test('native Photos review is visible and not an implicit network writer', () => {
  assert.match(ui, /Section\("不确定收据核对"\)/)
  assert.match(ui, /native-ios-photo-receipts-status/)
  assert.match(ui, /native-ios-photo-receipts-review/)
  assert.match(ui, /native-ios-photo-receipts-resume/)
  assert.match(ui, /receipts\.cancel\(\)/)
  assert.match(ui, /if mode == \.idle\s*\{\s*controller\.refresh/)
  assert.match(ui, /确认恢复当前 Owner 的前台自动备份/)
  assert.match(review, /XDriveIOSPhotoBackupUncertainReceiptRecovery\(/)
  assert.doesNotMatch(review, /\.uploadPrepared\(|\.uploadOnce\(|\.finalize\(|\.beginCreate\(|URLSession\(|WKWebView\(|WebOwner\(/)
  assert.match(legacy, /\.confirmReceipt\(/)
  assert.match(legacy, /XDriveIOSNodeReceiptReadbackVerifier\(/)
})

test('receipt count is scoped and read-only, without creating a new install Keychain secret', () => {
  const status = review.slice(review.indexOf('    func refresh('), review.indexOf('    func reconcile('))
  assert.match(status, /login\.verifiedAuthorization\(\)/)
  assert.match(status, /existingLocalScope\(owner: expected\)/)
  assert.match(status, /pendingReceiptSnapshot\(scope: scope, limit: 0\)/)
  assert.match(status, /self\.hasLedgerScope = scope != nil/)
  assert.match(status, /self\.generation == epoch/)
  assert.match(scope, /func existingLocalScope\(owner:/)
  assert.doesNotMatch(status, /\.localScopeAndTag\(|\.localScope\(|\.installationKey\(/)
})

test('reconciliation acquires the shared writer gate before any immutable readback', () => {
  const passage = review.slice(review.indexOf('    func reconcile('), review.indexOf('    func resumePausedAuto('))
  assert.ok(passage.indexOf('XDriveIOSOriginalRunGate.shared.acquire()') > 0)
  assert.ok(passage.indexOf('XDriveIOSOriginalRunGate.shared.acquire()') <
            passage.indexOf('pendingReceiptSnapshot('))
  assert.match(passage, /defer \{ XDriveIOSOriginalRunGate.shared.release\(gate\) \}/)
  assert.match(passage, /limit: Self\.maxPerReview/)
  assert.match(review, /private static let maxPerReview = 20/)
  assert.match(passage, /login\.verifiedAuthorization\(\)/)
  assert.match(passage, /XDriveIOSNativePhotoOwnerScope.matches\(login.owner, expected\)/)
  assert.match(passage, /case \.confirmed:/)
  assert.match(passage, /case \.ambiguousSession:/)
  assert.match(journal, /case \.creating, \.uploading, \.finalizing, \.needsReconciliation:/)
})

test('paused schedule resumes only with explicit consent, zero trusted pending, and active Owner', () => {
  const resume = review.slice(review.indexOf('    func resumePausedAuto('))
  const snapshot = resume.indexOf('pendingReceiptSnapshot(')
  const configure = resume.indexOf('scheduleStore.configure(')
  assert.ok(snapshot >= 0 && configure > snapshot)
  assert.match(resume, /let scope = try await XDriveIOSForegroundBackupIdentity\.shared/)
  assert.match(resume, /count == 0/)
  assert.match(resume, /current\.enabled, current\.pausedForReview/)
  assert.match(resume, /scheduleStore\.localStopGeneration == stopGeneration/)
  assert.match(resume, /UIApplication\.shared\.applicationState == \.active/)
  assert.match(resume, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(resume, /login\.verifiedAuthorization\(\)/)
  assert.match(resume, /XDriveIOSOriginalRunGate\.shared\.release\(gate\)/)
  assert.match(ui, /\.confirmationDialog\("确认恢复当前 Owner 的前台自动备份？"/)
  assert.match(ui, /receipts\.pending == 0 && receipts\.hasLedgerScope/)
  assert.match(store, /windowIndex: existing\?\.windowIndex \?\? 0/)
})

