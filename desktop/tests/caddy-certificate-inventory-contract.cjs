const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = (name) => fs.readFileSync(path.join(__dirname, '../..', name), 'utf8')

test('Caddy dual HTTPS inventory binds verified Host evidence and fixed Caddy TLS', () => {
  const inventory = read('internal/api/admin_caddy_certificates.go')
  const host = read('internal/api/admin_caddy_env_only.go')
  const dto = read('internal/api/admin_caddy_https_desired.go')
  assert.match(host, /caddyCertificateInventory\(c\.Request\.Context\(\), snap, host, observed\)/)
  assert.match(dto, /Certificates\s+\*caddyCertificateInventory/)
  const agent = read('internal/client/client.go')
  const desktopTransport = read('desktop/src/main/agent_client.cts')
  assert.match(agent, /Certificates\s+\*AdminCaddyCertificateInventory/)
  assert.match(agent, /HostEnvSHA256\s+string/)
  assert.match(desktopTransport, /certificates\?: \{/)
  assert.match(desktopTransport, /type AgentAdminCaddyCertificate = \{/)
  assert.doesNotMatch(desktopTransport, /import\('\.\.\/\.\.\/\.\.\/ui\/shared\/src'\)\.XDriveCaddyCertificates/)
  assert.match(inventory, /snap\.PendingRedeploy/)
  assert.match(inventory, /host\.TLSVerifiedDomainSHA256 ==/)
  assert.match(inventory, /host\.LANVerifiedIPSHA256 ==/)
  assert.match(inventory, /const caddyCertificateTLSAddress = "caddy:443"/)
  assert.match(inventory, /const caddyCertificateRootURL = "http:\/\/caddy:80\/_xdrive\/desktop\/lan-root\.crt"/)
  assert.match(inventory, /MinVersion: tls\.VersionTLS12, ServerName: name, RootCAs: roots/)
  assert.match(inventory, /len\(verified\.VerifiedChains\) == 0/)
  assert.match(inventory, /leaf\.VerifyHostname\(name\)/)
  assert.match(inventory, /ChainRootSHA256 = caddyCertificateSHA256\(root\.Raw\)/)
  assert.match(read('ui/shared/src/mui/CaddyCertificatePanel.tsx'), /chain_root_sha256/)
  assert.doesNotMatch(inventory, /InsecureSkipVerify:\s*true|exec\.Command|private_key|BEGIN PRIVATE KEY/)
})

test('shared Desktop DSM Web certificate panel downloads only user-clicked public material', () => {
  const component = read('ui/shared/src/mui/CaddyCertificatePanel.tsx')
  const detail = read('ui/shared/src/mui/CaddyDetailV1.tsx')
  assert.match(detail, /<XDriveCaddyCertificatePanel certificates={config\?\.certificates}/)
  assert.match(component, /certificate\.state === 'verified-local'/)
  assert.match(component, /root\.sha256/)
  assert.match(component, /savePublicCertificate\(root\.pem, 'xdrive-lan-root\.cer', true\)/)
  assert.match(component, /<Button/)
  assert.match(component, /VPN 与设备管理/)
  assert.match(component, /不要关闭证书校验/)
  assert.doesNotMatch(component, /window\.open\(|location\.assign\(|dangerouslySetInnerHTML|InsecureSkipVerify/)
})

test('native login and Web/PWA refuse automatic CA trust or TLS downgrade', () => {
  const ios = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
  const android = read('android/app/src/main/java/com/tfluid/xdrive/AuthScreens.kt')
  const web = read('web/src/ManualConnectionDialog.tsx')
  assert.match(ios, /native-ios-lan-certificate-help/)
  assert.match(android, /auth-lan-certificate-help/)
  // The newest master owns account-scoped Android passwords; the certificate
  // hint must not replace or disable that existing login surface.
  assert.match(android, /auth-remember-password/)
  assert.match(android, /auth-saved-password-login/)
  assert.match(android, /auth-forget-profile/)
  assert.match(web, /管理员 → Caddy → HTTPS 证书管理/)
  assert.doesNotMatch(ios + android, /trustAllCertificates|InsecureSkipVerify|proceed\(\)/)
})
