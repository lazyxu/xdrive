const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')

test('Admin maintenance never silently hides server backup CRUD when Host capability is absent', () => {
  const page = read('ui/shared/src/mui/SystemMaintenancePage.tsx')
  const desktop = read('desktop/src/renderer/App.tsx')
  assert.match(desktop, /capabilities\.includes\('admin-backups'\) \? maintenanceBackupPort : undefined/)
  assert.match(page, /backupPort \? \(/)
  assert.match(page, /data-xdrive-admin-backup-host-unavailable/)
  assert.match(page, /服务器备份、恢复与备份仓库校验/)
  assert.match(page, /恢复前必须另行保管部署配置与密钥/)
  assert.match(page, /不要在管理员网页中上传或展示这些密钥/)
  assert.match(page, /无法在此创建、查询、修改策略、删除、恢复或校验服务器备份/)
  assert.match(page, /Host Control \/ Agent/)
  assert.match(page, /不会绕过宿主权限直接访问备份目录/)
})

test('Online CAS integrity link remains available without impersonating backup Host control', () => {
  const page = read('ui/shared/src/mui/SystemMaintenancePage.tsx')
  const backup = read('ui/shared/src/mui/ServerBackupManagementPanel.tsx')
  const storage = read('ui/shared/src/mui/GlobalStorageStatsPage.tsx')
  assert.match(page, /onOpenStorage \? \(/)
  assert.match(page, /onClick=\{onOpenStorage\}/)
  assert.match(page, /不等同于备份校验/)
  assert.match(backup, /action: 'verify_all'/)
  assert.match(backup, /action: 'restore'/)
  assert.match(storage, /storage_verify/)
  assert.doesNotMatch(page, /adminServerBackupAction|cloudAdminBackupAction|backup\(\{/)
})
