'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const exported = read('ios/XDriveIOS/NativeFilesDownloadExport.swift')
const view = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const server = read('internal/api/router.go')

test('verified exact-Node signed download ticket never redirects, guesses bytes or imports WebView authority', () => {
  assert.match(server, /POST\("\/files\/:id\/download-ticket", s\.fileDownloadTicket\)/)
  assert.match(exported, /\/api\/v1\/nodes\/\\\(node.id\)/)
  assert.match(exported, /current == node/)
  assert.match(exported, /\/api\/v1\/files\/\\\(node.id\)\/download-ticket/)
  assert.match(exported, /\/api\/v1\/file-download\/\\\(node.id\)/)
  assert.match(exported, /parsed\.scheme == nil, parsed\.host == nil/)
  assert.match(exported, /query\[0\]\.name == "ticket"/)
  assert.match(exported, /URLSessionConfiguration\.ephemeral/)
  assert.match(exported, /completionHandler\(nil\)/)
  assert.match(exported, /session\.download\(/)
  assert.match(exported, /authenticated: false/)
  assert.match(exported, /int64Value == node\.size/)
  assert.match(exported, /stillCurrent == node/)
  assert.doesNotMatch(exported, /WKWebView\s*\(|document\.cookie|localStorage/)
})

test('native Files export remains a scoped, bounded temporary resource until user-initiated OS ShareLink', () => {
  assert.match(exported, /static let maximumTemporaryBytes: Int64 = 512 \* 1_048_576/)
  assert.match(exported, /FileProtectionType\.complete/)
  assert.match(exported, /prepared\?\.discard\(\)/)
  assert.match(exported, /output\.discard\(\)/)
  assert.match(exported, /login\.verifiedAuthorization\(\)/)
  assert.match(exported, /XDriveIOSNativePhotoOwnerScope\.matches\(after\.owner, expected\)/)
  assert.match(view, /ShareLink\(item: prepared\.fileURL\)/)
  assert.match(view, /需要在系统分享菜单中主动选择保存位置/)
  assert.match(view, /\.sheet\(item: \$selectedFile, onDismiss: \{ exporter\.invalidate\(\) \}\)/)
  assert.match(view, /\.onDisappear \{ exporter\.invalidate\(\) \}/)
  assert.match(view, /exporter\.invalidate\(\)\s*createEpoch = UUID\(\)/)
})
