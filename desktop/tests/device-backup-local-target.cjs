const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Own-only Desktop cloud target update cannot borrow Web or foreign mutation channels', () => {
  const server = read('internal', 'api', 'sources.go')
  const auth = read('internal', 'api', 'local_source_executor_auth.go')
  const client = read('internal', 'client', 'local_bound_rename.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_config.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalTargetDialog.tsx')
  const web = read('web', 'src', 'App.tsx')

  assert.match(server, /requireLocalSourceMutationTx\(tx, c, id\)/)
  assert.match(server, /owner_id = \? AND type = \? AND deleted_at IS NULL/)
  assert.match(server, /resetMirrorEvidence = true/)
  assert.match(auth, /clientDeviceCredentialMatches\(/)
  for (const header of ['X-XDrive-Device-ID', 'X-XDrive-Device-Token',
    'X-XDrive-Local-Root-ID', 'X-XDrive-Local-Root-Fingerprint']) {
    assert.ok(client.includes(header), 'missing native proof ' + header)
  }
  assert.match(agent, /localpush\.LoadRootGrant\(/)
  assert.match(agent, /cli\.LocalSourceBindingWithToken\(/)
  assert.match(agent, /cli\.RetargetLocalBoundSource\(/)
  assert.doesNotMatch(agent, /localpush\.EnsureDevice\(/)
  assert.match(ipc, /"device-backup-local-target"/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-target'\)/)
  assert.match(preload, /retargetDeviceBackupLocalSource:/)
  assert.match(app, /localTarget=\{localBackupTarget\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(dialog, /actions\.retarget\(sourceID, settings\.revision, target\.id\)/)
  assert.doesNotMatch(web, /localTarget=/)
  assert.doesNotMatch(web, /retargetDeviceBackupLocalSource/)
  assert.doesNotMatch(dialog, /(?:triggerSource|cancelSourceRun|startUpload)\(/)
})
