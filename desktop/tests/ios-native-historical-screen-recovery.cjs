'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const repo = path.resolve(__dirname, '..', '..')
const read = p => fs.readFileSync(path.join(repo, p), 'utf8')

test('native PhotoKit diagnostics reuse canonical continuous albums without another paging UI', () => {
  const inventory = read('ios/XDriveIOS/LocalPhotoInventoryScreen.swift')
  const scan = read('ios/XDriveIOS/PhotoKitScanPreviewScreen.swift')
  const albums = read('ios/XDriveIOS/NativePhotoAlbumBrowser.swift')
  assert.match(inventory, /struct LocalPhotoInventoryScreen: View/)
  assert.match(scan, /struct XDrivePhotoKitScanPreviewScreen: View/)
  assert.match(inventory, /NavigationLink \{\s*XDriveIOSNativePhotoAlbumsScreen\(\s*savedOffset: \$albumDirectoryOffset/)
  assert.match(inventory, /XDrivePhotoKitResourceInspector\.inspect\(/)
  assert.match(albums, /XDriveLocalPhotoAlbumPager\.readPage\(\s*offset: requestedOffset/)
  assert.match(scan, /XDrivePhotoKitBoundedSnapshotScanner\(/)
  for (const source of [inventory, scan]) {
    assert.doesNotMatch(source, /Button\("上一页"\)|Button\("下一页"\)|Button\("继续检查下一批/)
    assert.doesNotMatch(source, /LoginViewModel|KeychainSessionStore|WebView|window\.webkit|URLSession/)
    assert.doesNotMatch(source, /XDriveIOSJournaledOriginalUpload\(|NativeUploadSessionTransport\(|URLSession\(|\.uploadPreparedOriginal\(/)
  }
  assert.doesNotMatch(inventory, /\balbumPage\b|\balbumLoading\b|\balbumTask\b/)
  assert.match(inventory, /init\(onUploadStillPhoto:.*= nil\)/)
  assert.match(inventory, /onUploadStillPhoto != nil && model\.hasAccess/)
})

test('PhotoKit inventory remains permission scoped and cancels upload without retaining album state', () => {
  const inventory = read('ios/XDriveIOS/LocalPhotoInventoryScreen.swift')
  const album = read('ios/XDriveIOS/NativePhotoAlbumBrowser.swift')
  assert.match(inventory, /authorization == \.authorized \|\| authorization == \.limited/)
  assert.match(inventory, /PHPhotoLibrary\.requestAuthorization\(for: \.readWrite\)/)
  assert.match(inventory, /guard !Task\.isCancelled else \{ return \}/)
  assert.match(inventory, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(inventory, /\.task \{ await model\.inspect\(askPermission: false\) \}/)
  assert.match(inventory, /if phase != \.active/)
  assert.match(inventory, /albumDirectoryOffset = 0/)
  assert.match(inventory, /photoUploadTask\?\.cancel\(\)/)
  assert.match(inventory, /\.onDisappear \{/)
  assert.match(album, /libraryMonitor\.stop\(\)/)
  assert.match(album, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
})

test('continuous scan virtualizes 64-slot metadata windows and invalidates stale PhotoKit snapshots', () => {
  const view = read('ios/XDriveIOS/PhotoKitScanPreviewScreen.swift')
  const scanner = read('ios/XDriveIOS/PhotoKitBoundedSnapshotScanner.swift')
  assert.match(view, /private struct XDriveIOSNativeScanPreviewWindow: View/)
  assert.match(view, /ScrollView \{\s*LazyVStack/)
  assert.match(view, /XDriveIOSNativePhotoVirtualPagePolicy\.pageCount\(/)
  assert.match(view, /generation = UUID\(\)/)
  assert.match(view, /scanTask\?\.cancel\(\)/)
  assert.match(view, /let count = try await current\.start\(atOffset: offset\)/)
  assert.match(view, /let next = try await current\.nextPage\(\)/)
  assert.match(view, /try Task\.checkCancellation\(\)/)
  assert.match(view, /count == expectedTotal,[\s\S]*next\.totalAccessibleAssets == expectedTotal/)
  assert.match(view, /next\.startOffset == offset,[\s\S]*next\.items\.count == next\.nextOffset - offset/)
  assert.match(view, /await current\.reset\(\)/)
  assert.match(view, /if generation == token, scenePhase == \.active/)
  assert.match(view, /guard generation == staleGeneration,/)
  assert.match(view, /photoLibraryDidChange\(_ change: PHChange\)/)
  assert.match(view, /if phase != \.active \{ invalidate\(\) \}/)
  assert.match(view, /\.onDisappear \{\s*page = nil\s*if let scanner/)
  assert.match(view, /item\.isLive/)
  assert.match(scanner, /static let pageSize = 64/)
  assert.match(scanner, /func start\(atOffset requestedOffset: Int = 0,\s*requireStableResume: Bool = false\)/)
  // Preview pages remain ordinary PhotoKit ordering. Only a verified
  // original-backup scan may resolve equal-date 256-slot boundaries.
  assert.match(view, /let count = try await current\.start\(atOffset: offset\)/)
  assert.match(scanner, /if requireStableResume \{[\s\S]*?Self\.stableBackupBoundaryIndices\(/)
  assert.match(scanner, /\} else \{\s*boundaryIndices = \[:\]/)
  assert.match(scanner, /observer\.currentVersion\(\) == beginVersion,[\s\S]*?PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\) == status/)
  assert.match(scanner, /stableBoundaryPhysicalIndices = boundaryIndices/)
  assert.match(scanner, /stableBoundaryPhysicalIndices\.removeAll\(\)/)
  assert.match(scanner, /func nextPage\(\)/)
  assert.match(scanner, /observer\.currentVersion\(\) == changeVersion/)
  assert.match(scanner, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.doesNotMatch(view, /URLSession|UploadSession|requestImage|requestAVAsset|requestLivePhoto/)
})
