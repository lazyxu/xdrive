'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const ledger = read('ios/XDriveIOS/PhotoSyncEncryptedLedger.swift')
const controller = read('ios/XDriveIOS/NativePhotoReceiptReviewController.swift')
const recovery = read('ios/XDriveIOS/PhotoBackupUncertainReceiptRecovery.swift')

test('bounded exact pending receipt count keeps at most 20 records while streaming shards', () => {
  const start = ledger.indexOf('func pendingReceiptSnapshot(scope:')
  const end = ledger.indexOf('/// Read one authenticated operation', start)
  assert.ok(start >= 0 && end > start)
  const scan = ledger.slice(start, end)
  assert.match(scan, /limit >= 0, limit <= 20/)
  assert.match(scan, /XDrivePhotoPendingBatchAccumulator<XDrivePhotoSyncOperation>/)
  assert.match(scan, /accumulator\.consider\(item, isPending: isUncertain\(item\)\)/)
  assert.match(scan, /return \(pending: accumulator\.pending, batch: accumulator\.batch\)/)
  assert.match(scan, /case \.creating, \.uploading, \.finalizing, \.needsReconciliation:/)
  assert.match(scan, /case \.prepared, \.confirmed:/)
  assert.match(scan, /availableShardPrefixes\(scope: scope\)/)
  assert.match(scan, /try readShard\(scope: scope, key: key, prefix: prefix\)/)
  assert.match(scan, /try Task\.checkCancellation\(\)/)
  assert.doesNotMatch(scan, /var all =|all\.append|\+ shard\.operations/)
})

test('cross-version V1/V2 identity collision is fail-closed under encrypted scope', () => {
  const start = ledger.indexOf('func pendingReceiptSnapshot(scope:')
  const end = ledger.indexOf('/// Read one authenticated operation', start)
  const scan = ledger.slice(start, end)
  assert.match(scan, /let legacyIDs = Set\(legacy\.map\(\\\.id\)\)/)
  assert.match(scan, /let legacyFingerprints = Set\(legacy\.map\(\\\.assetFingerprint\)\)/)
  assert.match(scan, /!legacyIDs\.contains\(item\.id\)/)
  assert.match(scan, /!legacyFingerprints\.contains\(item\.assetFingerprint\)/)
  assert.match(scan, /throw XDrivePhotoSyncLedgerError\.identityMismatch/)
  assert.match(ledger, /authenticating: shardAAD\(scope: scope, prefix: prefix\)/)
  assert.match(ledger, /envelope\.operations\.allSatisfy/)
})

test('native Owner receipt controller retains bounded, exact and read-only review', () => {
  const refresh = controller.slice(controller.indexOf('func refresh('),
    controller.indexOf('func reconcile('))
  const review = controller.slice(controller.indexOf('func reconcile('),
    controller.indexOf('func resumePausedAuto('))
  assert.match(refresh, /pendingReceiptSnapshot\(scope: scope, limit: 0\)\.pending/)
  assert.match(review, /limit: Self\.maxPerReview/)
  assert.match(controller, /private static let maxPerReview = 20/)
  assert.match(review, /let snapshot = try await ledger\.pendingReceiptSnapshot/)
  assert.match(review, /for record in snapshot\.batch/)
  assert.match(review, /XDriveIOSPhotoBackupUncertainReceiptRecovery/)
  assert.match(review, /case \.confirmed:/)
  assert.match(review, /case \.ambiguousSession:/)
  assert.match(review, /self\.pending = latest\.pending/)
  assert.doesNotMatch(review, /ledger\.operations\(scope: scope\)/)
  assert.doesNotMatch(review, /uploadPreparedOriginal\(|beginCreate\(/)
})

test('reconcile single uncertain intent never loads the entire encrypted history', () => {
  assert.match(recovery, /ledger\.operation\(/)
  assert.doesNotMatch(recovery, /ledger\.operations\(scope: scope\)/)
  assert.match(recovery, /case \.prepared, \.confirmed:/)
  assert.match(recovery, /ledger\.markUnknown\(/)
  assert.match(recovery, /ledger\.confirmReceipt\(/)
  assert.doesNotMatch(recovery, /uploadPreparedOriginal\(|createUploadSession\(/)
})
