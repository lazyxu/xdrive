test('item-local automatic retry is durable, bounded and cannot reissue an uncertain UploadSession', () => {
  const db = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
  const queue = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
  const controller = read('ios/XDriveIOS/NativePhotoBackupController.swift')
  const bg = read('ios/XDriveIOS/BackgroundPhotoTask.swift')
  const swift = read('ios/tests/PhotoBackupChangeQueueStoreChecks.swift')
  assert.match(db, /CREATE TABLE IF NOT EXISTS automatic_retries/)
  assert.match(db, /r\.reason IN \('unavailable','originalMissing'\)/)
  assert.match(db, /COALESCE\(a\.attempts,0\)<3/)
  assert.match(db, /retryFailedAutomatically\(_ candidate: Pending/)
  assert.match(db, /BEGIN IMMEDIATE/)
  assert.match(db, /expectedBaselineToken: Data/)
  assert.match(db, /let delays: \[TimeInterval\] = \[15 \* 60, 60 \* 60, 6 \* 3600\]/)
  assert.match(db, /DELETE FROM automatic_retries/)
  assert.match(queue, /func retrySafeFailedCandidates\(owner:/)
  assert.match(queue, /PHAsset\.fetchAssets/)
  assert.match(queue, /verifyAuthorization\(stillMatches: epoch\)/)
  const automatic = controller.slice(controller.indexOf('private func start(login:'))
  const pending = automatic.indexOf('XDriveIOSOriginalPendingReceiptPreflight')
  const retry = automatic.indexOf('retrySafeFailedCandidates(')
  assert.ok(pending >= 0 && retry > pending, 'global unknown-ACK admission must precede auto requeue')
  assert.match(bg, /olderPending > 0/)
  assert.match(bg, /retrySafeFailedCandidates\(/)
  assert.match(swift, /automatic-retry\.sqlite3/)
  assert.doesNotMatch(db, /POST \/api\/v1\/uploads|uploadPreparedOriginal|finalizeUpload/)
})

