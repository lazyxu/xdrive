const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Device Backup UI exposes archive and paused restore only for the verified local device', () => {
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalArchiveDialog.tsx')
  const access = read('ui', 'shared', 'src', 'device-backup-local-feature-access.ts')
  assert.match(page, /archive: folder\.status !== 'archived' && Boolean\(localArchive\)/)
  assert.match(page, /restore: folder\.status === 'archived' && Boolean\(localArchive\)/)
  assert.match(page, /folder\.latest_run\?\.status === 'running'/)
  assert.match(page, /恢复（保持暂停）/)
  assert.match(page, /verifiedLocalDeviceID && localOwnsFolder\(archiveTarget\.id\)/)
  assert.match(access, /archive: current && supported\.archive/)
  assert.match(access, /restore: current && supported\.restore/)
  assert.match(dialog, /expectedStatus = mode === 'archive' \? 'archived' : 'paused'/)
  assert.match(dialog, /不会自动启动上传或计划任务/)
})

test('local Push archive and restore always preserve the owning Root grant', () => {
  const authorization = read('cmd', 'xdrive-agent', 'device_backup_local_config.go')
  const archive = read('cmd', 'xdrive-agent', 'device_backup_local_archive.go')
  const client = read('internal', 'client', 'local_bound_archive.go')
  const proofHeaders = read('internal', 'client', 'local_bound_rules.go')
  const api = read('internal', 'api', 'local_source_archive_integration_test.go')
  assert.match(authorization, /localBoundBackupAuthorization/)
  assert.match(authorization, /localpush\.LoadRootGrant/)
  assert.match(authorization, /meta\.SourceStatusArchived/)
  assert.match(archive, /ArchiveLocalBoundSource/)
  assert.match(archive, /RestoreLocalBoundSource/)
  assert.match(archive, /Root grant is intentionally retained/)
  assert.doesNotMatch(archive, /RemoveRootGrant/)
  assert.match(client, /localRulesProofHeaders\(req, proof\)/)
  for (const header of ['X-XDrive-Device-ID', 'X-XDrive-Device-Token', 'X-XDrive-Local-Root-ID', 'X-XDrive-Local-Root-Fingerprint']) {
    assert.ok(proofHeaders.includes(header), header)
  }
  assert.match(api, /ArchiveRestoreRequiresOwningDeviceAndRetainsRootBinding/)
  assert.match(api, /http\.StatusForbidden/)
})

test('local Push archive lifecycle uses private Agent IPC and an explicit capability', () => {
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const handlers = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_archive.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const renderer = read('desktop', 'src', 'renderer', 'App.tsx')
  assert.match(ipc, /device-backup-local-archive-restore/)
  assert.match(handlers, /CloudArchiveLocalBoundBackup/)
  assert.match(handlers, /CloudRestoreLocalBoundBackup/)
  assert.match(main, /agent:archive-device-backup-local-source/)
  assert.match(main, /agent:restore-device-backup-local-source/)
  assert.match(preload, /archiveDeviceBackupLocalSource/)
  assert.match(preload, /restoreDeviceBackupLocalSource/)
  assert.match(renderer, /localArchive: localBackupArchive/)
})
