'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const page = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const trash = read('ios/XDriveIOS/NativeFilesBatchTrash.swift')
const policy = read('ios/XDriveIOS/NativeFilesBatchTrashPolicy.swift')
const api = read('internal/api/batch_nodes.go')
const routes = read('internal/api/router.go')

test('real native multi-select is bounded to one currently verified Owner directory page', () => {
  assert.match(page, /@State private var selectedIDs = Set<UInt64>\(\)/)
  assert.match(page, /private var canSelectPage: Bool \{[\s\S]*?model\.verifiedPage && activeQuery\.isEmpty/)
  assert.match(page, /if selecting \{[\s\S]*?native-ios-files-select-/)
  assert.match(page, /selectedIDs = Set\(model\.entries\.map\(\\\.id\)\)/)
  assert.match(page, /native-ios-files-multi-select/)
  assert.match(page, /showingBatchTrashConfirmation = true/)
  assert.match(page, /selectedIDs == Set\(chosenItems\.map\(\\\.id\)\)/)
  assert.match(page, /XDriveIOSNativeFilesBatchTrashPolicy\.validSelection\(/)
  assert.match(page, /\.onChange\(of: login\.owner\) \{ _ in[\s\S]*?batchTrash\.invalidate\(\)/)
  assert.match(page, /private func reload\(resetOffset: Bool = false\) \{\s*selecting = false\s*selectedIDs\.removeAll\(\)/)
  assert.match(policy, /static let maxSelected = XDriveIOSNativeFilesPagePolicy\.pageSize/)
})
test('Server batch trash atomically validates revision/subtrees, not per-item fake progress', () => {
  assert.match(routes, /authed\.POST\("\/nodes\/batch\/delete", s\.batchDeleteNodes\)/)
  assert.match(api, /func \(s \*Server\) batchDeleteNodes\(c \*gin\.Context\)/)
  assert.match(api, /validateBatchNodeRefs\(req\.Items\)/)
  assert.match(api, /err := s\.DB\.Transaction\(func\(tx \*gorm\.DB\) error \{/)
  assert.match(api, /topLevelBatchDeleteRefs\(tx, uid, req\.Items\)/)
  assert.match(api, /revision_conflict/)
  assert.match(trash, /\/api\/v1\/nodes\/batch\/delete/)
  assert.match(trash, /XDriveIOSNativeFilesBatchTrashRequest\(/)
  assert.match(trash, /id: \$0\.id, revision: \$0\.revision/)
  assert.match(trash, /http\.statusCode == 200/)
  assert.match(trash, /validReceipt\(receipt, for: items\)/)
  assert.match(policy, /Set\(receipt\.deleted_ids\) == Set\(selected\)/)
  assert.doesNotMatch(trash, /WKWebView\s*\(|localStorage|\/api\/v1\/uploads/)
})
test('Owner change and cancellation report uncertain write rather than replaying batch delete', () => {
  assert.match(trash, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(trash, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(trash, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(trash, /func cancelCurrent\(\)/)
  assert.match(trash, /running\.cancel\(\)/)
  assert.match(trash, /结果可能不确定/)
  assert.match(page, /取消批量操作/)
  assert.match(page, /包括选中文件夹的所有子文件/)
})
