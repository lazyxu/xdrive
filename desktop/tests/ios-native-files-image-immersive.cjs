'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const file = fs.readFileSync(path.join(root, 'ios/XDriveIOS/NativeFilesViewer.swift'), 'utf8')
const zoom = fs.readFileSync(path.join(root, 'ios/XDriveIOS/NativeZoomablePhotoView.swift'), 'utf8')

test('Files still and thumbnail use same native photo single-tap chrome without changing zoom or paging', () => {
  const viewer = file.slice(file.indexOf('struct XDriveIOSNativeFilesViewer: View'))
  assert.match(viewer, /@State private var showImageChrome = true/)
  assert.match(viewer, /private var isStillImage: Bool/)
  assert.match(viewer, /case \.image\(_\), \.imageThumbnail\(_\): return true/)
  assert.match(viewer, /private func toggleImageChrome\(\) \{\s*guard authorized, isStillImage/)
  assert.equal((viewer.match(/\.onChromeTap \{ toggleImageChrome\(\) \}/g) || []).length, 2)
  assert.equal((viewer.match(/\.onNavigateSwipe \{ move\(\$0\) \}/g) || []).length, 2)
  assert.match(zoom, /singleTap\.require\(toFail: doubleTap\)/)
  assert.match(zoom, /scroll\.panGestureRecognizer\.require\(toFail: pagingPan\)/)
})

test('immersive still hides only image chrome; files PDF/audio/video/error and recoverable original export remain intact', () => {
  const viewer = file.slice(file.indexOf('struct XDriveIOSNativeFilesViewer: View'))
  // Hiding video chrome must not hide the previous/next bottom navigation.
  assert.match(viewer, /\.toolbar\(chromeVisible \? \.visible : \.hidden, for: \.navigationBar\)/)
  assert.match(viewer, /\.toolbar\(isNativeVideo \? \.visible :[\s\S]*?for: \.bottomBar\)/)
  assert.match(viewer, /\.statusBarHidden\(!chromeVisible\)/)
  // Keep the dark video canvas even during initial first-frame loading.
  assert.match(viewer, /\.background\(isStillImage \|\| isNativeVideo \|\| \(loading && expectsVideoCanvas\)\s*\? Color\.black : Color\(uiColor: \.systemBackground\)\)/)
  assert.match(viewer, /if isNativeVideo && !videoFirstFrameRecorded \{[\s\S]*?ProgressView\("正在加载视频首帧…"\)[\s\S]*?\.allowsHitTesting\(false\)/)
  assert.match(viewer, /if showImageChrome \{\s*XDriveIOSNativeViewerQualityPanel\(/)
  assert.match(viewer, /if showImageChrome \{\s*ScrollView \{[\s\S]*?originalExportFallback/)
  assert.match(viewer, /native-ios-files-viewer-thumbnail-recovery/)
  assert.match(viewer, /case \.video:[\s\S]*?XDriveIOSNativePhotoVideoSurface\(/)
  assert.match(viewer, /case \.audio:[\s\S]*?XDriveIOSNativeFileAudioSurface/)
  assert.match(viewer, /case \.pdf\(let document\):[\s\S]*?XDriveIOSNativePDFDocumentSurface/)
  assert.match(viewer, /case \.text\(let content, let truncated\):/)
  assert.match(viewer, /if authorized && exportFallbackEligible/)
  assert.match(viewer, /private func retire\(\) \{[\s\S]*?showImageChrome = true/)
  assert.match(viewer, /\.onChange\(of: login\.owner\) \{ _ in close\(\) \}/)
  assert.match(viewer, /\.onChange\(of: phase\)[\s\S]*?retire\(\)/)
  assert.match(viewer, /\.onDisappear \{ retire\(\) \}/)
  assert.doesNotMatch(viewer, /WKWebView|localStorage|userDefaults|\.upload\(/)
})
