const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('safe scheduled backups use one fixed Administrator Server/Agent/Host contract', () => {
  const server = read('internal/api/admin_backup_management.go')
  const host = read('scripts/server-control.sh')
  const agent = read('cmd/xdrive-agent/desktop_ipc_admin_backups.go')
  const electron = read('desktop/src/main/index.cts')
  const client = read('internal/client/admin_backups.go')
  const types = read('ui/shared/src/server-backup-admin.ts')
  const page = read('ui/shared/src/mui/SystemMaintenancePage.tsx')
  const schedule = read('ui/shared/src/mui/BackupScheduleControl.tsx')

  assert.match(server, /case "schedule":/)
  assert.match(server, /request.Preset != "daily"/)
  assert.match(server, /request\.Confirmation != "SCHEDULE "\+request\.Preset/)
  assert.match(server, /backup_schedule_not_trusted/)
  assert.match(server, /backup_policy_revision_changed/)
  assert.match(client, /Preset\s+string `json:"preset,omitempty"`/)
  assert.match(agent, /case "schedule":/)
  assert.match(electron, /schedule: \['action', 'preset', 'revision', 'confirmation'\]/)
  assert.match(electron, /case 'schedule': return/)
  assert.match(types, /action: 'schedule'/)
  assert.match(page, /<XDriveBackupScheduleControl port=\{backupPort\} \/>/)
  assert.match(schedule, /data-xdrive-admin-backup-schedule-control/)
  assert.match(schedule, /action: 'schedule', preset: selected, revision: expected/)
  assert.match(schedule, /SCHEDULE ' \+ selected/)
  assert.match(schedule, /selectedFromHost/)
  assert.match(schedule, /trustedSchedule/)
  assert.doesNotMatch(schedule, /shell_command|\.exec\(|crontab -|repository_dir/)
  assert.match(host, /backup_admin_schedule_expression\(\)/)
  assert.match(host, /backup_admin_write_schedule\(\)/)
  assert.match(host, /crontab "\$tmp_new"/)
  assert.match(host, /crontab "\$tmp_old"/)
  assert.match(host, /\[\[ "\$action" != policy && "\$action" != schedule \]\]/)
})

test('disabled schedule is persisted safely across installer upgrades', () => {
  const host = read('scripts/server-control.sh')
  const installer = read('deploy/install-server.sh')
  assert.match(host, /daily\) printf '%s\\n' '17 3 \* \* \*'/)
  assert.match(host, /weekly\) printf '%s\\n' '17 3 \* \* 0'/)
  assert.match(host, /disabled\) printf '%s\\n' disabled/)
  assert.match(host, /\[\[ "\$configured" != disabled \]\] \|\| configured=""/)
  assert.match(installer, /if \[\[ "\$schedule" != disabled \]\]; then/)
  assert.match(installer, /Backup schedule explicitly disabled/)
  assert.match(host, /managed <= 1/)
  assert.match(host, /grep -Fxc -- "\$expected_row"/)
})
