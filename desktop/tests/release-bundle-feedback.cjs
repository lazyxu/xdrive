'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..', '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const card = read('ui/shared/src/mui/ReleaseBundleCard.tsx')
const desktop = read('desktop/src/renderer/App.tsx')
const agent = read('cmd/xdrive-agent/client_update_current_server.go')
const provenance = read('internal/client/release_bundle_provenance.go')
const docs = read('docs/architecture/release-bundles.md')

test('cache polling cannot erase an install result for the same current Server Commit', () => {
  const refresh = card.slice(card.indexOf('const refresh = useCallback('), card.indexOf('const retry = async'))
  assert.ok(refresh.includes('const requestNumber = ++latestRefresh.current'))
  assert.ok(refresh.includes('if (requestNumber !== latestRefresh.current) return'))
  const change = refresh.indexOf('if (lastCommit.current !== result.commit)')
  const reset = refresh.indexOf('setActionFeedback(null)', change)
  const complete = refresh.indexOf('setState(result)', change)
  assert.ok(change !== -1 && reset > change && reset < complete, 'clear action feedback only when Server Commit changes')
  assert.ok(refresh.includes("setReadError('')"), 'a successful poll may clear only its own read error')
  assert.equal(refresh.includes('setError('), false, 'must not reset a shared install error')
  assert.ok(refresh.includes('latestRefresh.current++'), 'old Owner/Server poll results must be invalidated')
  assert.ok(refresh.includes('clearInterval(ticker)'), 'poller must be disposed on port change')
})

test('installation, cache retry and download failures have durable distinct feedback', () => {
  assert.ok(card.includes("const [actionFeedback, setActionFeedback] = useState<"))
  assert.ok(card.includes('{actionFeedback ? <XDriveStatusAlert tone={actionFeedback.tone}>'))
  assert.ok(card.includes("setActionFeedback({ tone: 'bad', message: reason instanceof Error"))
  assert.ok(card.includes("setActionFeedback({ tone: 'warning', message: 'Server Commit 已变化"))
  assert.ok(card.includes("setActionFeedback({ tone: 'warning', message: '重试请求未成功"))
  assert.ok(card.includes("setActionFeedback({ tone: 'bad', message: '本机安装包下载失败"))
  assert.ok(card.includes("setActionFeedback({ tone: 'neutral', message: '已提交本机更新"))
  assert.ok(card.includes('不能据此认定升级成功'))
  assert.equal(card.includes("setError('已提交本机更新"), false, 'submitted is not an installation failure or verified success')
})

test('current-Server install warning preserves immutable public admission and explicit consent', () => {
  assert.ok(card.includes('immutable:true'))
  assert.ok(card.includes('Release immutability'))
  assert.ok(card.includes('不影响 Server 或其他客户端'))
  assert.ok(card.includes('确认安装未经签名的个人 Windows 构建'))
  assert.ok(card.includes('验证并安装'))
  assert.ok(desktop.includes('clientReleaseBundlePort'))
  assert.ok(desktop.includes('retry: undefined'), 'ordinary users must not gain Host admin cache retry')
  assert.ok(agent.includes('client.VerifyCurrentBundlePublisher('), 'Agent must independently verify public GitHub before install')
  assert.ok(agent.includes('xupdate.InstallPreviouslyVerified('), 'native installer must independently recheck package bytes')
  assert.ok(provenance.includes('!release.Immutable'), 'mutable releases must remain rejected')
  assert.ok(docs.includes('Polling the cache must not erase a prior install'))
})
