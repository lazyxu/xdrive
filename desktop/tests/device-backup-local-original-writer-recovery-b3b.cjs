const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = (...parts) => fs.readFileSync(path.join(__dirname, '..', '..', ...parts), 'utf8')

test('historical recovery only runs inside original native fd and held writer lock', () => {
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_recovery_g2c2b.go')
  const scoped = read('cmd', 'xdrive-agent', 'device_backup_local_writer_recovery_g2c2d2b3b.go')
  const native = read('internal', 'localpush', 'native_file_held_window.go')
  const writer = read('internal', 'localpushwriter', 'held_observation.go')
  const tests = read('cmd', 'xdrive-agent', 'device_backup_local_writer_recovery_g2c2d2b3b_test.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  assert.ok(agent.includes('return d.recoverPreviousFirstLeafWithHeldWriter(ctx, d.scope)'))
  assert.ok(scoped.includes('d.readPriorFirstLeafOriginalEvidence(ctx, s)'))
  assert.ok(scoped.includes('localpush.WithHeldCurrentOriginalReadCheckpoint('))
  assert.ok(scoped.includes('native.NativeKey, s.ContentSHA256)'))
  assert.ok(scoped.includes('localpushwriter.WithHeldOriginalWriterObservation('))
  assert.ok(scoped.includes('d.recoverPreviousFirstLeafReadOnly(heldCtx, s)'))
  assert.ok(scoped.includes('native.PathKey != evidence.hint.Stage.CurrentPathKey'))
  assert.ok(native.includes('streamVerifiedInventoryFileBytesWithHeldCheckpoint('))
  assert.ok(writer.includes('lockNativeWriter(f)'))
  assert.ok(tests.includes('TestHistoricalOriginalWriterRecoveryRequiresQuarantineAndExcludesLiveWriter'))
  assert.ok(tests.includes('TestHistoricalOriginalWriterRecoveryRedactsFailureAndPreservesUncertainty'))
  for (const banned of ['localpushwriter.Begin(', 'StageVerifiedNativeOriginalBytes(', 'mintLocalPushOperationRequestKey(', 'CommitLocalPushFirstLeafWithOperation(', 'PrepareLocalPushOperation(', 'BindLocalPushOperationStage(', 'os.Remove(']) {
    assert.equal(scoped.includes(banned), false, 'historical recovery acquired write privilege: ' + banned)
  }
  assert.equal(ipc.includes('recoverPreviousFirstLeafWithHeldWriter'), false)
  assert.equal(ipc.includes('recoverLocalPushFirstLeafPrivate'), false)
})
