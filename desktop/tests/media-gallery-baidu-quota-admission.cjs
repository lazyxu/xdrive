'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')

test('A3d2m1b2b2b1 accounts are checked BEFORE claim and AGAIN before quota, never from a client', () => {
  const quota = read('internal/api/baidu_photo_map_index_quota_admission.go')
  const impl = read('internal/api/baidu_photo_map_index_execute.go')
  const routes = read('internal/api/router.go')
  const server = read('cmd/server/main.go')
  const web = read('web/src/api.ts')
  const native = read('desktop/src/main/index.cts')
  assert.match(quota, /accountPermit\(dispatchCtx, ownerID\)/)
  assert.match(quota, /executeBaiduPhotoMapIndexIntent\(dispatchCtx, privateDB/)
  assert.match(quota, /accountPermit\(workCtx, actualOwner\)/)
  assert.match(quota, /reserveBaiduGeoconvQuota\(workCtx, privateDB, actualOwner, 1\)/)
  assert.match(quota, /gorm\.Session\{Logger: logger\.Default\.LogMode\(logger\.Silent\)\}/)
  assert.match(impl, /validateBaiduPhotoMapIndexLease\(workCtx, db, lease\)/)
  assert.doesNotMatch(routes, /executeBaiduPhotoMapIndexQuotaAdmitted/)
  assert.doesNotMatch(server, /executeBaiduPhotoMapIndexQuotaAdmitted/)
  assert.doesNotMatch(web, /executeBaiduPhotoMapIndexQuotaAdmitted|BMAP_PROXY_URL|BrowserAK/)
  assert.doesNotMatch(native, /executeBaiduPhotoMapIndexQuotaAdmitted/)
  assert.doesNotMatch(quota, /http\.Get\(|http\.Post\(|ForwardWGS84ToBD09|BrowserAK|BMAP_PROXY_URL/)
})

