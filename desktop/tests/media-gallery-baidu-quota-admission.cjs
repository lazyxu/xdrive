test('A3 Geoconv flight stays Server-only and is acquired before source-claim, with independent cancellation cleanup', () => {
  const entry = read('internal/api/baidu_photo_map_index_quota_admission.go')
  const flight = read('internal/api/baidu_geoconv_flight.go')
  const model = read('internal/meta/baidu_geoconv_flight.go')
  const routes = read('internal/api/router.go')
  const main = read('cmd/server/main.go')
  const web = read('web/src/mediaGalleryAdapter.ts')
  const desktop = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const policy = read('internal/baidumapjsapi/resource_policy.go')
  assert.match(entry, /acquireBaiduGeoconvFlight\(dispatchCtx, privateDB, ownerID\)/)
  assert.match(entry, /releaseBaiduGeoconvFlight\(releaseCtx, privateDB, flight\)/)
  const acquireAt = entry.indexOf('flight, err := acquireBaiduGeoconvFlight')
  const cleanupAt = entry.indexOf('defer func() {', acquireAt)
  const cancelAt = entry.indexOf('if dispatchCtx.Err() != nil', cleanupAt)
  assert.ok(acquireAt >= 0 && cleanupAt > acquireAt && cancelAt > cleanupAt, 'cancellation must not bypass an acquired lease cleanup')
  assert.match(entry, /context\.WithTimeout\(context\.Background\(\), 2\*time\.Second\)/)
  assert.match(flight, /pg_advisory_xact_lock\(\?\)/)
  assert.match(flight, /baiduGeoconvFlightTTL\s*=\s*15 \* time\.Second/)
  assert.match(flight, /baiduGeoconvFleetFlightCap int64 = 2/)
  assert.match(main, /&meta\.BaiduGeoconvFlight\{\}/)
  assert.match(model, /xd_baidu_geoconv_flights/)
  assert.doesNotMatch(routes, /acquireBaiduGeoconvFlight|releaseBaiduGeoconvFlight/)
  assert.doesNotMatch(web, /acquireBaiduGeoconvFlight|releaseBaiduGeoconvFlight/)
  assert.doesNotMatch(desktop, /acquireBaiduGeoconvFlight|releaseBaiduGeoconvFlight/)
  assert.match(policy, /reviewedJSAPI4ChildResourceCount = 0/)
  assert.match(policy, /return ErrGateClosed/)
})

