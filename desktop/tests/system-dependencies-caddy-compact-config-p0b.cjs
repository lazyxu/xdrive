'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('Caddy editor defaults to truthful target summary; legacy CAS, draft and two-entry safety survive', () => {
  const src = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  assert.match(src, /data-xdrive-caddy-https-readonly-summary/)
  assert.match(src, /data-xdrive-caddy-https-edit-toggle/)
  assert.match(src, /typeof config\.desired_lan_enabled === 'boolean'/)
  assert.match(src, /未知（当前客户端未报告 LAN 目标）/)
  // Host-only IP is shown adjacent to the target only after real local TLS verification.
  assert.match(src, /config\.host_lan_configured === true/)
  assert.match(src, /config\.host_lan_tls_state === 'verified'/)
  assert.match(src, /data-xdrive-caddy-running-lan-ip/)
  assert.match(src, /section === 'config' && editing && \(<>/)
  assert.match(src, /disabled=\{!canEdit \|\| \(editing && changed\)\}/)
  assert.match(src, /\(lanEnabled \|\| enabled\)/)
  assert.match(src, /if \(!source.loadCaddyHTTPSConfig \|\| busy \|\| atomicSaving \|\| changed\) return/)
  assert.match(src, /const canEdit = !!config\?\.editable && !busy && !loading && !atomicSaving/)
  assert.match(src, /revision: config.revision, enabled, domain: domain.toLowerCase\(\)/)
  assert.match(src, /onConfigurationChanged\?\.\(\)/)
  assert.doesNotMatch(src, /docker restart|InsecureSkipVerify|apply_supported=true/)
})

test('AliDNS credentials are always editable without a disclosure; plaintext still requires explicit reveal', () => {
  const src = read('ui/shared/src/mui/CaddyAliDNSPanel.tsx')
  assert.doesNotMatch(src, /manageOpen|setManageOpen|data-xdrive-caddy-alidns-manage/)
  assert.match(src, /AccessKey ID（新值）/)
  assert.match(src, /AccessKey Secret（新值）/)
  assert.match(src, /type="password"/)
  assert.match(src, /临时显示已保存凭据/)
  assert.match(src, /Math\.min\(30, shown\.expires_in_seconds\)/)
  assert.match(src, /document\.addEventListener\('visibilitychange'/)
  assert.match(src, /window\.addEventListener\('blur'/)
  assert.match(src, /hide\(\)/)
  assert.match(src, /setShown\(null\)/)
  assert.match(src, /config.source === 'host-import'/)
  assert.match(src, /data-xdrive-caddy-alidns-host-pending/)
  assert.doesNotMatch(src, /docker restart|InsecureSkipVerify|ALIBABA_ACCESS_KEY_SECRET/)
})
