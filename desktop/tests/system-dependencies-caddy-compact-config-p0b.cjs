'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('Caddy editor defaults to truthful target summary; legacy CAS, draft and two-entry safety survive', () => {
  const src = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  assert.match(src, /data-xdrive-caddy-https-readonly-summary/)
  assert.match(src, /data-xdrive-caddy-https-edit-toggle/)
  assert.match(src, /typeof config\.desired_lan_enabled === 'boolean'/)
  assert.match(src, /未知（当前客户端未报告 LAN 目标）/)
  assert.match(src, /config\.host_observed && config\.host_lan_configured === true/)
  assert.match(src, /config\.host_lan_tls_state === 'verified'/)
  assert.match(src, /data-xdrive-caddy-lan-runtime/)
  assert.match(src, /data-xdrive-caddy-domain-runtime/)
  assert.match(src, /section === 'config' && editing && \(<>/)
  assert.match(src, /disabled=\{!canEdit \|\| \(editing && changed\)\}/)
  assert.match(src, /\(lanEnabled \|\| enabled\)/)
  assert.match(src, /if \(!source.loadCaddyHTTPSConfig \|\| busy \|\| atomicSaving \|\| changed\) return/)
  assert.match(src, /const canEdit = !!config\?\.editable && !busy && !loading && !atomicSaving/)
  assert.match(src, /revision: config.revision, enabled, domain: domain.toLowerCase\(\)/)
  assert.match(src, /onConfigurationChanged\?\.\(\)/)
  assert.doesNotMatch(src, /docker restart|InsecureSkipVerify|apply_supported=true/)
})

