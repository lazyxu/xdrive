const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Only the owning Agent may expose paused local backup drafts for recovery', () => {
  const server = read('internal', 'api', 'local_source_draft_list.go')
  const router = read('internal', 'api', 'router.go')
  const client = read('internal', 'client', 'devices.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_identity.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_drafts.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const panel = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalDrafts.tsx')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const web = read('web', 'src', 'App.tsx')

  assert.match(router, /GET\("\/device-backups\/local-drafts", s\.listOwningLocalSourceDrafts\)/)
  assert.match(server, /clientDeviceCredentialMatches\(device, c\.GetHeader\("X-XDrive-Device-Token"\)\)/)
  assert.match(server, /local_creator_device_id = \?/)
  assert.match(server, /NOT EXISTS \(SELECT 1 FROM xd_local_source_bindings/)
  assert.match(server, /Where\("id > \?", afterID\)/)
  for (const sensitive of ['root_fingerprint', 'active_transfer_path', 'last_error', 'ignore_rules', 'checkpoint']) {
    assert.equal(server.includes('json:"' + sensitive + '"'), false)
  }
  assert.match(client, /func \(c \*Client\) LocalSourceDrafts\(/)
  assert.match(agent, /localpush\.LoadDeviceRegistration\(/)
  assert.match(agent, /localpush\.LoadDeviceToken\(/)
  assert.ok(!agent.match(/func \(c \*agentController\) CloudLocalSourceDrafts[\s\S]*?localpush\.EnsureDevice\(/))
  assert.match(ipc, /desktopIPCLocalDraftReader/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-drafts'\)/)
  assert.match(preload, /getDeviceBackupLocalDrafts:/)
  assert.match(app, /localDrafts=\{localBackupDraftReader\}/)
  assert.match(page, /source && verifiedLocalDeviceID && localCreate && localDrafts/)
  assert.match(panel, /actions\.authorize\(draft\.source_id\)/)
  assert.match(panel, /actions\.discard\(draft\.source_id, draft\.revision\)/)
  assert.match(panel, /activeReaderRef\.current === actionReader/)
  assert.match(panel, /if \(!stillCurrent\(\)\) return/)
  assert.ok(!web.includes('getDeviceBackupLocalDrafts'), 'Web cannot use owning-device draft IPC')
  assert.ok(!web.includes('localDrafts='), 'Web does not receive local recovery capabilities')
})
