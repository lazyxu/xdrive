const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Agent hashes verified native bytes without promoting private advisory evidence', () => {
  const library = read('internal', 'localpush', 'evidence_live_content.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_preflight.go')
  const current = read('internal', 'localpush', 'file_content.go')
  const tests = read('internal', 'localpush', 'evidence_live_content_test.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(library, /HashCurrentLocalEvidenceBatch\(/)
  assert.match(library, /LoadLocalReconcileEvidence\(ctx, configDir, grant, sourceRevision\)/)
  assert.match(library, /StreamVerifiedPreviousInventoryJournal\(/)
  assert.match(library, /StreamVerifiedInventoryJournal\(/)
  assert.match(library, /LocalInventoryPathKey\(grant, "file", item\.Path\)/)
  assert.match(library, /identity\.Strong.*identity\.RenameCandidate/s)
  assert.match(library, /identity\.LinkCount != 1/)
  assert.match(library, /HashVerifiedInventoryFile\(ctx, grant, item, nil\)/)
  assert.match(library, /CloudContentVerified: false, Authoritative: false, MissingInferenceSafe: false/)
  assert.match(current, /openRootScopedRegularFile\(grant, relative\)/)
  assert.match(current, /os\.SameFile\(before, opened\)/)
  assert.match(current, /nativeAfter.*matchesNative\(nativeAfter\)/s)
  assert.match(tests, /TestLocalEvidenceLiveHashValidatesBothGenerationsAndOriginalBytes/)
  assert.match(tests, /TestLocalEvidenceLiveHashRejectsCancellationRotationAndRootSwap/)

  assert.match(agent, /cli\.PreflightLocalSourceItemEvidence\(/)
  assert.match(agent, /localpush\.HashCurrentLocalEvidenceBatch\(/)
  assert.match(agent, /LocallyHashedFiles/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /result\.LocallyHashedBytes = hashed\.HashedBytes/)
  assert.doesNotMatch(library, /BeginSourceRun|CommitSourceItem|SourceItemAlias\{|MirrorDeletion|UploadChunk/)
  assert.doesNotMatch(agent, /BeginSourceRun|CommitSourceItem|UploadChunk|MirrorDeletion/)
  assert.doesNotMatch(ipc, /HashCurrentLocalEvidenceBatch|LocallyHashedFiles/)
  assert.doesNotMatch(preload, /HashCurrentLocalEvidenceBatch|LocallyHashedFiles/)
  assert.doesNotMatch(web, /HashCurrentLocalEvidenceBatch|LocallyHashedFiles/)
})
