'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const source = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const browser = source('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const dashboard = source('ios/XDriveIOS/NativePhotosDashboard.swift')
const model = source('ios/XDriveIOS/NativeFilesChunkedMutation.swift')
const policy = source('ios/XDriveIOS/NativeFilesChunkedPolicy.swift')
