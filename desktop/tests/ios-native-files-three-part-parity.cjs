const exportPolicy = source('ios/XDriveIOS/NativeFilesBatchExportPolicy.swift')
const viewer = source('ios/XDriveIOS/NativeFilesViewerPolicy.swift')

test('Files gets one native three-way rail with the real collection screens', () => {
  assert.match(browser, /case recent, browse, favorites/)
  assert.match(browser, /switch quickSection/)
  assert.match(browser, /XDriveIOSNativeFilesCollectionScreen\(login: login, kind: \.recent\)/)
  assert.match(browser, /XDriveIOSNativeFilesCollectionScreen\(login: login, kind: \.favorites\)/)
  assert.match(browser, /case \.browse:\s*filesChrome/)
  assert.match(browser, /native-ios-files-quick-rail/)
  assert.match(browser, /native-ios-files-section-/)
  assert.match(browser, /if isHome \{\s*VStack\(spacing: 0\)/)
  assert.match(browser, /if !selecting \{/)
  assert.match(dashboard, /\.tag\(XDriveIOSNativeBottomTab\.files\)/)
  assert.doesNotMatch(browser, /WKWebView\(|UIHostingController\(rootView:.*React/)
})

test('2048 selected immutable Nodes split into exact 200-node server receipts', () => {
  assert.match(policy, /nodes\.count > XDriveIOSNativeFilesBatchTrashPolicy\.maxSelected/)
  assert.match(policy, /nodes\.count <= XDriveIOSNativeFilesSelectionPolicy\.maximumSelectedSnapshots/)
  assert.match(policy, /Set\(nodes\.map\(\\\.id\)\)\.count == nodes\.count/)
  assert.match(policy, /nodes\.allSatisfy/)
  assert.match(policy, /stride\(from: 0, to: ordered\.count, by: limit\)/)
  assert.match(server, /const maxNodeBatchItems = 200/)
  assert.match(model, /for \(index, batch\) in batches\.enumerated\(\)/)
  assert.match(model, /await login\.verifiedAuthorization\(\)/)
  assert.match(model, /XDriveIOSNativePhotoOwnerScope\.matches\(before\.owner, owner\)/)
  assert.match(model, /XDriveIOSNativePhotoOwnerScope\.matches\(after\.owner, owner\)/)
  assert.match(model, /XDriveIOSNativeFilesBatchTrashWriter\(/)
  assert.match(model, /XDriveIOSNativeFilesBatchTargetWriter\(/)
  assert.match(model, /try Task\.checkCancellation\(\)/)
  assert.match(model, /当前批次可能已提交/)
  assert.match(model, /不要盲目重试/)
  assert.doesNotMatch(model, /while true|repeatPost|retryCount|WKWebView/)
  assert.match(browser, /if chosenItems\.count > XDriveIOSNativeFilesBatchTrashPolicy\.maxSelected/)
  assert.match(browser, /if intent\.items\.count > XDriveIOSNativeFilesBatchTrashPolicy\.maxSelected/)
  assert.match(browser, /native-ios-files-chunked-cancel/)
})

test('bounded original upload, share-sheet export and multi-window native Viewer', () => {
  assert.match(upload, /static let maximumFiles = 64/)
  assert.match(upload, /static let maximumFiles = 128/)
  assert.match(upload, /static let maximumDirectories = 64/)
  assert.match(exportPolicy, /static let maximumFiles = 32/)
  assert.match(exportPolicy, /static let maximumAggregateBytes: Int64 = 2 \* 1_073_741_824/)
  assert.match(exportPolicy, /node\.size <= maximumPerFileBytes/)
  assert.match(viewer, /static let maximumLoadedRows = 4 \* 64/)
  assert.match(viewer, /loaded\.count <= maximumLoadedRows/)
  assert.match(browser, /XDriveIOSNativeFilesViewerPolicy\.maximumLoadedRows/)
  assert.match(browser, /siblings = source\.filter/)
  assert.doesNotMatch(model, /UserDefaults|localStorage|URLSession\.shared/)
})
