'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const audit = fs.readFileSync(path.join(root, 'ios/XDriveIOS/NativePhotoWholeLibraryAudit.swift'), 'utf8')

test('explicit foreground continuous mode chains existing verified 8-original read-only batches', () => {
  assert.match(audit, /static let maximumOriginalsPerBatch = 8/)
  assert.match(audit, /return checked - checked % XDrivePhotoBackupScanWindow\.maxItems/)
  assert.match(audit, /scanner\.start\(\s*atOffset: windowStart, requireStableResume: true/)
  assert.match(audit, /while page\.nextOffset <= self\.checked && !page\.finished/)
  assert.match(audit, /page\.items\.dropFirst\(skippedInPage\)\.prefix\(/)
  assert.match(audit, /func verifyContinuously\(login: XDriveIOSNativeOwnerLoginModel,/)
  const mode = audit.slice(audit.indexOf('    func verifyContinuously('),
    audit.indexOf('    private func verifyGeneration('))
  assert.match(mode, /let selected = login\.owner/)
  assert.match(mode, /UIApplication\.shared\.applicationState == \.active/)
  assert.match(mode, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\) == \.authorized/)
  assert.match(mode, /self\.verifyNext\(login: login,/)
  assert.match(mode, /guard let batch = self\.job else \{ return \}/)
  assert.match(mode, /await batch\.value/)
  assert.match(mode, /self\.continuousEpoch == ticket/)
  assert.match(mode, /self\.checked > previous/)
  assert.match(mode, /self\.checked == total \{ return \}/)
  assert.match(mode, /await Task\.yield\(\)/)
  assert.doesNotMatch(mode, /UploadSession|uploadPrepared|URLSession|\.settle\(|deleteNode/)
})

test('cancellation, Owner, PhotoKit access and UI lifecycle fence the continuous auditor', () => {
  assert.match(audit, /private var continuousJob: Task<Void, Never>\?/)
  assert.match(audit, /private var continuousEpoch = UUID\(\)/)
  assert.match(audit, /func reset\(\) \{\s*continuousEpoch = UUID\(\)\s*continuousJob\?\.cancel\(\)/)
  assert.match(audit, /verifyingContinuously = false/)
  assert.match(audit, /XDriveIOSNativePhotoOwnerScope\.matches\(\s*login\.owner, selected/)
  assert.match(audit, /self\.reset\(\)\s*self\.message = "账户、照片权限或前台状态已变化/)
  assert.match(audit, /\.onChange\(of: login\.owner\) \{ _ in audit\.reset\(\) \}/)
  assert.match(audit, /\.onChange\(of: phase\) \{ state in[\s\S]*?audit\.reset\(\)/)
  assert.match(audit, /\.onDisappear \{ audit\.reset\(\) \}/)
  assert.match(audit, /if audit\.busy \|\| audit\.verifyingContinuously/)
  // A continuous run must keep its initially consented iCloud policy.
  assert.match(audit, /Toggle\("核验时允许下载 iCloud 原件",[\s\S]*?\.disabled\(audit\.busy \|\| audit\.verifyingContinuously\)/)
  assert.match(audit, /native-ios-photo-whole-audit-continuous/)
})

test('continuous read-only verification cannot turn partial or historical counts into cloud completion', () => {
  assert.match(audit, /checked == total &&\s*currentlyVerified == total && unverified == 0/)
  assert.match(audit, /proof\.verifyAndWait\(/)
  assert.match(audit, /bound\.sourceID == self\.managedSourceID/)
  assert.match(audit, /bound\.targetNodeID == self\.managedTargetNodeID/)
  assert.match(audit, /if verified \{ self\.currentVerified \+= 1 \}/)
  assert.match(audit, /else \{ self\.unverified \+= 1 \}/)
  assert.match(audit, /ProgressView\(value: Double\(audit\.checked\),/)
  assert.match(audit, /扫描进度、部分通过都不是整库备份完成证明/)
  assert.match(audit, /可能消耗大量时间、网络和电量/)
  assert.doesNotMatch(audit, /UploadSessionTransport|uploadPrepared|beginCreate|finalize\(|deleteNode|\.settle\(/)
})
