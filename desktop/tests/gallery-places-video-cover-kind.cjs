'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname,'../..',name),'utf8')

test('both map SDK Hosts reuse the original Gallery video Poster with Owner-only provenance', () => {
  const parent=read('ui/shared/src/mui/MediaGalleryBaiduIsolatedPhotoSurface.tsx')
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const gallery=read('ui/shared/src/mui/MediaGallery.tsx')
  const video=read('ui/shared/src/mui/MediaGalleryPreviewMedia.tsx')
  const pg=read('internal/api/baidu_photo_map_cells.go')
  const child=read('deploy/baidu-isolated-child/child.js')
  const protocol=read('ui/shared/src/media-gallery-baidu-isolated-frame-host.ts')
  assert.match(pg,/m\.media_kind AS media_kind/)
  assert.match(pg,/media_kind,omitempty/)
  assert.match(read('internal/api/baidu_jsapi4_native_cells_http.go'),
    /baiduNativeMapCoverCellsForClient\(page\.Items, wantsKind\)/)
  assert.match(read('web/src/api.ts'),
    /'X-XDrive-Map-Cover-Kind': 'video-poster-v1'/)
  assert.match(pg,/cell\.MediaKind != meta\.MediaKindImage/)
  assert.match(parent,/const ownerCover=\(selection:MediaBaiduNativeCellSelection/)
  assert.match(parent,/representative\?\.media_kind==='video' && loadPreviewURL/)
  assert.match(parent,/<XDriveMediaAsyncVideoPoster/)
  assert.match(parent,/<XDriveMediaGalleryCoverThumbnail/)
  assert.match(parent,/saveVideoPoster=\{saveVideoPoster\}/)
  assert.equal((parent.match(/ownerCover\(pin\.selection/g)||[]).length,2,
    'map pin and bottom collection strip must use identical Owner media routing')
  assert.match(parent,/xDriveMountBaiduInlineMap/)
  assert.match(parent,/xDriveMountBaiduIsolatedFrame/)
  assert.match(map,/loadPreviewURL=\{loadPhotoCoverPreviewURL\}/)
  assert.match(map,/saveVideoPoster=\{savePhotoCoverVideoPoster\}/)
  assert.match(gallery,/loadPhotoCoverPreviewURL=\{loadPreviewURL\}/)
  assert.match(gallery,/savePhotoCoverVideoPoster=\{saveVideoPoster\}/)
  assert.match(video,/xDriveResolveMediaVideoPoster/)
  assert.match(video,/scheduleMediaPoster/)
  assert.match(video,/if \(suspended\) return/)
  assert.match(protocol,/reduced\.push\(\{ key, latitude: cell\.latitude, longitude: cell\.longitude,/)
  assert.doesNotMatch(child,/media_kind|node_id|PhotoAsset|loadThumbnail|loadPreviewURL/)
  assert.doesNotMatch(parent,/BMap\.Convertor|requestVideoPosterFromMap|window\.location\.href/)
})

test('Video covers never infer media type from untrusted SDK data or expand Server Cell permissions', () => {
  const parent=read('ui/shared/src/mui/MediaGalleryBaiduIsolatedPhotoSurface.tsx')
  const cellModel=read('ui/shared/src/models.ts')
  const validator=read('ui/shared/src/media-gallery-baidu-jsapi4-cells.ts')
  const range=read('ui/shared/src/media-gallery-baidu-jsapi4-cell-range.ts')
  assert.match(cellModel,/media_kind\?: 'image' \| 'video'/)
  assert.match(validator,/\('media_kind' in c && c\.media_kind !== 'image' && c\.media_kind !== 'video'\)/)
  assert.match(parent,/cell\.node_revision===selection\.node_revision/)
  assert.match(parent,/cell\.photo_count===selection\.photo_count/)
  assert.match(parent,/return <XDriveMediaGalleryCoverThumbnail/)
  assert.match(range,/node_revision: source\.node_revision!/)
  assert.doesNotMatch(parent,/const kind = .*\.name|media_kind=\{projected/)
})
