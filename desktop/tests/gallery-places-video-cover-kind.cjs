'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'../..',p),'utf8')
test('both SDK Hosts use the same trusted Gallery video poster chain',()=>{
 const parent=read('ui/shared/src/mui/MediaGalleryBaiduIsolatedPhotoSurface.tsx')
 const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
 const gallery=read('ui/shared/src/mui/MediaGallery.tsx')
 const poster=read('ui/shared/src/mui/MediaGalleryPreviewMedia.tsx')
 const host=read('ui/shared/src/media-gallery-baidu-isolated-frame-host.ts')
 const child=read('deploy/baidu-isolated-child/child.js')
 assert.match(parent,/representative\?\.media_kind==='video' && loadPreviewURL/)
 assert.match(parent,/<XDriveMediaAsyncVideoPoster/)
 assert.match(parent,/<XDriveMediaGalleryCoverThumbnail/)
 assert.match(parent,/saveVideoPoster=\{saveVideoPoster\}/)
 assert.equal((parent.match(/ownerCover\(pin\.selection/g)||[]).length,2)
 assert.match(parent,/xDriveMountBaiduInlineMap/)
 assert.match(parent,/xDriveMountBaiduIsolatedFrame/)
 assert.match(map,/loadPreviewURL=\{loadPhotoCoverPreviewURL\}/)
 assert.match(map,/saveVideoPoster=\{savePhotoCoverVideoPoster\}/)
 assert.match(gallery,/loadPhotoCoverPreviewURL=\{loadPreviewURL\}/)
 assert.match(gallery,/savePhotoCoverVideoPoster=\{saveVideoPoster\}/)
 assert.match(poster,/xDriveResolveMediaVideoPoster/)
 assert.match(poster,/scheduleMediaPoster/)
 assert.match(poster,/if \(suspended\) return/)
 assert.match(host,/reduced\.push\(\{ key, latitude: cell\.latitude, longitude: cell\.longitude,/)
 assert.doesNotMatch(child,/media_kind|node_id|PhotoAsset|loadThumbnail/)
})
