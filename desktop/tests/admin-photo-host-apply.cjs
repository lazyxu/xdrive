const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')

test('Photo Host apply has fixed audited enable-only queue and global revision gate', () => {
  const action = read('internal/api/admin_photo_host_apply.go')
  const models = read('internal/meta/admin_photo_host_apply.go')
  const router = read('internal/api/router.go')
  const saved = read('internal/api/admin_photo_host_desired.go')
  const preflight = read('internal/api/admin_photo_host_preflight.go')
  assert.ok(models.includes('xd_admin_photo_host_applies'))
  assert.ok(read('cmd/server/main.go').includes('&meta.AdminPhotoHostApply{}'))
  assert.ok(router.includes('admin.POST("/services/photo-intelligence/host/apply", s.adminPhotoHostApply)'))
  assert.ok(read('internal/api/router_contract_test.go').includes('"/api/v1/admin/services/photo-intelligence/host/apply"'))
  assert.ok(action.includes('recordAuditTx(tx,'), 'host dispatch must require committed audit')
  assert.ok(action.includes('photoHostApplyBusyTx('))
  assert.ok(action.includes('clause.Locking{Strength: "UPDATE"}'))
  assert.ok(action.includes('os.Link('), 'pending fixed queue cannot be overwritten')
  assert.ok(action.includes('writePhotoHostApplyRequest(s.HostControlDir, request)'))
  assert.ok(action.includes('control.RequestID != gate.RequestID'))
  assert.ok(action.includes('control.AppliedRevision == gate.Revision'))
  assert.ok(action.includes('"host-verified"'))
  assert.ok(saved.includes('photoHostApplyBusyTx(tx)'))
  assert.ok(preflight.includes('s.photoHostCanSubmit('))
  for (const dangerous of ['exec.Command(', 'docker compose down', 'stop photo-face', '--force-recreate']) {
    assert.equal(action.includes(dangerous), false, 'Server must not execute host commands: '+dangerous)
  }
})

