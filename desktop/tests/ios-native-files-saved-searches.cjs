'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const native = read('ios/XDriveIOS/NativeFilesSavedSearches.swift')
const policy = read('ios/XDriveIOS/NativeFilesSavedSearchPolicy.swift')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const server = read('internal/api/file_organization.go')
const web = read('web/src/api.ts')

test('Native Saved Searches use exact existing Web and Server routes and statuses', () => {
  for (const endpoint of ['/api/v1/file-saved-searches', '/api/v1/file-saved-searches/order']) {
    assert.ok(native.includes(endpoint))
    assert.ok(web.includes(endpoint))
  }
  assert.match(native, /method = "POST"[\s\S]*?responseStatus = 201/)
  assert.match(native, /method = "PATCH"[\s\S]*?responseStatus = 200/)
  assert.match(native, /method = "DELETE"[\s\S]*?responseStatus = 204/)
  assert.match(native, /method = "PUT"[\s\S]*?responseStatus = 204/)
  assert.match(server, /fileSavedSearchLimit\s*= 64/)
  assert.match(policy, /static let maximumItems = 64/)
})

test('Saved Search network is nonredirecting, Owner-authenticated and readback verified', () => {
  assert.match(native, /URLSessionConfiguration\.ephemeral/)
  assert.match(native, /completionHandler\(nil\)/)
  assert.match(native, /config\.httpShouldSetCookies = false/)
  assert.match(native, /requestCachePolicy = \.reloadIgnoringLocalCacheData/)
  assert.match(native, /req\.setValue\("Bearer " \+ accessToken/)
  assert.match(native, /let current = try await list\(in: client\)/)
  assert.match(native, /current\.contains\(created\)/)
  assert.match(native, /current\.contains\(changed\)/)
  assert.match(native, /current\.map\(\\\.id\) == ids/)
  assert.match(native, /current\.count \+ 1 == previous\.count/)
  assert.doesNotMatch(native, /URLSession\.shared|WKWebView|document\.cookie|UserDefaults|retry\s*\(/)
})

test('read, create, rename, update and delete reject stale Owner or unknown writes', () => {
  assert.match(native, /login\.verifiedAuthorization\(\)/)
  assert.match(native, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(native, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.match(native, /let previous = items/)
  assert.match(native, /private var epoch = UUID\(\)/)
  assert.match(native, /job\?\.cancel\(\)/)
  assert.match(native, /self\.verified = false\s*self\.status = "操作结果未确认/)
  assert.match(native, /\.confirmationDialog\(/)
  assert.match(native, /model\.perform\(\.delete\(item\.id\), login: login\)/)
})

test('real Native Files browse and Search UI launch Server Save Search, not fake local filtering', () => {
  assert.match(browser, /Section\("整理"\) \{[\s\S]*?Label\("智能文件夹"/)
  assert.match(browser, /native-ios-files-open-saved-searches/)
  assert.match(browser, /native-ios-files-save-current-search/)
  assert.match(browser, /\.sheet\(isPresented: \$showingSavedSearches/)
  assert.match(browser, /XDriveIOSNativeFilesSavedSearchesScreen\(/)
  assert.match(browser, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expectedOwner\)/)
  assert.match(browser, /let restored = saved\.filters\.native/)
  assert.match(browser, /searchFilters = restored[\s\S]*?else \{\s*reload\(resetOffset: true\)/)
  assert.match(browser, /private func applySavedSearch\(/)
  assert.match(native, /\.onDisappear \{\s*isVisible = false\s*clearPresentationIntents\(\)\s*model\.invalidate\(\)/)
})

test('Native Saved Search management uses authorized reorder and bounded UTF-8 names', () => {
  assert.match(policy, /static let maximumNameUTF8Bytes = 128/)
  assert.match(policy, /XDriveIOSNativeFilesPagePolicy\.validSearchRequest\(/)
  assert.match(policy, /sourceID: UInt64\?/)
  assert.match(policy, /tagID: UInt64\?/)
  assert.match(native, /XDriveIOSNativeFilesSavedSearchPolicy\.validReorder\(/)
  assert.match(native, /ids\.swapAt\(index, index \+ direction\)/)
  assert.match(native, /Button\("上移"\)/)
  assert.match(native, /Button\("下移"\)/)
  assert.match(native, /Button\("保存为智能文件夹"\)/)
  assert.match(native, /Button\("保存名称"\)/)
  assert.match(native, /Button\("确认删除", role: \.destructive\)/)
})
