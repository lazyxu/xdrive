'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname, '../..', name), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const location = read('ios/XDriveIOS/NativeFilesSearchLocation.swift')
const policy = read('ios/XDriveIOS/NativeFilesLocationPolicy.swift')
const router = read('internal/api/router.go')
const server = read('internal/api/node_location.go')
const position = read('internal/api/children_position.go')

test('native Files search has bounded actual Server parent location from list and grid', () => {
  assert.match(browser, /Button \{ requestLocation\(for: entry\) \}/)
  assert.match(browser, /native-ios-files-locate-/)
  assert.match(browser, /private func requestLocation\(for entry: XDriveIOSNativeFilesEntry\)/)
  assert.match(browser, /model\.verifiedPage,[\s\S]*?!activeQuery\.isEmpty, !selecting/)
  assert.match(browser, /model\.entries\.contains\(where: \{ \$0\.node == entry\.node \}\)/)
  assert.match(browser, /\.sheet\(item: \$locateIntent, onDismiss: \{\s*reload\(\)/)
  assert.match(browser, /lastViewedFile = entry\.node[\s\S]*?locateIntent = XDriveIOSNativeFilesLocateIntent/)
  assert.match(browser, /returnScroll\.scrollTo\(target\.id, anchor: \.center\)/)
})

test('native Files locate buttons stay inside concrete rows before the context menu modifier', () => {
  const start = browser.indexOf('@ViewBuilder private func fileEntryRow(')
  const end = browser.indexOf('@ViewBuilder private var filesContinuationStatus:', start)
  assert.ok(start >= 0 && end > start, 'native Files row must exist')
  const row = browser.slice(start, end)
  assert.match(row, /\.accessibilityIdentifier\("native-ios-files-locate-\\\(entry\.id\)"\)\s*\}\s*\}\s*\.contextMenu \{\s*Button\("文件夹操作"\)/)
  assert.match(row, /\.accessibilityIdentifier\("native-ios-files-locate-\\\(entry\.id\)"\)\s*\}\s*\}\s*\.contextMenu \{\s*Button\("文件操作"\)/)
})

test('location is a server-confirmed Owner path, not guessed search-hit text', () => {
  assert.match(router, /authed\.GET\("\/nodes\/:id\/location", s\.getNodeLocation\)/)
  assert.match(server, /func \(s \*Server\) getNodeLocation\(c \*gin\.Context\)/)
  assert.match(server, /queryNodeLocation\(c\.Request\.Context\(\), userID\(c\), nodeID\)/)
  assert.match(policy, /location\.node_id == selected\.id/)
  assert.match(policy, /location\.revision == selected\.revision/)
  assert.match(policy, /location\.parent_id == selected\.parent_id/)
  assert.match(policy, /location\.breadcrumbs\.first\?\.id == ownerRootID/)
  assert.match(policy, /Set\(location\.breadcrumbs\.map\(\\\.id\)\)\.count/)
  assert.match(location, /login\.verifiedAuthorization\(\)/)
  assert.match(location, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expectedOwner\)/)
  assert.match(location, /let before: XDriveIOSNativeFilesNode = try await read\(/)
  assert.match(location, /let after: XDriveIOSNativeFilesNode = try await read\(/)
  assert.match(location, /before == selected/)
  assert.match(location, /after == selected/)
  assert.match(position, /func \(s \*Server\) childrenPosition\(c \*gin\.Context\)/)
  assert.match(router, /authed\.GET\("\/nodes\/:id\/children\/position", s\.childrenPosition\)/)
  assert.match(location, /\/children\/position/)
  assert.match(location, /URLQueryItem\(name: "node_id", value: String\(selected\.id\)\)/)
  assert.match(location, /XDriveIOSNativeFilesLocationPolicy\.pageOffset/)
  assert.match(policy, /position\.revision == selected\.revision/)
  assert.match(policy, /position\.folders_first/)
})

test('return is inside same Files feature and reuses the only native browser', () => {
  assert.match(location, /XDriveIOSNativeFilesBrowser\(/)
  assert.match(location, /folderID: target\.folder\.id,/)
  assert.match(location, /target\.folder\.id == openedOwner\.rootNodeID/)
  assert.match(location, /initialOffset: target\.offset, focus: selected/)
  assert.match(browser, /model\.entries\.contains\(where: \{ \$0\.node == focusedNode \}\)/)
  assert.match(browser, /returnScroll\.scrollTo\(focusedNode\.id, anchor: \.center\)/)
  assert.match(location, /\.onChange\(of: login\.owner\)/)
  assert.match(location, /model\.invalidate\(\)/)
  assert.match(location, /Button\("关闭"\) \{ dismiss\(\) \}/)
  assert.match(location, /native-ios-files-locate-retry/)
  assert.doesNotMatch(location, /WKWebView|import WebKit|URLSession\.shared|POST.*\/api\/v1\/nodes/)
})

test('native location refuses cookie redirects, cross-owner and stale responses', () => {
  assert.match(location, /URLSessionConfiguration\.ephemeral/)
  assert.match(location, /completionHandler\(nil\)/)
  assert.match(location, /httpCookieAcceptPolicy = \.never/)
  assert.match(location, /Task\.checkCancellation\(\)/)
  assert.match(location, /generation == ticket/)
  assert.match(location, /owner\.instanceID/)
  assert.match(location, /ServerAddress\.parse\(owner\.origin\.absoluteString\)/)
  assert.match(location, /maximumBytes: 2 \* 1_048_576/)
})
