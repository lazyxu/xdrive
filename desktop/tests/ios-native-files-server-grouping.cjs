'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const view = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const range = read('ios/XDriveIOS/NativeCloudFilesPolicy.swift')
const grouping = read('ios/XDriveIOS/NativeFilesGroupingPolicy.swift')
const server = read('internal/api/file_explorer_grouping.go')
const children = read('internal/api/children_pagination.go')
const window = read('ios/XDriveIOS/NativeFilesContinuousWindowPolicy.swift')

test('grouped Native Range uses Server group and folders_first, never local 100k scan', () => {
  assert.match(view, /func children\(parentID: UInt64, offset: Int,[\s\S]*?grouping: String = "none",[\s\S]*?foldersFirst: Bool = true/)
  assert.match(view, /URLQueryItem\(name: "group", value: grouping\)/)
  assert.match(view, /URLQueryItem\(name: "folders_first", value: "false"\)/)
  assert.match(view, /XDriveIOSNativeFilesGroupingPolicy\.validIndexes\(/)
  assert.match(server, /switch grouping\.Group \{/)
  assert.match(children, /Groups\s+\[\]fileExplorerGroupIndexDTO/)
  assert.match(children, /options\.Grouping\.Group != "none"/)
  assert.match(window, /static let maximumVisibleItems = 4 \* pageSize/)
  assert.doesNotMatch(view, /while.*100000|for.*100000|listAllFiles|loadEveryNode/)
})

test('grouping metadata is scoped to verified Owner, folder, sort, and mode', () => {
  assert.match(view, /private var verifiedGrouping: String\?/)
  assert.match(view, /private var verifiedFoldersFirst: Bool\?/)
  assert.match(view, /verifiedGrouping == grouping && verifiedFoldersFirst == foldersFirst/)
  assert.match(view, /verifiedGrouping = nil[\s\S]*?verifiedFoldersFirst = nil[\s\S]*?groupIndexes = \[\]/)
  assert.match(view, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(view, /if grouping != "none" && requestOffset == 0 \{[\s\S]*?incomingGroupIndexes = page\.groups/)
  assert.match(view, /incomingGroupIndexes != self\.groupIndexes/)
  assert.match(view, /probe\.total == count/)
  assert.match(view, /groupIndexProbe\(parentID: UInt64/)
  assert.match(view, /URLQueryItem\(name: "limit", value: "1"\)/)
  assert.match(view, /grouping: grouping, foldersFirst: foldersFirst/)
})

test('list and icon grid have real index-based group headers and retained swipe actions', () => {
  assert.match(view, /Picker\("分组", selection: \$grouping\)/)
  assert.match(view, /Text\("按类型"\)\.tag\("type"\)/)
  assert.match(view, /Text\("按修改日期"\)\.tag\("modified"\)/)
  assert.match(view, /Text\("按大小"\)\.tag\("size"\)/)
  assert.match(view, /Toggle\("文件夹优先", isOn: \$foldersFirst\)/)
  assert.match(view, /ForEach\(model\.visibleGroups\) \{ group in/)
  assert.match(view, /ForEach\(model\.visibleGroups\) \{ group in[\s\S]*?filesGrid\(group\.entries\)/)
  assert.match(view, /ForEach\(group\.entries\) \{ entry in[\s\S]*?filesActionRow\(entry\)/)
  assert.match(view, /private func filesActionRow\([\s\S]*?fileEntryRow\(entry\)[\s\S]*?\.swipeActions\(/)
  assert.match(view, /requestContinuousNeighbor\(for: entry\.id\)/)
  assert.match(view, /if grouping != "none" && !isGlobalSearch/)
  assert.match(grouping, /position >= \$0\.start_index/)
  assert.match(grouping, /firstVisible \|\| found\.start_index == position/)
})

test('group index boundaries reject duplicates, holes and malformed full-folder counts', () => {
  assert.match(range, /var groups: \[XDriveIOSNativeFilesGroupIndex\]\? = nil/)
  assert.match(grouping, /groups\.count <= 4096/)
  assert.match(grouping, /group\.item_count <= total - nextStart/)
  assert.match(grouping, /group\.start_index == nextStart/)
  assert.match(grouping, /seen\.contains\(group\.key\)/)
  assert.match(grouping, /return nextStart == total/)
  assert.match(view, /page\.groups != nil \|\| page\.total_count == 0/)
  assert.match(view, /grouping: grouping, foldersFirst: foldersFirst/)
})
