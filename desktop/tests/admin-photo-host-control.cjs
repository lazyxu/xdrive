const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')

test('photo-host executor is fixed enable-only, never an admin-supplied Docker controller', () => {
  const host = read('scripts/server-control.sh')
  const block = host.slice(host.indexOf('photo_host_control_process() {'), host.indexOf('# Fixed-container Photo Intelligence Host Manager observation only.'))
  assert.ok(block.includes('"$enabled" != true'))
  assert.ok(block.includes('photo_host_control_probe'))
  assert.ok(block.includes('request_time_is_fresh'))
  assert.ok(block.includes('photo_host_control_recover'))
  assert.ok(block.includes('photo-host-control-request.json'))
  assert.ok(block.includes('--profile photo-intelligence'))
  assert.ok(block.includes('up -d --no-deps photo-face'))
  assert.equal(block.includes('--force-recreate'), false)
  assert.equal(block.includes('docker compose down'), false)
  assert.equal(block.includes('restart photo-face'), false)
  assert.ok(host.includes('photo_host_control_refresh || true'))
  assert.ok(host.includes('photo_host_control_process'))
  assert.ok(read('.github/workflows/ci.yml').includes('bash scripts/test-photo-host-enable-control.sh'))
  assert.ok(read('scripts/ci/gitlab-server-validation.sh').includes('bash scripts/test-photo-host-enable-control.sh'))
})

test('host-side revision proof must bind to audited Server dispatch token', () => {
  const api = read('internal/api/admin_photo_host_desired.go')
  const reader = read('internal/api/admin_photo_host_control_status.go')
  const shared = read('ui/shared/src/service-dependencies.ts')
  const agent = read('desktop/src/main/agent_client.cts')
  const client = read('internal/client/client.go')
  const ui = read('ui/shared/src/mui/PhotoHostDesiredPanel.tsx')
  for (const key of ['host_control_supported', 'host_control_state', 'host_control_revision', 'host_applied_revision', 'host_control_profile_verified']) {
    assert.ok(api.includes(key), 'Server missing '+key)
    assert.ok(client.includes(key), 'Go Client missing '+key)
    assert.ok(shared.includes(key), 'shared UI missing '+key)
    assert.ok(agent.includes(key), 'Agent DTO missing '+key)
  }
  assert.ok(api.includes('ApplySupported: false'))
  assert.ok(api.includes('HostControlState: "unavailable"'))
  assert.ok(api.includes('s.readPhotoHostControlStatus()'))
  assert.ok(reader.includes('os.Lstat'))
  assert.ok(reader.includes('info.Mode().IsRegular()'))
  assert.ok(reader.includes('!status.ProfileVerified'))
  assert.ok(reader.includes('status.AppliedRevision != status.Revision'))
  assert.ok(ui.includes('未经审计请求令牌匹配的宿主状态不可当作已应用'))
  const router = read('internal/api/router.go')
  assert.ok(router.includes('admin.POST("/services/photo-intelligence/host/apply", s.adminPhotoHostApply)'))
  const dispatcher = read('internal/api/admin_photo_host_apply.go')
  assert.ok(dispatcher.includes('recordAuditTx('), 'missing durable audit before host request')
  assert.ok(dispatcher.includes('writePhotoHostApplyRequest('))
  assert.ok(dispatcher.includes('photoHostApplyBusyTx('))
  assert.ok(dispatcher.includes('os.Link('), 'fixed host request must be no-clobber')
})
