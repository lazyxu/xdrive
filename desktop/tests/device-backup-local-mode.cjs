const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Own Desktop backup mode is capability/Root/revision fenced; Web and other desktops remain observers', () => {
  const server = read('internal', 'api', 'sources.go')
  const client = read('internal', 'client', 'local_bound_mode.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_config.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_mode.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalModeDialog.tsx')
  const web = read('web', 'src', 'App.tsx')

  assert.match(server, /requireLocalSourceMutationTx\(tx, c, id\)/)
  assert.match(server, /if mode != current.SyncMode \{\s*resetMirrorEvidence = true/)
  assert.match(agent, /localBoundBackupConfig\(ctx, sourceID\)/)
  assert.match(agent, /cli\.SetLocalBoundBackupMode\(ctx, sourceID, revision, mode, proof\)/)
  assert.doesNotMatch(agent, /localpush\.EnsureDevice\(/)
  for (const header of ['X-XDrive-Device-ID', 'X-XDrive-Device-Token',
    'X-XDrive-Local-Root-ID', 'X-XDrive-Local-Root-Fingerprint']) {
    assert.ok(client.includes(header), 'missing native proof ' + header)
  }
  assert.match(client, /UpdateSourceInput\{SyncMode: &mode\}/)
  assert.match(ipc, /"device-backup-local-mode"/)
  assert.match(handler, /decodeDesktopIPCJSON\(w, r, &input\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-mode'\)/)
  assert.match(preload, /setDeviceBackupLocalMode:/)
  assert.match(app, /localMode=\{localBackupMode\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(dialog, /mode !== 'mirror' \|\| mirrorConfirmed/)
  assert.match(dialog, /actions\.setMode\(sourceID, settings\.revision, mode\)/)
  assert.doesNotMatch(web, /localMode=/)
  assert.doesNotMatch(web, /setDeviceBackupLocalMode/)
  assert.doesNotMatch(dialog, /(?:triggerSource|startUpload|cancelSourceRun|deleteSource)\(/)
})
