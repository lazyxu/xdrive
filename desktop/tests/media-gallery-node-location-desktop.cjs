const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')

test('G06 Desktop location uses authenticated Server Node path and explicit Agent capability', () => {
  const handler = read('cmd/xdrive-agent/desktop_ipc.go')
  assert.match(handler, /"node-location"/)
  assert.match(handler, /GET \/v1\/cloud\/node-location/)
  assert.match(handler, /CloudNodeLocation\(context\.Context, uint64\)/)
  assert.match(handler, /invalid_node_id/)
  assert.match(handler, /node_location_unavailable/)
  const goClient = read('internal/client/node_location.go')
  assert.match(goClient, /func \(c \*Client\) NodeLocation\(/)
  assert.match(goClient, /"\/api\/v1\/nodes\/"\+strconv\.FormatUint\(nodeID, 10\)\+"\/location"/)
  assert.match(read('cmd/xdrive-agent/cloud_files.go'), /return cli\.NodeLocation\(ctx, nodeID\)/)
})

test('G06 Desktop renderer aborts location requests through Main and Agent HTTP context', () => {
  const main = read('desktop/src/main/index.cts')
  const client = read('desktop/src/main/agent_client.cts')
  const preload = read('desktop/src/preload/index.cts')
  const types = read('desktop/src/renderer/global.d.ts')
  const gallery = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const files = read('desktop/src/renderer/DesktopFileExplorer.tsx')
  const app = read('desktop/src/renderer/App.tsx')
  assert.match(main, /'agent:get-node-location'/)
  assert.match(main, /requireAgentCapability\(hello, 'node-location'\)/)
  assert.match(main, /viewportRequests\.run\(event\.sender, requestID, async \(signal\) =>/)
  assert.match(main, /requireAgentClient\(\)\.nodeLocation\(nodeID, signal\)/)
  assert.match(client, /nodeLocation\(nodeID: number, signal\?: AbortSignal\)/)
  assert.match(client, /\/v1\/cloud\/node-location\?node_id=/)
  assert.match(preload, /getNodeLocation: \(nodeID: number, requestID\?: string\)/)
  assert.match(types, /getNodeLocation: \(nodeID: number, requestID\?: string\)/)
  assert.match(gallery, /getNodeLocation: \(nodeID, signal\) => xDriveDesktopViewportRequest/)
  assert.match(files, /loadNodeLocation=\{!trashActive && nodeLocationSupported/)
  assert.match(files, /onShowInFolder=\{trashActive \? undefined/)
  assert.match(app, /nodeLocationSupported: agent\.hello\?\.capabilities\.includes\('node-location'\)/)
  assert.match(app, /loadCloudDirectory\(location\.parent_id, ancestry\)/)
  assert.doesNotMatch(read('ui/shared/src/mui/MediaGallery.tsx').slice(
    0, read('ui/shared/src/mui/MediaGallery.tsx').indexOf('export interface XDriveMediaGalleryProps'),
  ), /loadNodeLocation\(item\.node\.id/)
})
