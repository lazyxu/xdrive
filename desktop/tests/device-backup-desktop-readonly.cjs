const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Desktop Push uses only bounded read projection end to end', () => {
  const go = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const cloud = read('cmd', 'xdrive-agent', 'cloud_files.go')
  const dto = read('internal', 'client', 'device_backups.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const agent = read('desktop', 'src', 'main', 'agent_client.cts')
  const renderer = read('desktop', 'src', 'renderer', 'App.tsx')
  assert.match(go, /GET \/v1\/device-backups", h\.deviceBackups/)
  assert.match(go, /GET \/v1\/device-backups\/runs", h\.deviceBackupRuns/)
  assert.match(go, /device-backup-read/)
  assert.match(go, /CloudDeviceBackupOverview\(r\.Context\(\)\)/)
  assert.match(go, /CloudDeviceBackupRuns\(r\.Context\(\), sourceID, limit, offset\)/)
  assert.match(cloud, /cli\.DeviceBackupOverview\(ctx\)/)
  assert.match(cloud, /cli\.DeviceBackupRunSummaries\(ctx, sourceID, limit, offset\)/)
  assert.match(dto, /"\/api\/v1\/device-backups"/)
  for (const privateField of ['RootFingerprint', 'CredentialHash', 'ActiveTransferPath', 'LastError', 'LocalPath', 'IgnoreRules', 'Checkpoint']) {
    assert.equal(dto.includes(privateField + ' '), false, 'read DTO must not carry ' + privateField)
  }
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-read'\)/)
  assert.match(main, /Number\.isSafeInteger\(requestedLimit\)/)
  assert.match(main, /Number\.isSafeInteger\(requestedOffset\)/)
  assert.match(preload, /getDeviceBackups: \(\) => ipcRenderer\.invoke\('agent:get-device-backups'\)/)
  assert.match(agent, /deviceBackups\(\) \{/)
  assert.match(renderer, /<XDriveDeviceBackupPage[\s\S]*?source=\{deviceBackupSource\}/)
  assert.match(renderer, /status\?\.server, status\?\.username, status\?\.auth_status/)
})

test('Desktop device backups have no alternative unrestricted Source fallback', () => {
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const renderer = read('desktop', 'src', 'renderer', 'App.tsx')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  assert.equal(page.includes('sourceOverview('), false)
  assert.equal(page.includes('sourceItems('), false)
  assert.match(ipc, /device_backups_unavailable/)
  assert.match(renderer, /agent\.hello\?\.capabilities\.includes\('device-backup-read'\)/)
  assert.equal(renderer.includes('deviceBackupSource: sourceManagerAdapter'), false)
})
