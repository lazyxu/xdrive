'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const mutation = read('ios/XDriveIOS/NativeFilesSingleMutation.swift')
const policy = read('ios/XDriveIOS/NativeCloudFilesPolicy.swift')
const go = read('internal/api/handlers.go')

test('native Files folder has separate accessible management action while preserving child navigation', () => {
  assert.match(browser, /NavigationLink\(value: XDriveIOSNativeFilesFolder\(/)
  assert.match(browser, /openManagement\(for: entry\.node\)/)
  assert.match(browser, /native-ios-files-folder-more-/)
  assert.match(browser, /Button\("文件夹操作"\) \{ openManagement\(for: entry\.node\) \}/)
  assert.match(browser, /directory: node\?\.isDirectory == true \? node : nil/)
  assert.match(browser, /file: node\?\.isDirectory == false \? node : nil/)
  assert.match(browser, /directory: intent\.directory/)
  assert.match(policy, /var isDirectory: Bool \{ type == "dir" \}/)
})
test('directory rename and subtree trash use the existing versioned Node mutation with real confirmation', () => {
  assert.match(panel, /else if let directory \{/)
  assert.match(panel, /Button\("重命名文件夹"\)/)
  assert.match(panel, /Button\("将文件夹移入回收站", role: \.destructive\)/)
  assert.match(panel, /将“\\\(directory\.name\)”及其子文件移入回收站/)
  assert.match(panel, /会影响这个文件夹中的全部内容及其共享链接/)
  assert.match(panel, /mutator\.perform\(node: directory,[\s\S]*?kind: \.rename\(renameDraft\)/)
  assert.match(panel, /mutator\.perform\(node: directory, kind: \.trash,/)
  assert.match(mutation, /\(node\.type == "file" \|\| node\.type == "dir"\)/)
  assert.match(mutation, /node\.parent_id != nil/)
  assert.match(mutation, /forHTTPHeaderField: "If-Match"/)
  assert.match(mutation, /method: "PATCH", revision: node\.revision, name: name/)
  assert.match(mutation, /method: "DELETE", revision: node\.revision/)
  assert.match(mutation, /try await requireCurrent\(node, session: session\)/)
  assert.match(mutation, /current == node/)
  assert.match(mutation, /checkedResponse\(response, accepted: 204\)/)
  assert.match(go, /func \(s \*Server\) deleteNode\(c \*gin\.Context\)/)
  assert.match(go, /activeSubtreeIDsDB\(tx, userID\(c\), id\)/)
  assert.match(go, /yikeManagedTargetInIDsDB\(c\.Request\.Context\(\), tx, userID\(c\), ids\)/)
  assert.match(go, /func \(s \*Server\) updateNode\(c \*gin\.Context\)/)
})
test('root and stale Owner cannot reach a directory mutation; one existing file transport is reused', () => {
  assert.match(mutation, /node\.parent_id != nil/)
  assert.match(mutation, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(mutation, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.match(panel, /if !verified \{\s*invalidate\(\)\s*dismiss\(\)/)
  assert.match(panel, /mutator\.invalidate\(\)/)
  assert.doesNotMatch(browser, /WKWebView|document\.cookie|\/api\/v1\/file-operations/)
})
