const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')

test('OCR recognized text is detail-only, Owner scoped and source revision fenced', () => {
  const api = read('internal/api/media.go')
  const detail = read('internal/api/media_ocr.go')
  const search = read('internal/api/media_filters.go')
  assert.match(api, /ocr, err := s\.mediaOCRDetails\(c\.Request\.Context\(\), node\.OwnerID, node, metadata\)/)
  assert.match(detail, /owner_id = \? AND primary_node_id = \?/)
  assert.match(detail, /metadata\.NodeRevision != node\.Revision/)
  assert.match(detail, /state\.InputFingerprint != mediaOCRInputFingerprint/)
  assert.match(search, /search_ocr_state\.input_fingerprint = /)
  assert.match(search, /xd_media_metadata\.node_revision = n\.revision/)
  assert.doesNotMatch(api.slice(api.indexOf('func (s *Server) materializeMediaItems('),
    api.indexOf('func (s *Server) materializeMediaItemsByNodeIDs(')), /OCR:\s+ocr/)
})

test('Web, Desktop, Mobile share one on-demand OCR inspector without list polling', () => {
  const shared = read('ui/shared/src/mui/MediaGallery.tsx')
  const inspector = read('ui/shared/src/mui/MediaGalleryDetails.tsx')
  const ocr = read('ui/shared/src/mui/MediaGalleryOCRDetails.tsx')
  const web = read('web/src/mediaGalleryAdapter.ts')
  const desktop = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  assert.match(web, /getItem: \(nodeID, signal\) => api\.mediaItem\(nodeID, signal\)/)
  assert.match(desktop, /agent\.getMediaItem\(nodeID, requestID\)/)
  assert.match(desktop, /agent\.cancelMediaItem\(requestID\)/)
  assert.match(shared, /loadMediaItem=\{isTrashSection \? undefined : loadMediaItem\}/)
  assert.match(inspector, /<XDriveMediaOCRDetails/)
  assert.match(ocr, /abort\(\)/)
  assert.match(ocr, /value\.node\.revision !== item\.node\.revision/)
  assert.match(ocr, /navigator\.clipboard\.writeText\(readyText\)/)
})

test('OCR failure reason is sanitized and shared across Web, Mobile and Desktop', () => {
  const runner = read('internal/photointelligence/smart_runner.go')
  const classifier = read('internal/photointelligence/smart_failure.go')
  const detail = read('internal/api/media_ocr.go')
  const model = read('ui/shared/src/models.ts')
  const client = read('internal/client/media.go')
  const component = read('ui/shared/src/mui/MediaGalleryOCRDetails.tsx')
  assert.ok(runner.includes('message := SmartFailureCodeFromStored(reason)'))
  assert.ok(!runner.includes('message := strings.TrimSpace(cause.Error())'))
  assert.ok(classifier.includes('func SmartFailureCodeFromStored(raw string) string'))
  assert.ok(detail.includes('SmartFailureCodeFromStored(state.LastError)'))
  assert.ok(detail.includes('metadata.NodeRevision != node.Revision'))
  assert.ok(model.includes('model_auth_rejected'))
  assert.ok(client.includes('Reason   string `json:"reason,omitempty"`'))
  assert.ok(component.includes('ocrFailureLabels[ocr.reason'))
  assert.ok(!component.includes('ocr.last_error'))
})
