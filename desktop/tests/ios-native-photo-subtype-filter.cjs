'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const filter = read('ios/XDriveIOS/NativePhotoMediaFilterPolicy.swift')
const scanner = read('ios/XDriveIOS/NativeGalleryMediaScanner.swift')
const timeline = read('ios/XDriveIOS/NativePhotoTimelineBrowser.swift')
const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')

test('native gallery filters are independent criteria with stable combined identities', () => {
  assert.match(filter, /enum XDriveIOSNativePhotoMediaFilterCriterion: String, CaseIterable, Identifiable/)
  assert.match(filter, /struct XDriveIOSNativePhotoMediaFilter: Hashable, CaseIterable, Identifiable, RawRepresentable/)
  assert.match(filter, /var requiresFavorite: Bool \{ isEnabled\(\.favorites\) \}/)
  assert.match(filter, /var requiresLive: Bool \{ isEnabled\(\.livePhotos\) \}/)
  assert.match(filter, /var requiresScreenshot: Bool \{ isEnabled\(\.screenshots\) \}/)
  assert.match(filter, /joined\(separator: "\+"\)/)
  assert.match(filter, /func setting\([\s\S]*?enabled: Bool[\s\S]*?\) -> Self/)
  assert.match(filter, /var fetchKind: String\?/)
  assert.match(filter, /var isAll: Bool/)
  assert.match(filter, /var allItemsTitle: String/)
})

test('PhotoKit combines all active predicates in one real filtered fetch', () => {
  assert.match(filter, /NSCompoundPredicate\(andPredicateWithSubpredicates: predicates\)/)
  assert.match(filter, /favorite == YES/)
  assert.match(filter, /PHAssetMediaSubtype\.photoLive\.rawValue/)
  assert.match(filter, /PHAssetMediaSubtype\.photoScreenshot\.rawValue/)
  assert.match(scanner, /mediaFilter\.applyPredicates\(to: options\)/)
  assert.match(scanner, /if mediaFilter\.fetchKind == "image"[\s\S]*else if mediaFilter\.fetchKind == "video"/)
  assert.match(scanner, /filter\.includes\(kind: kind\)/)
  assert.match(scanner, /observer\.current\(\) == version/)
  assert.match(scanner, /let end = min\(snapshot\.count, start \+ 64\)/)
  assert.match(scanner, /filter\.requiresFavorite \|\| asset\.isFavorite/)
  assert.doesNotMatch(scanner, /UploadSession|PhotoSyncLedger|UserDefaults/)
})

test('date index uses the identical combined PhotoKit predicate and cursor identity', () => {
  assert.match(timeline, /mediaFilter\.applyPredicates\(to: options\)/)
  assert.match(timeline, /if mediaFilter\.fetchKind == "image"[\s\S]*else if mediaFilter\.fetchKind == "video"/)
  assert.match(timeline, /mediaFilter\.includes\(kind: kind\)/)
  assert.match(timeline, /mediaFilter\.requiresFavorite/)
  assert.match(timeline, /mediaFilter\.requiresLive/)
  assert.match(timeline, /mediaFilter\.requiresScreenshot/)
  assert.match(timeline, /model\.indexFilter == mediaFilter/)
  assert.match(timeline, /filterValue: mediaFilter\.rawValue/)
  assert.match(timeline, /mediaFilter\.isAll/)
  assert.match(timeline, /Button\(mediaFilter\.allItemsTitle\)/)
})

test('gallery exposes simultaneous filter toggles and resets its complete cursor on change', () => {
  assert.match(wall, /Menu \{[\s\S]*Section\("媒体类型"\)/)
  assert.match(wall, /Toggle\("照片", isOn: mediaFilterBinding\(for: \.photos\)\)/)
  assert.match(wall, /Toggle\("视频", isOn: mediaFilterBinding\(for: \.videos\)\)/)
  assert.match(wall, /Toggle\("收藏", isOn: mediaFilterBinding\(for: \.favorites\)\)/)
  assert.match(wall, /Toggle\("实况", isOn: mediaFilterBinding\(for: \.livePhotos\)\)/)
  assert.match(wall, /Toggle\("截屏", isOn: mediaFilterBinding\(for: \.screenshots\)\)/)
  assert.match(wall, /Button\("重置筛选"\) \{ mediaFilter = \.all \}/)
  assert.match(wall, /\.onChange\(of: mediaFilter\) \{ _ in[\s\S]*?selectedCandidates\.removeAll\(\)[\s\S]*?savedOffset = 0\s*reload\(\)/)
  assert.match(wall, /mediaFilter\.rawValue/)
  assert.match(wall, /Text\(mediaFilter\.emptyMessage\)/)
  assert.doesNotMatch(wall, /Picker\("媒体类型"/)
})
