'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')
const go = read('internal/client/media_baidu_jsapi4_release.go')
const ctrl = read('cmd/xdrive-agent/cloud_media_baidu_jsapi4_release.go')
const ipc = read('cmd/xdrive-agent/desktop_ipc_baidu_jsapi4_release.go')
const routes = read('cmd/xdrive-agent/desktop_ipc.go')
const client = read('desktop/src/main/agent_client.cts')
test('Child Origin comes only from the authenticated signed Server status, not Renderer',()=>{
  assert.match(go,/\/api\/v1\/media\/places\/baidu-jsapi\/status/)
  assert.match(go,/authorized_signed_release/)
  assert.match(go,/https:\/\//)
  assert.match(go,/if len\(raw\) != len\(fields\)/)
  assert.match(go,/IsolatedChildOrigin/)
  assert.match(ctrl,/cli\.MediaBaiduJSAPI4Release\(ctx\)/)
  assert.match(routes,/GET \/v1\/media\/places\/baidu-jsapi4-release/)
  assert.match(ipc,/CloudMediaBaiduJSAPI4Release\(context\.Context\)/)
  assert.match(ipc,/r\.URL\.RawQuery != ""/)
  assert.match(ipc,/private, no-store/)
  assert.match(client,/mediaBaiduJSAPI4Release\(signal\?: AbortSignal\)/)
  assert.match(client,/GET', '\/v1\/media\/places\/baidu-jsapi4-release'/)
  assert.doesNotMatch(read('desktop/src/preload/index.cts'),/getMediaBaiduJSAPI4Release|mediaBaiduJSAPI4Release/)
  assert.doesNotMatch(read('desktop/src/renderer/mediaGalleryAdapter.ts'),/mediaBaiduJSAPI4Release/)
  assert.match(read('internal/api/baidu_jsapi_config.go'),/s\.currentBaiduJSAPI4OperatorRelease\(c\.Request\.Context\(\)\)/)
})
