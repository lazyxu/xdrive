const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('Desktop cancellation has a true Agent IPC capability and transport-owned Go context', () => {
  const agent = read('cmd/xdrive-agent/cloud_files.go')
  const api = read('cmd/xdrive-agent/desktop_ipc.go')
  const ctrl = read('cmd/xdrive-agent/controller.go')
  const manager = read('internal/transfer/model.go')
  assert.match(api, /"transfer-cancel"/)
  assert.match(api, /POST \/v1\/transfers\/cancel/)
  assert.match(api, /h\.ctrl\.\(interface\{ CancelTransfer\(string\) error \}\)/)
  assert.match(ctrl, /func \(c \*agentController\) CancelTransfer\(id string\) error/)
  assert.match(manager, /func \(m \*Manager\) Cancel\(id string\) error/)
  assert.match(agent, /handle\.BindCancel\(cancel\)/)
  assert.match(agent, /errors\.Is\(err, context\.Canceled\)/)
})

test('Desktop renderer only shows cancel for a current owned task on a capable Agent', () => {
  const preload = read('desktop/src/preload/index.cts')
  const main = read('desktop/src/main/index.cts')
  const client = read('desktop/src/main/agent_client.cts')
  const renderer = read('desktop/src/renderer/App.tsx')
  const globalTypes = read('desktop/src/renderer/global.d.ts')
  const sharedModel = read('ui/shared/src/transfers.ts')
  const popover = read('ui/shared/src/mui/TransferPopover.tsx')
  assert.match(preload, /cancelTransfer: \(id: string\) => ipcRenderer\.invoke\('agent:cancel-transfer'/)
  assert.match(main, /requireAgentCapability\(hello, 'transfer-cancel'\)/)
  assert.match(client, /cancelTransfer\(id: string\)/)
  assert.match(client, /cancelable\?: boolean/)
  assert.match(globalTypes, /cancelTransfer: \(id: string\) => Promise<DesktopResult<AgentTransfers>>/)
  assert.match(sharedModel, /cancelable\?: boolean/)
  assert.match(renderer, /task\.cancelable === true/)
  assert.match(renderer, /onCancel=\{\(id\) => \{ void cancelTransfer\(id\) \}\}/)
  assert.match(popover, /canCancel\?: \(id: string\) => boolean/)
  assert.match(popover, /取消传输/)
})
