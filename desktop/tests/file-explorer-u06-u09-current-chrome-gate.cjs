'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('U06/U09 PR branch drives original native Chrome 100k Search return and Server-ordered regroup tests', () => {
  const workflow = read('.github/workflows/ci.yml')
  const browser = read('desktop/scripts/file-explorer-search-return-browser.cjs')
  const prepareStart = workflow.indexOf('      - name: Prepare opt-in native Chrome iOS 27 Web acceptance')
  const prepareEnd = workflow.indexOf('      - name: U12 real Chrome Files deep destination', prepareStart)
  const runStart = workflow.indexOf('      - name: U06 native Chromium Search to containing folder and Back/Forward regression')
  const runEnd = workflow.indexOf('      - uses: actions/upload-artifact@v4', runStart)
  assert.ok(prepareStart > 0 && prepareEnd > prepareStart && runStart > prepareEnd && runEnd > runStart)
  const prepare = workflow.slice(prepareStart, prepareEnd)
  const runner = workflow.slice(runStart, runEnd)
  const gate = "startsWith(github.head_ref, 'test/files-search-return-chromium-u06-')"
  assert.ok(prepare.includes(gate), 'Chrome setup must be enabled by exact U06 prefix')
  assert.ok(runner.includes(gate), 'real Chrome U06 runner must be enabled by the same prefix')
  assert.ok(prepare.includes('XD_CHROME='), 'Chrome must be discovered during setup')
  assert.ok(runner.includes('XDRIVE_BROWSER_EXECUTABLE="$XD_CHROME"'), 'runner must use prepared Chrome')
  assert.ok(runner.includes('--case=all'), 'must execute real grouped return, cancellation, sort and 100k cases')
  assert.ok(browser.includes("if (!options.case || options.case === 'all' || options.case === 'return')"))
  assert.ok(browser.includes("await attempt(`M04 grouped ${mode} deep return`"))
  const u09Prefix = "test/files-search-return-chromium-u06-u09-sort-group-"
  assert.ok(browser.includes("process.env.GITHUB_HEAD_REF?.startsWith('" + u09Prefix + "')"))
  assert.ok(browser.includes("if (u09cEnabled) await attempt('U09-C 100k Server reordering"))
  assert.ok(browser.includes("pageFor('details', 900, false, true)"))
  assert.ok(browser.includes("original.count === 100_000"))
  assert.ok(browser.includes("'100005'"), 'grouped logical ARIA row count must describe all 100k items')
  assert.ok(browser.includes("check('U09-C sort keeps only a bounded sparse window"))
  assert.ok(browser.includes("check('U09-C old deep identity cannot remain selected at its obsolete ordinal'"))
})
