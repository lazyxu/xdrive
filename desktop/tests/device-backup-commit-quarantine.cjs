const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const read = (...parts) => fs.readFileSync(path.join(__dirname, '..', '..', ...parts), 'utf8')

test('L03-E0 commit intents are quarantined and own-Agent only, never canonical identity writes', () => {
  const model = read('internal', 'meta', 'local_source_commit_intent.go')
  const handler = read('internal', 'api', 'local_source_commit_intents.go')
  const router = read('internal', 'api', 'router.go')
  const contract = read('internal', 'api', 'router_contract_test.go')
  const migration = read('cmd', 'server', 'main.go')
  const web = read('web', 'src', 'App.tsx')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')

  assert.match(model, /LocalSourceCommitIntentStateQuarantined = "quarantined"/)
  assert.match(model, /idx_xd_local_ci_ev/)
  assert.match(model, /idx_xd_local_ci_gen_item/)
  assert.match(model, /idx_xd_local_ci_gen_path/)
  assert.match(router, /"\/sources\/:id\/local-identity\/commit-intents", s\.requireLocalSourceExecutor\(\), s\.quarantineLocalSourceCommitIntents/)
  assert.match(contract, /"\/api\/v1\/sources\/:id\/local-identity\/commit-intents"/)
  assert.match(migration, /&meta\.LocalSourceCommitIntent\{\}/)
  assert.match(handler, /s\.requireLocalSourceProofTx\(tx, c, sourceID, "", false\)/)
  assert.match(handler, /source\.Status != meta\.SourceStatusPaused/)
  assert.match(handler, /sameQuarantinedLocalIntent/)
  assert.match(handler, /CommitSupported: false, Authoritative: false, MissingInferenceSafe: false/)
  assert.match(handler, /tx\.Create\(&intent\)/)
  assert.doesNotMatch(handler, /tx\.(Create|Save|Updates|Delete)\(&?(?:meta\.)?(?:SourceItem|SourceItemAlias|SyncRun|Node|FileVersion|ContentBlob)/)
  assert.doesNotMatch(handler, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  assert.doesNotMatch(web, /commit-intents|quarantineLocalSourceCommitIntents/)
  assert.doesNotMatch(preload, /commit-intents|quarantineLocalSourceCommitIntents/)
  assert.doesNotMatch(main, /commit-intents|quarantineLocalSourceCommitIntents/)
})
