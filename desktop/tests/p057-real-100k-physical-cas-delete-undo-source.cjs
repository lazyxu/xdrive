'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const source = name => readFileSync(path.join(root, name), 'utf8')

test('P057 tests true 100k on-disk SHA-distinct physical source, owned queued delete and Undo, not Fake metadata', () => {
  const code = source('internal/api/p057_real_physical_cas_delete_undo_100k_performance_linux_test.go')
  const old = source('internal/api/p056_real_physical_cas_copy_undo_100k_performance_linux_test.go')
  const route = source('internal/api/router.go')
  assert.match(code, /func TestP057Real100KPhysicalCASDeleteUndo\(/)
  assert.match(code, /p047SourceCount/)
  assert.match(code, /store\.Put\(ctx, key, bytes\.NewReader\(payload\)\)/)
  assert.match(code, /p055RealCASAllocated\(ctx, store\)/)
  assert.match(code, /source_aggregate_sha256/)
  assert.match(code, /meta\.FileOperationTypeDelete/)
  assert.match(code, /meta\.FileOperationTypeUndo/)
  assert.match(code, /processNextFileOperation\(ctx\)/)
  assert.match(code, /http\.StatusAccepted/)
  assert.match(code, /http\.StatusNotFound/)
  assert.match(code, /bytes\.Equal\(actual, payload\)/)
  assert.match(code, /physical_allocated_bytes_after_undo/)
  assert.match(old, /meta\.FileOperationTypeCopy/)
  assert.match(route, /POST\("\/file-operations"/)
  assert.match(route, /POST\("\/file-operations\/:id\/undo"/)
  assert.doesNotMatch(code, /t\.Parallel\(\)/)
})

