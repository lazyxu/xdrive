const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Device Backup local creation is only wired by Desktop Agent capabilities', () => {
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalCreateDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  assert.match(app, /!deviceBackupSource \|\| !localFolderGrantSupported/)
  assert.match(app, /agent\.hello\?\.capabilities\.includes\('external-sources'\)/)
  assert.match(app, /localCreate:\s*localBackupCreate/)
  // The browser is shared by two separately capability-gated owning-Desktop
  // actions. Creation itself still requires localCreate and Root grants.
  assert.match(app, /targetBrowser:\s*localBackupCreate \|\| localBackupTarget \? desktopSourceTargetBrowser : undefined/)
  assert.match(app, /localTarget:\s*localBackupTarget/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(page, /target: Boolean\(localTarget && targetBrowser\)/)
  assert.match(page, /localActions\.target \?/)
  assert.equal(web.includes('localCreate='), false)
  assert.match(page, /localCreate && source/) 
  // Creation no longer asks the user to pick an ordinary cloud folder.
  // Only the already device-scoped Server chooses the actual target Node.
  assert.doesNotMatch(dialog, /targetBrowser|target!\.id/)
  assert.match(page, /currentLocalDevice,/)
  assert.match(page, /xDriveLocalBackupFeatureAccess\(\{/)
  assert.match(dialog, /actions\.create\(normalizedName, 0\)/)
  assert.match(dialog, /actions\.authorize\(current\.id\)/)
  assert.match(dialog, /actions\.discard\(current\.id, current\.revision\)/)
  assert.equal(dialog.includes('X-XDrive-Device-Token'), false)
  assert.equal(dialog.includes('X-XDrive-Local-Root-Fingerprint'), false)
  assert.equal(dialog.includes('nativeSelectedPath'), false)
  assert.equal(page.includes('sourceOverview('), false)
  assert.equal(page.includes('sourceItems('), false)
  assert.equal(page.includes('cancelSourceRun('), false)
})

