const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Device Backup local creation is only wired by Desktop Agent capabilities', () => {
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalCreateDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  assert.match(app, /!deviceBackupSource \|\| !localFolderGrantSupported/)
  assert.match(app, /agent\.hello\?\.capabilities\.includes\('external-sources'\)/)
  assert.match(app, /localCreate=\{localBackupCreate\}/)
  assert.match(app, /targetBrowser=\{localBackupCreate \? desktopSourceTargetBrowser : undefined\}/)
  assert.equal(web.includes('localCreate='), false)
  assert.match(page, /localCreate && targetBrowser/)
  assert.match(dialog, /actions\.create\(name\.trim\(\), target!\.id\)/)
  assert.match(dialog, /actions\.authorize\(current\.id\)/)
  assert.match(dialog, /actions\.discard\(current\.id, current\.revision\)/)
  assert.equal(dialog.includes('X-XDrive-Device-Token'), false)
  assert.equal(dialog.includes('X-XDrive-Local-Root-Fingerprint'), false)
  assert.equal(dialog.includes('nativeSelectedPath'), false)
  assert.equal(page.includes('sourceOverview('), false)
  assert.equal(page.includes('sourceItems('), false)
  assert.equal(page.includes('cancelSourceRun('), false)
})

test('Staged picker cancellation is fenced by creating Agent and cannot start local Push', () => {
  const agent = read('cmd', 'xdrive-agent', 'cloud_files.go')
  const api = read('internal', 'api', 'local_source_drafts.go')
  const source = read('internal', 'api', 'source_runs.go')
  const desktop = read('desktop', 'src', 'renderer', 'App.tsx')
  assert.match(agent, /cli\.DiscardLocalSourceDraft\(ctx, sourceID, revision, deviceID, secret\)/)
  assert.match(api, /LocalCreatorDeviceID/)
  assert.match(api, /clientDeviceCredentialMatches\(device/)
  assert.match(api, /errLocalDraftNotEmpty/)
  assert.match(source, /if source\.Kind == meta\.SourceKindLocalFolder/)
  assert.match(desktop, /schedule_type: 'manual'/)
  assert.match(desktop, /sync_mode: 'backup'/)
})
