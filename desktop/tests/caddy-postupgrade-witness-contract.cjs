const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('Caddy installer verifies the running Server witness only AFTER trusted Host Control startup', () => {
  const src = read('deploy/install-server.sh')
  const commit = src.lastIndexOf('commit_upgrade_transaction\n')
  const install = src.lastIndexOf('"$BIN_DIR/server-control.sh" install')
  const witness = src.lastIndexOf('caddy-host witness-check')
  assert.ok(commit > 0 && install > commit && witness > install)
  const end = src.indexOf('\necho\nif [[ -n "$(env_value XD_DOMAIN)" ]]', witness)
  assert.ok(end > witness)
  const newStage = src.slice(install, end)
  assert.match(newStage, /running Server verified a fresh local HTTPS witness/)
  assert.match(newStage, /System Dependencies may show unknown/)
  assert.doesNotMatch(newStage, /docker (?:restart|stop|rm)|compose (?:up|down|restart)|ALIYUN_ACCESS_KEY_SECRET/)
  assert.match(src, /compose exec -T server xdrive-server caddy-host witness-check/)
  assert.match(newStage, /caddy_witness_one_shot_attempted=0/)
  assert.match(newStage, /Caddy local observation: snapshot-missing/)
  assert.match(newStage, /Caddy local observation: snapshot-stale/)
  assert.match(newStage, /XD_CADDY_OBSERVER_ONCE=1 XD_CONFIG_DIR="\$XDRIVE_HOME"/)
  assert.match(newStage, /timeout 30s "\$BIN_DIR\/server-control\.sh" caddy-observe/)
  assert.doesNotMatch(newStage, /(?:docker|compose) (?:restart|stop|rm|up|down)/)
})

test('read-only Server witness does not acquire host control, secrets, SQL or fabricated WAN acceptance', () => {
  const cli = read('cmd/server/caddy_host_adopt.go')
  const api = read('internal/api/admin_caddy_host_observation_reason.go')
  const doctor = read('scripts/server-doctor.sh')
  const start = cli.indexOf('if args[0] == "witness-check"')
  const end = cli.indexOf('if args[0] != "adopt-stdin"')
  assert.ok(start > 0 && end > start)
  const readOnly = cli.slice(start, end)
  assert.match(readOnly, /CaddyHostReadOnlyWitness/)
  // Comments are not executable actions: check the actual statements, not a harmless disclaimer.
  const readOnlyCode = readOnly.replace(/^[ \t]*\/\/.*$/gm, '')
  assert.doesNotMatch(readOnlyCode, /Docker|exec\.Command|Seal\(|Open\(|gorm\.|restart|StopCaddy/)
  assert.match(api, /s\.readCaddyHostStatus\(\)/)
  assert.match(api, /validCaddyTLSVerifiedDomainDigest/)
  assert.match(doctor, /unsupported-or-unavailable-server-witness/)
  assert.doesNotMatch(doctor.slice(doctor.indexOf('caddy_witness_output=""'), doctor.indexOf('caddy_witness_reason="unsupported-or-unavailable-server-witness"')), /record WARN .*"\$caddy_witness_output"/)
})

test('postupgrade Server doctor separates host-produced snapshot from missing Server mount without leaking file bytes', () => {
  const src = read('scripts/server-doctor.sh')
  const test = read('scripts/test-server-doctor.sh')
  assert.match(src, /caddy_host_meta_state\(\)/)
  assert.match(src, /host-snapshot-present-server-unreadable/)
  assert.match(src, /host-snapshot-not-produced/)
  assert.match(src, /running-server-witness-cli-unavailable/)
  assert.match(test, /poison-must-not-leak/)
  const meta = src.slice(src.indexOf('caddy_host_meta_state()'), src.indexOf('\ncompose() {'))
  assert.doesNotMatch(meta, /cat |sed -n|docker |openssl|curl |restart|rm -f|eval/)
})
