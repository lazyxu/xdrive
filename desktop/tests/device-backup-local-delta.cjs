const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Desktop local delta stays private, cancellable and not Web enabled', () => {
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_delta.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_delta.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalDeltaDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')

  assert.match(agent, /localBoundBackupConfig\(deltaCtx, sourceID\)/)
  assert.match(agent, /cli\.LocalBoundRules\(deltaCtx, sourceID, proof\)/)
  assert.match(agent, /localpush\.LoadRootGrant\(/)
  assert.match(agent, /localpush\.StreamInventoryGenerationDelta\(/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /MissingInferenceSafe: false/)
  assert.match(agent, /Authoritative: false/)
  assert.doesNotMatch(agent, /PublishLocalReconcileEvidence|BeginSourceRun|UploadChunk|CommitSourceItem|MirrorMissingFullScans|SourceItemAlias/)
  assert.match(ipc, /"device-backup-local-delta"/)
  assert.match(ipc, /GET \/v1\/device-backups\/local-delta/)
  assert.match(handler, /CloudLocalBoundBackupDelta\(r\.Context\(\), sourceID\)/)
  assert.match(handler, /"private, no-store"/)
  assert.match(client, /localBoundBackupDelta\(sourceID: number, signal\?: AbortSignal\)/)
  assert.match(client, /165_000, signal/)
  assert.match(main, /localDeltaRequests\.set\(key, controller\)/)
  assert.match(main, /localDeltaRequests\.get\(key\)\?\.abort\(\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-delta'\)/)
  assert.match(preload, /getDeviceBackupLocalDelta:/)
  assert.match(preload, /cancelDeviceBackupLocalDelta:/)
  assert.match(app, /localDelta=\{localBackupDelta\}/)
  assert.match(page, /localDelta && verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(dialog, /crypto\.randomUUID\(\)/)
  assert.match(dialog, /actions\.cancel\(requestID\)/)
  assert.match(dialog, /result\.previous_items !== result\.absent_candidates/)
  assert.doesNotMatch(web, /getDeviceBackupLocalDelta|localDelta=/)
  const readModel = dto.slice(0, dto.indexOf('// Separate private Agent-only draft projection.'))
  assert.doesNotMatch(readModel, /absent_candidates|previous_items/)
  assert.doesNotMatch(dialog, /(?:startUpload|triggerSource|cancelSourceRun|deleteSource|createSource)\(/)
})
