const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const repo = path.resolve(__dirname, '../..')
const read = (...segments) => fs.readFileSync(path.join(repo, ...segments), 'utf8')

test('one Server provisioning function owns the immutable Push/Pull prefixes', () => {
  const server = read('internal', 'api', 'source_managed_provision.go')
  const source = read('internal', 'api', 'sources.go')
  const schema = read('cmd', 'server', 'main.go')
  const namespaceMigration = read('cmd', 'server', 'source_name_index.go')
  assert.match(server, /func provisionManagedSourceTargetTx\(/)
  assert.match(server, /segments = \[\]string\{yikeTargetRootName, "Push"\}/)
  assert.match(server, /segments = \[\]string\{yikeTargetRootName, "Pull", connector\}/)
  assert.match(server, /errSourceManagedDirectoryOccupied/)
  assert.match(source, /provisionManagedSourceTargetTx\(c\.Request\.Context\(\), tx, source, devicePtr\)/)
  assert.match(source, /managed Push\/Pull target is server-provisioned/)
  assert.match(schema, /migrateSourceNameNamespaceIndex\(db\)/)
  assert.match(namespaceMigration, /idx_xd_sources_owner_direction_name/)
  assert.match(schema, /idx_xd_sources_owner_yike_account/)
})

test('native destination and DSM Push use flat leaves but preserve Device ID authorization', () => {
  const native = read('internal', 'api', 'ios_photo_backup_destination.go')
  const dsm = read('internal', 'api', 'synology_push_managed_provision.go')
  const local = read('internal', 'api', 'local_push_managed_provision.go')
  const android = read('internal', 'api', 'sources.go')
  assert.match(native, /boundDeviceID, bound := meta\.SourceDeviceID\(source\)/)
  assert.match(native, /!bound \|\| boundDeviceID != device\.ID/)
  assert.doesNotMatch(native, /managedPushDeviceFolderName/)
  assert.doesNotMatch(dsm, /managedPushDeviceFolderName/)
  assert.doesNotMatch(local, /managedPushDeviceFolderName/)
  assert.match(android, /SourceKindAndroidPhotos/)
  assert.match(android, /native photos target requires registered device proof/)
})

test('unsettled Source operations block managed target rename without changing Node ID', () => {
  const rename = read('internal', 'api', 'source_managed_rename.go')
  assert.match(rename, /requireSourceTargetRenameQuiescentTx/)
  assert.match(rename, /meta\.LocalPushCommonUploadOperation/)
  assert.match(rename, /\[\]string\{"reserved", "bound"\}/)
  assert.match(rename, /meta\.UploadSession/)
  assert.match(rename, /source\.RunRequestedAt != nil/)
  assert.match(rename, /"revision": gorm\.Expr\("revision \+ 1"\)/)
  assert.match(rename, /idx|source\.TargetNodeID|target\.ID/)
})

test('Source Manager shows only an editable last segment and keeps failed drafts', () => {
  const dialog = read('ui', 'shared', 'src', 'mui', 'SourceManagerCreateDialog.tsx')
  const manager = read('ui', 'shared', 'src', 'mui', 'SourceManager.tsx')
  const preset = read('ui', 'shared', 'src', 'mui', 'SourceBasicFields.tsx')
  assert.match(dialog, /label="目标文件夹名称"/)
  assert.match(dialog, /同步文件夹 \/ Push/)
  assert.match(dialog, /同步文件夹 \/ Pull/)
  assert.match(dialog, /只允许修改最后一级目录名称/)
  assert.doesNotMatch(dialog, /onClick=\{\(\) => onLoadTargetDirectory/)
  assert.match(manager, /target_node_id: 0/)
  assert.match(manager, /未自动删除或归档/)
  assert.match(manager, /new TextEncoder\(\)\.encode\(normalizedName\)\.length/)
  assert.match(preset, /option\.value !== 'synology_push'/)
})


