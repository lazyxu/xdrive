'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = filename => fs.readFileSync(path.join(root, filename), 'utf8')

test('A3c12 Browser AK stays a separate admin secret, never a Static Server AK', () => {
  const server = read('internal/api/baidu_jsapi_config.go')
  const api = read('internal/client/client.go')
  const web = read('web/src/api.ts')
  assert.match(server, /baiduJSAPISecretName\s*=\s*"baidu-jsapi-v4"/)
  assert.match(server, /ConnectorSecrets\.Seal\(/)
  assert.match(api, /type AdminBaiduJSAPIConfig struct/)
  assert.match(api, /json:"desired_enabled"/)
  assert.match(api, /json:"browser_ak,omitempty"/)
  assert.match(web, /adminBaiduJSAPIConfig\(\)/)
  assert.match(web, /adminSaveBaiduJSAPIConfig\(/)
  assert.match(read('web/src/App.tsx'), /loadBaiduJSAPIConfig:\s*\(\)\s*=> api\.adminBaiduJSAPIConfig\(/)
})

test('A3c12 Desktop uses bounded Agent IPC, not Browser AK in Renderer', () => {
  const go = read('cmd/xdrive-agent/desktop_ipc_admin_baidu_jsapi.go')
  const bridge = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const agent = read('desktop/src/main/agent_client.cts')
  const routes = read('cmd/xdrive-agent/desktop_ipc.go')
  assert.match(routes, /"GET \/v1\/cloud\/admin-baidu-jsapi"/)
  assert.match(routes, /"PUT \/v1\/cloud\/admin-baidu-jsapi"/)
  assert.match(go, /decodeDesktopIPCJSONLimit\(w, r, &input, 1024\)/)
  assert.match(go, /validDesktopBaiduJSAPIInput\(input\)/)
  assert.match(bridge, /requireAgentCapability\(hello, 'admin-services'\)/)
  assert.match(bridge, /agent:cloud-set-admin-baidu-jsapi/)
  assert.match(preload, /cloudSetAdminBaiduJSAPIConfig/)
  assert.match(agent, /'PUT', '\/v1\/cloud\/admin-baidu-jsapi'/)
  assert.match(read('desktop/src/renderer/App.tsx'), /saveBaiduJSAPIConfig:/)
  assert.doesNotMatch(read('desktop/src/renderer/App.tsx'), /BrowserAK\s*:/)
})

test('A3c12 shared mobile/wide configuration never labels saved intent as entitlement', () => {
  const component = read('ui/shared/src/mui/BaiduJSAPIDesiredPanel.tsx')
  const parent = read('ui/shared/src/mui/ServiceDependenciesPage.tsx')
  const policy = read('internal/baidumapjsapi/resource_policy.go')
  const pin = read('internal/baidumapjsapi/release_attestation.go')
  assert.match(component, /data-xdrive-baidu-jsapi4-admin/)
  assert.match(component, /config\?\.runtime_enabled === true/)
  assert.match(component, /authorized_signed_release/)
  assert.match(component, /onDirtyChange/)
  assert.match(parent, /baiduJSAPIDirty/)
  assert.match(parent, /XDriveBaiduJSAPIDesiredPanel source=\{source\}/)
  assert.match(policy, /reviewedJSAPI4ChildResourceCount = 0/)
  assert.match(read('internal/api/baidu_jsapi4_managed_runtime.go'), /StartBaiduJSAPI4ManagedRelease\(/)
  assert.match(pin, /VerifyManagedJSAPI4ProductionRelease\(/)
  assert.doesNotMatch(component, /_BMapSecurityConfig|\.src\s*=|fetch\(/)
})
