const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('native Desktop preview remains private and cancels all the way into Go context', () => {
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_preview.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_preview.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalPreviewDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')

  assert.match(agent, /localBoundBackupConfig\(scanCtx, sourceID\)/)
  assert.match(agent, /cli\.LocalBoundRules\(scanCtx, sourceID, proof\)/)
  assert.match(agent, /localpush\.LoadRootGrant\(/)
  assert.match(agent, /\.ScanInventory\(scanCtx, grant,/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /context\.WithTimeout\(ctx, 35\*time\.Second\)/)
  assert.match(agent, /MissingInferenceSafe: false/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorMissingFullScans|ScanInventoryToJournal|HashVerifiedInventoryFile/)
  assert.match(ipc, /"device-backup-local-preview"/)
  assert.match(ipc, /GET \/v1\/device-backups\/local-preview/)
  assert.match(handler, /CloudLocalBoundBackupPreview\(r\.Context\(\), sourceID\)/)
  assert.match(handler, /"private, no-store"/)
  assert.match(client, /localBoundBackupPreview\(sourceID: number, signal\?: AbortSignal\)/)
  assert.match(client, /40_000, signal/)
  assert.match(main, /localPreviewRequests\.set\(key, controller\)/)
  assert.match(main, /localPreviewRequests\.get\(key\)\?\.abort\(\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-preview'\)/)
  assert.match(preload, /getDeviceBackupLocalPreview:/)
  assert.match(preload, /cancelDeviceBackupLocalPreview:/)
  assert.match(app, /localPreview=\{localBackupPreview\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(page, /previewTarget\.source === source/)
  assert.match(dialog, /crypto\.randomUUID\(\)/)
  assert.match(dialog, /actions\.cancel\(requestID\)/)
  assert.doesNotMatch(web, /getDeviceBackupLocalPreview|localPreview=/)
  assert.ok(dto.includes('export interface XDriveLocalBackupPreview'))
  const readModel = dto.slice(0, dto.indexOf('// Separate private Agent-only draft projection.'))
  assert.doesNotMatch(readModel, /scanned_directories|skipped_unsafe_items/)
  assert.doesNotMatch(dialog, /(?:startUpload|triggerSource|cancelSourceRun|deleteSource|createSource)\(/)
})
