test('native Notes images use only authenticated in-Note relative assets', () => {
  const client = file('ios/XDriveIOS/NativeNotesClient.swift')
  const screen = file('ios/XDriveIOS/NativeNotesScreen.swift')
  const preview = file('ios/XDriveIOS/NativeNotesMarkdownPreview.swift')

  assert.match(client, /func readNoteImage\(noteID: String, relativePath: String\)/)
  assert.match(client, /func uploadMyNoteImage\(noteID: String, bytes: Data\)/)
  assert.match(client, /parts\.count == 3, parts\[0\] == "_assets"/)
  assert.match(client, /parts\[1\]\.lowercased\(\) == ownerID/)
  assert.match(client, /\/api\/v1\/notes\/mine\//)
  assert.match(client, /completionHandler\(nil\)/)
  assert.match(client, /config\.httpShouldSetCookies = false/)
  assert.match(client, /result\.sha256\.lowercased\(\) == checksum/)

  assert.match(screen, /imagePickerOpen = true/)
  assert.match(screen, /\.fileImporter\(/)
  assert.match(screen, /await client\.uploadMyNoteImage\(noteID: id, bytes: bytes\)/)
  assert.match(screen, /markdown \+=/)
  assert.match(screen, /XDriveIOSNativeNotesMarkdownPreview\(/)
  assert.match(preview, /XDriveIOSNativeNotesInlineImage\(/)
  assert.match(preview, /await login\.verifiedAuthorization\(\)/)
  assert.match(preview, /await client\.readNoteImage\(/)
  assert.doesNotMatch(preview, /WKWebView|webView|URLSession\(shared\)/)
})

test('explicit iOS Markdown plus pictures import stays Owner-bound and does not infer Apple Notes IDs', () => {
  const client = file('ios/XDriveIOS/NativeNotesClient.swift')
  const screen = file('ios/XDriveIOS/NativeNotesScreen.swift')
  const policy = file('ios/XDriveIOS/NativeNotesManualImportPolicy.swift')
  assert.match(screen, /allowsMultipleSelection: true/)
  assert.match(screen, /private func readSelectedImportFile\(/)
  assert.match(screen, /handle\.read\(upToCount: maxBytes \+ 1\)/)
  assert.match(screen, /XDriveIOSNativeManualNotesImportPolicy\.references\(in: original\)/)
  assert.match(screen, /XDriveIOSNativeManualNotesImportPolicy\.selectedImages\(/)
  assert.match(screen, /"manual-md:" \+ UUID\(\)\.uuidString\.lowercased\(\)/)
  assert.match(screen, /await client\.importIOSNoteImage\(/)
  assert.match(screen, /await client\.importIOSMarkdown\(/)
  assert.match(screen, /with: path, noteID: first\.id/)
  assert.match(client, /func importIOSNoteImage\(noteID: String, bytes: Data\)/)
  assert.match(client, /\/api\/v1\/notes\/ios\/images\/import\//)
  assert.match(client, /result\.sha256\.lowercased\(\) == checksum/)
  assert.match(policy, /case unsafeImageReference/)
  assert.match(policy, /case missingSelectedImage/)
  assert.match(policy, /matches\.reversed\(\)/)
  assert.doesNotMatch(screen, /URLSession\.shared|WKWebView|WebView\(/)
})
