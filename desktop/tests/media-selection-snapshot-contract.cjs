const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const repo = path.resolve(__dirname, '../..')
const read = (p) => fs.readFileSync(path.join(repo, p), 'utf8')

test('G07 snapshot API is owner-scoped, sparse, capped, expiring and versioned', () => {
  const router = read('internal/api/router.go')
  const implementation = read('internal/api/media_selection_snapshot.go')
  assert.match(router, /authed\.POST\("\/media\/selection-snapshots", s\.createMediaSelectionSnapshot\)/)
  assert.match(router, /authed\.GET\("\/media\/selection-snapshots\/:token", s\.getMediaSelectionSnapshot\)/)
  assert.match(router, /authed\.PATCH\("\/media\/selection-snapshots\/:token\/exclusion", s\.updateMediaSelectionExclusion\)/)
  assert.match(router, /authed\.DELETE\("\/media\/selection-snapshots\/:token", s\.deleteMediaSelectionSnapshot\)/)
  assert.match(implementation, /mediaSelectionMaxItems = 100000/)
  assert.match(implementation, /Limit\(mediaSelectionMaxItems \+ 1\)/)
  assert.match(implementation, /mediaSelectionPageMax\s+= 200/)
  assert.match(implementation, /mediaSelectionTTL\s+= 15 \* time\.Minute/)
  assert.match(implementation, /ownerID: userID\(c\)/)
  assert.match(implementation, /session\.ownerID != userID\(c\)/)
  assert.match(implementation, /"selection exceeds 100000 items; narrow the query"/)
  assert.match(implementation, /"version"/)
  assert.match(implementation, /setExcluded\(nodeID uint64, excluded bool, version uint64\)/)
  assert.match(implementation, /MediaItem|mediaSelectionNode/)
  assert.doesNotMatch(implementation, /Store\.Open|Thumbnail|DownloadOriginal|start.*TaskCenter/)
})

test('G07 server day snapshots use IANA time zone and existing shared scoped query', () => {
  const impl = read('internal/api/media_selection_snapshot.go')
  assert.match(impl, /mediaIANAZone\(options\.TimeZone\)/)
  assert.match(impl, /start\.AddDate\(0, 0, 1\)\.UTC\(\)/)
  assert.match(impl, /mediaItemsBaseQuery\(c\.Request\.Context\(\), userID\(c\), options, albumID\)/)
  assert.match(impl, /if options\.SortBy == "added"/)
  assert.match(impl, /xd_media_metadata\.captured_at/)
  assert.match(impl, /"scope": "known_photo_assets"/)
  const unit = read('internal/api/media_selection_snapshot_test.go')
  const integration = read('internal/api/media_selection_snapshot_integration_test.go')
  assert.match(unit, /TestMediaSelection100KReviewRemainsPageBounded/)
  assert.match(unit, /TestMediaSelectionDayBoundsRespectsDSTAndSortMode/)
  assert.match(integration, /TestMediaSelectionPostgresFreezesOnlyOwnerMatchedDay/)
})
