'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const src = p => fs.readFileSync(path.join(root, p), 'utf8')
const app = src('ios/XDriveIOS/NativePhotosDashboard.swift')
const api = src('ios/XDriveIOS/NativeServerMediaGalleryTransport.swift')
const view = src('ios/XDriveIOS/NativeServerMediaGallery.swift')

test('canonical Server PhotoAsset range and Owner album REST are native read-only', () => {
  assert.match(api, /"\/api\/v1\/media\/items"/)
  assert.match(api, /"\/api\/v1\/media\/albums"/)
  assert.match(api, /URLQueryItem\(name: "range", value: "true"\)/)
  assert.match(api, /URLQueryItem\(name: "limit", value: String\(Self.pageSize\)\)/)
  assert.match(api, /static let pageSize = 48/)
  assert.match(api, /page\.offset == offset, page\.limit == Self\.pageSize/)
  assert.match(api, /page\.items\.count <= Self\.pageSize/)
  assert.match(api, /XDriveIOSNativeMediaRejectRedirect/)
  assert.match(api, /completionHandler\(nil\)/)
  assert.match(api, /httpShouldSetCookies = false/)
  assert.match(api, /Bearer " \+ accessToken/)
  assert.doesNotMatch(api, /WKWebView|document\.cookie|UploadSessionTransport|LocalPhotoKitUploader/)
})
test('thumbnail is revision-bound, bounded and downsampled without original fallback', () => {
  assert.match(api, /"\/api\/v1\/media\/items\/\\\(item.id\)\/thumbnail"/)
  assert.match(api, /String\(item\.node\.revision\)/)
  assert.match(api, /bytes\.count <= 2 \* 1_048_576/)
  assert.match(api, /kCGImageSourceThumbnailMaxPixelSize as String: 280/)
  assert.match(api, /Task\.detached\(priority: \.utility\)/)
  assert.match(api, /ticket\.url\.hasPrefix\("\/api\/v1\/file-preview\/"\)/)
  assert.match(api, /request\.httpShouldHandleCookies = false/)
  assert.match(api, /bearer: false, maximum: 32 \* 1_048_576/)
})
test('new Cloud PhotoAsset Gallery is under the fixed Gallery tab; old originals remain distinct', () => {
  assert.match(app, /case local, albums, cloud, originals, map/)
  assert.match(app, /XDriveIOSNativeServerMediaWall\(login: login, album: nil\)/)
  assert.match(app, /XDriveIOSNativeCloudOriginalGallery\(login: login\)/)
  assert.match(app, /case \.originals:\s*openGallery\(\.originals\)/)
  assert.match(app, /case \.cloud:\s*openGallery\(\.cloud\)/)
  assert.match(view, /NavigationLink\s*\{\s*XDriveIOSNativeServerMediaAlbums\(login: login\)/)
  assert.match(view, /XDriveIOSNativeServerMediaWall\(login: login, album: album\)/)
  assert.match(view, /\.fullScreenCover\(item: \$selected\)/)
  assert.match(view, /\.onChange\(of: login\.owner\)/)
  assert.match(view, /if selected != nil \{ model\.suspendForViewer\(\) \}/)
  assert.match(view, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
})
