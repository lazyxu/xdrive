test('canonical PhotoAsset Viewer retires signed media on scene/Owner changes', () => {
  const begin = view.indexOf('struct XDriveIOSNativeServerMediaPreview: View')
  const end = view.indexOf('/// Root and album-specific media wall', begin)
  assert.ok(begin >= 0 && end > begin)
  const preview = view.slice(begin, end)
  assert.match(preview, /@Environment\(\\\.scenePhase\) private var phase/)
  assert.match(preview, /@State private var previewRequestID = UUID\(\)/)
  assert.match(preview, /\.task\(id: previewRequestID\)/)
  assert.doesNotMatch(preview, /\.task\(id: item\.id\)/)
  assert.match(preview, /phase == \.active, let expected = login\.owner/)
  assert.match(preview, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(preview, /previewRequestID == requestID/)
  assert.match(preview, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(preview, /\.onChange\(of: phase\) \{ _ in[\s\S]*?retirePreview\(\)/)
  assert.match(preview, /\.onChange\(of: login\.owner\) \{ _ in[\s\S]*?retirePreview\(\)[\s\S]*?dismiss\(\)/)
  assert.match(preview, /\.onDisappear \{ retirePreview\(\) \}/)
  const afterNetwork = preview.slice(preview.indexOf(').preview(item)'))
  assert.match(afterNetwork, /try Task\.checkCancellation\(\)[\s\S]*?phase == \.active, previewRequestID == requestID/)
  assert.match(preview, /catch is CancellationError \{/)
  assert.match(preview, /previewRequestID = UUID\(\)[\s\S]*?player\?\.pause\(\)[\s\S]*?image = nil[\s\S]*?failure = nil/)
})
