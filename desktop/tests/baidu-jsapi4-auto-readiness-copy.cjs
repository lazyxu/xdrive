'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')

test('both JSAPI4 SDK hosts share Server auto-readiness wording without manual credential review', () => {
  const panel = read('ui/shared/src/mui/BaiduJSAPIDesiredPanel.tsx')
  const snapshot = read('ui/shared/src/mui/BaiduJSAPIConfigSnapshot.tsx')
  const server = read('internal/api/baidu_jsapi_config.go')
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  assert.match(panel, /Server 自动检查并生效/)
  assert.match(panel, /不需要额外人工签名或生产账户凭证审核/)
  assert.match(panel, /动态地图服务已就绪/)
  assert.match(panel, /动态地图服务尚未就绪/)
  assert.match(panel, /不是额外的生产账户人工凭证审批/)
  assert.doesNotMatch(panel, /尚无完整、逐项审核的地图子资源白名单|完成固定百度 JSAPI4 子资源清单审查/)
  assert.doesNotMatch(panel, /Server 已签名授权动态地图|尚未获得 Server 签名放行|当前 Server 尚未授权运行/)
  assert.match(snapshot, /key: 'activation_state', value: config\.activation_state/)
  assert.match(snapshot, /Server 自动计算的兼容协议状态/)
  // Preserve the original, read-only Server wire contract and its exact security boundaries.
  assert.match(panel, /config\.activation_state === 'authorized_signed_release'/)
  assert.match(server, /currentBaiduJSAPI4OperatorRelease\(/)
  assert.match(panel, /releaseBlockerIDs\.includes\(reason\)/)
  assert.match(panel, /未放行时不会试探加载脚本/)
  assert.match(map, /mapMode === 'prototype'/)
  assert.match(map, /mintBaiduIsolatedChildTicket/)
  assert.doesNotMatch(panel, /fetch\(|window\._BMapSecurityConfig/)
})
