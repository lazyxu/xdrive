'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname,'../..',p),'utf8')
const doc = read('docs/architecture/clipboard-sync.md')
const page = read('ui/shared/src/mui/ClipboardPage.tsx')
test('current Clipboard architecture distinguishes merged v1/v2 and native Viewer from past candidates',()=>{
  assert.match(doc, /Current source status \(2026-11-08\)/)
  assert.match(doc, /#4106.*Final Gate/)
  assert.match(doc, /#4110.*Files Viewer/)
  assert.match(doc, /Desktop and DSM outbound Agent\/CGI transports remain \*\*v1 text-only/)
  assert.match(doc, /Direct local image\/file Clipboard ingestion/)
  assert.match(doc, /Android Keystore/)
  assert.doesNotMatch(doc, /#4086 consolidation candidate \(not merged/)
  assert.doesNotMatch(doc, /Android enrollment still requires native implementation/)
  assert.doesNotMatch(doc, /new candidate\)/)
})
test('shared Clipboard page explains actual Host capabilities without misrepresenting background OS access',()=>{
  assert.match(page, /port\.listDevices\s*\?/)
  assert.match(page, /port\.watchLocalClipboard\s*\?/)
  assert.match(page, /定向发送文本及现有云端文件引用/)
  assert.match(page, /只有明确开启后才在解锁且页面可见时运行/)
  assert.doesNotMatch(page, /当前版本没有设备定向发送或后台自动监控/)
})