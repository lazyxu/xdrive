  assert.match(store, /func saveAnchor\(owner:/)
  assert.doesNotMatch(store, /Bearer|accessToken|NodeDTO|signedTicket|saveToKeychain/)
  assert.match(browser, /func referencedDirectory\(nodeID: UInt64\) async throws/)
  assert.match(browser, /let current = try await reader\.referencedDirectory\(nodeID: savedFolderID\)/)
  assert.match(browser, /let first = try await reader\.children\(/)
  assert.match(browser, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, owner\)/)
  assert.match(browser, /pathDestination = XDriveIOSNativeFilesFolder\(/)
