const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const repo = path.resolve(__dirname, '../..')
const read = (file) => fs.readFileSync(path.join(repo, file), 'utf8')

test('Agent durable transfer history uses private account-scoped atomic storage', () => {
  const disk = read('cmd/xdrive-agent/transfer_history_storage.go')
  const manager = read('internal/transfer/history.go')
  assert.match(disk, /userconfig\.Dir\(\)/)
  assert.match(disk, /transfer-history-v1-/)
  assert.match(disk, /os\.CreateTemp/)
  assert.match(disk, /tmp\.Sync\(\)/)
  assert.match(disk, /os\.Rename/)
  assert.match(disk, /agentTransferHistoryIdentity/)
  assert.match(disk, /agentTransferHistoryVersion/)
  assert.match(manager, /HistorySnapshot\(limit int\)/)
  assert.match(manager, /RestoreHistory\(tasks \[\]Task\)/)
  assert.match(manager, /InstantBytesPerSecond = 0/)
})

test('Agent restores on startup/account change and saves on completion and clear', () => {
  const ctrl = read('cmd/xdrive-agent/controller.go')
  const mgr = read('internal/transfer/model.go')
  const disk = read('cmd/xdrive-agent/transfer_history_storage.go')
  assert.match(ctrl, /c\.loadInitialTransferHistory\(\)/)
  assert.match(ctrl, /c\.switchTransferHistory\(cfg\)/)
  assert.match(ctrl, /c\.stopTransferHistory\(\)/)
  assert.match(ctrl, /persistTransferHistoryLocked\(\)/)
  assert.match(mgr, /markHistoryDirtyForLocked\(id\)/)
  assert.match(mgr, /markHistoryDirtyLocked\(\)/)
  assert.match(disk, /runTransferHistoryWriter/)
})
