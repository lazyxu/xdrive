const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')
const web = read('web', 'src', 'WebOverviewPage.tsx')
const home = read('ui','shared','src','mui','HomePage.tsx')
const desktop = read('desktop','src','renderer','App.tsx')

test('Home Recent/Favorites never advertise a false zero before an authorized first read', () => {
  assert.ok(web.includes('const listsVerified = acceptedLists !== null'))
  assert.ok(web.includes('listsSnapshot?.source === api && listsSnapshot.scope === lifecycleKey'))
  assert.ok(web.includes('recentVerified={listsVerified}'))
  assert.ok(web.includes('favoritesVerified={listsVerified}'))
  assert.ok(home.includes('data-xdrive-home-list-first-read'))
  assert.ok(home.includes('available && verified && items.length > 0'))
  assert.ok(home.includes('!verified ? ('))
  assert.equal(home.includes('useXDriveDeferredLoading'), false,
    'Home first-read indexes never create a 300ms presentation timer')
  assert.equal(home.includes('正在读取列表…'), false,
    'a cold Home must remain visually silent even during slow GET')
  assert.ok(home.includes('aria-busy={!error || undefined}'))
  assert.ok(home.includes('data-xdrive-home-list-verified-empty'))
  assert.ok(home.includes('minHeight: 160'))
  assert.ok(home.includes('minHeight: 96, display: \'grid\', placeItems: \'center\''))
  assert.equal(home.includes('<XDriveStatePanel'), false)
  assert.ok(!web.includes('setRecentItems([])'))
})

test('a failed read cannot claim a true empty list or discard last accepted items', () => {
  assert.ok(web.includes('readRequestRef.current !== epoch'))
  assert.ok(web.includes('setListsSnapshot({'))
  assert.ok(web.includes('readRequestRef.current += 1'))
  assert.ok(web.includes('const listsFailed = !listsVerified && Boolean(currentRead?.failed)'))
  assert.ok(web.includes('recentError={listsFailed'))
  assert.ok(web.includes('favoritesError={listsFailed'))
  assert.ok(home.includes('最近使用'))
  assert.ok(home.includes('收藏'))
  assert.ok(home.includes('recentVerified = true'))
  assert.ok(home.includes('favoritesVerified = true'))
  assert.ok(desktop.includes("view === 'overview'"), 'Desktop overview remains independent and unchanged')
})

test('existing thumbnails and file navigation are preserved independently', () => {
  assert.ok(home.includes('<XDriveFileExplorerThumbnail'))
  assert.ok(web.includes('api.mediaThumbnail(id, requestSignal)'))
  assert.ok(web.includes('api.fileRecent(6)'))
  assert.ok(web.includes('api.fileFavorites()'))
  assert.ok(web.includes('onOpenDirectory(entry.node.id, entry.crumbs)'))
})
