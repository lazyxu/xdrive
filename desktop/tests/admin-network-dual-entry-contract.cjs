const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('Caddy network policy is two separate audited, revisioned desired entries', () => {
  const models = read('internal/meta/admin_caddy_https_setting.go')
  const api = read('internal/api/admin_caddy_https_desired.go')
  const validate = read('internal/api/admin_caddy_https_validation.go')
  const shared = read('ui/shared/src/service-dependencies.ts')
  const goClient = read('internal/client/client.go')
  const main = read('desktop/src/main/agent_client.cts')
  const preload = read('desktop/src/preload/index.cts')
  const compose = read('deploy/docker-compose.yml')
  for (const key of ['LANEnabled', 'LANIP']) {
    assert.match(models, new RegExp('\\b' + key + '\\b'))
    assert.match(api, new RegExp('\\b' + key + '\\b'))
    assert.match(goClient, new RegExp('\\b' + key + '\\b'))
  }
  for (const key of ['desired_lan_enabled', 'desired_lan_ip', 'host_lan_configured']) {
    assert.ok(shared.includes(key))
    assert.ok(main.includes(key))
    assert.ok(api.includes('json:"' + key + '"'))
  }
  assert.match(preload, /lan_enabled\?: boolean/)
  assert.match(compose, /XD_LAN_HTTPS_IP: \$\{XD_LAN_HTTPS_IP:-\}/)
  assert.ok((compose.match(/XD_DOMAIN: \$\{XD_DOMAIN:-\}/g) || []).length >= 2,
    'both Caddy and Server must receive the read-only deployment domain hint')
  assert.match(api, /recordCaddyHTTPSRevisionTx/)
  assert.match(api, /validCaddyIngressSelection/)
  assert.match(api, /errCaddyHTTPSIngress/)
  assert.match(api, /recordAuditTx/)
  assert.match(api, /ApplySupported: false/)
  assert.match(api, /desired\.Revision == 0/)
  assert.match(api, /os\.Getenv\("XD_DOMAIN"\)/)
  assert.match(api, /validCaddyHTTPSDomain\(hostDomain\)/)
  assert.match(api, /strings\.ToLower\(hostDomain\)/)
  assert.match(validate, /ip\.Is4\(\) && ip\.IsPrivate\(\)/)
  assert.match(validate, /domainEnabled \|\| lanEnabled/)
})

test('shared Caddy MUI page requires at least one enabled HTTPS entry, rejects stale LAN contract', () => {
  const page = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  const evidence = read('ui/shared/src/mui/CaddyPreflightPanel.tsx')
  const web = read('web/src/App.tsx')
  const desk = read('desktop/src/renderer/App.tsx')
  assert.match(page, /validPrivateLANIP/)
  assert.match(page, /label="期望局域网 IPv4 地址"/)
  assert.match(page, /期望启用局域网 IP HTTPS/)
  assert.match(page, /不能同时关闭局域网 IP HTTPS 和公网域名 HTTPS/)
  assert.match(page, /const supportsLAN =/)
  assert.match(page, /!supportsLAN \|\| !valid/)
  assert.match(page, /lan_enabled: lanEnabled, lan_ip: lanIP/)
  assert.match(page, /data-xdrive-caddy-evidence-location/)
  assert.doesNotMatch(page, /config\.host_lan_configured|config\.host_lan_tls_state/)
  assert.match(evidence, /result\.host_lan_local_tls_verified/)
  assert.match(evidence, /data-xdrive-caddy-desired-lan-local-match/)
  assert.match(page, /仅保存期望配置（不操作 Caddy）/)
  assert.match(page, /局域网 IP HTTPS · 默认部署入口/)
  assert.match(page, /公网域名 HTTPS · 可选入口/)
  assert.ok(page.indexOf('局域网 IP HTTPS · 默认部署入口') <
    page.indexOf('公网域名 HTTPS · 可选入口'),
    'the default LAN access method should appear first')
  assert.match(web, /XDriveServiceDependenciesPage/)
  assert.match(desk, /XDriveServiceDependenciesPage/)
  for (const bad of ['docker.sock', 'adminRestartHost', 'adminStopHost']) {
    assert.equal(page.includes(bad), false)
  }
})

test('LAN and domain are NOT automatically applied just by saving desired settings', () => {
  const api = read('internal/api/admin_caddy_https_desired.go')
  const preflight = read('internal/api/admin_caddy_preflight.go')
  const caddy = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  const docs = read('docs/network-manual-connection.md')
  assert.match(api, /RequiresRestrictedMaintenance: true/)
  assert.match(api, /ApplyState: state, Editable: true, ApplySupported: false/)
  assert.match(api, /"host_applied": false/)
  assert.match(caddy, /不修改宿主机 \.env/)
  assert.match(docs, /NET-M4/)
  assert.match(preflight, /restricted-apply/)
  assert.doesNotMatch(api, /adminCaddyHTTPSApply\(c \*gin\.Context\)/)
})
