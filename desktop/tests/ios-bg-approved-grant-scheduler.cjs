'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const native = read('ios/XDriveIOS/ApprovedBackgroundPhotoVault.swift')
const boot = read('ios/XDriveIOS/BackgroundPhotoTask.swift')
const login = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
const controller = read('ios/XDriveIOS/NativePhotoBackupController.swift')
const backup = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')
const credential = read('ios/XDriveIOS/PhotoBackgroundGrantManager.swift')

test('native-only background grant uses independent Device authorization', () => {
  assert.match(credential, /func enableAfterNativeConfirmation\(/)
  assert.match(credential, /func verifyRemote\(owner: XDriveNativeOwnerRoot, accessToken: String\)/)
  assert.match(credential, /XDriveIOSApprovedPhotoBGVault\.shared\.install/)
  assert.match(login, /native-ios-offline-emergency-stop/)
  assert.match(login, /XDriveIOSBackgroundPhotoTask\.revokePendingRequests\(\)/)
  assert.match(controller, /XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(backup, /native-ios-photos-auto-disable/)
  assert.doesNotMatch(login + backup, /WKWebView|xdriveIOSHost|window\.webkit/)
})

test('locked-screen credentials cannot outlive Owner, server, scope or expiry', () => {
  assert.match(native, /kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly/)
  assert.match(native, /com\.lazyxu\.xdrive\.ios\.photos\.bg-approved\.v1/)
  assert.match(native, /differentOwnerStillApproved/)
  assert.match(native, /XDriveIOSBGApprovalPolicy\.validLifetime/)
  assert.match(native, /XDriveIOSBGApprovalPolicy\.validInterval/)
  assert.match(native, /revokePendingRequests\(\)/)
  assert.match(native, /serverExpiry <= item\.expiresAt/)
  assert.match(native, /proof\.server_instance_id == item\.instanceID/)
  assert.match(native, /proof\.root_node_id == item\.rootNodeID/)
  assert.match(native, /proof\.device_id == item\.deviceID/)
  assert.match(native, /proof\.upload_authorized/)
  assert.match(native, /httpShouldHandleCookies = false/)
  assert.match(native, /willPerformHTTPRedirection/)
  assert.match(native, /completionHandler\(nil\)/)
  assert.match(credential, /XDriveIOSApprovedPhotoBGVault\.shared\.install/)
  assert.match(credential, /XDriveIOSApprovedPhotoBGVault\.shared\.cancelLocally/)
})

test('BGProcessingTask runs one scoped original only after approved native proof', () => {
  assert.match(boot, /BGTaskScheduler\.shared\.register/)
  assert.match(boot, /BGProcessingTaskRequest\(identifier: identifier\)/)
  assert.match(boot, /requiresNetworkConnectivity = true/)
  assert.match(boot, /proveInBackground\(\)/)
  assert.match(boot, /UIApplication\.shared\.isProtectedDataAvailable/)
  assert.match(boot, /XDriveIOSForegroundPhotoBackupMVP\(/)
  assert.match(boot, /approvedBackgroundGrant: approved/)
  assert.match(boot, /maximumNewOriginals: 1/)
  assert.match(boot, /task\.expirationHandler = \{[\s\S]*?guard activeRunID == runID else \{ return \}[\s\S]*?expiration\.systemExpired = true[\s\S]*?operation\.cancel\(\)/)
  assert.match(boot, /if beganOriginalWrite, let attemptedOwner \{[\s\S]*?XDriveIOSBGOriginalWindowStore\.shared\.pause\(/)
  assert.match(boot, /else if expiration\.systemExpired &&[\s\S]*?localStopVersion == stopVersionAtStart/)
  assert.match(boot, /hasTrustedBackgroundExecutionGrant: Bool \{ false \}/)
  assert.doesNotMatch(boot,
    /uploadPreparedOriginal\(|startUploadSession\(|createUploadSession\(|PHAsset\.fetchAssets\(/)
})

test('iOS system Photos privacy prompt accurately discloses opt-in native background uploads', () => {
  const project = read('ios/project.yml')
  const line = project.split('\n').find(row => row.includes('NSPhotoLibraryUsageDescription:'))
  assert.ok(line, 'xDrive iOS must disclose the purpose of protected PhotoKit reads')
  assert.match(line, /手动备份由你主动启动/)
  assert.match(line, /另外开启自动备份并明确批准后台授权/)
  assert.match(line, /iOS 允许时才可能在前台或后台读取并向当前账户的 xDrive 服务器上传原件/)
  assert.match(line, /你可以随时停止/)
  assert.doesNotMatch(line, /不会在后台自动上传|永远不会后台|保证后台持续/)
  assert.match(project, /BGTaskSchedulerPermittedIdentifiers:/)
  assert.match(project, /UIBackgroundModes:/)
  assert.match(credential, /func enableAfterNativeConfirmation\(/)
  assert.match(native, /kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly/)
})
