'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const browser = read('ios/XDriveIOS/NativePhotoTimelineBrowser.swift')
const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
const index = read('ios/XDriveIOS/NativePhotoTimelinePolicy.swift')

test('year and month dates show actual PhotoKit thumbnail covers without another pagination wall', () => {
  assert.match(browser, /private struct XDriveIOSNativeTimelineCoverTile: View/)
  assert.match(browser, /XDriveIOSNativeSquarePhotoTile\(candidate: representative\)/)
  assert.match(browser, /LazyVGrid\(columns:/)
  assert.match(browser, /GridItem\(\.adaptive\(minimum: 138, maximum: 230\)/)
  assert.match(browser, /ForEach\(index\.groups\(for: scale\)\)/)
  assert.match(browser, /XDriveIOSNativeTimelineCoverTile\(\s*group: group,\s*totalSlots: index\.totalSlots,\s*mediaFilter: mediaFilter/)
  assert.match(wall, /ForEach\(0\.\.<XDriveIOSNativePhotoVirtualPagePolicy\.pageCount\(total: total\)/)
  assert.doesNotMatch(browser, /Button\("上一页"\)|Button\("下一页"\)/)
})

test('visible covers use exact filtered numeric slot and reject stale/revoked PhotoKit contents', () => {
  const cover = browser.slice(browser.indexOf('private struct XDriveIOSNativeTimelineCoverTile: View'),
    browser.indexOf('struct XDriveIOSNativeLocalPhotoTimelineContainer: View'))
  assert.match(cover, /@State private var representative: XDrivePhotoKitScanCandidate\?/)
  assert.match(cover, /XDriveIOSNativeGalleryMediaScanner\(\)/)
  assert.match(cover, /atOffset: group\.firstPageOffset, mediaFilter: mediaFilter/)
  assert.match(cover, /batch = try await reader\.nextPage\(\)/)
  assert.match(cover, /try Task\.checkCancellation\(\)/)
  assert.match(cover, /await reader\.reset\(\)/)
  assert.match(cover, /let position = group\.firstSlot - group\.firstPageOffset/)
  assert.match(cover, /count == totalSlots, batch\.totalAccessibleAssets == totalSlots/)
  assert.match(cover, /batch\.startOffset == group\.firstPageOffset/)
  assert.match(cover, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\) == permission/)
  assert.match(cover, /matchesGroup\(candidate\)/)
  assert.match(cover, /\.onDisappear \{ representative = nil \}/)
  assert.doesNotMatch(cover, /requestImage\(|requestAVAsset\(|URLSession|UserDefaults|upload|PHAsset\.fetchAssets/)
  assert.match(index, /var firstPageOffset: Int \{ \(firstSlot \/ 64\) \* 64 \}/)
})

test('tapping year drills into months, then days, then the same continuous wall', () => {
  assert.match(browser, /case \.year where group\.key != "unknown":[\s\S]*selectedYearKey = group\.key[\s\S]*scale = \.month/)
  assert.match(browser, /case \.month where group\.key != "unknown":[\s\S]*selectedMonthKey = group\.key[\s\S]*scale = \.day/)
  assert.match(browser, /if group\.scale == \.month, let year = selectedYearKey/)
  assert.match(browser, /if group\.scale == \.day, let month = selectedMonthKey/)
  assert.match(browser, /Button\("所有年份"\)/)
  assert.match(browser, /Button\("返回月份"\)/)
  assert.match(browser, /if scale == \.day \{\s*ForEach\(index\.groups\(for: scale\)\)/)
  assert.match(browser, /jump\(to: group\.firstPageOffset\)/)
  assert.match(browser, /savedOffset = requestedOffset\s*wallRevision &\+= 1/)
  assert.match(browser, /XDriveIOSNativeLocalContinuousGalleryScreen\(/)
  assert.match(browser, /model\.indexFilter == mediaFilter/)
  assert.match(browser, /model\.invalidate\(\)/)
})
