'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const source = read('ios/XDriveIOS/NativeFilesOperationHistory.swift')
const policy = read('ios/XDriveIOS/NativeFilesOperationPolicy.swift')
const files = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const api = read('web/src/api.ts')
const undo = read('internal/api/file_operations_undo.go')
const redo = read('internal/api/file_operations_redo.go')
const go = read('internal/api/file_operations.go')

test('Native Files uses exactly the existing Owner-scoped Server Operation queue', () => {
  assert.match(source, /"\/api\/v1\/file-operations"/)
  assert.match(source, /value: String\(XDriveIOSNativeFilesOperationPolicy\.maximumHistory\)/)
  assert.match(source, /path \+= "\/" \+ id/)
  assert.match(source, /path \+= "\/" \+ action\.rawValue/)
  assert.match(api, /undoFileOperation\(id: string\)/)
  assert.match(api, /redoFileOperation\(id: string\)/)
  assert.match(undo, /c\.JSON\(http\.StatusAccepted, toFileOperationDTO\(operation\)\)/)
  assert.match(redo, /c\.JSON\(http\.StatusAccepted, toFileOperationDTO\(operation\)\)/)
  assert.match(go, /Where\("owner_id = \?", userID\(c\)\)/)
  assert.match(policy, /static let maximumHistory = 50/)
})

test('Undo and Redo action are explicitly confirmed, never replayed on lost ACK', () => {
  assert.match(source, /\.confirmationDialog\(/)
  assert.match(source, /Button\("确认" \+ \(pending\?\.action\.label \?\? ""\)\)/)
  assert.match(source, /expectedStatus: 202/)
  assert.match(source, /XDriveIOSNativeFilesOperationPolicy\.accepted\(/)
  assert.match(source, /let detail = try await send\(/)
  assert.match(source, /verified\.undo_of_id == original\.id/)
  assert.match(source, /verified\.redo_of_id == original\.id/)
  assert.match(source, /服务器已接受.*任务；请刷新查看最终结果/)
  assert.match(source, /结果尚未确认。请先刷新操作历史核对，不要重复提交。/)
  assert.match(policy, /item\.status == "completed"/)
  assert.match(policy, /item\.undoable && item\.type != "undo"/)
  assert.match(policy, /item\.redoable && item\.type == "undo"/)
  assert.doesNotMatch(source, /while\s*\(true\)|retryUndo|retryRedo/)
})

test('Native operations transport refuses cross-Owner URLs, cookies and redirects', () => {
  assert.match(source, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(source, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(source, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.match(source, /URLSessionConfiguration\.ephemeral/)
  assert.match(source, /completionHandler\(nil\)/)
  assert.match(source, /config\.httpShouldSetCookies = false/)
  assert.match(source, /config\.urlCache = nil/)
  assert.match(source, /"Bearer " \+ accessToken/)
  assert.match(source, /UUID\(uuidString: id\) != nil/)
  assert.doesNotMatch(source, /WKWebView|document\.cookie|URLSession\.shared|UserDefaults/)
})

test('Files browse exposes genuine operation history without refreshing idle navigation', () => {
  assert.match(files, /Label\("操作历史及撤销"/)
  assert.match(files, /native-ios-files-open-operations/)
  assert.match(files, /native-ios-files-operations/)
  assert.match(files, /\.sheet\(isPresented: \$showingFileOperations, onDismiss:/)
  assert.match(files, /XDriveIOSNativeFilesOperationHistoryScreen\(/)
  assert.match(files, /if operationWasAccepted \{[\s\S]*?reload\(\)/)
  assert.match(files, /showingFileOperations = false[\s\S]*?fileOperationsOwner = nil/)
  assert.match(files, /private func presentFileOperations\(\)/)
  assert.match(source, /\.onDisappear \{ model\.invalidate\(\) \}/)
})
