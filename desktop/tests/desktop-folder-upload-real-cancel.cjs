const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const repo = path.join(__dirname, '..', '..')
const read = (name) => fs.readFileSync(path.join(repo, name), 'utf8')

test('Desktop folder upload owns the actual Agent group HTTP context', () => {
  const ctrl = read('cmd/xdrive-agent/controller.go')
  const transfer = read('internal/transfer/model.go')
  const cloud = read('cmd/xdrive-agent/cloud_files.go')
  assert.match(ctrl, /handle\.BindGroupCancelContext\(groupCtx, cancel\)/)
  assert.match(transfer, /func \(m \*Manager\) UploadGroupContext\(/)
  assert.match(transfer, /context\.AfterFunc\(owner, cancel\)/)
  assert.match(cloud, /c\.transfers\.UploadGroupContext\(ctx, transferID, true\)/)
  assert.match(cloud, /agentUploadTransferContext\(transportCtx, handle\)/)
  assert.match(cloud, /c\.transfers\.UploadGroupContext\(ctx, groupID, false\)/)
})

test('Desktop preflight cancellation crosses capability-gated IPC and shared UI', () => {
  const main = read('desktop/src/main/index.cts')
  const agent = read('desktop/src/main/agent_client.cts')
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  const preload = read('desktop/src/preload/index.cts')
  const explorer = read('desktop/src/renderer/DesktopFileExplorer.tsx')
  const shared = read('ui/shared/src/mui/FileExplorerUploadController.ts')
  const app = read('desktop/src/renderer/App.tsx')
  for (const file of [main, ipc, app]) assert.match(file, /transfer-upload-group-cancel/)
  assert.match(main, /cloudUploadPreflight\(parentID, name\.trim\(\), ownerID\)/)
  assert.match(agent, /\.\.\.\(groupID \? \{ group_id: groupID \} : \{\}\)/)
  assert.match(preload, /'agent:cloud-upload-preflight', parentID, name, groupID/)
  assert.match(explorer, /isCancelled: transferGroupUploadCancelSupported/)
  assert.match(explorer, /liveTransferTasks\.current/)
  assert.match(shared, /if \(isGroupCancelled\(\) \|\| isUserAbort\(error\)\)/)
})

test('Cancellation is strictly enabled for real contexts, without fake pause', () => {
  const transfer = read('internal/transfer/model.go')
  const renderer = read('desktop/src/renderer/App.tsx')
  assert.match(transfer, /e\.task\.Kind != KindUpload/)
  assert.match(renderer, /task\.cancelable === true/)
  assert.doesNotMatch(read('ui/shared/src/mui/TransferPopover.tsx'), /暂停传输|继续传输/)
})
