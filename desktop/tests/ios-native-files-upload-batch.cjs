'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const policy = read('ios/XDriveIOS/NativeFilesUploadBatchPolicy.swift')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const upload = read('ios/XDriveIOS/NativeFilesManualUpload.swift')
const stager = read('ios/XDriveIOS/NativeManualDocumentStage.swift')
const receipt = read('ios/XDriveIOS/NativeFilesUploadConfirmationPolicy.swift')
const server = read('internal/api/router.go')

test('one native Files picker supports explicit bounded multi-selection, retains single importer', () => {
  assert.match(panel, /isPresented: \$showingImporter, allowedContentTypes: \[\.item\]/)
  assert.match(panel, /uploader\.start\(\s*fileURL: pickedURL, login: login/)
  assert.match(panel, /isPresented: \$showingMultiImporter,[\s\S]*?allowsMultipleSelection: true/)
  assert.match(panel, /uploader\.start\(\s*files: pickedURLs, login: login/)
  assert.match(panel, /native-ios-files-manual-batch-upload/)
  assert.match(panel, /showingMultiImporter = false/)
  assert.match(policy, /static let maximumFiles = 8/)
  assert.match(policy, /Set\(names\.map \{ \$0\.lowercased\(\) \}\)\.count == files\.count/)
  assert.match(policy, /files\.allSatisfy\(\{ \$0\.isFileURL \}\)/)
})

test('one existing gated UploadSession writer sequentially processes each staged item', () => {
  assert.match(upload, /func start\(fileURL: URL,[\s\S]*?start\(files: \[fileURL\]/)
  assert.match(upload, /guard XDriveIOSNativeFilesUploadBatchPolicy\.validSelection\(files\)/)
  assert.match(upload, /XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(upload, /defer \{[\s\S]*?XDriveIOSOriginalRunGate\.shared\.release\(gate\)/)
  assert.match(upload, /for \(index, fileURL\) in files\.enumerated\(\)/)
  assert.match(upload, /let name = try await uploadOne\(/)
  assert.match(upload, /let staged = try await XDriveManualDocumentStager\.stage\(fileURL\)/)
  assert.match(upload, /defer \{ staged\.delete\(\) \}/)
  assert.match(upload, /XDriveNativeUploadSessionTransport\(/)
  assert.match(upload, /let receipt = try await writer\.uploadOnce\(\s*from: staged\.fileURL, name: staged\.originalName, parentID: parentID/)
  assert.match(server, /authed\.POST\("\/uploads", s\.createUploadSession\)/)
  assert.match(stager, /maxFirstFileBytes: Int64 = 128 \* 1_048_576/)
})

test('each item re-verifies Owner, exact destination and committed Node/SHA before next', () => {
  assert.match(upload, /let initial = try await login\.verifiedAuthorization\(\)/)
  assert.match(upload, /let beforeUpload = try await login\.verifiedAuthorization\(\)/)
  assert.match(upload, /let afterUpload = try await login\.verifiedAuthorization\(\)/)
  assert.match(upload, /requireDestination\(parentID, expectedName: expectedFolderName\)/)
  assert.match(upload, /try await proof\.requireCommitted\(receipt, parentID: parentID/)
  assert.match(upload, /XDriveIOSNativeFilesUploadConfirmationPolicy\.matches\(/)
  assert.match(receipt, /node\.sha256\?\.lowercased\(\) == hash/)
  assert.match(upload, /confirmed \+= 1/)
  assert.match(upload, /try Task\.checkCancellation\(\)[\s\S]*?onConfirmed\(\)/)
  assert.doesNotMatch(upload, /URLSession\.shared|WKWebView|uploadPreparedOriginal\(/)
})

test('cancellation or any uncertain ACK stops subsequent uploads without invented byte progress', () => {
  assert.match(upload, /func cancelCurrentTransfer\(\) \{\s*guard busy, let running else \{ return \}\s*running\.cancel\(\)/)
  assert.match(upload, /catch is CancellationError \{/)
  assert.match(upload, /catch XDriveManualDocumentStageError\.tooLarge/)
  assert.match(upload, /已确认 \\?\(confirmed\).*当前请求结果可能不确定/)
  assert.match(upload, /请刷新目录核对，不要盲目重复提交/)
  assert.match(upload, /status = files\.count == 1/)
  assert.doesNotMatch(upload, /DispatchQueue\.main\.asyncAfter|Task\.sleep|retry\(/)
})
