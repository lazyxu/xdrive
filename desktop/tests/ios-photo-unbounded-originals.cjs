'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const file = name => fs.readFileSync(path.join(root, name), 'utf8')

test('native photo, video and Live originals have no iOS media byte ceilings', () => {
  const policy = file('ios/XDriveIOS/PhotoBackupMediaPolicy.swift')
  const exporter = file('ios/XDriveIOS/PhotoKitOriginalExporter.swift')
  const runner = file('ios/XDriveIOS/ForegroundPhotoBackupMVP.swift')
  const preparer = file('ios/XDriveIOS/PhotoKitStagedIntentPreparer.swift')
  const manual = file('ios/XDriveIOS/IOSManualPhotoOriginalUpload.swift')
  const upload = file('ios/XDriveIOS/NativeUploadSessionTransport.swift')
  for (const name of ['stillLimit', 'videoLimit', 'backgroundVideoLimit'])
    assert.match(policy, new RegExp('static let '+ name + ': Int64 = \\.max'))
  assert.match(exporter, /maximumBytesPerResource: Int64 = \.max/)
  assert.doesNotMatch(exporter, /maximumBytesPerResource <= 4_294_967_296/)
  assert.match(runner, /maximumBytesPerResource: \.max/)
  assert.doesNotMatch(preparer, /original.byteCount <= maximumOriginalBytes/)
  assert.match(manual, /maximumBytesPerResource: \.max/)
  assert.doesNotMatch(manual, /still.byteCount <= 128 \* 1_048_576/)
  assert.match(upload, /expectedSize > 0/)
  assert.doesNotMatch(upload, /expectedSize <= (?:1_073_741_824|XDriveIOSOriginalBackupMediaPolicy.videoLimit)/)
  assert.match(upload, /private static let chunkBytes = 8 \* 1_048_576/)
})

test('Live originals use one atomic ZIP64 archive without a ZIP32 byte limit', () => {
  const archive = file('ios/XDriveIOS/LiveOriginalArchive.swift')
  assert.match(archive, /let size: UInt64/)
  assert.match(archive, /let offset: UInt64/)
  assert.match(archive, /zip64Extra\(size: entry.size, offset: record.offset\)/)
  assert.match(archive, /UInt32\(0x06064b50\)/)
  assert.match(archive, /UInt32\(0x07064b50\)/)
  assert.doesNotMatch(archive, /UInt32\(cursor\)|UInt32\(part.input.byteCount\)/)
  assert.match(archive, /func checksum\(_ source: URL, expected: Int64\)/)
  assert.match(archive, /throw XDriveIOSLiveArchiveFailure.resourceChanged/)
  assert.match(archive, /throw XDriveIOSLiveArchiveFailure.storageUnavailable/)
  assert.match(archive, /try handle.synchronize\(\)/)
})

test('Server retains Owner-scoped admission and global quota instead of iOS size caps', () => {
  const bg = file('internal/api/ios_photo_background_uploads.go')
  const managed = file('internal/api/ios_photo_managed_uploads.go')
  const shared = file('internal/api/uploads.go')
  assert.doesNotMatch(bg, /iosBackgroundOriginalMaxBytes/)
  assert.doesNotMatch(managed, /iosBackgroundOriginalMaxBytes/)
  assert.match(bg, /req.Size > 0 &&/)
  assert.match(managed, /req.Size > 0 &&/)
  assert.match(managed, /requireIOSPhotoManagedUploadTx/)
  assert.match(shared, /req.Size < 0 \|\| req.Size > s.MaxUploadBytes/)
  assert.match(shared, /ensureQuotaForStorageKey/)
  assert.match(shared, /expectedSize := expectedPartSize/)
  assert.match(bg, /req.ChunkSize == defaultUploadChunkSize/)
})
