const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')
const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
const hook = read('ui/shared/src/mui/useDeferredLoading.ts')
const originalSearchContract = read('desktop/tests/media-gallery-search-feedback.cjs')
const originalCold = read('desktop/tests/gallery-cold-quiet-loading.cjs')

test('shared wide Gallery query feedback keeps the committed count/chips through short network refresh',()=>{
  assert.ok(gallery.includes('data-xdrive-gallery-search-feedback'))
  assert.ok(gallery.includes('data-xdrive-gallery-query-quiet-feedback'))
  assert.ok(gallery.includes('showCollectionFilters && !compactGallery && loading'))
  assert.ok(gallery.includes('data-xdrive-gallery-query-progress-slot'))
  assert.ok(gallery.includes('aria-busy={loading || undefined}'))
  assert.ok(gallery.includes('width: 16, height: 16, flexShrink: 0'))
  assert.ok(gallery.includes("pointerEvents: 'none'"))
  assert.ok(gallery.includes('showDelayedGalleryQuery'))
  assert.ok(gallery.includes("logicalItemCount.toLocaleString('zh-CN') + ' 个匹配项目'"))
  assert.ok(gallery.includes('loading && logicalItemCount === 0 && !keepAcceptedEmpty'))
  assert.ok(gallery.includes('结果待确认'))
  assert.ok(gallery.includes('collectionError ? \'查询失败\''))
  assert.ok(gallery.includes('data-xdrive-gallery-applied-filter'))
  assert.ok(gallery.includes('data-xdrive-gallery-pending-filters'))
  assert.ok(gallery.includes('xDriveGalleryAppliedChips'))
  assert.equal(gallery.includes("loading ? '正在查询…'"), false,
    'quick refresh must not insert a new wide text that wraps the filter chip row')
  assert.ok(originalSearchContract.includes('G05 UI separates draft from applied state'))
  assert.ok(originalCold.includes('300') || hook.includes('XDRIVE_WORKSPACE_LOADING_FEEDBACK_DELAY_MS = 300'))
})
test('index-status check has an unchanged interactive button label and a non-hit-testing delayed spinner slot',()=>{
  const start = gallery.indexOf('data-xdrive-gallery-index-status-request')
  const end = gallery.indexOf('</Button>',start)
  assert.ok(start>=0 && end>start)
  const buttonStart = gallery.lastIndexOf('<Button', start)
  assert.ok(buttonStart > 0 && buttonStart < start,
    'the same actual MUI Button owns its disabled and stable-label props')
  const label = gallery.slice(buttonStart,end)
  assert.ok(label.includes("disabled={indexStatusLoading}"))
  assert.ok(label.includes('data-xdrive-gallery-index-quiet-action'))
  assert.ok(label.includes("indexStatus ? '刷新索引状态' : '查看索引状态'"))
  assert.ok(label.includes('data-xdrive-gallery-index-progress-slot'))
  assert.ok(label.includes('aria-busy={indexStatusLoading || undefined}'))
  assert.ok(label.includes("pointerEvents: 'none'"))
  assert.ok(label.includes('showDelayedIndexCheck'))
  assert.ok(gallery.includes('showCollectionFilters && !compactGallery && Boolean(indexStatusLoading)'))
  assert.equal(label.includes('检查索引中…'),false)
  assert.ok(gallery.includes('onClick={onRequestIndexStatus}'))
})
test('same network feedback hook defers 300ms visually only while requests and progress owners remain unchanged',()=>{
  assert.ok(gallery.includes("import { useXDriveDeferredPendingLoading } from './useDeferredLoading'"))
  assert.ok(hook.includes('XDRIVE_WORKSPACE_LOADING_FEEDBACK_DELAY_MS = 300'))
  assert.ok(hook.includes('return pending && visible'))
  assert.ok(gallery.includes('XDriveMediaAsyncThumbnail'))
  assert.ok(gallery.includes('XDriveMediaAsyncVideoPoster'))
  assert.ok(gallery.includes('hasRequestedPhotoRange'))
  assert.ok(gallery.includes('showDelayedColdPhotoLoad'))
  assert.ok(gallery.includes('data-xdrive-places-pagination-quiet-status'),
    'keep P49 actual Places pagination slot, not an invented Gallery-prefixed ID')
})
