'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const audit = read('ios/XDriveIOS/NativePhotoWholeLibraryAudit.swift')
const proof = read('ios/XDriveIOS/NativeCurrentPhotoReceiptModel.swift')
const screen = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')

test('current library audit uses exact existing one-photo Owner Node/SHA receipt proof', () => {
  assert.match(proof, /func verifyAndWait\(localIdentifier:/)
  assert.match(proof, /verify\(localIdentifier: localIdentifier, login: login,/)
  assert.match(proof, /await currentWorker\.value/)
  assert.match(proof, /!Task\.isCancelled && currentNodeVerified/)
  assert.match(audit, /proof\.verifyAndWait\(/)
  assert.match(proof, /existingReceiptForCurrentOriginal\(/)
  assert.match(proof, /auth\.verifyNodeReceipt\(/)
})

test('audit is bounded, foreground only, full-permission and PhotoKit-generation fenced', () => {
  assert.match(audit, /static let maximumOriginalsPerBatch = 8/)
  assert.match(audit, /stableWindowStart\(\s*for: self\.checked/)
  assert.match(audit, /scanner\.start\(\s*atOffset: windowStart, requireStableResume: true/)
  assert.match(audit, /while page\.nextOffset <= self\.checked && !page\.finished/)
  assert.match(audit, /page\.items\.dropFirst\(skippedInPage\)\.prefix\(/)
  assert.match(audit, /page\.items\.dropFirst\(skippedInPage\)\.prefix\(\s*XDriveIOSNativePhotoWholeLibraryAuditPolicy\.maximumOriginalsPerBatch/)
  assert.match(audit, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\) == \.authorized/)
  assert.match(audit, /XDriveIOSPhotoKitLibraryEpoch\.matches\(\s*photoToken, as: latest\.token/)
  assert.match(audit, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, requestedOwner\)/)
  assert.match(audit, /\.onChange\(of: login\.owner\)/)
  assert.match(audit, /\.onChange\(of: phase\)/)
  assert.match(audit, /\.onDisappear \{ audit\.reset\(\) \}/)
})

test('whole library completion requires exact total and fresh confirmed Node proof for all assets', () => {
  assert.match(audit, /checked == total &&\s*currentlyVerified == total && unverified == 0/)
  assert.match(audit, /if verified \{ self\.currentVerified \+= 1 \}/)
  assert.match(audit, /else \{ self\.unverified \+= 1 \}/)
  assert.match(audit, /let proof = XDriveIOSNativeCurrentPhotoReceiptModel\(\)/)
  assert.match(audit, /self\.completeAt = Date\(\)/)
  assert.match(audit, /本轮逐项核验已全部通过；仅代表核验期间的原件及云端 Node 状态/)
  assert.match(audit, /扫描进度、部分通过都不是整库备份完成证明/)
  assert.doesNotMatch(audit, /UploadSessionTransport|uploadPrepared|beginCreate|finalize\(|deleteNode|\.settle\(/)
  assert.match(screen, /XDriveIOSNativePhotoWholeLibraryAuditSection\(login: login\)/)
})
