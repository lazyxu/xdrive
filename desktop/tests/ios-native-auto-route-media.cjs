const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname, '..', '..', 'ios', 'XDriveIOS', name), 'utf8')

test('native Files and cloud media never give a signed remote ticket directly to AVPlayer', () => {
  const files = read('NativeFilesViewer.swift')
  const cloud = read('NativeCloudOriginalGallery.swift')
  assert.match(files, /case \.video\(let url\):[\s\S]*?XDriveIOSRoutedMediaLoader\(ticketURL: url\)/)
  assert.match(files, /case \.audio\(let url\):[\s\S]*?XDriveIOSRoutedMediaLoader\(ticketURL: url, isAudio: true\)/)
  assert.doesNotMatch(files, /AVPlayer\(url: url\)|AVPlayerItem\(url: url\)/)
  assert.match(files, /routedMediaLoader\?\.cancelAll\(\)/)
  assert.match(cloud, /let loader = try XDriveIOSRoutedMediaLoader\(ticketURL: url\)/)
  assert.doesNotMatch(cloud, /AVPlayer\(url: url\)/)
  assert.match(cloud, /AVPlayer\(url: live\.files\.motionURL\)/, 'local paired Live motion remains local')
  assert.match(cloud, /routedMediaLoader\?\.cancelAll\(\)/)
})

test('remote AV ranges remain bounded, TLS-pinned, nonredirecting and Owner scoped', () => {
  const source = read('NativeRoutedMediaResource.swift')
  const policy = read('NativeRoutedHTTPRange.swift')
  assert.match(source, /AVAssetResourceLoaderDelegate/)
  assert.match(source, /XDriveIOSAutoRoute\.shared\.canRoute/)
  assert.match(source, /XDriveIOSAutoRoute\.ephemeralConfiguration\(\)/)
  assert.match(source, /session\.bytes\(for: request\)/)
  assert.match(source, /http\.statusCode == 206/)
  assert.match(source, /ByteRange\.parse\(http\.value\(forHTTPHeaderField: "Content-Range"\)\)/)
  assert.match(source, /httpShouldSetCookies = false/)
  assert.match(source, /completionHandler\(nil\)/)
  assert.match(source, /XDriveIOSAutoRouteSafety\.isNetworkFailure\(error\)/)
  assert.match(source, /dataRequest\.respond\(with: buffer\)/)
  assert.doesNotMatch(source, /URLSession\.shared|URLSessionConfiguration\.background|\.data\(for: request\)/)
  assert.match(policy, /candidate\.last - candidate\.first < maximumBytes/)
})
