const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')

test('older Server backup snapshots use a bounded read-only Host-to-Admin pipeline', () => {
  const host = read('scripts/server-control.sh')
  const router = read('internal/api/router.go')
  const api = read('internal/api/admin_backup_snapshot_page.go')
  const shared = read('ui/shared/src/server-backup-admin.ts')
  const panel = read('ui/shared/src/mui/ServerBackupManagementPanel.tsx')
  const pager = read('ui/shared/src/mui/BackupSnapshotIndexPager.tsx')
  const web = read('web/src/App.tsx')
  const webAPI = read('web/src/api.ts')
  const agent = read('cmd/xdrive-agent/desktop_ipc_admin_backups.go')
  const agentRouter = read('cmd/xdrive-agent/desktop_ipc.go')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const renderer = read('desktop/src/renderer/App.tsx')

  assert.match(host, /backup_admin_snapshot_index\(\)/)
  assert.match(host, /xdrive-backup-snapshot-index-v1/)
  assert.match(router, /admin.GET\("\/backups\/snapshots"/)
  assert.match(api, /validBackupSnapshotIndex/)
  assert.match(api, /unverified_identity_only/)
  assert.match(api, /backup_snapshot_index_truncated/)
  assert.match(shared, /readSnapshotIndexPage\?\(/)
  assert.match(panel, /page\.inventory\.total_snapshots > 100/)
  assert.match(panel, /XDriveBackupSnapshotIndexPager/)
  assert.match(pager, /data-xdrive-admin-backup-older-snapshots/)
  assert.match(pager, /const firstOlderOffset = 100/)
  assert.match(pager, /const pageSize = 50/)
  assert.match(pager, /不能从此列表直接恢复或删除/)
  assert.doesNotMatch(pager, /action: 'restore'|action: 'delete'|action: 'prune'/)
  assert.match(webAPI, /\/api\/v1\/admin\/backups\/snapshots\?offset=/)
  assert.match(web, /readSnapshotIndexPage:/)
  assert.match(agent, /boundedAdminBackupSnapshotPageQuery/)
  assert.match(agentRouter, /GET \/v1\/cloud\/admin-backups\/snapshots/)
  assert.match(main, /agent:cloud-admin-backup-snapshots/)
  assert.match(main, /requireDesktopAdminBackups/)
  assert.match(preload, /cloudAdminBackupSnapshotPage:/)
  assert.match(renderer, /readSnapshotIndexPage: async query/)
})
