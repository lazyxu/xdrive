'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root,file),'utf8')

test('Viewer uses actual per-photo EXIF GPS to offer an isolated dynamic map', () => {
  const viewer = read('ui/shared/src/mui/MediaGalleryViewerLocationDialog.tsx')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  assert.match(viewer, /const latitude = item\?\.metadata\.latitude/)
  assert.match(viewer, /const longitude = item\?\.metadata\.longitude/)
  assert.match(viewer, /Number\.isFinite\(latitude\) && Number\.isFinite\(longitude\)/)
  assert.match(viewer, /Math\.abs\(latitude\) <= 90 && Math\.abs\(longitude\) <= 180/)
  assert.match(viewer, /validGPS \?/)
  assert.match(viewer, /onOpenDynamicMap/)
  assert.match(viewer, /打开照片地图/)
  assert.doesNotMatch(viewer, /授权一小时|撤销授权|地图位置隐私授权/)
  assert.match(gallery, /initialNativeCamera=\{baiduNativeCameraSnapshot\}/)
  assert.match(map, /XDriveMediaGalleryBaiduIsolatedPhotoSurface/)
  assert.doesNotMatch(viewer, /MediaGalleryBaiduStaticMap|loadBaiduStaticMap/)
})

test('Owner place samples are not secretly substituted with grid midpoint coordinates', () => {
  const places = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const server = read('internal/api/media_places.go')
  const filters = read('internal/api/media_filters.go')
  assert.match(places, /Number\.isFinite\(selectedPlace\.sample_latitude\)/)
  assert.match(places, /Number\.isFinite\(selectedPlace\.sample_longitude\)/)
  assert.doesNotMatch(places, /selectedPlace\.latitude|selectedPlace\.longitude/)
  assert.match(server, /mediaPlaceValidGPSPredicate/)
  assert.match(filters, /mediaPlaceValidGPSPredicate/)
  assert.doesNotMatch(places, /MediaGalleryBaiduStaticMap|loadStaticMap/)
})
