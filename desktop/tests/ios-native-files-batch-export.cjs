'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const policy = read('ios/XDriveIOS/NativeFilesBatchExportPolicy.swift')
const model = read('ios/XDriveIOS/NativeFilesBatchExport.swift')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const original = read('ios/XDriveIOS/NativeFilesDownloadExport.swift')

test('one verified 64-item Owner page can batch-export only 2-8 actual files, aggregate <= 512 MiB', () => {
  assert.match(policy, /static let maximumFiles = 8/)
  assert.match(policy, /static let maximumAggregateBytes: Int64 = 512 \* 1_048_576/)
  assert.match(policy, /Set\(nodes\.map\(\\\.id\)\)\.count == nodes\.count/)
  assert.match(policy, /node\.parent_id == parentID, node\.type == "file"/)
  assert.match(policy, /total <= maximumAggregateBytes - node\.size/)
  assert.match(browser, /XDriveIOSNativeFilesBatchExportPolicy\.validSelection\(/)
  assert.match(browser, /selectedIDs == Set\(chosenItems\.map\(\\\.id\)\)/)
  assert.match(browser, /native-ios-files-batch-export/)
})

test('batch reuses the precise signed single-file exporter, verifying Owner before and after each download', () => {
  assert.match(original, /struct XDriveIOSNativeFilesExportReader/)
  assert.match(model, /for \(index, node\) in selected\.enumerated\(\)/)
  assert.match(model, /XDriveIOSNativeFilesExportReader\(/)
  assert.match(model, /await login\.verifiedAuthorization\(\)/)
  assert.match(model, /XDriveIOSNativePhotoOwnerScope\.matches\(after\.owner, expected\)/)
  assert.match(original, /guard current == node/)
  assert.match(original, /guard stillCurrent == node/)
  assert.match(original, /session\.download\(/)
  assert.match(model, /staged\.append\(file\)/)
  assert.doesNotMatch(model, /\/api\/v1\/download\/archive|\/api\/v1\/uploads|uploadOnce|WKWebView|document\.cookie/)
})

test('all staged bytes are retired on failure/cancel/Owner navigation, never claim Save to Files', () => {
  assert.match(model, /if !published \{\s*staged\.forEach \{ \$0\.discard\(\) \}/)
  assert.match(model, /prepared\.forEach \{ \$0\.discard\(\) \}/)
  assert.match(model, /cancelCurrentTransfer\(\)/)
  assert.match(model, /task\.cancel\(\)/)
  assert.match(model, /throw CancellationError\(\)/)
  assert.match(browser, /batchExport\.invalidate\(\)/)
  assert.match(browser, /\.sheet\(isPresented: \$showingBatchShare, onDismiss:/)
  assert.match(model, /UIActivityViewController\(activityItems: files, applicationActivities: nil\)/)
  assert.match(model, /尚未保存到 iPhone/)
  assert.doesNotMatch(model, /status = "已保存到|Data\(contentsOf:|UserDefaults/)
})
