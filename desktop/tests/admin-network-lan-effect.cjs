const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')

test('NET-M5-A private-IP TLS effect uses a fixed local CA, not a server Docker apply', () => {
  const host = read('scripts/server-control.sh')
  const api = read('internal/api/admin_caddy_host_status.go')
  const contract = read('internal/api/admin_caddy_lan_local_effect.go')
  const desired = read('internal/api/admin_caddy_https_desired.go')
  const page = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  const evidence = read('ui/shared/src/mui/CaddyPreflightPanel.tsx')
  const shared = read('ui/shared/src/service-dependencies.ts')
  const desktop = read('desktop/src/main/agent_client.cts')
  const service = read('internal/api/admin_service_dependencies.go')
  assert.match(host, /caddy_local_lan_tls_state\(\)/)
  assert.match(host, /caddy_valid_private_lan_ip\(\)/)
  assert.match(host, /docker exec xdrive-caddy cat/)
  assert.match(host, /pki\/authorities\/local\/root\.crt/)
  assert.match(host, /curl -fsS --noproxy '\*' --cacert/)
  assert.match(host, /lan_verified_ip_sha256/)
  assert.match(host, /lan_generation_before/)
  assert.doesNotMatch(host, /curl -k|--insecure|https:\/\/\$domain/)
  assert.match(api, /LANHTTPSConfigured/)
  assert.match(api, /LANVerifiedIPSHA256/)
  assert.match(api, /len\(raw\) > 768/)
  assert.match(contract, /host\.LANVerifiedIPSHA256 == hex\.EncodeToString/)
  assert.match(desired, /caddyLANLocalEffectState\(host, observed, hostLANIP\)/)
  assert.match(shared, /host_lan_tls_state\?:/)
  assert.match(desktop, /host_lan_tls_state\?:/)
  assert.match(page, /data-xdrive-caddy-running-lan-ip/)
  assert.match(evidence, /data-xdrive-caddy-desired-lan-local-match/)
  assert.match(contract, /host\.LANVerifiedIPSHA256 == hex\.EncodeToString/)
  assert.match(service, /declaredLAN/)
  assert.equal(desired.includes('adminStartCaddyApply'), false)
})
