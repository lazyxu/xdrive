const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Desktop snapshot is private, cancellable, journal-only and not Web enabled', () => {
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_snapshot.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_snapshot.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalSnapshotDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')

  assert.match(agent, /localBoundBackupConfig\(scanCtx, sourceID\)/)
  assert.match(agent, /cli\.LocalBoundRules\(scanCtx, sourceID, proof\)/)
  assert.match(agent, /localpush\.LoadRootGrant\(/)
  assert.match(agent, /localpush\.BeginInventoryJournal\(/)
  assert.match(agent, /writer\.Append/)
  assert.match(agent, /writer\.Commit\(stats\)/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /VerifyInventoryJournal\(/)
  assert.match(agent, /MissingInferenceSafe: false/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorMissingFullScans|HashVerifiedInventoryFile/)
  assert.match(ipc, /"device-backup-local-snapshot"/)
  assert.match(ipc, /POST \/v1\/device-backups\/local-snapshot/)
  assert.match(handler, /CloudSaveLocalBoundBackupSnapshot\(r\.Context\(\), sourceID\)/)
  assert.match(handler, /"private, no-store"/)
  assert.match(client, /localBoundBackupSnapshot\(sourceID: number, signal\?: AbortSignal\)/)
  assert.match(client, /195_000, signal/)
  assert.match(main, /localSnapshotRequests\.set\(key, controller\)/)
  assert.match(main, /localSnapshotRequests\.get\(key\)\?\.abort\(\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-snapshot'\)/)
  assert.match(preload, /saveDeviceBackupLocalSnapshot:/)
  assert.match(preload, /cancelDeviceBackupLocalSnapshot:/)
  assert.match(app, /localSnapshot=\{localBackupSnapshot\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(dialog, /crypto\.randomUUID\(\)/)
  assert.match(dialog, /actions\.cancel\(request\.current\)/)
  assert.doesNotMatch(web, /saveDeviceBackupLocalSnapshot|localSnapshot=/)
  const readModel = dto.slice(0, dto.indexOf('// Separate private Agent-only draft projection.'))
  assert.doesNotMatch(readModel, /has_verified_previous|saved_snapshot/)
  assert.doesNotMatch(dialog, /(?:startUpload|triggerSource|cancelSourceRun|deleteSource|createSource)\(/)
})
