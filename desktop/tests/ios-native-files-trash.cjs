'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const screen = read('ios/XDriveIOS/NativeFilesTrash.swift')
const policy = read('ios/XDriveIOS/NativeFilesTrashPolicy.swift')
const router = read('internal/api/router.go')
const server = read('internal/api/history_trash.go')

test('recycle bin is a native Files subroute, never another app tab', () => {
  assert.match(browser, /NavigationLink[\s\S]*?XDriveIOSNativeFilesTrashScreen\(login: login\)/)
  assert.match(browser, /native-ios-files-open-trash/)
  assert.match(screen, /struct XDriveIOSNativeFilesTrashScreen: View/)
  assert.doesNotMatch(screen, /WKWebView|import WebKit|document\.cookie|URLSession\.shared/)
})
test('real Owner-scoped bounded deleted-only Server page uses exact range metadata', () => {
  assert.match(router, /authed\.GET\("\/trash", s\.trashList\)/)
  assert.match(server, /func \(s \*Server\) trashListRange/)
  assert.match(server, /deleted_at IS NOT NULL AND xd_nodes\.trash_root_id = xd_nodes\.id/)
  assert.match(policy, /static let pageSize = XDriveIOSNativeFilesPagePolicy\.pageSize/)
  assert.match(policy, /page\.total_count_included/)
  assert.match(policy, /!\(item\.deleted_at \?\? ""\)\.isEmpty/)
  for (const token of ['"range", value: "true"', '"include_count", value: "true"', '"sort", value:', '"offset", value:', '"limit", value:']) {
    assert.ok(screen.includes(token), 'missing Server range parameter: ' + token)
  }
  assert.match(screen, /login\.verifiedAuthorization\(\)/)
  assert.match(screen, /XDriveIOSNativePhotoOwnerScope\.matches/)
  assert.match(screen, /URLSessionConfiguration\.ephemeral/)
  assert.match(screen, /completionHandler\(nil\)/)
})
test('restore and permanent delete use version fences, correct HTTP receipts and no blind replay', () => {
  assert.match(router, /authed\.POST\("\/trash\/:id\/restore", s\.trashRestore\)/)
  assert.match(router, /authed\.DELETE\("\/trash\/:id", s\.trashDeletePermanently\)/)
  assert.match(server, /root\.Revision != expected/)
  assert.match(server, /errTrashParentUnavailable/)
  assert.match(screen, /verified\.items\.contains\(node\)/)
  assert.match(screen, /forHTTPHeaderField: "If-Match"/)
  assert.match(screen, /method: "POST", revision: node\.revision/)
  assert.match(screen, /method: "DELETE", revision: node\.revision/)
  assert.match(screen, /status: 200, maxBytes: 65_536/)
  assert.match(screen, /status: 204, maxBytes: 0/)
  assert.match(screen, /validRestored\(restored, from: node\)/)
  assert.match(screen, /request\("\/api\/v1\/nodes\/\\\(node\.id\)"\)/)
  assert.match(screen, /不能盲目重试/)
  assert.doesNotMatch(screen, /retry.*POST|retry.*DELETE|DispatchQueue\.main\.asyncAfter/)
})
test('tab owner and background changes invalidate pending read/write and stale deletion intent', () => {
  assert.match(screen, /\.onDisappear \{[\s\S]*?model\.invalidate\(\)[\s\S]*?mutation\.invalidate\(\)/)
  assert.match(screen, /\.onChange\(of: login\.owner\)/)
  assert.match(screen, /\.onChange\(of: phase\)/)
  assert.match(screen, /model\.items\.contains\(item\)/)
  assert.match(screen, /showingDeleteConfirmation = true/)
  assert.match(screen, /pendingDelete = nil/)
  assert.match(screen, /Button\("恢复到原位置"\)/)
  assert.match(screen, /Button\("彻底删除", role: \.destructive\)/)
  assert.match(screen, /busy = false\s*running = nil\s*onConfirmed\(\)/)
  assert.match(screen, /private func reload\(\) \{\s*guard !mutation\.busy else \{ return \}/)
})


test('recycle bin continuously appends verified Server ranges without visible paging buttons', () => {
  assert.doesNotMatch(screen, /Button\("上一页"\)|Button\("下一页"\)/)
  assert.match(screen, /var canLoadMore: Bool/)
  assert.match(screen, /model\.items\.last\?\.id == item\.id/)
  assert.match(screen, /model\.loadMore\(login: login\)/)
  assert.match(screen, /model\.retryMore\(login: login\)/)
  assert.match(screen, /native-ios-files-trash-loading-more/)
  assert.match(screen, /native-ios-files-trash-retry-more/)
  assert.match(screen, /XDriveIOSNativeFilesTrashPolicy\.validAppend\(/)
  assert.match(screen, /self\.loadedIDs\.formUnion\(page\.items\.map\(\\\.id\)\)/)
  assert.match(policy, /alreadyLoadedIDs\.isDisjoint\(with: Set\(next\.items\.map\(\\\.id\)\)\)/)
  assert.match(policy, /next\.offset == alreadyLoadedCount/)
  assert.match(policy, /next\.total_count == total/)
  assert.match(screen, /case \.invalidOwner, \.malformed,/)
  assert.match(screen, /self\.items = \[\]\s*self\.loadedIDs\.removeAll\(\)/)
})

