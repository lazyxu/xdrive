test('native Recently Deleted exposes the same server sort and direction choices as PWA', () => {
  assert.match(server, /case "name", "updated", "size", "type":/)
  assert.match(policy, /static let defaultSort = "name"/)
  assert.match(policy, /static let defaultOrder = "asc"/)
  assert.match(policy, /\["name", "updated", "size", "type"\]\.contains\(sort\)/)
  assert.match(policy, /order == "asc" \|\| order == "desc"/)
  assert.match(screen, /URLQueryItem\(name: "sort", value: sort\)/)
  assert.match(screen, /URLQueryItem\(name: "order", value: order\)/)
  assert.match(screen, /validRange\(page, offset: offset, sort: sort, order: order\)/)
  assert.match(screen, /Picker\("排序方式", selection: \$sort\)[\s\S]*?Text\("名称"\)\.tag\("name"\)[\s\S]*?Text\("删除时间"\)\.tag\("updated"\)[\s\S]*?Text\("大小"\)\.tag\("size"\)[\s\S]*?Text\("类型"\)\.tag\("type"\)/)
  assert.match(screen, /Picker\("排序顺序", selection: \$order\)[\s\S]*?Text\("升序"\)\.tag\("asc"\)[\s\S]*?Text\("降序"\)\.tag\("desc"\)/)
  assert.match(screen, /\.onChange\(of: sort\)[\s\S]*?reload\(\)/)
  assert.match(screen, /\.onChange\(of: order\)[\s\S]*?reload\(\)/)
  assert.match(screen, /model\.loadMore\(login: login, sort: sort, order: order\)/)
  assert.match(screen, /model\.retryMore\(login: login, sort: sort, order: order\)/)
  assert.match(screen, /perform\(action, node: node, offset: offset, sort: sort, order: order\)/)
  assert.match(screen, /node: item, offset: pageOffset, sort: sort, order: order, login: login/)
})
