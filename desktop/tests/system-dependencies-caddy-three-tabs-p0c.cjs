'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')
test('Caddy uses three real top-level views, not the shared accordion on the active Caddy path', () => {
  const parent = read('ui','shared','src','mui','ServiceDependenciesPage.tsx')
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  assert.match(parent, /selectedPage === 'caddy' && selectedItem \? \(/)
  assert.match(parent, /<XDriveCaddyDetailV1/)
  assert.match(parent, /source=\{source\} service=\{selectedItem\}/)
  assert.match(caddy, /data-xdrive-caddy-v1-navigation/)
  for (const name of ['概览','配置','历史']) assert.ok(caddy.includes('label="'+name+'"'))
  assert.match(caddy, /activeTab === 'config'/)
  assert.match(caddy, /activeTab === 'history'/)
  assert.match(caddy, /activeTab === 'verify'/)
  assert.match(caddy, /onTabChange\(next === 'overview' \? 'status' : next\)/)
  // Old verify links must permit manually collapsing evidence rather than
  // leave the button stuck open while tab=verify forces evidenceOpen.
  assert.match(caddy, /if \(activeTab === 'verify'\) \{[\s\S]*?setShowEvidence\(false\)[\s\S]*?onTabChange\('status'\)/)
  assert.match(parent, /navigateTo\(\{ service: 'caddy', tab \}\)/)
  assert.match(parent, /selectedTabs.filter\(\(tab\) => tab !== 'verify'\)/)
  assert.equal(caddy.includes('docker.sock'), false)
  assert.equal(caddy.includes('docker restart'), false)
  assert.equal(caddy.includes('InsecureSkipVerify'), false)
})
test('Caddy trust evidence and target drift never become applied or public WAN proof', () => {
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  assert.match(caddy, /const bad = service\.health_state === 'failed'/)
  assert.doesNotMatch(caddy, /service\.status === 'unavailable'/)
  assert.match(caddy, /网关状态尚未完整确认/)
  assert.match(caddy, /caddy_host_witness_reason/)
  assert.match(caddy, /host_observed === true/)
  assert.match(caddy, /host_lan_tls_state === 'verified'/)
  assert.match(caddy, /typeof config\?\.desired_lan_enabled === 'boolean'/)
  assert.match(caddy, /typeof config\?\.desired_lan_ip === 'string'/)
  assert.match(caddy, /desired_lan_enabled === false/)
  assert.doesNotMatch(caddy, /desired_lan_enabled !== true/)
  // Unknown old-client LAN target fields must not be promoted to "off".
  assert.match(caddy, /hasKnownLANTarget && Boolean\(config\?\.host_lan_ip\)/)
  assert.match(caddy, /desired_lan_ip !== config\?\.host_lan_ip/)
  assert.match(caddy, /data-xdrive-caddy-v1-runtime-desired-drift/)
  assert.match(caddy, /data-xdrive-caddy-v1-technical-evidence/)
  assert.match(caddy, /公网上实际可达|此处未证明公网可达/)
  assert.match(caddy, /当前设备信任 Caddy Local CA/)
  assert.match(caddy, /8443/)
  assert.match(caddy, /caddy_local_domain_https_state === 'verified'/)
  assert.match(caddy, /<XDriveCaddyPreflightPanel source=\{source\}/)
  assert.match(caddy, /七项|独立证据/)
})
test('Caddy config draft stays mounted across same-service views, AliDNS plaintext hides and history is lazy', () => {
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  const alidns = read('ui','shared','src','mui','CaddyAliDNSPanel.tsx')
  const editor = read('ui','shared','src','mui','CaddyHTTPSDesiredPanel.tsx')
  assert.match(caddy, /visitedConfig \|\| screen === 'config'/)
  assert.match(caddy, /hidden=\{screen !== 'config'\}/)
  assert.match(caddy, /active=\{screen === 'config'\}/)
  assert.match(caddy, /\{screen === 'history' && \(/)
  assert.match(caddy, /section="history"/)
  assert.match(caddy, /data-xdrive-caddy-v1-history-draft-fence/)
  assert.match(caddy, /component="fieldset" disabled=\{hasUnsavedEdits\}/)
  assert.match(caddy, /onDirtyChange=\{onHTTPSDirtyChange\}/)
  assert.match(caddy, /onDirtyChange=\{onAliDNSDirtyChange\}/)
  assert.match(alidns, /if \(!active\) hide\(\)/)
  assert.match(alidns, /Math.min\(30, shown.expires_in_seconds\)/)
  assert.match(alidns, /manageOpen &&/)
  assert.match(editor, /data-xdrive-caddy-https-readonly-summary/)
  assert.doesNotMatch(editor, /config\.host_lan_tls_state/)
})
