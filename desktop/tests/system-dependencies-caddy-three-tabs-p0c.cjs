'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Caddy v1.2 uses a flat single page; old verify/history links resolve to visible anchors', () => {
  const parent = read('ui','shared','src','mui','ServiceDependenciesPage.tsx')
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  assert.match(parent, /selectedPage === 'caddy' && selectedItem \? \(/)
  assert.match(parent, /<XDriveCaddyDetailV1/)
  assert.match(caddy, /data-xdrive-caddy-single-page="true"/)
  for (const anchor of ['caddy-v1-overview', 'caddy-v1-config', 'caddy-v1-evidence'])
    assert.ok(caddy.includes(anchor), anchor)
  assert.match(caddy, /activeTab === 'verify' \? 'caddy-v1-evidence'/)
  assert.match(caddy, /activeTab === 'config' \|\| activeTab === 'history' \? 'caddy-v1-config'/)
  assert.match(caddy, /scrollIntoView\(\{ block: 'start', behavior: 'auto' \}\)/)
  for (const forbidden of [
    'historyOpen', 'showHistory', 'caddy-v1-history', 'XDriveCaddyHostBaselinePreviewPanel',
    'data-xdrive-caddy-v1-runtime-desired-drift', 'showEvidence', 'Accordion', '<Tabs', '<Tab ',
  ]) assert.equal(caddy.includes(forbidden), false, forbidden)
  // Other services retain their own audit history. Only Caddy UI removes it.
  assert.match(parent, /const historyExpanded = selectedTabs.includes\('history'\)/)
})

test('Caddy running status is one conclusion, not repeated unknown or misleading applied/WAN badges', () => {
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  const https = read('ui','shared','src','mui','CaddyHTTPSDesiredPanel.tsx')
  assert.match(caddy, /service\.health_state === 'failed'/)
  assert.match(caddy, /网关运行正常/)
  assert.match(caddy, /onRefreshStatus\(\)/)
  assert.doesNotMatch(caddy, /公网实际可达：未验证|当前设备信任 Caddy Local CA|生效未确认|管理目标已保存，运行另验/)
  assert.doesNotMatch(caddy, /配置历史|运行与目标配置存在差异|data-xdrive-caddy-v1-runtime-desired-drift/)
  assert.match(https, /config\.host_observed && config\.host_lan_configured === true/)
  assert.match(https, /config\.host_lan_tls_state === 'verified'/)
  assert.match(https, /config\.host_https_configured === true/)
  assert.match(https, /config\.host_tls_state === 'verified'/)
  assert.match(https, /data-xdrive-caddy-lan-runtime/)
  assert.match(https, /data-xdrive-caddy-domain-runtime/)
  assert.doesNotMatch(https, /生效待核验|本机 TLS 验证不等于公网 HTTPS 可访问/)
})

test('Caddy flat editor preserves atomic Save, manual checks, and credential disclosure safety', () => {
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  const alidns = read('ui','shared','src','mui','CaddyAliDNSPanel.tsx')
  const https = read('ui','shared','src','mui','CaddyHTTPSDesiredPanel.tsx')
  const preflight = read('ui','shared','src','mui','CaddyPreflightPanel.tsx')
  assert.match(caddy, /<XDriveCaddyHTTPSDesiredPanel source=\{source\} refreshID=\{atomicRefreshID\}/)
  assert.match(caddy, /inlineEdit atomicMode atomicSaving=\{savingAtomic\} onAtomicDraft=\{setHTTPSDraft\}/)
  assert.match(caddy, /<XDriveCaddyAliDNSPanel source=\{source\} refreshID=\{atomicRefreshID\}/)
  assert.match(caddy, /atomicMode atomicSaving=\{savingAtomic\} onAtomicDraft=\{setAliDraft\}/)
  assert.match(caddy, /<XDriveCaddyPreflightPanel source=\{source\}/)
  assert.match(caddy, /source\.saveCaddyConfiguration\(input\)/)
  assert.match(caddy, /result\.host_applied !== false/)
  assert.match(caddy, /result\.apply_supported !== false/)
  assert.match(caddy, /data-xdrive-caddy-v1-deploy-gate/)
  assert.doesNotMatch(caddy, /applyCaddy|restartCaddy|source\.deploy/)
  assert.match(https, /\(lanEnabled \|\| enabled\)/)
  assert.doesNotMatch(alidns, /manageOpen|data-xdrive-caddy-alidns-manage/)
  assert.match(alidns, /type="password" autoComplete="new-password"/)
  assert.match(alidns, /Math\.min\(30, shown\.expires_in_seconds\)/)
  assert.match(alidns, /document\.addEventListener\('visibilitychange'/)
  assert.match(alidns, /window\.addEventListener\('blur'/)
  assert.match(alidns, /active && shown &&/)
  assert.match(preflight, /onClick=\{\(\) => \{ void check\(\) \}\}/)
  assert.doesNotMatch(preflight, /useEffect\(\(\) => \{[\s\S]*?void check\(\)/)
  assert.doesNotMatch(preflight, /applyCaddy|restartCaddy|InsecureSkipVerify/)
})
