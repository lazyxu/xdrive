'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')
test('Caddy v1.1 uses one page, not tabs, and legacy deep links anchor in it', () => {
  const parent = read('ui','shared','src','mui','ServiceDependenciesPage.tsx')
  const caddy = read('ui','shared','src','mui','CaddyDetailV1.tsx')
  assert.match(parent, /selectedPage === 'caddy' && selectedItem \? \(/)
  assert.match(parent, /<XDriveCaddyDetailV1/)
  assert.match(parent, /navigateTo\(\{ service: 'caddy', tab \}\)/)
  assert.match(caddy, /data-xdrive-caddy-single-page="true"/)
  assert.doesNotMatch(caddy, /<Tabs\b|<Tab\b|data-xdrive-caddy-v1-navigation/)
  for (const id of ['caddy-v1-overview','caddy-v1-evidence','caddy-v1-config','caddy-v1-history']) assert.ok(caddy.includes(id))
  for (const tab of ['verify','config','history']) assert.ok(caddy.includes("activeTab === '"+tab+"'"))
  assert.match(caddy, /scrollIntoView\(\{ block: 'start', behavior: 'auto' \}\)/)
  assert.match(caddy, /if \(activeTab === 'verify'\) \{[\s\S]*?onTabChange\('status'\)/)
  assert.match(caddy, /if \(activeTab === 'history'\) \{[\s\S]*?onTabChange\('status'\)/)
  for (const forbidden of ['docker.sock','docker restart','InsecureSkipVerify']) assert.equal(caddy.includes(forbidden),false)
})
