'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (pathName) => fs.readFileSync(path.join(root, pathName), 'utf8')

test('v1.1 atomic Caddy desired save has one Web and Desktop request with dual CAS', () => {
  const api = read('web/src/api.ts')
  const web = read('web/src/App.tsx')
  const shared = read('ui/shared/src/service-dependencies.ts')
  const renderer = read('desktop/src/renderer/App.tsx')
  const global = read('desktop/src/renderer/global.d.ts')
  const preload = read('desktop/src/preload/index.cts')
  const main = read('desktop/src/main/index.cts')
  const client = read('desktop/src/main/agent_client.cts')

  assert.match(shared, /export type XDriveCaddyConfigurationSaveInput/)
  for (const field of ['https_revision','alidns_revision','lan_enabled','lan_ip','access_key_secret']) {
    assert.ok(shared.includes(field), field)
  }
  assert.match(shared, /host_applied: false/)
  assert.match(shared, /apply_supported: false/)
  assert.match(api, /adminSaveCaddyConfiguration\(input:[\s\S]*?'\/api\/v1\/admin\/services\/caddy\/config'/)
  assert.match(web, /saveCaddyConfiguration: \(input:[\s\S]*?api\.adminSaveCaddyConfiguration\(input\)/)
  assert.match(renderer, /saveCaddyConfiguration: async \(input:[\s\S]*?agent\.cloudSaveAdminCaddyConfiguration\(input\)/)
  assert.match(global, /cloudSaveAdminCaddyConfiguration:/)
  assert.match(preload, /agent:cloud-save-admin-caddy-config/)
  assert.match(main, /agent:cloud-save-admin-caddy-config/)
  assert.match(main, /requireAgentCapability\(hello, 'admin-services'\)/)
  assert.match(main, /Both Caddy revisions and at least one edited group/)
  assert.match(main, /lan_enabled: https\.lan_enabled, lan_ip: https\.lan_ip/)
  assert.match(main, /alidns\.action === 'clear'/)
  assert.match(client, /PUT', '\/v1\/cloud\/admin-caddy\/config', input/)
  const first = client.indexOf('cloudSaveAdminCaddyConfiguration(input:')
  const last = client.indexOf('cloudAdminCaddyHTTPSRevisions()', first)
  assert.ok(first >= 0 && last > first)
  assert.doesNotMatch(client.slice(first, last), /cloudSetAdminCaddyAliDNS|cloudSetAdminCaddyHTTPS/)
})

test('Go Agent transport enforces JSON bounds and never applies Caddy', () => {
  const client = read('internal/client/admin_caddy_configuration.go')
  const agent = read('cmd/xdrive-agent/cloud_caddy_configuration.go')
  const ipc = read('cmd/xdrive-agent/desktop_ipc_admin_caddy_configuration.go')
  const mux = read('cmd/xdrive-agent/desktop_ipc.go')
  assert.match(client, /http\.MethodPut, "\/api\/v1\/admin\/services\/caddy\/config"/)
  assert.match(agent, /SaveAdminCaddyConfiguration\(ctx, input\)/)
  assert.match(mux, /PUT \/v1\/cloud\/admin-caddy\/config/)
  assert.match(ipc, /DisallowUnknownFields\(\)/)
  assert.match(ipc, /http\.MaxBytesReader\(w, r\.Body, 2048\)/)
  assert.match(ipc, /input\.HTTPSRevision == nil \|\| input\.AliDNSRevision == nil/)
  assert.match(ipc, /!\*cfg\.Enabled && !\*cfg\.LANEnabled/)
  assert.match(ipc, /validDesktopCaddyAliDNSPair/)
  assert.match(ipc, /http\.StatusNotImplemented/)
  assert.match(ipc, /Cache-Control", "no-store"/)
  for (const candidate of [client, agent, ipc]) {
    assert.doesNotMatch(candidate, /docker\.sock|docker restart|exec\.Command|HostApply\(/i)
  }
})
