const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Own Desktop raw ignore rules use exact Root proof; other desktops/Web stay redacted', () => {
  const router = read('internal', 'api', 'router.go')
  const server = read('internal', 'api', 'local_source_rules.go')
  const source = read('internal', 'api', 'sources.go')
  const client = read('internal', 'client', 'local_bound_rules.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_rules.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_rules.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalRulesDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  const safeDTO = read('ui', 'shared', 'src', 'device-backups.ts')

  assert.match(router, /GET\("\/sources\/:id\/local-rules", s\.requireLocalSourceExecutor\(\), s\.getLocalSourceIgnoreRules\)/)
  assert.match(server, /requireLocalSourceProofTx\(tx, c, id, "", false\)/)
  assert.match(server, /localSourceExecutorContextKey/)
  assert.match(server, /Cache-Control", "private, no-store"/)
  assert.match(source, /dto\.IgnoreRules = ""/)
  assert.match(source, /if \*req\.IgnoreRules != current\.IgnoreRules \{\s*resetMirrorEvidence = true/)
  for (const header of ['X-XDrive-Device-ID', 'X-XDrive-Device-Token',
    'X-XDrive-Local-Root-ID', 'X-XDrive-Local-Root-Fingerprint']) {
    assert.ok(client.includes(header), 'missing private Root proof header ' + header)
  }
  assert.match(client, /UpdateSourceInput\{IgnoreRules: &rules\}/)
  assert.match(agent, /localBoundBackupConfig\(ctx, sourceID\)/)
  assert.match(agent, /cli\.LocalBoundRules\(ctx, sourceID, proof\)/)
  assert.match(agent, /sourcepkg\.CompileIgnoreRules\(rules\)/)
  assert.doesNotMatch(agent, /localpush\.EnsureDevice\(/)
  assert.match(ipc, /"device-backup-local-rules"/)
  assert.match(handler, /decodeDesktopIPCJSONLimit\(w, r, &input,/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-rules'\)/)
  assert.match(preload, /getDeviceBackupLocalRules:/)
  assert.match(preload, /setDeviceBackupLocalRules:/)
  assert.match(app, /localRules=\{localBackupRules\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(dialog, /actions\.update\(sourceID, loaded\.revision, rules\)/)
  assert.doesNotMatch(web, /localRules=/)
  assert.doesNotMatch(web, /getDeviceBackupLocalRules/)
  assert.doesNotMatch(safeDTO.slice(0, safeDTO.indexOf('export interface XDriveLocalBoundBackupRules')), /ignore_rules/)
  assert.doesNotMatch(dialog, /(?:triggerSource|startUpload|cancelSourceRun|deleteSource)\(/)
})
