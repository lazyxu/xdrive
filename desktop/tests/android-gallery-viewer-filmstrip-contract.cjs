'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = relative => fs.readFileSync(path.join(__dirname, '../..', relative), 'utf8')

test('Android Gallery filmstrip is a bounded Viewer-only child of the real photo/video host', () => {
  const app = read('android/app/src/main/java/com/tfluid/xdrive/DriveApp.kt')
  const viewer = read('android/app/src/main/java/com/tfluid/xdrive/GalleryViewerFilmstrip.kt')
  const policy = read('android/app/src/main/java/com/tfluid/xdrive/GalleryViewerFilmstripPolicy.kt')
  const owner = read('android/app/src/main/java/com/tfluid/xdrive/DriveController.kt')
  assert.match(app, /GalleryViewerFilmstrip\([\s\S]*?active = photo,[\s\S]*?loaded = state\.galleryItems/)
  assert.match(app, /Box\(Modifier\.weight\(1f\)\.fillMaxWidth\(\)\)/)
  assert.match(app, /GalleryVideoPlayer\(photo, controller, galleryThumbnails\)/)
  assert.match(app, /GalleryPhotoViewer\(photo, controller, galleryThumbnails\)/)
  assert.match(viewer, /galleryViewerFilmstripWindow\(loaded\.size, index\)/)
  assert.match(viewer, /thumbnails\.get\(item\.node\.id\.toString\(\)/)
  assert.doesNotMatch(viewer, /galleryThumbnail\(|galleryImageBytes\(|galleryVideoPlayback\(|Media3|http[s]?:|openGalleryViewer\(/)
  assert.match(policy, /GALLERY_VIEWER_FILMSTRIP_MAX_TILES = 9/)
  assert.match(owner, /expectedEpoch == galleryViewerEpoch/)
  assert.match(owner, /galleryViewerFilmstripSelectionAllowed\(/)
  assert.match(owner, /cancelGalleryViewerPage\(\)[\s\S]*?closeActiveVideoPlayback\(\)[\s\S]*?galleryViewerEpoch\+\+/)
  assert.match(owner, /current\.viewerReturnToFiles/)
})
