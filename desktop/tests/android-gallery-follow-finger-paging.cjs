'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const cloud = read('android/app/src/main/java/com/tfluid/xdrive/GalleryPhotoViewer.kt')
const local = read('android/app/src/main/java/com/tfluid/xdrive/NativeLocalMediaStoreGallery.kt')
const gate = read('android/app/src/main/java/com/tfluid/xdrive/GalleryViewerSwipeGate.kt')

test('Cloud Gallery uses continuous finger-follow translation before its Owner-scoped shift', () => {
  assert.match(cloud, /awaitPointerEvent\(PointerEventPass\.Initial\)/)
  assert.match(cloud, /galleryPhotoFingerDrag\(/)
  assert.match(cloud, /fingerTracking = true\s+swipeX = offset/)
  assert.match(cloud, /translationX = pan\.x \+ if \(zoom <= 1\.001f\) visualSwipeX else 0f/)
  assert.match(cloud, /swipeX = if \(direction > 0\) -width else width/)
  assert.match(cloud, /delay\(150\)/)
  assert.match(cloud, /controller\.state\.value\.galleryViewer == photo/)
  assert.match(cloud, /liveSwipeFence\.mayPreviewFingerDrag\(\)/)
  assert.match(cloud, /liveSwipeFence\.mayShift\(/)
})

test('Android MediaStore still Viewer snaps back on cancel and only shifts verified loaded neighbors', () => {
  assert.match(local, /detectHorizontalDragGestures/)
  assert.match(local, /galleryPhotoFingerDrag\(/)
  assert.match(local, /onDragCancel = \{\s*dragging = false\s*slideTarget = 0f/)
  assert.match(local, /visualOffset by animateFloatAsState/)
  assert.match(local, /translationX = visualOffset/)
  assert.match(local, /currentKey == mediaKey/)
  assert.match(local, /nativeLocalViewerSwipeDirection\(/)
  assert.match(gate, /neighborAvailable/)
  assert.match(gate, /deltaX \* 0\.18f/)
  assert.match(gate, /!singlePointer \|\| !atDefaultZoom/)
})
