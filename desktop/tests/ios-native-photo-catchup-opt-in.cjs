'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = filename => fs.readFileSync(path.join(root, filename), 'utf8')
const policy = read('ios/XDriveIOS/PhotoAutoSchedulePolicy.swift')
const schedule = read('ios/XDriveIOS/PhotoAutoScheduleStore.swift')
const screen = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')

test('catch-up is never silently enabled for an old or ordinary Owner schedule', () => {
  assert.match(schedule, /var catchUpWhenBehind: Bool\? = nil/)
  assert.match(schedule, /catchUpWhenBehind: existing\?\.catchUpWhenBehind/)
  assert.match(schedule, /if state\.catchUpWhenBehind == true/)
  assert.match(schedule, /guard var state = status\(owner: owner\), state\.enabled/)
  assert.match(schedule, /\(!enabled \|\| !state\.pausedForReview\)/)
  assert.match(schedule, /state\.nextDueAt = enabled/)
  assert.match(schedule, /: max\(state\.nextDueAt, regularDue\)/)
})

test('only a verified, explicitly consented foreground Owner can accelerate', () => {
  assert.match(screen, /confirmationDialog\("允许当前账户加速积压备份？"/)
  assert.match(screen, /native-ios-photos-catchup-enable/)
  assert.match(screen, /native-ios-photos-catchup-disable/)
  assert.match(screen, /let selected = catchUpConsentOwner/)
  assert.match(screen, /let proof = try await login\.verifiedAuthorization\(\)/)
  assert.match(screen, /XDriveIOSNativePhotoOwnerScope\.matches\(proof\.owner, selected\)/)
  assert.match(screen, /localStopGeneration == stopVersion/)
  assert.match(screen, /phase == \.active/)
  assert.match(screen, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(screen, /setCatchUp\(owner: selected, enabled: true\)/)
  assert.match(screen, /setCatchUp\(owner: selected, enabled: false\)/)
  assert.equal(screen.split('showCatchUpConsent = false').length - 1, 3)
})

test('one-minute cooldown is bounded and never bypasses uncertain ACK or epoch checks', () => {
  assert.match(policy, /static let catchUpCooldown: TimeInterval = 60/)
  assert.match(policy, /guard !needsReview, libraryUnchanged/)
  assert.match(policy, /uploaded <= scanned/)
  assert.match(policy, /followingWindow != 0 && followingWindow != currentWindow/)
  assert.match(schedule, /currentWindow: completedWindow, followingWindow: state\.windowIndex/)
  assert.match(schedule, /needsReview: pending,/)
  assert.match(schedule, /libraryUnchanged: unchanged/)
  assert.doesNotMatch(schedule, /UploadSessionTransport|WKWebView|newUploadWriter/)
  assert.doesNotMatch(screen, /UploadSessionTransport|WKWebView/)
})
