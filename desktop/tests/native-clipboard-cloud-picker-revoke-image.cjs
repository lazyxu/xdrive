  assert.match(ios,/XDriveIOSNativeClipboardCloudPicker\(/)
  assert.match(ios,/private struct XDriveIOSNativeClipboardCloudPicker: View/)
  assert.match(ios,/XDriveIOSNativeFilesReader\(/)
  assert.match(ios,/\.children\(parentID: requestedFolder, offset: requestedOffset,/)
  assert.match(ios,/sort: "name", order: "asc"/)
  assert.match(ios,/result\.offset == requestedOffset, result\.items\.count <= 64/)
  assert.match(ios,/Set\(result\.items\.map\(\\\.id\)\)\.count == result\.items\.count/)
  assert.match(ios,/result\.items\.allSatisfy\(\{ \$0\.id > 0 && \$0\.parent_id == requestedFolder \}\)/)
  assert.match(ios,/XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, openedOwner\)/)
  assert.match(ios,/reader\.referencedFile\(nodeID: selected\.id\)/)
  assert.match(ios,/current\.revision == selected\.revision/)
  assert.match(ios,/current\.parent_id == selected\.parent_id/)
  assert.match(ios,/current\.name == selected\.name, current\.size == selected\.size/)
  assert.match(ios,/\.onDisappear \{ requestID = UUID\(\) \}/)
  assert.match(ios,/TextField\("已核验的云端文件 Node", text: \$referenceNodeID\)[\s\S]*?\.disabled\(true\)/)
