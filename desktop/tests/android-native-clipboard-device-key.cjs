'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const controller=read('android/app/src/main/java/com/tfluid/xdrive/DriveController.kt')
const api=read('android/core/src/main/kotlin/com/tfluid/xdrive/core/XDriveApi.kt')
const screen=read('android/app/src/main/java/com/tfluid/xdrive/NativeClipboardScreens.kt')

test('Android recipient authorization uses existing enrolled identity without E2EE key creation',()=>{
  assert.match(controller,/service\.clipboardEnrollRecipient\(token, existing\.second\)/)
  assert.match(controller,/AndroidPhotoDeviceCredentialStore\(context\)\.verifyExisting/)
  assert.match(controller,/NativeClipboardRecipient\(existing\.second\)/)
  assert.doesNotMatch(controller,/AndroidClipboardDeviceKeyStore|XDriveClipboardTargetCrypto|XDriveClipboardCrypto/)
  assert.doesNotMatch(screen,/PasswordVisualTransformation|XDriveClipboardTargetCrypto|XDriveClipboardCrypto|AES\/GCM/)
  assert.equal(fs.existsSync(path.join(root,'android/app/src/main/java/com/tfluid/xdrive/AndroidClipboardDeviceKeyStore.kt')),false)
})
test('Android plain targeted message still binds Owner, Node and device UUID',()=>{
  assert.match(api,/data class XDriveClipboardWrite\(/)
  assert.match(api,/content == "asset:\$nodeID"/)
  assert.match(api,/targetDeviceID != null && nodeID > 0/)
  assert.match(api,/clipboardListForDevice/)
  assert.match(api,/deviceIdentity = enrolled/)
  assert.match(api,/values = emptyMap\(\), deviceIdentity = enrolled/)
})