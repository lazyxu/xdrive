'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const policy = read('ios/XDriveIOS/NativeCurrentPhotoReceiptPolicy.swift')
const model = read('ios/XDriveIOS/NativeCurrentPhotoReceiptModel.swift')
const ledger = read('ios/XDriveIOS/PhotoSyncEncryptedLedger.swift')
const screen = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')

test('one selected original is checked against exact current Owner/Node and source SHA, not historic counts', () => {
  assert.match(screen, /PhotosPicker\(selection: \$selectedOriginalToVerify/)
  assert.match(screen, /item\?\.itemIdentifier/)
  assert.match(screen, /Section\("逐照片当前云端原件核验"\)/)
  assert.match(screen, /Toggle\("核验时允许按需下载 iCloud 原件"/)
  assert.match(screen, /originalProof\.verify\(/)
  assert.match(screen, /originalProof\.currentNodeVerified/)
  assert.match(screen, /originalProof\.verifiedAt/)
  assert.match(screen, /原件 SHA-256/)
  assert.match(screen, /Live Photo 双资源 ZIP 暂不支持单项核验/)
  assert.match(model, /login\.verifiedAuthorization\(\)/)
  assert.match(model, /\.existingLocalScope\(owner: owner\)/)
  assert.match(model, /\.localScopeAndTag\(owner: owner, localIdentifier: localIdentifier\)/)
  assert.match(model, /XDrivePhotoKitOriginalExporter\.stage\(/)
  assert.match(model, /allowICloudDownload: allowICloudOriginals/)
  assert.match(model, /let sha256 = try Self\.hashOriginal\(original\)/)
  assert.match(model, /XDriveIOSNativeCurrentPhotoReceiptPolicy\.destinationName\(/)
  assert.match(model, /\.existingReceiptForCurrentOriginal\(/)
  assert.match(model, /receipt\.state == \.confirmed/)
  assert.match(model, /try await auth\.verifyNodeReceipt\(/)
  assert.match(model, /XDriveIOSNativePhotoProofStamp\.current\(localIdentifier\) == stamp/)
  assert.match(model, /canPublishCurrentProof\(/)
  assert.match(model, /self\.currentNodeVerified = true/)
  assert.match(model, /PHPhotoLibrary\.shared\(\)\.unregisterChangeObserver\(observer\)/)
  assert.doesNotMatch(model, /uploadPrepared|beginCreate|beginFinalize|performChanges|recordSession/)
})

test('encrypted Owner ledger exact lookup never creates Keychain identity or backup operations', () => {
  const start = ledger.indexOf('func existingReceiptForCurrentOriginal(')
  const end = ledger.indexOf('/// Report the exact number of potentially committed', start)
  assert.ok(start >= 0 && end > start)
  const getter = ledger.slice(start, end)
  assert.match(getter, /guard let key = try existingEncryptionKeyForReadOnly\(\)/)
  assert.match(getter, /let legacy = try read\(scope: scope, key: key\)\.operations/)
  assert.match(getter, /availableShardPrefixes\(scope: scope\)/)
  assert.match(getter, /legacyIDs\.contains\(item\.id\)/)
  assert.match(getter, /legacyFingerprints\.contains\(item\.assetFingerprint\)/)
  assert.match(getter, /item\.destinationParentID == scope\.rootNodeID/)
  assert.match(getter, /item\.sha256 == sha256/)
  assert.match(getter, /SecItemCopyMatching\(query as CFDictionary, &raw\)/)
  assert.match(getter, /if status == errSecItemNotFound \{ return nil \}/)
  assert.doesNotMatch(getter, /SecItemAdd|ledger\.prepare|beginCreate|writeShard|write\(scope|encryptionKey\(\)/)
})

test('proof policy does not mistake a matching local receipt for remotely verified completion', () => {
  assert.match(policy, /static func destinationName\(/)
  assert.match(policy, /"-xios-" \+ tag \+ "-" \+ String\(sha256\.prefix\(12\)\)/)
  assert.match(policy, /static func canVerifySingleOriginal\(kind: String, isLive: Bool\)/)
  assert.match(policy, /kind == "image" && !isLive/)
  assert.match(policy, /static func canPublishCurrentProof\(/)
  assert.match(policy, /ownerNodeReadbackSucceeded && sourceStillSame/)
  assert.doesNotMatch(policy, /URLSession|UploadSession|PHAsset|import Photos|import Security/)
  assert.match(screen, /此结果仅代表核验时刻，不能据此宣布全部照片已备份/)
  assert.match(screen, /\.onDisappear \{[\s\S]*?originalProof\.cancel\(\)/)
  assert.match(screen, /\.onChange\(of: login\.owner\) \{ _ in[\s\S]*?originalProof\.cancel\(\)/)
})
