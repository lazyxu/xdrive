const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')
const panel = read('ui', 'shared', 'src', 'mui', 'SyncActivityPanel.tsx')
const task = read('ui', 'shared', 'src', 'mui', 'TaskCenterPage.tsx')
const main = read('desktop', 'src', 'main', 'index.cts')
const client = read('desktop', 'src', 'main', 'agent_client.cts')
const preload = read('desktop', 'src', 'preload', 'index.cts')
const renderer = read('desktop', 'src', 'renderer', 'App.tsx')
const go = read('cmd', 'xdrive-agent', 'desktop_ipc_sync_activity.go')

test('Windows history has one shared task entry and never invents legacy results', () => {
  assert.match(task, /<XDriveSyncActivityPanel/)
  assert.match(panel, /旧版本同步不会补造历史/)
  assert.match(panel, /未记录的文件不代表没有变化/)
  assert.match(panel, /run\.detail_complete && run\.outcome === 'no_change'/)
  assert.match(panel, /data-xdrive-sync-run-id/)
  assert.match(panel, /ITEM_PAGE_SIZE = 50/)
  assert.match(panel, /PAGE_SIZE = 20/)
})
test('Agent and Electron use one lossless timestamp cursor through every layer', () => {
  assert.match(go, /strconv\.FormatInt\(tail\.StartedAt\.UnixNano\(\),10\)/)
  assert.match(go, /strconv\.FormatInt\(tail\.AppliedAt\.UnixNano\(\),10\)/)
  assert.match(panel, /before_started_at: string/)
  assert.match(panel, /before_applied_at: string/)
  assert.match(client, /before_started_at: string/)
  assert.match(main, /validat(ed|ing)SyncCursor/)
  assert.match(preload, /agent:get-sync-run-items/)
})
test('Task history is gated on verified Windows capability and identity scope', () => {
  assert.match(main, /requireAgentCapability\(hello, 'sync-activity-history'\)/)
  assert.match(renderer, /capabilities\.includes\('sync-activity-history'\)/)
  assert.match(renderer, /syncActivitySessionKey:/)
  assert.match(task, /key=\{syncActivitySessionKey\}/)
})

test('metadata-only actions never pretend to download original file bytes', () => {
  assert.match(panel, /item.direction === 'upload' \|\| item.direction === 'download'/)
  assert.match(panel, /无网络传输/)
  assert.match(panel, /网络字节未采集/)
})
