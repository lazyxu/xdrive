const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname,'../..')
const read = name => fs.readFileSync(path.join(root,name),'utf8')

function firstMatchMinHeight(code,marker) {
  const i=code.indexOf(marker)
  assert.ok(i>0,'missing real page marker: '+marker)
  const snippet=code.slice(i,i+220)
  const match=snippet.match(/minHeight: (\d+)/)
  assert.ok(match,'missing stable minimum height on '+marker)
  return Number(match[1])
}

test('P65 shared FileExplorer cold and truly accepted empty keep identical geometry',()=>{
  const file=read('ui/shared/src/mui/FileExplorer.tsx')
  const web=read('web/src/WebFileExplorer.tsx')
  const desktop=read('desktop/src/renderer/DesktopFileExplorer.tsx')
  assert.equal(firstMatchMinHeight(file,'data-xdrive-file-explorer-cold-first-range'),180)
  assert.equal(firstMatchMinHeight(file,'data-xdrive-file-explorer-verified-empty'),180)
  assert.equal(firstMatchMinHeight(file,'data-xdrive-file-explorer-unverified-first-read'),180)
  assert.equal(firstMatchMinHeight(file,'data-xdrive-file-explorer-empty-read-error'),180)
  const start=file.indexOf(') : logicalItemCount === 0 ? (',file.indexOf('data-xdrive-file-explorer-cold-first-range'))
  const end=file.indexOf(") : viewMode === 'details' ? (",start)
  assert.ok(start>0&&end>start)
  const accepted=file.slice(start,end)
  assert.ok(accepted.includes('data-xdrive-file-explorer-verified-empty'))
  assert.ok(accepted.includes('<XDriveStatePanel variant="plain" message={emptyMessage} />'))
  assert.equal(accepted.includes('loading message='),false)
  for(const [name,source]of [['Web',web],['Desktop',desktop]]) {
    assert.ok(source.includes('<XDriveFileExplorer'),name+' must retain shared page')
    assert.ok(source.includes('virtualCollection='),name+' must retain sparse Range')
  }
  assert.ok(file.includes('keepAcceptedEmpty'))
  assert.ok(file.includes('data-xdrive-file-explorer-empty-read-error'))
})

test('P65 shared Gallery cold, authorized-empty and error have equal minimum height',()=>{
  const gallery=read('ui/shared/src/mui/MediaGallery.tsx')
  const cold=firstMatchMinHeight(gallery,'data-xdrive-gallery-cold-pending')
  const empty=firstMatchMinHeight(gallery,'data-xdrive-gallery-empty')
  const failed=firstMatchMinHeight(gallery,'data-xdrive-gallery-load-error')
  assert.equal(cold,220)
  assert.equal(empty,cold,'an accepted empty first Range must not shrink the photo wall')
  assert.equal(failed,cold,'a failed first Range must not shrink the photo wall')
  assert.ok(gallery.includes('aria-busy={loading || !hasRequestedPhotoRange || undefined}'))
  assert.ok(gallery.includes('(!hasRequestedPhotoRange && logicalItemCount === 0)'))
  assert.ok(gallery.includes('const keepAcceptedEmpty = hasRequestedPhotoRange &&'))
  assert.ok(gallery.includes("data-xdrive-gallery-photo-wall"))
  assert.ok(gallery.includes('XDriveMediaAsyncThumbnail'))
  assert.ok(gallery.includes('XDriveMediaAsyncVideoPoster'))
  assert.ok(!gallery.includes('showDelayedColdPhotoLoad'))
  assert.ok(!gallery.includes('正在加载图库…'))
})

test('P65 existing Mobile Web Files accepted/cold/error slots remain height-stable',()=>{
  const mobile=read('web/src/MobileFiles.tsx')
  assert.equal(firstMatchMinHeight(mobile,'data-mobile-files-zero-state'),180)
  assert.equal(firstMatchMinHeight(mobile,'data-mobile-files-trash-first-read'),180)
  assert.equal(firstMatchMinHeight(mobile,'data-mobile-files-trash-read-error'),180)
  assert.ok(mobile.includes('data-mobile-files-cold-read-slot={coldUnconfirmedBrowse || undefined}'))
  assert.ok(mobile.includes('aria-busy={zeroStatePending || undefined}'))
  assert.ok(mobile.includes('coldDirectoryFirstRead'))
  assert.ok(mobile.includes('keepAcceptedEmptyDirectory'))
})
