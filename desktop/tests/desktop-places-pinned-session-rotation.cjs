'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=f=>fs.readFileSync(path.join(root,f),'utf8')

test('LAN map trust only exists in a per-generation ephemeral HTTPS partition',()=>{
  const main=read('desktop/src/main/index.cts')
  const guest=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const renderer=read('desktop/src/renderer/App.tsx')
  const types=read('desktop/src/renderer/global.d.ts')
  const helper=read('desktop/src/main/places_guest_lan_tls.cts')
  assert.match(main,/let desktopPlacesWebPartition = 'xdrive-places-web-' \+ randomUUID\(\)/)
  assert.match(main,/const oldPartition = desktopPlacesWebPartition/)
  assert.match(main,/desktopPlacesWebPartition = 'xdrive-places-web-' \+ randomUUID\(\)/)
  assert.match(main,/session\.fromPartition\(oldPartition, \{cache:false\}\)\.clearStorageData/)
  assert.match(main,/placesSession\.setCertificateVerifyProc/)
  assert.match(main,/verifyDesktopPlacesLANCertificate\(request,pin,target\.origin,stillCurrent\)/)
  assert.match(main,/placesSession\.webRequest\.onBeforeRequest/)
  assert.match(main,/placesGuestIPRequestAllowed\(details\.url,allowed\)/)
  assert.match(main,/partition!==desktopPlacesWebPartition/)
  assert.match(main,/params\.partition!==desktopPlacesWebPartition/)
  assert.match(main,/pending\.partition!==desktopPlacesWebPartition/)
  assert.match(main,/return \{ok:true,data:\{allowed:true,partition:desktopPlacesWebPartition\}\}/)
  assert.match(main,/closeDesktopPlacesGuests\(\)/)
  assert.match(types,/allowed:true;partition:string/)
  assert.match(renderer,/result\.data\.partition/)
  assert.match(guest,/partition:embedPrepared\?\.partition/)
  assert.doesNotMatch(guest,/partition:'xdrive-places-web',src/)
  assert.match(helper,/rejectUnauthorized: true/)
  assert.match(helper,/checkServerIdentity: \(_host, cert\) => tls\.checkServerIdentity\(ip, cert\)/)
  assert.doesNotMatch(main,/ignore-certificate-errors|allowRunningInsecureContent/)
})
