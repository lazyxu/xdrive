'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('Places uses only the independently signed HTTPS JSAPI4 child renderer', () => {
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const child = read('ui/shared/src/mui/MediaGalleryBaiduIsolatedPhotoSurface.tsx')
  const web = read('web/src/mediaGalleryAdapter.ts')
  assert.match(map, /XDriveMediaGalleryBaiduIsolatedPhotoSurface/)
  assert.match(map, /activation_state === 'authorized_signed_release'/)
  assert.match(map, /mintBaiduIsolatedChildTicket/)
  assert.match(map, /listBaiduNativeCells/)
  assert.match(child, /mintChildTicket\(lifetime\.signal\)/)
  assert.match(child, /xDriveSelectBaiduNativeCell\(page,bounds,cell\)/)
  assert.match(web, /mintBaiduIsolatedChildTicket/)
  assert.doesNotMatch(map, /MediaGalleryBaiduStaticMap|MediaGalleryBaiduPrototypeMap|loadBaiduStaticMap/)
  assert.doesNotMatch(web, /loadBaiduStaticMap|mediaBaiduStaticMap/)
})

test('denied server release never activates a second map implementation', () => {
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  assert.match(map, /server_release_blocked/)
  assert.match(map, /childFailed/)
  assert.match(map, /data-xdrive-baidu-map-unavailable/)
  assert.match(map, /setRetry/)
  assert.equal(fs.existsSync(path.join(root, 'ui/shared/src/mui/MediaGalleryBaiduStaticMap.tsx')), false)
  assert.equal(fs.existsSync(path.join(root, 'ui/shared/src/media-gallery-places-runtime.ts')), false)
  assert.equal(fs.existsSync(path.join(root, 'ui/shared/src/media-gallery-baidu-camera.ts')), false)
})
