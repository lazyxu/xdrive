'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=file=>fs.readFileSync(path.join(root,file),'utf8')

test('default prototype and signed HTTPS Child share one Gallery controller',()=>{
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const gallery=read('ui/shared/src/mui/MediaGallery.tsx')
  const web=read('web/src/mediaGalleryAdapter.ts')
  const route=read('internal/api/router.go')
  assert.doesNotMatch(map,/XDriveMediaGalleryBaiduPrototypeMap/)
  assert.match(map,/XDriveMediaGalleryBaiduIsolatedPhotoSurface/)
  assert.match(map,/mode=\{mapMode === 'prototype' \? 'inline' : 'isolated'\}/)
  assert.match(map,/getInlinePrototypeConfig=\{getBaiduJSAPIPrototype\}/)
  assert.match(map,/getInlineSignedStatus=\{getBaiduJSAPI4Status\}/)
  assert.match(map,/data-xdrive-map-mode-prototype/)
  assert.match(map,/data-xdrive-map-mode-isolated/)
  assert.match(map,/window\.location\.replace\(href\)/)
  assert.match(map,/activation_state === 'authorized_signed_release'/)
  assert.match(gallery,/getBaiduJSAPIPrototype=\{source\.getBaiduJSAPIPrototype\}/)
  assert.match(gallery,/onOpenViewportPhotos=\{onOpenViewportPhotos\}/)
  assert.match(web,/getBaiduJSAPIPrototype: signal => api\.mediaBaiduJSAPIPrototype\(signal\)/)
  assert.match(route,/authed\.GET\("\/media\/places\/baidu-jsapi\/prototype"/)
  assert.doesNotMatch(map,/MediaGalleryBaiduStaticMap|loadBaiduStaticMap/)
})
test('denied signed release remains in isolated mode instead of silent downgrade',()=>{
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const mode=read('ui/shared/src/media-gallery-places-map-mode.ts')
  assert.match(map,/server_release_blocked/)
  assert.match(map,/data-xdrive-baidu-map-unavailable/)
  assert.match(map,/hasMapPorts/)
  assert.match(mode,/places_map_mode/)
  assert.match(mode,/url\.searchParams\.delete/)
  assert.match(mode,/url\.searchParams\.set/)
  assert.equal(fs.existsSync(path.join(root,'ui/shared/src/mui/MediaGalleryBaiduStaticMap.tsx')),false)
})
