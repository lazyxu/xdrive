const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const repo = path.join(__dirname, '..', '..')
const view = fs.readFileSync(path.join(repo, 'ui/shared/src/mui/DeviceBackupPage.tsx'), 'utf8')
const web = fs.readFileSync(path.join(repo, 'web/src/App.tsx'), 'utf8')
const desktop = fs.readFileSync(path.join(repo, 'desktop/src/renderer/App.tsx'), 'utf8')

test('first device overview reserves stable quiet space before genuine response', () => {
  assert.ok(view.includes('data-xdrive-device-backup-first-read'))
  assert.ok(view.includes('minHeight: 180'))
  assert.ok(view.includes('loading && !overview ? ('))
  assert.equal(view.includes('正在读取设备备份…'), false, 'unverified device first read is silent')
  assert.ok(view.includes('data-xdrive-device-backup-first-read aria-busy="true"'))
  assert.ok(view.includes('source && (!overview || overview.devices.length === 0) ? 180 : undefined'),
    'verified zero must keep the cold footprint')
  assert.ok(view.includes('if (!source || !loading || !overview) return'))
  assert.ok(view.includes('window.setTimeout(() => setDelayedRead({ source, revision: refreshID }), 300)'))
  assert.ok(view.includes('window.clearTimeout(timer)'))
  assert.ok(view.includes('source && overview && loading && delayedRead?.source === source'))
  assert.ok(view.includes('delayedRead.revision === refreshID'))
  assert.ok(view.includes('!overview || overview.devices.length === 0'))
})

test('device refresh keeps accepted same-account cards without exposing foreign account data', () => {
  assert.ok(view.includes('overview: prev.source === source ? prev.overview : null'))
  assert.ok(view.includes('if (active) setSnapshot((prev) => prev.source === source'))
  assert.ok(view.includes('? { ...prev, loading: false, failed: true }'))
  assert.ok(view.includes('设备备份刷新失败；已保留上次成功读取的设备信息'))
  assert.ok(view.includes('disabled={loading}'))
  assert.ok(view.includes("position: 'absolute', top: 0, left: 0, right: 0"))
  assert.ok(view.includes('overview && showReadProgress'))
  assert.equal(view.includes('setSnapshot({ source, overview: null, loading: true, failed: false })'), false)
  assert.ok(view.includes('snapshot.source === source'))
  assert.ok(view.includes('folderScopeRef.current.source !== source'))
})

test('only the existing owner-redacted shared device API is used on Web and Desktop', () => {
  assert.ok(view.includes('void source.list().then((result)'))
  assert.ok(view.includes('source.foldersPage(deviceID, 100, cursor)'))
  assert.ok(view.includes('source.runs(id, pageSize, (page - 1) * pageSize)'))
  assert.ok(web.includes('<XDriveDeviceBackupPage'))
  assert.ok(desktop.includes('<XDriveDeviceBackupPage'))
  assert.equal(view.includes('sourceOverview('), false)
  assert.equal(view.includes('localRoot'), false)
})
