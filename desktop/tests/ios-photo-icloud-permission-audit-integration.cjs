'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('iCloud PhotoKit failure and limited-share original exporter integrate without weakening backup', () => {
  const exporter = read('ios/XDriveIOS/PhotoKitOriginalExporter.swift')
  const foreground = read('ios/XDriveIOS/ForegroundPhotoBackupMVP.swift')
  const background = read('ios/XDriveIOS/BackgroundPhotoTask.swift')
  const sharing = read('ios/XDriveIOS/NativeLocalPhotoShare.swift')
  const receipt = read('ios/XDriveIOS/NativeCurrentPhotoReceiptModel.swift')
  assert.match(exporter, /case iCloudDownloadRequired/)
  assert.match(exporter, /photoError\.domain == PHPhotosErrorDomain/)
  assert.match(exporter, /PHPhotosError\.networkAccessRequired\.rawValue/)
  assert.match(exporter, /allowLimitedPhotoAccess: Bool = false/)
  assert.match(exporter, /return status == \.authorized \|\|\s*\(allowLimitedPhotoAccess && status == \.limited\)/)
  assert.equal((exporter.match(/guard authorized\(allowLimitedPhotoAccess: allowLimitedPhotoAccess\)/g) || []).length, 3)
  assert.match(sharing, /allowLimitedPhotoAccess: true/)
  assert.match(receipt, /allowLimitedPhotoAccess: true/)
  assert.match(foreground, /allowLimitedPhotoAccess: true/)
  assert.match(foreground, /case \.managedForeground, \.background:/)
  assert.match(background, /allowICloudOriginals: downloadICloudInBG/)
  assert.match(background, /network\.mayDownloadICloudInBackground/)
  assert.match(foreground, /requireWiFiWhileDownloading: sourceWiFiOnly && allowICloud/)
})

test('the same Owner queue includes iCloud wait and bounded visible-photo statuses', () => {
  const actor = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
  const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
  const badges = read('ios/XDriveIOS/NativeVisiblePhotoQueueBadgePolicy.swift')
  const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
  assert.match(actor, /func retryWaitingICloudCandidates\(owner:/)
  assert.match(actor, /func visibleStatuses\(owner:/)
  assert.match(actor, /guard localIdentifiers\.count <= 64 else/)
  assert.match(actor, /XDriveIOSPhotoKitLibraryEpoch\.matches\(baseline\.token, as: epoch\.token\)/)
  assert.match(store, /case waitingICloud/)
  assert.match(store, /func retryWaitingICloud\(_ candidate: Pending,/)
  assert.match(badges, /case "waitingICloud":/)
  assert.match(badges, /当前云端原件仍需重新核验/)
  assert.match(wall, /visibleBackupQueueStates = states/)
  assert.doesNotMatch(actor, /UploadSessionTransport|uploadPrepared\(|\.finalize\(|deleteNode\(/)
})
