const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '../..', file), 'utf8')

test('Backup history paginates 100 bounded Host receipts without changing restore safety', () => {
  const page = read('ui/shared/src/mui/ServerBackupManagementPanel.tsx')
  const api = read('internal/api/admin_backup_management.go')
  const host = read('scripts/server-control.sh')
  assert.match(page, /data-xdrive-admin-backup-history-filters/)
  assert.match(page, /TablePagination/)
  assert.match(page, /const historyPageSize = 20/)
  assert.match(page, /filteredHistory\.slice\(/)
  assert.match(page, /最多保留最近 100 条宿主机真实执行结果/)
  assert.match(api, /len\(events\) > 100/)
  assert.match(api, /backup-admin-history.json", 256<<10/)
  assert.match(host, /operations=events\[:100\]/)
  assert.match(host, /len\(old\)>100/)
  assert.match(host, /len\(raw\)>262144/)
  assert.match(page, /action: 'restore_database_only'/)
  assert.match(page, /selectedDatabaseOnly/)
})
