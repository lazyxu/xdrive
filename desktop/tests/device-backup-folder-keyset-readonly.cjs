const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('folder paging projects only owner-scoped safe Source summaries', () => {
  const server = read('internal', 'api', 'device_backup_folder_page.go')
  const routes = read('internal', 'api', 'router.go')
  const client = read('internal', 'client', 'device_backups.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const cloud = read('cmd', 'xdrive-agent', 'cloud_files.go')
  const web = read('web', 'src', 'api.ts')
  const shared = read('ui', 'shared', 'src', 'device-backups.ts')
  assert.ok(routes.includes('GET("/device-backups/folders", s.listDeviceBackupFolderPage)'))
  assert.ok(server.includes('JOIN xd_local_source_bindings b ON b.source_id = xd_sources.id'))
  assert.ok(server.includes('xd_sources.kind = ? AND xd_sources.direction = ?'))
  assert.ok(server.includes('xd_sources.id > ?'))
  assert.ok(server.includes('Limit(limit + 1)'))
  assert.ok(server.includes('deviceBackupFolderReadDTO'))
  assert.ok(server.includes('safeDeviceBackupRun(run)'))
  assert.ok(client.includes('DeviceBackupFoldersPage('))
  assert.ok(cloud.includes('CloudDeviceBackupFoldersPage('))
  assert.ok(ipc.includes('GET /v1/device-backups/folders'))
  assert.ok(ipc.includes('desktopIPCDeviceBackupFolderPager'))
  assert.ok(web.includes('deviceBackupFoldersPage('))
  assert.ok(shared.includes('export interface XDriveDeviceBackupFolderPage'))
  for (const leaked of ['RootFingerprint', 'CredentialHash', 'ActiveTransferPath', 'IgnoreRules', 'Checkpoint']) {
    const dto = client.slice(client.indexOf('type DeviceBackupFolder struct {'), client.indexOf('type DeviceBackupDevice struct {'))
    assert.equal(dto.includes(leaked), false, 'unsafe raw Source field exposed: ' + leaked)
  }
  assert.equal(server.includes('db.Where("device_id = ?"'), false, 'folder scope must also bind owner')
})
