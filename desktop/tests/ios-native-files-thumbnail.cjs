'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const collections = read('ios/XDriveIOS/NativeFilesCollections.swift')
const policy = read('ios/XDriveIOS/NativeFilesThumbnailPolicy.swift')
const runtime = read('ios/XDriveIOS/NativeFilesThumbnail.swift')
const slots = read('ios/XDriveIOS/NativeFilesThumbnailSlots.swift')
const router = read('internal/api/router.go')
const server = read('internal/api/media.go')

test('Files list, grid and collection rows render only visible source-revision thumbnail tiles', () => {
  assert.match(browser, /XDriveIOSNativeFilesThumbnailTile\(/)
  assert.match(browser, /height: 72, viewerActive: selectedFile != nil/)
  assert.match(browser, /height: 40, width: 40, viewerActive: selectedFile != nil/)
  assert.match(collections, /XDriveIOSNativeFilesThumbnailTile\(/)
  assert.match(runtime, /\.task\(id: identity\)/)
  assert.match(runtime, /visible: !viewerActive && phase == \.active/)
  assert.match(runtime, /\.onDisappear \{ bitmap = nil \}/)
  assert.match(runtime, /nodeID: node\.id, revision: node\.revision/)
  assert.match(runtime, /ownerID: owner\?\.ownerID/)
  assert.match(runtime, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.match(runtime, /if let bitmap/)
})

test('native thumbnail reads actual media derivative instead of original/Viewer ticket', () => {
  assert.match(router, /authed\.GET\("\/media\/items\/:id\/thumbnail", s\.mediaThumbnail\)/)
  assert.match(server, /func \(s \*Server\) mediaThumbnail\(c \*gin\.Context\)/)
  assert.match(server, /requireMediaSourceRevision\(c, node\.Revision\)/)
  assert.match(policy, /static let maximumBytes = 2 \* 1_048_576/)
  assert.match(policy, /static let maximumConcurrent = 2/)
  assert.match(runtime, /URLQueryItem\(name: "revision", value: String\(node\.revision\)\)/)
  assert.match(runtime, /URLSessionConfiguration\.ephemeral/)
  assert.match(runtime, /completionHandler\(nil\)/)
  assert.match(runtime, /http\.statusCode == 200/)
  assert.match(runtime, /data\.count <= XDriveIOSNativeFilesThumbnailPolicy\.maximumBytes/)
  assert.match(runtime, /CGImageSourceCreateThumbnailAtIndex/)
  assert.match(runtime, /kCGImageSourceThumbnailMaxPixelSize/)
  assert.doesNotMatch(runtime, /\/api\/v1\/files\/.*content|file-preview|download-ticket|URLSession\.shared|WKWebView|WebKit/)
})

test('one cancellation-aware global limiter prevents 64 concurrent derivative requests', () => {
  assert.match(slots, /actor XDriveIOSNativeFilesThumbnailSlots/)
  assert.match(slots, /private var inFlight = 0/)
  assert.match(slots, /withCheckedThrowingContinuation/)
  assert.match(slots, /withTaskCancellationHandler/)
  assert.match(slots, /cancelWaiting\(_ id: UUID\)/)
  assert.match(slots, /defer \{ release\(\) \}/)
  assert.match(runtime, /XDriveIOSNativeFilesThumbnailSlots\.shared\.perform/)
  assert.match(runtime, /worker\.cancel\(\)/)
  assert.match(runtime, /Task\.checkCancellation\(\)/)
})
