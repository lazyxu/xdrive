'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const upload = read('ios/XDriveIOS/NativeFilesManualUpload.swift')
const download = read('ios/XDriveIOS/NativeFilesDownloadExport.swift')
const writer = read('ios/XDriveIOS/NativeUploadSessionTransport.swift')

test('native file transfers provide explicit, accessible cancel without inventing a completed outcome', () => {
  assert.match(panel, /if uploader\.busy \{\s*Button\("取消当前上传", role: \.cancel\)/)
  assert.match(panel, /uploader\.cancelCurrentTransfer\(\)/)
  assert.match(panel, /native-ios-files-upload-cancel/)
  assert.match(panel, /if exporter\.busy \{\s*Button\("取消当前下载", role: \.cancel\)/)
  assert.match(panel, /exporter\.cancelCurrentTransfer\(\)/)
  assert.match(panel, /native-ios-files-download-cancel/)
  assert.match(panel, /createBusy \|\| exporter\.busy \|\| uploader\.busy/)
})
test('upload cancel preserves uncertain server-ack semantics instead of misreporting no write', () => {
  assert.match(upload, /func cancelCurrentTransfer\(\) \{\s*guard busy, let running else \{ return \}\s*running\.cancel\(\)/)
  assert.match(upload, /已请求取消上传；若服务器已接收请求，结果可能不确定/)
  assert.match(upload, /本次已取消。若上传请求已发出，结果可能不确定/)
  assert.match(upload, /XDriveIOSOriginalRunGate\.shared\.release\(gate\)/)
  assert.match(writer, /throw XDriveNativeUploadError\.uncertainCommit/)
  assert.doesNotMatch(upload, /status = "上传成功"|status = "没有上传"/)
})
test('download cancel continues to release private staged bytes and never asserts Saved to Files', () => {
  assert.match(download, /func cancelCurrentTransfer\(\) \{\s*guard busy, let task else \{ return \}\s*task\.cancel\(\)/)
  assert.match(download, /已请求取消下载；正在清理临时文件/)
  assert.match(download, /prepared\?\.discard\(\)/)
  assert.match(download, /output\.discard\(\)/)
  assert.match(download, /下载已取消；没有保存到 iPhone/)
  assert.doesNotMatch(download, /UserDefaults|WKWebView|document\.cookie/)
})
