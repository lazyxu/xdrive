'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')
const bg = read('ios/XDriveIOS/BGOriginalWindowStore.swift')
const fg = read('ios/XDriveIOS/PhotoAutoScheduleStore.swift')
const epoch = read('ios/XDriveIOS/PhotoKitLibraryEpoch.swift')
const policy = read('ios/XDriveIOS/PhotoCursorEpochPolicy.swift')
const scheduler = read('ios/XDriveIOS/BackgroundPhotoTask.swift')

test('BG cursor remains restricted to authenticated approved Owner and native Photos',()=>{
  const reserve = bg.slice(bg.indexOf('func reserveDue('), bg.indexOf('func record('))
  assert.match(reserve, /approved\.matches\(owner, now: now\)/)
  assert.match(reserve, /state\.dueAt <= now/)
  assert.match(reserve, /let epoch = try XDriveIOSPhotoKitLibraryEpoch\.capture\(\)/)
  assert.match(reserve, /XDrivePhotoCursorEpochPolicy\.trustedWindow\(/)
  assert.match(reserve, /state\.libraryChangeEpoch = epoch\.serialized/)
  assert.match(reserve, /state\.libraryAuthorizationRaw = epoch\.authorization/)
  assert.ok(reserve.indexOf('approved.matches(') < reserve.indexOf('XDriveIOSPhotoKitLibraryEpoch.capture()'))
  assert.ok(reserve.indexOf('state.libraryChangeEpoch = epoch.serialized') < reserve.indexOf('try store(state, owner: owner)'))
  assert.match(scheduler, /\.proveInBackground\(\)/)
  assert.match(scheduler, /\.reserveDue\(owner: owner, approved: approved\)/)
  assert.ok(scheduler.indexOf('.proveInBackground()') < scheduler.indexOf('reserveDue('))
})

test('BG stage completion cannot persist a cursor for a changed photo library',()=>{
  const body = bg.slice(bg.indexOf('func record('), bg.indexOf('func pause('))
  assert.match(body, /approved\.matches\(owner, now: now\)/)
  assert.match(body, /let epoch = try XDriveIOSPhotoKitLibraryEpoch\.capture\(\)/)
  assert.match(body, /XDrivePhotoCursorEpochPolicy\.canResume\(/)
  assert.match(body, /state\.windowIndex = unchanged/)
  assert.match(body, /\) : 0/)
  assert.match(body, /state\.libraryChangeEpoch = epoch\.serialized/)
  assert.match(body, /state\.pausedForReview = unresolved/)
  assert.match(body, /state\.lastCommittedAt = now/)
  assert.doesNotMatch(body, /clearLocalRecords|UploadSession|PHAsset\.fetchAssets|revokePendingRequests/)
})

test('both native auto stores use one secure PhotoKit epoch, preserving legacy schedules',()=>{
  assert.match(bg, /var libraryChangeEpoch: Data\? = nil/)
  assert.match(bg, /var libraryAuthorizationRaw: Int\? = nil/)
  assert.match(fg, /var libraryChangeEpoch: Data\? = nil/)
  assert.match(fg, /var libraryAuthorizationRaw: Int\? = nil/)
  assert.match(fg, /XDriveIOSPhotoKitLibraryEpoch\.capture\(\)/)
  assert.match(fg, /XDriveIOSPhotoKitLibraryEpoch\.matches\(/)
  assert.match(epoch, /PHPhotoLibrary\.shared\(\)\.currentChangeToken/)
  assert.match(epoch, /requiringSecureCoding: true/)
  assert.match(epoch, /NSKeyedUnarchiver\.unarchivedObject\(/)
  assert.match(epoch, /PHPersistentChangeToken\.self/)
  assert.match(epoch, /archived\.count <= 65_536/)
  assert.match(policy, /previousAuthorization == currentAuthorization/)
  assert.doesNotMatch(bg, /\.localIdentifier\b|\bvar (?:accessToken|grantSecret|deviceToken)\b/)
  assert.doesNotMatch(epoch, /\.localIdentifier|accessToken|grantSecret|deviceToken/)
})
