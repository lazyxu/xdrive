'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const picker = read('ios/XDriveIOS/NativeFilesDestinationPicker.swift')
const mutation = read('ios/XDriveIOS/NativeFilesDestinationMutation.swift')
const policy = read('ios/XDriveIOS/NativeFilesDestinationReceiptPolicy.swift')
const api = read('internal/api/handlers.go')

test('native directory copy/move reuse current Owner destination and Server Node routes', () => {
  assert.match(panel, /Button\("复制文件夹到…"\)/)
  assert.match(panel, /Button\("移动文件夹到…"\)/)
  assert.match(panel, /destinationIntent = \.init\(node: directory, kind: \.copy\)/)
  assert.match(panel, /destinationIntent = \.init\(node: directory, kind: \.move\)/)
  assert.match(picker, /reader\.children\(/)
  assert.match(mutation, /\(original\.type == "file" \|\| original\.type == "dir"\)/)
  assert.match(mutation, /destination\.id != original\.id/)
  assert.match(mutation, /XDriveIOSNativeFilesDestinationReceiptPolicy\.copied\(/)
  assert.match(mutation, /XDriveIOSNativeFilesDestinationReceiptPolicy\.moved\(/)
  assert.match(mutation, /guard saved == created/)
  assert.match(api, /func \(s \*Server\) copyNode\(c \*gin\.Context\)/)
  assert.match(api, /func \(s \*Server\) updateNode\(c \*gin\.Context\)/)
})
test('directory cannot select self or descend into itself; root blocked and Server denies cycles', () => {
  assert.match(picker, /allSelected\.contains\(where: \{ \$0\.isDirectory && \$0\.id == folder\.id \}\)/)
  assert.match(picker, /\.disabled\(allSelected\.contains\(where: \{ \$0\.isDirectory && \$0\.id == entry\.id \}\)\)/)
  assert.match(policy, /targetID != original\.id/)
  assert.match(policy, /original\.parent_id != nil/)
  assert.match(policy, /result\.type == original\.type/)
  assert.match(api, /s\.isDescendant\(uid, req\.ParentID, source\.ID\)/)
  assert.match(api, /s\.isDescendant\(userID\(c\), \*req\.ParentID, id\)/)
  assert.doesNotMatch(mutation, /WKWebView|localStorage/)
})
