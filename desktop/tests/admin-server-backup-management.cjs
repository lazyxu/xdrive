test('Server backups use authenticated Admin API and a fixed Host Control request, not browser paths', () => {
  assert.match(routes, /admin.Use\(s.requireAdmin\(\)\)/)
  assert.match(routes, /admin.GET\("\/backups", s.adminBackupManagement\)/)
  assert.match(routes, /admin.POST\("\/backups\/actions", s.adminSubmitBackupManagement\)/)
  assert.match(api, /DisallowUnknownFields\(\)/)
  assert.match(api, /os.Link\(temp.Name\(\), filepath.Join\(dir, "backup-admin-request.json"\)\)/)
  assert.match(api, /backupAdminSnapshotID/)
  assert.match(api, /backup_snapshot_not_current/)
  assert.doesNotMatch(client, /\/api\/v1\/admin\/backups\/actions[\s\S]{0,260}shell_command/)
})

test('Host Control owns all fixed actions; no generic execution or v2 raw deletion', () => {
  for (const name of ['create', 'verify', 'verify_all', 'drill', 'plan', 'restore', 'delete', 'prune', 'policy']) {
    assert.ok(host.includes('\n    ' + name + ')'), 'missing Host command ' + name)
  }
  assert.match(host, /backup_admin_snapshot_directory/)
  assert.match(host, /backup_admin_write_policy/)
  assert.match(host, /backup_admin_delete_v1/)
  assert.match(host, /backup prune --keep-last/)
  assert.match(host, /backup verify/)
  assert.match(host, /backup_admin_verify_all/)
  assert.match(host, /backup drill/)
  assert.match(host, /backup_admin_valid_drill_result/)
  assert.match(host, /backup_admin_process_request/)
  assert.match(host, /backup-admin-operation.lock/)
  assert.doesNotMatch(host.slice(host.indexOf('backup_admin_execute()'), host.indexOf('backup_admin_json_int()')), /eval |bash -c |rm -rf/)
})

