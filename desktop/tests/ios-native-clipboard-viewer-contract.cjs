'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')
const clipboard = read('ios/XDriveIOS/NativeClipboardScreen.swift')
const files = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const dashboard = read('ios/XDriveIOS/NativePhotosDashboard.swift')
test('iOS received node ref rechecks current Owner and decrypts before file open',()=>{
 assert.match(clipboard,/entry\.text == "asset:\\?\(nodeID\)"/)
 assert.match(clipboard,/authorizedClient\(for: generation\)/)
 assert.match(clipboard,/reader\.referencedFile\(nodeID: nodeID\)/)
 assert.match(clipboard,/sessionGeneration == generation/)
 assert.match(clipboard,/onOpenReferencedFile\(client\.owner, node\)/)
 assert.doesNotMatch(clipboard,/UIPasteboard\.general\.string = "asset:/)
})
test('iOS existing read-only Files reader verifies one exact Owner file Node',()=>{
 assert.match(files,/func referencedFile\(nodeID: UInt64\)/)
 assert.match(files,/endpoint\("\/api\/v1\/nodes\//)
 assert.match(files,/node\.id == nodeID, node\.type == "file"/)
 assert.match(files,/node\.revision > 0/)
})
test('iOS root presents existing native Viewer and clears on Owner switch',()=>{
 assert.match(dashboard,/fullScreenCover\(item: \$clipboardViewerIntent\)/)
 assert.match(dashboard,/XDriveIOSNativeFilesViewer\(/)
 assert.match(dashboard,/onNavigate: \{ _ in false \}/)
 assert.match(dashboard,/clipboardViewerIntent = nil/)
 assert.match(dashboard,/XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, selected\.owner\)/)
})