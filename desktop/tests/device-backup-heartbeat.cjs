const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Agent heartbeat is credential-only, background and not a Push execution capability', () => {
  const server = read('internal', 'api', 'device_backup_heartbeat.go')
  const routes = read('internal', 'api', 'router.go')
  const meta = read('internal', 'meta', 'client_devices.go')
  const client = read('internal', 'client', 'devices.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_heartbeat.go')
  const controller = read('cmd', 'xdrive-agent', 'controller.go')
  assert.match(meta, /HeartbeatAt\s+\*time\.Time/)
  assert.match(routes, /POST\("\/devices\/self\/heartbeat", s\.heartbeatClientDevice\)/)
  assert.match(server, /clientDeviceCredentialMatches\(device, token\)/)
  assert.match(server, /clause\.Locking\{Strength: "UPDATE"\}/)
  assert.match(server, /device\.HeartbeatAt == nil/)
  assert.match(server, /return "unknown"/)
  assert.match(server, /return "offline"/)
  assert.match(client, /SendDeviceHeartbeat\(/)
  assert.match(agent, /localpush\.LoadDeviceRegistration/)
  assert.match(agent, /localpush\.LoadDeviceToken/)
  assert.match(agent, /ErrDeviceNotRegistered/)
  assert.match(agent, /latest\.SessionID != cfg\.SessionID/)
  assert.match(agent, /cli\.SendDeviceHeartbeat\(ctx, deviceID, token\)/)
  assert.match(controller, /go c\.runDeviceBackupHeartbeat\(\)/)
  assert.doesNotMatch(agent, /RegisterClientDevice|EnsureDevice|BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  assert.doesNotMatch(server, /BeginSourceRun|UploadChunk|CommitSourceItem|SourceItemAlias|MirrorDeletion|LocalSourceBinding/)
})

test('Web and foreign Desktop still use only redacted device states and never a heartbeat mutator', () => {
  const projection = read('internal', 'api', 'device_backup_read.go')
  const shared = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')
  const web = read('web', 'src', 'App.tsx')
  assert.match(projection, /deviceBackupConnectionState\(device, time\.Now\(\)\.UTC\(\)\)/)
  assert.match(shared, /device\.connection_state === 'online'/)
  assert.match(shared, /device\.connection_state === 'offline'/)
  assert.match(dto, /connection_state: 'unknown' \| 'online' \| 'offline'/)
  assert.doesNotMatch(web, /SendDeviceHeartbeat|heartbeatClientDevice|runDeviceBackupHeartbeat/)
})
