'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')
const album = read('ios/XDriveIOS/NativeOwnerMapClusterAlbum.swift')
const viewer = read('ios/XDriveIOS/NativeServerMediaGallery.swift')
const spatial = read('ios/XDriveIOS/NativeOwnerMapSelectionPolicy.swift')

test('cross-place L3 is opt-in only: ordinary cloud Gallery retains exact within-place cursor', () => {
  assert.match(viewer, /var canCrossMapPlace: \(\([\s\S]*?XDriveIOSNativeMediaRange, XDriveIOSNativeMediaItem, Int[\s\S]*?\) -> Bool\)\? = nil/)
  assert.match(viewer, /private func canCrossRange\(_ direction: Int\) -> Bool \{/)
  assert.match(viewer, /guard ownerAuthorized, !rangeCrossing, onCrossRange != nil/)
  assert.match(viewer, /let page = visibleRange, let position = loadedPosition/)
  assert.match(viewer, /XDriveIOSNativePhotoAssetRangeCursorPolicy\.adjacentOffset\(/)
  assert.match(viewer, /return canCrossMapPlace\?\(page, viewed, direction\) == true/)
  assert.match(album, /canCrossMapPlace: \{ previous, anchor, direction in/)
  assert.match(album, /page\.sameVisibleSnapshot\(as: previous\)/)
  assert.match(album, /previous\.offset == cursor\.offset/)
  assert.match(album, /adjacentClusterPlace\(\s*current: cursor, previous: previous,\s*selectedIndex: index, direction: direction/)
  assert.match(viewer, /let next = direction > 0\s*\? nextPage\.items\.first : nextPage\.items\.last/)
})

