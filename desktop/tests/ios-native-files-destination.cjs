'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const picker = read('ios/XDriveIOS/NativeFilesDestinationPicker.swift')
const mutation = read('ios/XDriveIOS/NativeFilesDestinationMutation.swift')
const policy = read('ios/XDriveIOS/NativeFilesDestinationReceiptPolicy.swift')
const go = read('internal/api/router.go')

test('native copy/move choose a real bounded current-Owner directory, never synthetic IDs', () => {
  assert.match(panel, /Button\("复制到…"\)/)
  assert.match(panel, /Button\("移动到…"\)/)
  assert.match(panel, /XDriveIOSNativeFilesDestinationPicker\(/)
  assert.match(panel, /destinationWriter\.perform\(/)
  assert.match(picker, /NavigationStack\(path: \$path\) \{/)
  assert.match(picker, /NavigationLink\(value: XDriveIOSNativeFilesDestination\(/)
  assert.match(picker, /reader\.children\(/)
  assert.match(picker, /parentID: folder\.id, offset: offset, sort: "name", order: "asc"/)
  assert.match(picker, /page != nil && !busy && failure == nil/)
  assert.match(picker, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, originalOwner\)/)
  assert.match(picker, /kind == \.move && allSelected\.contains\(where: \{ \$0\.parent_id == folder\.id \}\)/)
})
test('copy/move use real Server endpoints, exact source and target GET, version and post-commit readback', () => {
  assert.match(go, /authed\.POST\("\/nodes\/:id\/copy", s\.copyNode\)/)
  assert.match(go, /authed\.PATCH\("\/nodes\/:id", s\.updateNode\)/)
  assert.match(mutation, /guard source == original/)
  assert.match(mutation, /target\.type == "dir"/)
  assert.match(mutation, /method: "POST"/)
  assert.match(mutation, /method: "PATCH"/)
  // Swift's URLSession data(for:) wrapper is async for both write paths.
  assert.equal((mutation.match(/let bytes = try await response\(/g) || []).length, 2,
    'both copy and move await response')
  assert.match(mutation, /revision: original\.revision, accepted: 200/)
  assert.match(mutation, /forHTTPHeaderField: "If-Match"/)
  assert.match(mutation, /XDriveIOSNativeFilesDestinationReceiptPolicy\.copied\(/)
  assert.match(mutation, /XDriveIOSNativeFilesDestinationReceiptPolicy\.moved\(/)
  assert.match(mutation, /guard saved == created/)
  assert.match(mutation, /if kind == \.copy \{[\s\S]*?let unchangedSource = try await readNode\(original\.id, session: client\)[\s\S]*?guard unchangedSource == original/)
  assert.match(mutation, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(mutation, /不要盲目重复操作/)
  assert.match(policy, /result\.revision > original\.revision/)
  assert.doesNotMatch(mutation, /WKWebView\s*\(|document\.cookie/)
})


test('native copy/move target can create a folder, enter only its Server-confirmed ID and reverify the target', () => {
  assert.match(picker, /@State private var path: \[XDriveIOSNativeFilesDestination\] = \[\]/)
  assert.match(picker, /NavigationStack\(path: \$path\)/)
  assert.match(picker, /onCreated: \{ destination in path\.append\(destination\) \}/)
  assert.match(picker, /Label\("新建文件夹", systemImage: "folder\.badge\.plus"\)/)
  assert.match(picker, /\.disabled\(!canCreateFolder\)/)
  assert.match(picker, /\.alert\("新建文件夹", isPresented: \$showingCreate\)/)
  assert.match(picker, /TextField\("文件夹名称", text: \$folderDraft\)/)
  assert.match(picker, /XDriveIOSNativeFilesFolderNamePolicy\.normalized\(folderDraft\)/)
  assert.match(picker, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(picker, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, originalOwner\)/)
  assert.match(picker, /XDriveIOSNativeFilesDirectoryCreator\([\s\S]*?\.create\(parentID: folder\.id, name: name\)/)
  assert.match(picker, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(picker, /onCreated\(XDriveIOSNativeFilesDestination\(id: createdID, name: name\)\)/)
  assert.match(picker, /creationTask\?\.cancel\(\)/)
  assert.match(picker, /createStatus = "创建结果未确认，请先刷新目录核对/)
  assert.match(picker, /\.onChange\(of: login\.owner\) \{ _ in invalidate\(\) \}/)
  assert.match(picker, /page != nil && !busy && failure == nil && !creating/)
  assert.match(picker, /parentID: folder\.id, offset: offset, sort: "name", order: "asc"/)
  assert.doesNotMatch(picker, /URLSession\(configuration:|WKWebView|\.uploadOnce\(/)
})
