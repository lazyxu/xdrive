'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')
const view = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const picker = read('ios/XDriveIOS/NativeFilesDestinationPicker.swift')
const mutation = read('ios/XDriveIOS/NativeFilesDestinationMutation.swift')
const server = read('internal/api/router.go')

test('native Files copy/move offers a real 64-item Owner directory chooser, not arbitrary folder IDs', () => {
  assert.match(view, /Label\("上传文件", systemImage: "square.and.arrow.up"\)/)
  assert.match(view, /Button\("复制到…"\)/)
  assert.match(view, /Button\("移动到…"\)/)
  assert.match(view, /XDriveIOSNativeFilesDestinationPicker\(/)
  assert.match(view, /destinationIntent = nil[\s\S]*?destinationWriter\.perform\(/)
  assert.match(picker, /NavigationStack \{/)
  assert.match(picker, /NavigationLink\(value: XDriveIOSNativeFilesDestination\(/)
  assert.match(picker, /reader\.children\(/)
  assert.match(picker, /parentID: folder\.id, offset: offset, sort: "name", order: "asc"/)
  assert.match(picker, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, originalOwner\)/)
  assert.match(picker, /page != nil && !busy && failure == nil/)
  assert.match(picker, /kind == \.move && selected\.parent_id == folder\.id/)
  assert.match(view, /\.onDisappear \{[\s\S]*?destinationWriter\.invalidate\(\)/)
})

test('exact-Owner file copy/move use current source/target Node, Server If-Match and confirm readback', () => {
  assert.match(server, /authed\.POST\("\/nodes\/:id\/copy", s\.copyNode\)/)
  assert.match(server, /authed\.PATCH\("\/nodes\/:id", s\.updateNode\)/)
  assert.match(mutation, /let source = try await readNode\(original\.id, session: client\)/)
  assert.match(mutation, /guard source == original/)
  assert.match(mutation, /let target = try await readNode\(destination\.id, session: client\)/)
  assert.match(mutation, /target\.type == "dir"/)
  assert.match(mutation, /method: "POST"/)
  assert.match(mutation, /method: "PATCH"/)
  assert.match(mutation, /revision: original\.revision, accepted: 200/)
  assert.match(mutation, /"If-Match"/)
  assert.match(mutation, /XDriveIOSNativeFilesDestinationReceiptPolicy\.copied\(/)
  assert.match(mutation, /XDriveIOSNativeFilesDestinationReceiptPolicy\.moved\(/)
  assert.match(mutation, /let saved = try await readNode\(created\.id, session: client\)/)
  assert.match(mutation, /guard saved == created/)
  assert.match(mutation, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(mutation, /结果未确认，请先核对云端，不要盲目重复操作/)
  assert.doesNotMatch(mutation, /WKWebView|localStorage|\/api\/v1\/uploads/)
})
