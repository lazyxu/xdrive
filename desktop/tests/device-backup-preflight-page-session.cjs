const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const dialog = fs.readFileSync(path.join(root, 'ui/shared/src/mui/DeviceBackupLocalEvidencePreflightDialog.tsx'), 'utf8')

test('owning Desktop content preflight fences page cursor, account scope and Source revision', () => {
  assert.match(dialog, /pageResult && pageResult\.cursor === afterID/)
  assert.match(dialog, /sessionRevision\.current !== null && sessionRevision\.current !== value\.revision/)
  assert.match(dialog, /setRevisionChanged\(true\)/)
  assert.match(dialog, /setObservedPages\(\{\}\)/)
  assert.match(dialog, /\[sourceID, actions\]/)
  assert.match(dialog, /value\.next_after_id > afterID/)
  assert.match(dialog, /!value\.has_more \|\| value\.checked > 0/)
  assert.match(dialog, /setObservedPages\(\(previous\) => \(\{ \.\.\.previous, \[afterID\]: value \}\)\)/)
  assert.match(dialog, /!loading && !revisionChanged && totalSafe/)
})

test('manual aggregate is a bounded read-only sample with no durable authority', () => {
  assert.match(dialog, /totals\.sampledBytes/)
  assert.match(dialog, /totals\.unsampled/)
  assert.match(dialog, /Number\.isSafeInteger/)
  assert.match(dialog, /并非原子快照或全量 100k 验证/)
  assert.match(dialog, /value\.content_verified === false && value\.commit_supported === false/)
  assert.match(dialog, /value\.authoritative === false && value\.missing_inference_safe === false/)
  assert.match(dialog, /void actions\.cancel\(requestID\)/)
  assert.doesNotMatch(dialog, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
})
