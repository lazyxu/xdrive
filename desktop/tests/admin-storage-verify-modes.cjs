const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('Global Storage defaults to fast read-only verify, with explicit deep SHA-256', () => {
  const page = read('ui/shared/src/mui/GlobalStorageStatsPage.tsx')
  assert.match(page, /useState<'fast' \| 'deep'>\('fast'\)/)
  assert.match(page, /aria-label="在线存储完整性校验模式"/)
  assert.match(page, /'storage_verify_fast' : 'storage_verify'/)
  assert.match(page, /fast：检查数据库引用/)
  assert.match(page, /不能替代备份仓库校验及实际恢复演练/)
  assert.match(read('web/src/App.tsx'), /'storage_verify_fast' \| 'storage_verify'/)
  assert.match(read('desktop/src/renderer/App.tsx'), /system-maintenance:\$\{kind\}/)
})

test('fast and deep keep separate historical kinds, but share authorization and lease', () => {
  const go = read('internal/api/system_maintenance_tasks.go')
  const model = read('internal/meta/models.go')
  const tasks = read('ui/shared/src/background-tasks.ts')
  assert.match(model, /SystemMaintenanceKindStorageVerifyFast\s*= "storage_verify_fast"/)
  assert.match(go, /case meta\.SystemMaintenanceKindStorageVerify, meta\.SystemMaintenanceKindStorageVerifyFast:/)
  assert.match(go, /mode = maintenance\.VerifyModeFast/)
  assert.match(go, /VerifyWithOptions\(ctx, s\.DB, root, maintenance\.VerifyOptions\{Mode: mode\}\)/)
  assert.match(go, /storage verifier did not attest fast mode/)
  assert.match(go, /meta\.SystemMaintenanceKindStorageVerifyFast,[\s\S]*?meta\.SystemMaintenanceKindStorageRepair/)
  assert.match(tasks, /system\.maintenance\.storage_verify_fast/)
  assert.match(tasks, /存储 SHA-256 深度校验/)
  assert.match(read('internal/api/system_maintenance_tasks_integration_test.go'), /SystemMaintenanceKindStorageVerifyFast/)
})

test('storage repair confirmation stays bound to the same authenticated storage adapter and global scope', () => {
  const page = read('ui/shared/src/mui/GlobalStorageStatsPage.tsx')
  assert.match(page, /repairConfirmation\?\.api === api/)
  assert.match(page, /repairConfirmation\.scope === scope && scope === 'global'/)
  assert.match(page, /onClick=\{\(\) => \{ if \(scope === 'global'\) setRepairConfirmation\(\{ api, scope \}\) \}\}/)
  assert.match(page, /title="确认执行在线 CAS 存储修复？"/)
  assert.match(page, /confirmLabel="确认执行修复"/)
  assert.match(page, /if \(!repairConfirmCurrent \|\| !onRunStorageMaintenance\)/)
  assert.match(page, /void runStorageMaintenance\('storage_repair'\)/)
  assert.match(page, /setRepairConfirmation\(null\)/)
  assert.match(page, /它不是只读校验、备份恢复或损坏文件内容自动修复/)
})
