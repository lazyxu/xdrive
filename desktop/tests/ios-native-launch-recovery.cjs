'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('cold launch offers isolated rescue before native Owner and Photos construction', () => {
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  const recovery = read('ios/XDriveIOS/NativeLaunchCheckpoint.swift')
  const login = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
  assert.match(app, /interruptedStage = XDriveIOSNativeLaunchCheckpoint\.begin\(\)/)
  assert.match(app, /if normalStartup \{\s*XDriveIOSNativeOwnerLoginScreen\(\)/)
  assert.match(app, /native-ios-startup-recovery/)
  assert.match(app, /native-ios-startup-retry/)
  assert.match(recovery, /case restoringSession/)
  assert.match(recovery, /case mountingWorkspace/)
  assert.match(recovery, /return prior == \.ready \? nil : prior/)
  assert.doesNotMatch(recovery, /SecItemDelete|removePersistentDomain|PHPhotoLibrary|reset\(/)
  const begin = app.indexOf('XDriveIOSNativeLaunchCheckpoint.begin()')
  const bg = app.indexOf('XDriveIOSBackgroundPhotoTask.registerAtLaunch()')
  assert.ok(begin >= 0 && bg > begin, 'record boot before BG register')
  assert.match(login, /XDriveIOSNativeLaunchCheckpoint\.mark\(\.restoringSession\)/)
  assert.match(login, /XDriveIOSNativeLaunchCheckpoint\.mark\(\.mountingWorkspace\)/)
  assert.match(login, /XDriveIOSNativeLaunchCheckpoint\.mark\(\.ready\)/)
  assert.ok(login.indexOf('mark(.restoringSession)') < login.indexOf('await model.restore()'))
  assert.ok(login.indexOf('mark(.ready)') > login.indexOf('await model.restore()'))
})

test('BGTaskScheduler registers only once with validated bundled identifier', () => {
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  const task = read('ios/XDriveIOS/BackgroundPhotoTask.swift')
  const body = task.slice(task.indexOf('static func registerAtLaunch()'),
    task.indexOf('@MainActor\n    private static func handle'))
  assert.match(app, /XDriveIOSBackgroundPhotoTask\.registerAtLaunch\(\)/)
  assert.match(body, /guard !attemptedRegistration else \{ return \}/)
  assert.match(body, /attemptedRegistration = true/)
  assert.match(body, /BGTaskSchedulerPermittedIdentifiers/)
  assert.match(body, /allowed\.contains\(identifier\)/)
  assert.match(body, /registeredAtLaunch = BGTaskScheduler\.shared\.register\(/)
  assert.match(task, /guard registeredAtLaunch else \{\s*throw XDriveIOSBGRegistrationFailure\.unavailable/)
})
