test('cold launch offers isolated rescue before native Owner and Photos construction', () => {
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  const recovery = read('ios/XDriveIOS/NativeLaunchCheckpoint.swift')
  const login = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
  const model = read('ios/XDriveIOS/NativeOwnerLoginModel.swift')
  const metrics = read('ios/XDriveIOS/NativeCrashMetricCollector.swift')
  assert.match(app, /interruption = XDriveIOSNativeLaunchCheckpoint\.beginReport\(\)/)
  assert.match(app, /if normalStartup \{\s*XDriveIOSNativeOwnerLoginScreen\(\s*safeStartup: safeStartup/)
  assert.match(app, /native-ios-startup-recovery/)
  assert.match(app, /native-ios-startup-retry/)
  assert.match(recovery, /case restoringSession/)
  assert.match(recovery, /case mountingWorkspace/)
  assert.match(recovery, /if let previous, previous != \.ready \{[\s\S]*?return report/)
  assert.doesNotMatch(recovery, /SecItemDelete|removePersistentDomain|PHPhotoLibrary|reset\(/)
  const begin = app.indexOf('XDriveIOSNativeLaunchCheckpoint.beginReport()')
  const bg = app.indexOf('XDriveIOSBackgroundPhotoTask.registerAtLaunch()')
  assert.ok(begin >= 0 && bg > begin, 'record boot before BG register')
  assert.match(login, /XDriveIOSNativeLaunchCheckpoint\.mark\(\.restoringSession\)/)
  assert.match(login, /XDriveIOSNativeLaunchCheckpoint\.mark\(\.mountingWorkspace\)/)
  assert.match(login, /XDriveIOSNativeLaunchCheckpoint\.mark\(\.ready\)/)
  assert.ok(login.indexOf('mark(.restoringSession)') < login.indexOf('await model.restore()'))
  assert.ok(login.indexOf('mark(.ready)') > login.indexOf('await model.restore()'))
  assert.match(model, /markPostLogin\(\.restoredOwnerVerified\)\s+owner = verified/)
  assert.match(model, /markPostLogin\(\.manualOwnerVerified\)\s+owner = verified/)
  assert.match(recovery, /mark\(\.initializing, defaults: defaults\)[\s\S]*?removeObject\(forKey: stepKey\)[\s\S]*?removeObject\(forKey: dateKey\)[\s\S]*?return report/)
  assert.match(recovery, /defaults\.set\(step\.rawValue, forKey: stepKey\)[\s\S]*?defaults\.synchronize\(\)/)
  assert.match(recovery, /if phase == \.ready \{[\s\S]*?removeObject\(forKey: stepKey\)/)
  assert.match(app, /native-ios-postlogin-crash-step/)
  assert.match(app, /native-ios-startup-diagnostic-login/)
  assert.match(app, /native-ios-system-crash-diagnostic/)
  assert.match(app, /XDriveIOSNativeCrashMetricCollector\.shared\.start\(\)/)
  const harness = read('ios/scripts/prepare-navigation-runtime-smoke.py')
  // The disposable CI fixture explicitly supports original b9 and current
  // crash-recovery root calls, and rejects unknown app entry points.
  assert.match(harness, /XDriveIOSNativeStartupRoot\(interruptedStage: interruptedStage\)/)
  assert.match(harness, /XDriveIOSNativeStartupRoot\(interruption: interruption\)/)
  assert.match(harness, /Unexpected iOS App entry; test harness must be audited/)
  assert.match(harness, /-xdrive-ui-postlogin-recovery-fixture/)
  assert.match(harness, /markPostLogin\(\.openingDashboard\)/)
  assert.match(harness, /if matches\[0\]\.endswith\("\(interruption: interruption\)"\):/)
  const uiTest = read('ios/UITests/XDriveIOSNavigationRuntimeUITests.swift')
  assert.match(uiTest, /func testInterruptedPostLoginOpensRecoveryAndIsolatedSignInWithoutDashboard\(/)
  assert.match(uiTest, /native-ios-postlogin-crash-step/)
  assert.match(uiTest, /native-ios-startup-diagnostic-login/)
  assert.match(uiTest, /XCTAssertFalse\(app\.buttons\["native-ios-diagnostic-open-dashboard"\]\.exists\)/)
  assert.match(metrics, /func didReceive\(_ payloads: \[MXDiagnosticPayload\]\)/)
  assert.doesNotMatch(metrics, /jsonRepresentation|bearer|refreshToken|password/)
})

test('workspace ready is acknowledged by mounted UI, not a cancelled restore view task', () => {
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  const login = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
  const checkpoint = read('ios/XDriveIOS/NativeLaunchCheckpoint.swift')
  const taskStart = login.indexOf('        .task {')
  const taskEnd = login.indexOf('        .onReceive(', taskStart)
  assert.ok(taskStart >= 0 && taskEnd > taskStart, 'startup task exists')
  const startupTask = login.slice(taskStart, taskEnd)
  assert.match(startupTask, /guard !restoreFinished else \{ return \}/)
  assert.match(startupTask, /guard !Task\.isCancelled else \{ return \}/)
  assert.match(startupTask, /mark\(\.mountingWorkspace\)/)
  assert.doesNotMatch(startupTask, /Task\.sleep|mark\(\.ready\)|tickIfDue/)
  assert.match(login, /XDriveIOSNativePhotosDashboard\([\s\S]*?\.onAppear \{ workspaceAppeared\(\) \}/)
  assert.match(login, /\.navigationBarTitleDisplayMode\(\.inline\)\s*\}\s*\.onAppear \{ workspaceAppeared\(\) \}/)
  assert.match(login, /readinessTask = Task \{ @MainActor in[\s\S]*?try await Task\.sleep[\s\S]*?readinessTicket == ticket[\s\S]*?mark\(\.ready\)/)
  assert.match(login, /workspaceDisappeared\(\) \{[\s\S]*?readinessTask\?\.cancel\(\)/)
  assert.match(checkpoint, /restoreComplete && workspaceVisible && foreground/)
  assert.match(checkpoint, /startupReady && !safeStartup && foreground/)
  assert.doesNotMatch(app, /SecItemDelete|removePersistentDomain/)
})

test('mountingWorkspace rescue offers safe entry with no automatic Owner restore or backup', () => {
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  const login = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
  assert.match(app, /Button\("安全进入（不自动登录和备份）"\)/)
  assert.match(app, /safeStartup = true[\s\S]*?normalStartup = true/)
  assert.match(app, /native-ios-startup-safe-entry/)
  assert.match(app, /Button\("尝试完整重新启动原生客户端"\)/)
  assert.match(app, /safeStartup = false[\s\S]*?normalStartup = true/)
  assert.match(login, /if !safeStartup \{[\s\S]*?purgeLegacyRefreshToken\(\)[\s\S]*?await model\.restore\(\)/)
  assert.match(login, /guard !Task\.isCancelled else \{ return \}[\s\S]*?mark\(\.mountingWorkspace\)/)
  assert.match(login, /if safeStartup \{[\s\S]*?native-ios-startup-safe-mode/)
  assert.match(login, /mayAutoBackup\([\s\S]*?safeStartup: safeStartup/)
  assert.match(login, /backup\.startLibraryChangeMonitoring\(login: model\)/)
  assert.match(login, /if !safeStartup \{\s*backup\.startLibraryChangeMonitoring\(login: model\)/)
  const boot = login.slice(login.indexOf('        .task {'), login.indexOf('        .onReceive('))
  assert.doesNotMatch(boot, /clearSavedLogin\(\)|removePersistentDomain|XDriveIOSNativeOwnerSessionStore\.clear/)
})

test('BGTaskScheduler registers only once with validated bundled identifier', () => {
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  const task = read('ios/XDriveIOS/BackgroundPhotoTask.swift')
  const body = task.slice(task.indexOf('static func registerAtLaunch()'),
    task.indexOf('@MainActor\n    private static func handle'))
  assert.match(app, /XDriveIOSBackgroundPhotoTask\.registerAtLaunch\(\)/)
  assert.match(body, /guard !attemptedRegistration else \{ return \}/)
  assert.match(body, /attemptedRegistration = true/)
  assert.match(body, /BGTaskSchedulerPermittedIdentifiers/)
  assert.match(body, /allowed\.contains\(identifier\)/)
  assert.match(body, /registeredAtLaunch = BGTaskScheduler\.shared\.register\(/)
  assert.match(task, /guard registeredAtLaunch else \{\s*throw XDriveIOSBGRegistrationFailure\.unavailable/)
})
