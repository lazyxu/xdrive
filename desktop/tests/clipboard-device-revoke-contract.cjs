'use strict'
const assert = require('node:assert/strict')
const test = require('node:test')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')
const ui = read('ui/shared/src/mui/ClipboardPage.tsx')
const api = read('web/src/api.ts')
const adapter = read('web/src/clipboardDataPort.ts')
test('Clipboard device revocation is an explicit two-step Owner UI action', () => {
  assert.match(ui,/setConfirmRevoke\(true\)/)
  assert.match(ui,/撤销此设备的 Clipboard 授权/)
  assert.match(ui,/确认撤权/)
  assert.match(ui,/setConfirmRevoke\(false\)/)
  assert.match(ui,/await port\.revokeDevice!\(selected, signal\)/)
  assert.match(ui,/setTargetDevices\(rows => rows\.filter\(row => row\.device_id !== selected\)\)/)
})
test('revocation uses narrow Owner API, no native device identity or SourceRun writer', () => {
  assert.match(adapter,/revokeDevice: \(id, signal\) => api\.clipboardRevokeDevice\(id, signal\)/)
  const fragment=api.slice(api.indexOf('  clipboardRevokeDevice('),api.indexOf('  clipboardItems(',api.indexOf('  clipboardRevokeDevice(')))
  assert.match(fragment,/method: 'POST'/)
  assert.match(fragment,/encodeURIComponent\(deviceID\)/)
  assert.match(fragment,/cache: 'no-store'/)
  assert.doesNotMatch(fragment,/SourceRun|Device-Token|UploadSession|plaintext/)
})
