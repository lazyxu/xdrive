test('Desktop and Web mount the same HTTPS Places UI with prototype default',()=>{
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const gallery=read('ui/shared/src/mui/MediaGallery.tsx')
  const desktop=read('desktop/src/renderer/App.tsx')
  const web=read('web/src/App.tsx')
  const mode=read('ui/shared/src/media-gallery-places-map-mode.ts')
  assert.match(map,/data-xdrive-desktop-places-shared-web/)
  assert.match(map,/component=\{'webview' as 'div'\}/)
  assert.match(map,/display:'flex',width:'100%'/)
  assert.match(map,/desktopEmbeddedPlacesURL/)
  assert.match(gallery,/desktopEmbeddedPlacesURL=\{desktopEmbeddedPlacesURL\}/)
  assert.match(desktop,/desktopEmbeddedPlacesURL: xDriveDesktopEmbeddedPlacesURL\(status\?\.server\)/)
  assert.match(web,/data-xdrive-desktop-places-web-page/)
  assert.equal((web.match(/<XDriveMediaGalleryPage\b/g)||[]).length,1,
    'normal Web and embedded HTTPS map must share one Gallery implementation')
  assert.match(web,/onOpenViewer=\{placesEmbedRequested \? undefined :/)
  assert.match(web,/onSectionRouteChange=\{placesEmbedRequested \? undefined :/)
  assert.match(web,/initialMapPhotoScope=\{placesEmbedRequested \? placesEmbedScope/)
  assert.match(web,/<XDriveMediaGalleryPage/)
  assert.match(mode,/if \(selections.length === 0\) return 'prototype'/)
  assert.match(desktop,/\?desktop_places_embed=1#\/app\/gallery\?section=places/)
  assert.doesNotMatch(map,/allowRunningInsecureContent/)
})

test('webview guest exposes no native Agent, only same-Owner HTTPS Web login',()=>{
  const main=read('desktop/src/main/index.cts')
  const guest=read('desktop/src/preload/places_embed.cts')
  const web=read('web/src/App.tsx')
  assert.match(main,/webviewTag: true/)
  const html=read('desktop/src/renderer/index.html')
  assert.match(html,/frame-src http:\/\/127\.0\.0\.1:\* https:/)
  assert.match(main,/session\.fromPartition\(desktopPlacesWebPartition,\{cache:false\}\)/)
  assert.match(main,/placesSession\.setPermissionRequestHandler/)
  assert.match(main,/placesSession\.setPermissionCheckHandler\(\(\)=>false\)/)
  assert.match(main,/will-attach-webview/)
  assert.match(main,/params\.src!==expected/)
  assert.match(main,/params\.partition!==desktopPlacesWebPartition/)
  assert.match(main,/preferences\.nodeIntegration=false/)
  assert.match(main,/preferences\.contextIsolation=true/)
  assert.match(main,/preferences\.sandbox=true/)
  assert.match(main,/desktopPlacesGuests\.set\(guest\.id,identity\)/)
  assert.match(main,/event\.senderFrame!==event\.sender\.mainFrame/)
  assert.match(main,/closeDesktopPlacesGuests\(\)/)
  assert.match(main,/if \(guest && !guest\.isDestroyed\(\)\) guest\.close\(\)/)
  assert.match(main,/guest\.close\(\);return/)
  assert.doesNotMatch(main,/guest\.destroy\(\)/)
  assert.match(guest,/contextBridge\.exposeInMainWorld\('xdrivePlacesEmbedBridge'/)
  assert.doesNotMatch(guest,/node:fs|readFile\(|exec\(|getMedia|cloud[A-Z]|setCookie/)
  assert.deepEqual([...guest.matchAll(/ipcRenderer\.invoke\('([^']+)'/g)]
    .map(m=>m[1]).sort(),
    ['desktop:places-embed-consume','desktop:places-embed-expected-owner'],
    'Guest preload may call only these two Owner-bound read-only IPC operations')
  assert.match(web,/profile\.username!==placesEmbedOwner/)
  assert.match(web,/placesEmbedStatus==='denied'/)
  assert.match(web,/placesEmbedRequested && !placesEmbedBridge/)
  assert.match(web,/不会显示其他账户的照片/)
})

test('filtered Desktop HTTPS maps do not silently widen to all-library positions',()=>{
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const web=read('web/src/App.tsx')
  assert.match(map,/xDriveNormalizeBaiduMapPhotoScope\(embedScopeRef.current\)/)
  // The production prepare path is deadline- and cancellation-fenced;
  // never reintroduce an unbounded .then() on an Owner-scoped grant.
  assert.match(map,/return embedPrepareRef\.current!\(scope\)/)
  assert.match(map,/void xDrivePlacesRequestWithDeadline\(/)
  assert.match(map,/request,controller\.signal,XDRIVE_PLACES_EMBED_PREPARE_TIMEOUT_MS/)
  assert.match(map,/if\(!active \|\| controller\.signal\.aborted\)return/)
  assert.match(map,/setEmbedPrepared\(\{key:embedIdentity,state:'denied'\}\)/)
  assert.match(web,/initialMapPhotoScope=\{placesEmbedRequested \? placesEmbedScope/)
  assert.match(web,/placesEmbedStatus!=='ready' \|\| !placesEmbedScope/)
  assert.match(map,/did-fail-load/)
  assert.match(map,/render-process-gone/)
  assert.doesNotMatch(map,/setDesktopFallback|GPS 备用地图|OwnerGPSOverview|data-xdrive-owner-gps/)
})

test('Map session or SDK failure is explicit, retryable and never changes provider',()=>{
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const main=read('desktop/src/main/index.cts')
  assert.match(map,/data-xdrive-desktop-map-unavailable/)
  assert.match(map,/data-xdrive-baidu-map-unavailable/)
  assert.match(map,/重试 Web 地图/)
  assert.match(map,/onClick=\{\(\) => setEmbedRetry\(n=>n\+1\)\}/)
  assert.doesNotMatch(map,/GPS 备用地图|GPS 位置概览|desktopFallback/)
  assert.doesNotMatch(main,/GPS 备用地图/)
})
