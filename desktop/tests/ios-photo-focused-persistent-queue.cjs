'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')

const controller = read('ios/XDriveIOS/NativePhotoBackupController.swift')
const runner = read('ios/XDriveIOS/ForegroundPhotoBackupMVP.swift')
const queue = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
const schedule = read('ios/XDriveIOS/PhotoAutoScheduleStore.swift')
const helperStart = controller.indexOf('private func prepareFocusedIncrementalQueue(')
const focusedStart = controller.indexOf('private func runFocused(', helperStart)
assert.ok(helperStart > 0 && focusedStart > helperStart, 'Focused queue helper must be isolated')
const prepare = controller.slice(helperStart, focusedStart)
const focused = controller.slice(focusedStart)

test('Focused queue admission is only for a live, consented, nonpaused only-new Owner', () => {
  assert.match(prepare, /status\(owner: owner\)/)
  assert.match(prepare, /plan\.enabled, plan\.backupStartRule == \.onlyNew/)
  assert.match(prepare, /!plan\.pausedForReview/)
  assert.match(prepare, /!plan\.requiresFullLibraryReconciliation/)
  assert.match(prepare, /active\.enabled, active\.backupStartRule == \.onlyNew/)
  assert.match(prepare, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, owner\)/)
  assert.match(prepare, /XDriveIOSNativePhotoOwnerScope\.matches\(runningOwner, owner\)/)
  assert.match(prepare, /UIApplication\.shared\.applicationState == \.active/)
  assert.match(prepare, /displayEpoch == uiEpoch/)
  assert.match(prepare, /current\.authorization == expectedEpoch\.authorization/)
  assert.match(prepare, /expectedEpoch\.serialized, as: current\.token/)
})

test('Focused prepares the exact durable change history before any positional source writes', () => {
  assert.match(prepare, /try Task\.checkCancellation\(\)/)
  assert.match(prepare, /queue\.replay\(owner: owner, maximumEvents: 4\)/)
  assert.match(prepare, /queue\.isCaughtUp\(owner: owner\)/)
  assert.match(prepare, /guard batch\.events > 0 else/)
  assert.match(prepare, /await Task\.yield\(\)/)
  assert.match(queue, /store\.apply\([\s\S]*?expectedToken: previousToken, nextToken: nextToken/)
  const created = focused.indexOf('let focusedChangeQueue = try await prepareFocusedIncrementalQueue(')
  const firstWindow = focused.indexOf('let resume = XDriveIOSPhotoFocusedResumeStore.shared.resume(')
  const source = focused.indexOf('let result = try await XDriveIOSForegroundPhotoBackupMVP(')
  assert.ok(created >= 0 && firstWindow > created && source > firstWindow)
  assert.match(focused, /changeQueue: focusedChangeQueue/)
  assert.match(runner, /changeQueue\.pendingCandidates\([\s\S]*?owner: owner, limit: 64/)
  assert.match(runner, /changeQueue\.settle\([\s\S]*?candidate\.pending, result: \.confirmed, owner: owner/)
  assert.doesNotMatch(prepare, /UploadSession|finalize\(|uploadPrepared\(/)
})

test('Lost PhotoKit history pauses only-new auto until separate full-library recovery consent', () => {
  assert.match(prepare, /Failure\.requiresExplicitBaseline/)
  assert.match(prepare, /Failure\.invalidArchivedToken/)
  assert.match(prepare, /Failure\.historyUnavailable/)
  assert.match(prepare, /requireFullLibraryReconciliation\(owner: owner\)/)
  assert.match(prepare, /Failure\.authorizationChanged[\s\S]*?throw XDriveIOSFocusedBackupFailure\.libraryChanged/)
  assert.match(schedule, /func confirmFullLibraryReconciliation\(/)
  assert.doesNotMatch(prepare, /installNewOnlyBaseline|completeFullLibraryReconciliation|finishFullLibraryReconciliation|reserveDue\(/)
})

test('Focused retains the existing bounded original writer, receipt and cursor safety', () => {
  assert.match(focused, /XDriveIOSNativePhotoBackupDestinationModel\s*\.readExistingForUpload\(/)
  assert.match(focused, /managed\.destination\.sourceID == initialSourceID/)
  assert.match(focused, /managed\.destination\.targetNodeID == initialTargetNodeID/)
  assert.match(focused, /XDriveIOSPhotoFocusedResumeStore\.shared\.saveCompletedWindow\(/)
  assert.match(focused, /XDriveIOSPhotoFocusedBackupPolicy\.afterWindow\(/)
  assert.match(focused, /state\.pausedForReview = true/)
  assert.match(runner, /static let maxNewOriginalsPerRun = 20/)
  assert.match(runner, /case \.requiresReview:/)
  assert.doesNotMatch(prepare, /XDriveNativeUploadSessionTransport|URLSession\(/)
})


test('Focused accepts a genuine twenty-item priority queue before positional scanning without bypassing review', () => {
  const policy = read('ios/XDriveIOS/PhotoFocusedBackupPolicy.swift')
  const checks = read('ios/tests/PhotoFocusedBackupPolicyChecks.swift')
  assert.match(policy, /queuedUploaded >= 0, queuedUploaded <= uploaded/)
  assert.match(policy, /uploaded - queuedUploaded <= scanned/)
  assert.match(policy, /uploaded <= XDriveIOSPhotoAutoSchedulePolicy\.maxNewFiles/)
  assert.match(focused, /XDriveIOSPhotoFocusedBackupPolicy\.afterWindow\([\s\S]*?queuedUploaded: result\.changeQueueUploaded/)
  assert.match(runner, /var changeQueueUploaded = 0/)
  assert.match(runner, /report\.changeQueueUploaded \+= 1/)
  assert.match(checks, /scanned: 0, uploaded: 20,[\s\S]*?needsReview: false, queuedUploaded: 20/)
  assert.match(checks, /scanned: 0, uploaded: 20,[\s\S]*?needsReview: false, queuedUploaded: 19/)
  assert.match(checks, /index: 2, visibleTotal: 513, scanned: 1, uploaded: 20/)
  assert.doesNotMatch(policy, /UploadSession|URLSession|Server\.shared/)
})
