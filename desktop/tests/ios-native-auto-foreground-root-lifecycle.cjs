'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const login = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')
const dash = read('ios/XDriveIOS/NativePhotosDashboard.swift')
const ctrl = read('ios/XDriveIOS/NativePhotoBackupController.swift')
const backupScreen = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')

test('one authenticated native root owns the foreground schedule across Photos navigation', () => {
  assert.match(login, /@StateObject private var model = XDriveIOSNativeOwnerLoginModel/)
  assert.match(login, /@StateObject private var backup = XDriveIOSNativePhotoBackupController/)
  assert.match(login, /@Environment\(\\.scenePhase\) private var phase/)
  assert.match(login, /\.onReceive\(Timer\.publish\(every: 60/)
  assert.match(login, /\.onChange\(of: phase\)/)
  assert.match(login, /\.onChange\(of: model.owner\)/)
  assert.match(login, /backup\.tickIfDue\(login: model\)/)
  assert.match(login, /else \{ backup\.cancel\(\) \}/)
  assert.match(login, /if model\.owner != nil \{[\s\S]*?XDriveIOSNativePhotosDashboard\(/)
  assert.doesNotMatch(login, /showingNativeWorkspace|verifiedAccount\(/)
  assert.match(dash, /@ObservedObject var backup: XDriveIOSNativePhotoBackupController/)
  assert.match(dash, /XDriveIOSNativePhotoBackupScreen\(login: login, controller: backup\)/)
  assert.doesNotMatch(dash, /Timer\.publish|@StateObject private var backup|backup\.cancel\(\)/)
})

test('root Owner switching and logout cannot keep a previous upload alive', () => {
  const changes = login.slice(login.indexOf('.onChange(of: model.owner)'),login.indexOf('    private var loginForm'))
  assert.ok(changes.indexOf('backup.cancel()') < changes.indexOf('backup.refresh(owner: model.owner)'))
  assert.ok(changes.indexOf('backup.refresh(owner: model.owner)') < changes.indexOf('backup.tickIfDue(login: model)'))
  assert.match(login, /guard let gate = XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(login, /XDriveIOSPhotoAutoScheduleStore\.shared\.disableAllOnThisDevice\(\)/)
  assert.match(login, /XDriveIOSBackgroundPhotoTask\.revokePendingRequests\(\)/)
  assert.match(ctrl, /guard !busy, running == nil/)
  assert.match(ctrl, /XDriveIOSOriginalRunGate\.shared\.release\(gate\)/)
})

test('Photos permission revocation and limited access are accurately disclosed on foreground return', () => {
  assert.match(dash, /@Environment\(\\\.scenePhase\) private var phase/)
  assert.match(dash, /@State private var photoAuthorization = PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(dash, /onChange\(of: phase\) \{ state in[\s\S]*?photoAuthorization = PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)[\s\S]*?backup\.refresh\(owner: login\.owner\)/)
  assert.match(dash, /if state\.pausedForReview[\s\S]*?备份计划已保存：照片权限不可用[\s\S]*?前台自动备份：仅处理已授权照片/)
  assert.match(backupScreen, /native-ios-photos-auto-permission-blocked/)
  assert.match(backupScreen, /native-ios-photos-auto-permission-limited/)
  assert.match(backupScreen, /onChange\(of: phase\) \{ state in[\s\S]*?photoAuthorization = PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(backupScreen, /Live ZIP 通过双资源校验后可在 Viewer 中播放原生实况/)
  assert.doesNotMatch(backupScreen, /尚不支持云端动态播放/)
  assert.doesNotMatch(dash + backupScreen, /PHPhotoLibrary\.requestAuthorization|PHPhotoLibrary\.shared\(\)\.performChanges/)
})

test('revoked PhotoKit permission cannot silently accept a manual original backup', () => {
  const manual = backupScreen.slice(backupScreen.indexOf('Section("手动备份")'),
    backupScreen.indexOf('Section("前台自动增量")'))
  const startManual = ctrl.slice(ctrl.indexOf('    func startManual('),
    ctrl.indexOf('    func tickIfDue('))
  assert.match(manual, /if photoAuthorization != \.authorized && photoAuthorization != \.limited/)
  assert.match(manual, /native-ios-photos-manual-permission-blocked/)
  assert.match(manual, /\.disabled\(controller\.busy \|\| background\.busy \|\| login\.owner == nil \|\|\s*\(photoAuthorization != \.authorized && photoAuthorization != \.limited\)\)/)
  assert.match(startManual, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expectedOwner\)/)
  assert.match(startManual, /guard \[\.authorized, \.limited\]\.contains\(\s*PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)\s*\) else \{/)
  assert.match(startManual, /if !busy \{ progress = nil \}/)
  assert.match(startManual, /errorMessage = "照片读取权限已变化；未启动原件上传/)
  const permission = startManual.indexOf('PHPhotoLibrary.authorizationStatus(for: .readWrite)')
  const start = startManual.indexOf('start(login: login, kind: .manual')
  assert.ok(permission > 0 && start > permission, 'recheck authorization before any native manual original writer')
  assert.doesNotMatch(startManual, /requestAuthorization|URLSession|UploadSessionTransport/)
})

test('saved auto-backup status and enable action do not advertise success without Photos access', () => {
  const auto = backupScreen.slice(backupScreen.indexOf('Section("前台自动增量")'),
    backupScreen.indexOf('Section("可选系统后台原件备份")'))
  const paused = auto.indexOf('if active.pausedForReview')
  const blocked = auto.indexOf('else if photoAuthorization != .authorized && photoAuthorization != .limited')
  const limited = auto.indexOf('else if photoAuthorization == .limited')
  const enabled = auto.indexOf('Label("前台自动备份已开启"')
  assert.ok(paused >= 0 && paused < blocked && blocked < limited && limited < enabled,
    'pending receipt pause outranks revoked/limited permission status')
  assert.match(auto, /备份计划已保存：照片权限不可用/)
  assert.match(auto, /前台自动备份：仅处理已授权照片/)
  assert.match(auto, /\.disabled\(controller\.busy \|\| background\.busy \|\| login\.owner == nil \|\|\s*\(photoAuthorization != \.authorized && photoAuthorization != \.limited\)\)\s*\.accessibilityIdentifier\("native-ios-photos-auto-enable"\)/)
  assert.match(backupScreen, /onChange\(of: phase\) \{ state in[\s\S]*?photoAuthorization = PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.doesNotMatch(auto, /requestAuthorization|UploadSession|performChanges/)
})
