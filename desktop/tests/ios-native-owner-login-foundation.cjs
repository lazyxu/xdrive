'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

const store = read('ios/XDriveIOS/NativeOwnerSessionStore.swift')
const model = read('ios/XDriveIOS/NativeOwnerLoginModel.swift')
const screen = read('ios/XDriveIOS/NativeOwnerLoginScreen.swift')

test('native Login remains SwiftUI and mounts only after native Photos integration', () => {
  assert.match(screen, /struct XDriveIOSNativeOwnerLoginScreen: View/)
  assert.match(screen, /@StateObject private var model = XDriveIOSNativeOwnerLoginModel/)
  assert.match(screen, /native-ios-login-server/)
  assert.match(screen, /native-ios-login-username/)
  assert.match(screen, /native-ios-login-password/)
  assert.match(screen, /native-ios-login-submit/)
  assert.match(read('ios/XDriveIOS/NativePhotosDashboard.swift'), /native-ios-login-signout/)
  assert.doesNotMatch(screen, /WebView|URLSession|fetch\(|window\.webkit/)
  const app = read('ios/XDriveIOS/XDriveIOSApp.swift')
  assert.match(app, /XDriveIOSNativeOwnerLoginScreen\(\)/, 'verified native Photos cutover')
  assert.doesNotMatch(app, /XDriveWebAppHome\(\)/)
  assert.match(screen, /XDriveIOSNativePhotosDashboard\(\s*login: model,\s*backup: backup,/)
})

test('new native Keychain namespace never reuses purged legacy refresh or background Device secrets', () => {
  const retired = read('ios/XDriveIOS/IOSRetiredNativeLogin.swift')
  assert.match(store, /com\.lazyxu\.xdrive\.ios\.native-owner-session\.v2/)
  assert.match(store, /kSecAttrAccessibleWhenUnlockedThisDeviceOnly/)
  assert.match(store, /kSecAttrService as String: service/)
  assert.match(store, /kSecAttrAccount as String: account/)
  assert.match(store, /SecItemUpdate/)
  assert.match(store, /guard try load\(\) == value/)
  assert.match(store, /SecItemDelete/)
  assert.match(retired, /com\.lazyxu\.xdrive\.ios\.session/)
  assert.doesNotMatch(store, /com\.lazyxu\.xdrive\.ios\.session"/)
  assert.doesNotMatch(store, /bg-approved|device-identity|WhenUnlockedThisDeviceOnly.*AfterFirstUnlock/)
  assert.doesNotMatch(store, /UserDefaults\.standard\.set|import WebKit|WKWebView\(|document\.cookie|print\(/)
})

test('native login and restoration re-prove exact Server Owner/root, not JS cookies', () => {
  assert.match(model, /AuthService\(origin: origin\)\.login\(/)
  assert.match(model, /AuthService\(origin: origin\)\.refresh\(/)
  assert.match(model, /XDriveNativeOwnerRootVerifier\(/)
  assert.match(model, /ownerMatchesSaved\(verified, saved: saved\)/)
  assert.match(model, /refreshed\.username == saved\.username/)
  assert.match(model, /response\.username == requestedUsername/)
  assert.match(model, /generation == ticket/)
  assert.match(model, /sameScope\(fresh, snapshot\.verifiedOwner\)/)
  assert.match(model, /XDriveIOSNativeOwnerSessionStore\.clear\(\)/)
  assert.match(model, /refreshed\.must_change_password != true/)
  assert.match(model, /response\.must_change_password != true/)
  assert.match(model, /serverText == serverInput/)
  assert.doesNotMatch(model, /import WebKit|WKWebView\(|window\.webkit|document\.cookie|localStorage|setCookie|SecItemAdd\(/)
  assert.match(read('ios/XDriveIOS/AuthService.swift'), /completionHandler\(nil\)/)
  assert.match(read('ios/XDriveIOS/OwnerRootVerifier.swift'), /"\/api\/v1\/me"/)
  assert.match(read('ios/XDriveIOS/OwnerRootVerifier.swift'), /"\/api\/v1\/nodes\/root"/)
})

test('native logout clears the in-memory session before revocation and does not forge remote success', () => {
  const logout = model.slice(model.indexOf('func signOut() async'))
  assert.ok(logout.indexOf('generation &+= 1') < logout.indexOf('active = nil'))
  assert.ok(logout.indexOf('active = nil') < logout.indexOf('XDriveIOSNativeOwnerSessionStore.clear()'))
  assert.ok(logout.indexOf('XDriveIOSNativeOwnerSessionStore.clear()') < logout.indexOf('AuthService(origin: previous.origin).logout'))
  assert.match(logout, /服务器会话撤销尚未确认/)
})
