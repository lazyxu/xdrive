'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const map = read('ios/XDriveIOS/NativeLocalPhotoMap.swift')
const spatial = read('ios/XDriveIOS/NativeLocalPhotoMapSpatialPolicy.swift')
const swift = read('ios/tests/NativeLocalPhotoMapSpatialPolicyChecks.swift')

test('native PhotoKit map does not rescan 100k assets on every camera gesture', () => {
  assert.match(spatial, /enum XDriveIOSNativeLocalMapAutoRefinePolicy \{/)
  assert.match(spatial, /static let settleNanoseconds: UInt64 = 900_000_000/)
  assert.match(spatial, /static func shouldRefine\(/)
  assert.match(spatial, /visibleLatitude <= maximumLatitudeSpan/)
  assert.match(spatial, /visibleLongitude <= maximumLongitudeSpan/)
  assert.match(spatial, /if !XDriveIOSNativeLocalMapSpatialPolicy\.containsViewport\(/)
  assert.match(spatial, /return visibleLatitude \* 4 <= scannedLatitude &&/)
  assert.match(spatial, /static func expandedViewport\(/)
  assert.match(map, /private func scheduleAutomaticRefinement\(_ current: MKCoordinateRegion\)/)
  assert.match(map, /autoRefineTask\?\.cancel\(\)/)
  assert.match(map, /try await Task\.sleep\(/)
  assert.match(map, /generation == ticket/)
  assert.match(map, /XDriveIOSNativeLocalMapSpatialPolicy\.matchesViewport\(\s*cameraViewport, current: finalViewport/)
  assert.match(map, /XDriveIOSNativeLocalMapAutoRefinePolicy\.shouldRefine\(\s*finalViewport, scanned: globalViewport/)
  assert.match(map, /scanFullLibrary\(viewport: padded, preserveCurrentMap: true\)/)
  assert.match(map, /onCamera: \{ current in[\s\S]*?scheduleAutomaticRefinement\(current\)/)
  assert.match(map, /onCameraWillChange: \{[\s\S]*?autoRefineTask\?\.cancel\(\)[\s\S]*?suspendForSheet\(\)/)
  assert.doesNotMatch(map, /Timer\.scheduledTimer|DispatchQueue\.main\.asyncAfter|UserDefaults\.|UploadSession/)
})

test('auto refinement keeps the old inert MapKit camera while a bounded PhotoKit scan runs', () => {
  assert.match(map, /preserveCurrentMap: Bool = false/)
  assert.match(map, /let keepOldMap = preserveCurrentMap && viewport != nil && globalComplete/)
  assert.match(map, /if keepOldMap \{[\s\S]*?suspendForSheet\(\)[\s\S]*?globalCameraMoving = true/)
  assert.match(map, /if keepOldMap \{[\s\S]*?globalCameraMoving = false[\s\S]*?else \{\s*globalCells = \[\]/)
  assert.match(map, /globalCells = index\.cells[\s\S]*?globalViewport = viewport[\s\S]*?globalComplete = true/)
  assert.match(map, /private var refinedViewportIsCurrent: Bool \{[\s\S]*?containsViewport\(/)
  assert.match(map, /canSelectCells: refinedViewportIsCurrent/)
  assert.match(map, /guard phase == \.active, !busy, globalComplete/)
  assert.match(map, /private func suspendForSheet\(\) \{\s*autoRefineTask\?\.cancel\(\)/)
  assert.match(map, /if target == nil \|\|[\s\S]*?map\.setRegion\(cameraReturn, animated: false\)/)
  assert.match(map, /Button\("细化当前视窗的定位照片"\)/)
  assert.match(map, /Button\("还原已授权全库概览"\)/)
  assert.doesNotMatch(map, /isNetworkAccessAllowed = true|localStorage|CoreData/)
})

test('PhotoKit WGS84 auto-refine policy has executed Swift fixtures for coverage, zoom, dateline and cancellation gates', () => {
  assert.match(spatial, /static func containsViewport\(/)
  assert.match(spatial, /let start = delta < 0 \? delta \+ 360 : delta/)
  assert.match(swift, /precondition\(Policy\.containsViewport\(expandedSF, current: sanFrancisco\)\)/)
  assert.match(swift, /precondition\(!Auto\.shouldRefine\(sanFrancisco, scanned: expandedSF\)\)/)
  assert.match(swift, /precondition\(!Auto\.shouldRefine\(nearby, scanned: expandedSF\)\)/)
  assert.match(swift, /precondition\(Auto\.shouldRefine\(zoomed, scanned: expandedSF\)\)/)
  assert.match(swift, /precondition\(Auto\.shouldRefine\(farAway, scanned: expandedSF\)\)/)
  assert.match(swift, /precondition\(!Auto\.shouldRefine\(worldCamera, scanned: nil\)\)/)
  assert.match(swift, /precondition\(Policy\.containsViewport\(datelineWindow, current: wrappedCamera\)\)/)
})
