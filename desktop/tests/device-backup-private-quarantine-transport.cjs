const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('L03-E0b quarantine calls remain owning-Agent private without SourceRun authority', () => {
  const server = read('internal', 'api', 'local_source_commit_intents.go')
  const route = read('internal', 'api', 'router.go')
  const client = read('internal', 'client', 'local_source_commit_intents.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_commit_intents.go')
  const testClient = read('internal', 'client', 'local_source_commit_intents_test.go')
  const testAgent = read('cmd', 'xdrive-agent', 'device_backup_local_commit_intents_test.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(server, /LocalSourceCommitIntentStateQuarantined/)
  assert.match(server, /CommitSupported: false, Authoritative: false, MissingInferenceSafe: false/)
  assert.match(route, /"\/sources\/:id\/local-identity\/commit-intents", s\.requireLocalSourceExecutor\(\)/)
  assert.match(client, /QuarantineLocalSourceCommitIntents\(/)
  assert.match(client, /localRulesProofHeaders\(req, proof\)/)
  assert.match(client, /DisallowUnknownFields\(\)/)
  assert.match(client, /resp\.StatusCode != http\.StatusCreated && resp\.StatusCode != http\.StatusOK/)
  assert.match(client, /got\.CommitSupported == nil/)
  assert.match(client, /got\.Authoritative == nil/)
  assert.match(client, /got\.MissingInferenceSafe == nil/)
  assert.match(agent, /quarantineLocalBoundBackupEvidencePage\(/)
  assert.match(agent, /localBoundBackupConfig\(workCtx, sourceID\)/)
  assert.match(agent, /localpush\.LoadLocalReconcileEvidence\(/)
  assert.match(agent, /localpush\.HashCurrentLocalEvidenceBatch\(/)
  assert.match(agent, /cli\.CheckLocalSourceItemCloudMetadata\(/)
  assert.match(agent, /cli\.PreflightLocalSourceItemEvidence\(/)
  assert.match(agent, /submitLocalQuarantineBatch\(/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /localFolderGrantMu\.TryLock\(\)/)
  assert.match(testClient, /TestOwningAgentQuarantineClientRequestContextCancellation/)
  assert.match(testAgent, /TestSubmitLocalQuarantineBatchRejectsUnsafeCallsAndContextCancellation/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  assert.doesNotMatch(client, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  for (const exposed of [ipc, main, preload, web]) {
    assert.doesNotMatch(exposed, /local-identity\/commit-intents|quarantineLocalBoundBackupEvidencePage|QuarantineLocalSourceCommitIntents/)
  }
})
