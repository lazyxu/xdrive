const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..', '..')
const read = (filename) => fs.readFileSync(path.join(root, filename), 'utf8')

test('G11: cleanup distinguishes primary-hash matches from full-asset equivalence', () => {
  const handler = read('internal/api/media_cleanup.go')
  const comparison = read('internal/api/media_cleanup_equivalence.go')
  const query = read('internal/api/media_cleanup_comparison_query.go')
  const client = read('internal/client/media.go')
  const models = read('ui/shared/src/models.ts')
  const ui = read('ui/shared/src/mui/MediaGalleryCleanup.tsx')
  assert.match(handler, /AssetComparison.*asset_comparison/)
  assert.match(handler, /duplicateAssetComparisons\(ctx, ownerID, aggregates, byHash\)/)
  assert.match(comparison, /duplicateAssetUnverified/)
  assert.match(comparison, /reflect\.DeepEqual/)
  assert.match(comparison, /SourceNodeRevision != member\.NodeRevision/)
  assert.match(query, /duplicateComparisonMaxAssets/)
  assert.match(client, /AssetComparison.*asset_comparison/)
  assert.match(models, /asset_comparison\?: 'identical' \| 'different' \| 'unverified'/)
  assert.match(ui, /完整资产待核对/)
  assert.match(ui, /group\.asset_comparison_reason/)
  assert.match(ui, /只会处理选中的真实文件/)
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  assert.match(gallery, /asset_comparison === 'identical'/)
  assert.match(handler, /RecommendedKeepNodeID:\s+keepID/)
  assert.match(gallery, /主原文件相同副本/)
  assert.doesNotMatch(ui, /个完全相同副本/)
})
