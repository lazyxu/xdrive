'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const policy = read('ios/XDriveIOS/NativePhotoMapPolicy.swift')
const scanner = read('ios/XDriveIOS/PhotoKitBoundedSnapshotScanner.swift')
const local = read('ios/XDriveIOS/NativeLocalPhotoMap.swift')
const calendar = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
const timeline = read('ios/XDriveIOS/NativePhotoTimelineBrowser.swift')
const dashboard = read('ios/XDriveIOS/NativePhotosDashboard.swift')
const owner = read('ios/XDriveIOS/NativeOwnerPhotoMapGallery.swift')
const cluster = read('ios/XDriveIOS/NativeOwnerMapClusterAlbum.swift')
const reader = read('ios/XDriveIOS/NativeServerMediaGalleryTransport.swift')
const cloud = read('ios/XDriveIOS/NativeServerMediaGallery.swift')
const overview = read('internal/api/media_places_map_overview.go')
const viewport = read('internal/api/media_places_viewport.go')
const places = read('internal/api/media_places.go')
const trip = read('internal/api/media_trip_exact_map.go')

test('PhotoKit calendar day/year scope survives map scan, exact place re-scan and Viewer', () => {
  assert.match(policy, /struct XDriveIOSNativePhotoMapCaptureRange: Equatable/)
  assert.match(policy, /calendar\.date\(byAdding: \.day, value: 1/)
  assert.match(policy, /func contains\(_ capturedAt: Date\?\)/)
  assert.match(scanner, /captureRange: XDriveIOSNativePhotoMapCaptureRange\? = nil/)
  assert.match(scanner, /format: "creationDate >= %@ AND creationDate < %@"/)
  assert.match(scanner, /andPredicateWithSubpredicates: \[existing, timePredicate\]/)
  assert.match(local, /inheritedCaptureRange: XDriveIOSNativePhotoMapCaptureRange\? = nil/)
  assert.match(local, /captureRange: selection\.captureRange/)
  assert.match(local, /captureRange: activeCaptureRange/)
  assert.match(local, /onChange\(of: activeMapMembership\)/)
  assert.match(local, /captureRange: activeCaptureRange, tripID: chosenLocalTrip\?\.id/)
  assert.match(local, /native-ios-local-map-capture-menu/)
  assert.match(calendar, /calendarMapRange = XDriveIOSNativePhotoMapCaptureRange\.dayKey/)
  assert.match(calendar, /inheritedCaptureRange: calendarMapRange/)
  assert.match(timeline, /setMapDateScope\(XDriveIOSNativePhotoMapCaptureRange\.year\(year\)\)/)
  assert.match(timeline, /setMapDateScope\(XDriveIOSNativePhotoMapCaptureRange\.month\(/)
  assert.match(timeline, /setMapDateScope\(XDriveIOSNativePhotoMapCaptureRange\.dayKey\(/)
  assert.match(timeline, /Button\(mediaFilter\.allItemsTitle\) \{\s*exactDateTarget = nil\s*setMapDateScope\(nil\)\s*jump\(to: 0\)/)
  assert.match(timeline, /mapCaptureRange = range\s*onMapDateScope\?\(range\)/)
  assert.match(calendar, /@Binding var calendarMapRange: XDriveIOSNativePhotoMapCaptureRange\?/)
  assert.match(dashboard, /onMapDateScope: \{ galleryMapCaptureRange = \$0 \}/)
  assert.match(dashboard, /inheritedCaptureRange: galleryMapCaptureRange/)
  assert.match(owner, /inheritedCaptureRange: inheritedCaptureRange/)
})

test('Owner map, 48-item wall and cross-page Viewer use one absolute date window', () => {
  assert.match(owner, /inheritedCaptureRange: XDriveIOSNativePhotoMapCaptureRange\? = nil/)
  assert.match(owner, /captureRange: activeCaptureRange/)
  assert.match(owner, /onChange\(of: activeCaptureRange\)/)
  assert.match(owner, /native-ios-owner-map-capture-menu/)
  assert.match(cluster, /let captureRange: XDriveIOSNativePhotoMapCaptureRange\?/)
  assert.match(cluster, /placeID: facet\.id, captureRange: selection\.captureRange/)
  assert.match(reader, /URLQueryItem\(name: "captured_from"/)
  assert.match(reader, /URLQueryItem\(name: "captured_to"/)
  assert.match(cloud, /pageCaptureRange == captureRange/)
  assert.match(cloud, /source\.pageCaptureRange == captureRange/)
  assert.match(cloud, /captureRange\?\.fromRFC3339/)
  assert.match(cloud, /model\.acceptVerifiedViewerRange\(/)
  assert.match(cloud, /model\.adoptVisibleRange\(/)
})

test('Server map and real-place counts share exact date+Owner SQL and reject bad query', () => {
  assert.match(overview, /func parseMediaMapOverviewScopedQuery\(/)
  assert.match(overview, /mediaCapturedBoundary\(fromValues\[0\], zone\)/)
  assert.match(overview, /mediaCapturedBoundary\(toValues\[0\], zone\)/)
  assert.match(overview, /mediaMapCaptureFilter\(mediaPlacesBaseQuery/)
  assert.match(viewport, /mediaMapCaptureFilter\(mediaPlacesBaseQuery/)
  assert.match(places, /mediaMapCaptureFilter\(mediaPlacesBaseQuery/)
  assert.match(overview, /mediaMapOverviewBucketBounds\(fitted/)
  assert.match(trip, /mediaMapOverviewBucketBounds\(fitted, r\.BucketRow, r\.BucketCol\)/)
  assert.doesNotMatch(trip, /reader\.page\(|allOwnerPhotoIDs|clientEnumerate/)
})
