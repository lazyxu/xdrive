test('1: gallery backup entry shares task, Focused, settings, audit and cache navigation', () => {
  for (const label of ['查看备份任务队列', '集中备份（需确认）',
    '备份设置', '逐项核验当前云端原件', '释放本机缓存空间（不删除照片原件）']) {
    assert.ok(dashboard.includes('Button("' + label + '")'))
  }
  assert.match(dashboard, /Menu \{ backupMenuItems \}/)
  assert.match(dashboard, /native-ios-backup-cache-sheet-close/)
  assert.match(dashboard, /launchAction: backupLaunchAction, launchNonce: backupLaunchNonce/)
  assert.match(backup, /case \.focused: openDetails\(\.progress\)/)
  assert.match(backup, /case \.queue: showTaskList = true/)
  assert.match(backup, /XDriveIOSNativePhotoBackupTaskList\(login: login, controller: controller\)/)
})

test('2: queue and authorized library are independently paged with strict Owner/PhotoKit gates', () => {
  assert.match(store, /func page\(state: ItemState\? = nil, offset: Int = 0, limit: Int = 32\)/)
  assert.match(store, /guard \(1\.\.\.64\)\.contains\(limit\), \(0\.\.\.1_000_000\)\.contains\(offset\)/)
  assert.match(store, /LEFT JOIN failure_reasons r ON r\.asset_id=e\.asset_id AND r\.revision=e\.revision/)
  assert.match(store, /WHERE e\.state=\?/)
  assert.match(store, /ORDER BY e\.queue_order DESC,e\.asset_id ASC LIMIT \? OFFSET \?/)
  assert.match(queue, /func page\(owner: XDriveNativeOwnerRoot,/)
  assert.match(queue, /XDriveIOSPhotoKitLibraryEpoch\.matches\(epoch\.serialized, as: after\.token\)/)
  assert.match(taskModel, /Self\.changePageSize \+ 1/)
  assert.match(taskModel, /let scanner = XDrivePhotoKitBoundedSnapshotScanner\(\)/)
  assert.match(taskModel, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, owner\)/)
  assert.match(taskModel, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\) == \.authorized/)
  assert.match(tasks, /Button\("上一页"\)/)
  assert.match(tasks, /Button\("下一页"\)/)
  assert.match(tasks, /item\.state == "failed" \? "核对并重试" : "优先处理"/)
  assert.doesNotMatch(taskModel + tasks, /createUploadSession|finalizeUploadSession|deleteNode/)
})

test('3 and 4: both Galleries display bounded truthful per-item state and processing/exclusion', () => {
  for (const raw of ['pending', 'waitingICloud', 'failed', 'confirmed', 'processing',
    'unverified', 'excluded']) {
    assert.ok(policy.includes('case "' + raw + '":'), raw)
  }
  assert.match(policy, /当前云端原件仍需重新核验/)
  assert.doesNotMatch(policy, /title: "已备份"/)
  assert.match(local, /XDriveIOSNativeVisiblePhotoQueueBadgePolicy/)
  assert.match(unified, /XDriveIOSNativeVisiblePhotoQueueBadgePolicy/)
  assert.match(local, /queue\.isCaughtUp\(owner: owner\)/)
  assert.match(unified, /queue\.isCaughtUp\(owner: owner\)/)
  assert.match(local, /case \.olderThanStart: return "excluded"/)
  assert.match(unified, /case \.olderThanStart: return "excluded"/)
  assert.match(dashboard, /backup\.busy \? backup\.progress\?\.activeLocalIdentifier : nil/)
  assert.match(writer, /var activeLocalIdentifier: String\? = nil/)
  assert.match(writer, /report\.activeLocalIdentifier = candidate\.id/)
  assert.match(writer, /report\.activeLocalIdentifier = localIdentifier/)
  assert.match(policy, /let defaultValue: \(\(String, Bool\) -> Void\)\? = nil/)
})

test('5 and 6: direct one-photo priority and failed retry only call existing one-writer API after native Owner consent', () => {
  assert.match(local, /\.contextMenu \{[\s\S]*?优先备份此原件/)
  assert.match(unified, /\.contextMenu \{[\s\S]*?优先备份此原件/)
  assert.match(gallery, /priorityBackup\(local\.id\)/)
  assert.match(viewer, /native-ios-local-viewer-priority-original/)
  assert.match(viewer, /priorityAction\(selectedID, false\)/)
  assert.match(tasks, /\.confirmationDialog\([\s\S]*?controller\.startSingle\(/)
  assert.match(dashboard, /showPriorityConsent = true/)
  assert.match(dashboard, /backup\.startSingle\(/)
  assert.match(controller, /func startSingle\(login: XDriveIOSNativeOwnerLoginModel,/)
  assert.match(controller, /retryFailedSingle\(/)
  assert.match(controller, /XDriveIOSForegroundPhotoBackupMVP\(/)
  assert.match(dashboard, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.doesNotMatch(local + unified + dashboard + tasks, /uploadPrepared\(|finalizeUploadSession\(/)
})

