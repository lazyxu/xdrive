'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

const dashboard = read('ios/XDriveIOS/NativePhotosDashboard.swift')
const backup = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')
const tasks = read('ios/XDriveIOS/PhotoQueueSummarySection.swift')
const taskModel = read('ios/XDriveIOS/NativePhotoQueueSummaryModel.swift')
