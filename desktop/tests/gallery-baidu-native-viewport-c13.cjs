'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('A3c13 new map viewport is fixed BD09 and never reuses original GPS endpoint', () => {
  const route = read('internal/api/router.go')
  const handler = read('internal/api/baidu_jsapi4_native_viewport_http.go')
  const query = read('internal/api/baidu_photo_map_viewport.go')
  assert.match(route, /authed\.GET\("\/media\/places\/baidu-jsapi\/viewport", s\.listBaiduNativeMapViewport\)/)
  assert.match(handler, /currentBaiduJSAPI4OperatorRelease/)
  assert.match(handler, /verifiedMapBootstrapIdentity/)
  assert.match(handler, /meta\.BaiduPhotoMapSpaceBD09LL/)
  assert.match(handler, /queryBaiduPhotoMapViewport/)
  assert.doesNotMatch(handler, /mediaPlacesWithinViewport|StaticStepCenter|\bWGS84Coordinate\s*\{/)
  assert.match(query, /c\.revision = p\.consent_revision/)
  assert.match(query, /p\.source_latitude = m\.latitude AND p\.source_longitude = m\.longitude/)
  assert.match(query, /p\.primary_node_id AS node_id/)
  assert.match(read('internal/api/router_contract_test.go'), /baidu-jsapi\/viewport/)
})

test('A3c13 all three client paths share the same Server bound and cancellation', () => {
  const web = read('web/src/api.ts')
  const webAdapter = read('web/src/mediaGalleryAdapter.ts')
  const ui = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const desktopAdapter = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const bridge = read('desktop/src/main/index.cts')
  const client = read('desktop/src/main/agent_client.cts')
  const preload = read('desktop/src/preload/index.cts')
  const agent = read('cmd/xdrive-agent/desktop_ipc_baidu_native_viewport.go')
  assert.match(web, /mediaBaiduNativeViewport\(/)
  assert.match(web, /\/media\/places\/baidu-jsapi\/viewport/)
  assert.match(webAdapter, /listBaiduNativeViewport/)
  assert.match(ui, /listBaiduNativeViewport/)
  assert.match(ui, /resolveXDriveTransport\(/)
  assert.match(desktopAdapter, /getMediaBaiduNativeViewport/)
  assert.match(desktopAdapter, /xDriveDesktopViewportRequest\(signal/)
  assert.match(preload, /getMediaBaiduNativeViewport/)
  assert.match(bridge, /agent:get-media-baidu-native-viewport/)
  assert.match(bridge, /requireAgentCapability\(hello, 'media-gallery'\)/)
  assert.match(client, /\/v1\/media\/places\/baidu-native-viewport/)
  assert.match(agent, /parseDesktopIPCMediaPlacesViewport/)
  assert.match(agent, /q\.Get\("coordinate_space"\) != "bd09ll"/)
  assert.match(read('cmd/xdrive-agent/desktop_ipc.go'), /"GET \/v1\/media\/places\/baidu-native-viewport"/)
  assert.doesNotMatch(web, /ak=|_BMapSecurityConfig/)
})

