const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Desktop determines verified local identity only from Agent OS enrollment and Server credential proof', () => {
  const server = read('internal', 'api', 'client_devices.go')
  const router = read('internal', 'api', 'router.go')
  const client = read('internal', 'client', 'devices.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_identity.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  assert.ok(router.includes('GET("/devices/self", s.verifyCurrentClientDevice)'))
  assert.ok(server.includes('clientDeviceCredentialMatches(device, c.GetHeader("X-XDrive-Device-Token"))'))
  assert.ok(server.includes('device.RevokedAt') || server.includes('clientDeviceCredentialMatches('))
  assert.ok(client.includes('req.Header.Set("X-XDrive-Device-ID", deviceID)'))
  assert.ok(client.includes('req.Header.Set("X-XDrive-Device-Token", deviceToken)'))
  assert.ok(agent.includes('localpush.LoadDeviceRegistration('))
  assert.ok(agent.includes('localpush.LoadDeviceToken('))
  assert.ok(agent.includes('cli.VerifyLocalDevice(ctx, deviceID, secret)'))
  assert.ok(agent.includes('latest.SessionID != cfg.SessionID'))
  assert.equal(agent.includes('localpush.EnsureDevice('), false, 'read-only verification must not enroll a new device')
  assert.ok(ipc.includes('"device-backup-local-device"'))
  assert.ok(ipc.includes('GET /v1/device-backups/local-device'))
  assert.ok(main.includes("requireAgentCapability(hello, 'device-backup-local-device')"))
  assert.ok(preload.includes("ipcRenderer.invoke('agent:get-device-backup-local-device')"))
})

test('Shared Desktop device grouping is scoped and remains strictly read-only', () => {
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const web = read('web', 'src', 'App.tsx')
  assert.ok(dto.includes('verifiedLocalDevice?(): Promise<string | null>'))
  assert.ok(page.includes('localIdentity.source === source'))
  assert.ok(page.includes("setLocalIdentity({ source, deviceID: null })"))
  assert.ok(page.includes('if (active) setLocalIdentity({ source, deviceID: deviceID || null })'))
  assert.ok(page.includes("label: '本机'"))
  assert.ok(page.includes("label: '其他设备'"))
  assert.ok(page.includes('overview.devices.some((device) => device.id === verifiedLocalDeviceID)'))
  assert.ok(app.includes('getDeviceBackupLocalDevice()'))
  assert.ok(app.includes('status?.server, status?.username, status?.auth_status'))
  assert.ok(web.includes('source={deviceBackupSource}'))
  assert.equal(web.includes('getDeviceBackupLocalDevice'), false)
  for (const action of ['triggerSource', 'cancelSourceRun', 'updateSource', 'deleteSource', 'revokeClientDevice']) {
    assert.equal(page.includes(action), false, 'device grouping must not add mutation control ' + action)
  }
})
