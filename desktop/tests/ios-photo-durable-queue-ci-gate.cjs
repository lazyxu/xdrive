'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const yml = read('.github/workflows/ios-unsigned-ipa.yml')

test('iOS IPA executes actual PhotoKit SQLite queue crash and revision tests', () => {
  const start = yml.indexOf('- name: Verify crash-durable Owner-local PhotoKit queue SQLite')
  const end = yml.indexOf('- name: Verify V2 PhotoKit journal shard routing', start)
  assert.ok(start > 0 && end > start)
  const step = yml.slice(start, end)
  assert.match(step, /set -euo pipefail/)
  assert.match(step, /swiftc -swift-version 5 -parse-as-library/)
  assert.match(step, /ios\/XDriveIOS\/PhotoBackupChangeQueueStore.swift/)
  assert.match(step, /ios\/tests\/PhotoBackupChangeQueueStoreChecks.swift/)
  assert.match(step, /-lsqlite3/)
  assert.match(step, /xdrive-ios-photo-queue-sqlite"/)
  assert.match(step, /desktop\/tests\/ios-photo-persistent-failure-reasons.cjs/)
  assert.match(step, /desktop\/tests\/ios-photo-single-failed-retry.cjs/)
  assert.doesNotMatch(step, /\|\| true|continue-on-error|if: always\(\)/)
})

test('the executable fixture inspects private obsolete failure rows, not just filtered counts', () => {
  const fixture = read('ios/tests/PhotoBackupChangeQueueStoreChecks.swift')
  const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
  assert.match(fixture, /import SQLite3/)
  assert.match(fixture, /SELECT COUNT\(\*\) FROM failure_reasons/)
  assert.match(fixture, /rawFailureReasonRows\(at: lifecycleFile\) == 3/)
  assert.match(fixture, /rawFailureReasonRows\(at: lifecycleFile\) == 1/)
  assert.match(fixture, /rawFailureReasonRows\(at: lifecycleFile\) == 0/)
  assert.match(fixture, /70 failed revisions must include a non-head item/)
  assert.match(store, /try execute\("DELETE FROM failure_reasons"\)/)
  assert.doesNotMatch(fixture, /UploadSessionTransport|uploadPrepared\(/)
})
