const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('automatic incremental runs only on the owning Agent and reuses the original batch worker', () => {
  const controller = read('cmd','xdrive-agent','controller.go')
  const scheduler = read('cmd','xdrive-agent','device_backup_local_auto_scheduler.go')
  const nativeOnly = read('cmd','xdrive-agent','device_backup_local_auto_scheduler_unsupported.go')
  const dialog = read('ui','shared','src','mui','DeviceBackupLocalScheduleDialog.tsx')
  assert.ok(controller.includes('go c.runLocalPushAutoScheduler()'))
  assert.ok(scheduler.includes('//go:build linux || windows'))
  assert.ok(nativeOnly.includes('//go:build !linux && !windows'))
  assert.ok(scheduler.includes('DeviceBackupFoldersPage(ctx, deviceID, localPushAutoPageSize, after)'))
  assert.ok(scheduler.includes('localpush.LoadDeviceRegistration('))
  assert.ok(scheduler.includes('c.localBoundBackupConfig(ctx, sourceID)'))
  assert.ok(scheduler.includes('scopedAPI.LocalBoundSchedule(ctx, sourceID, proof)'))
  assert.ok(scheduler.includes('localpush.LoadRootGrant('))
  assert.ok(scheduler.includes('localpush.ReadVerifiedCommonBatchCheckpoint('))
  assert.ok(scheduler.includes('localBackupRuleSessionUnchanged(account)'))
  assert.ok(scheduler.includes('c.CloudStartLocalBoundBackupCommonBatch(ctx, sourceID)'))
  assert.ok(scheduler.includes('checkpoint.State != "partial" || checkpoint.UncertainFiles != 0'))
  assert.ok(scheduler.includes('sourceschedule.NextRunAt('))
  assert.ok(scheduler.includes('localPushAutoAttemptCooldown'))
  assert.ok(scheduler.includes('if busy {'))
  assert.ok(dialog.includes('请先手动完成一次当前 Source 版本的增量备份'))
  assert.ok(dialog.includes('暂停、取消、不确定任务及撤权不会自动重启'))
  assert.ok(dialog.includes('保存计划'))
  assert.equal(scheduler.includes('CreateSource('), false)
  assert.equal(scheduler.includes('Delete('), false)
  assert.equal(scheduler.includes('Stage('), false)
  assert.equal(scheduler.includes('UploadSession('), false)
  assert.equal(scheduler.includes('new OperationID'), false)
})

test('automatic scheduler never changes Web/mobile/remote Desktop permissions', () => {
  const web = read('web','src','App.tsx')
  const scheduler = read('cmd','xdrive-agent','device_backup_local_auto_scheduler.go')
  assert.equal(web.includes('CloudStartLocalBoundBackupCommonBatch'), false)
  assert.equal(scheduler.includes('Renderer'), false)
  assert.ok(scheduler.includes('checkpoint.SourceRevision != saved.Revision'))
  assert.ok(scheduler.includes('checkpoint.BackupComplete || checkpoint.RetirementSafe'))
})
