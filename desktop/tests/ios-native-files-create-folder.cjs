'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const creator = read('ios/XDriveIOS/NativeFilesDirectoryCreator.swift')
const policy = read('ios/XDriveIOS/NativeFilesFolderNamePolicy.swift')
const go = read('internal/api/handlers.go')

test('new folder is one explicit verified native Files action on current real directory', () => {
  assert.match(panel, /Button\("新建文件夹"\)/)
  assert.match(panel, /XDriveIOSNativeFilesFolderNamePolicy\.normalized\(folderDraft\)/)
  assert.match(panel, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(panel, /XDriveIOSNativePhotoOwnerScope\.matches\(\s*auth\.owner, expectedOwner/)
  assert.match(panel, /parentID: folderID, name: name/)
  assert.match(panel, /创建结果未确认，请先刷新目录核对/)
  assert.match(creator, /\/api\/v1\/nodes\/\\\(parentID\)\/directories/)
  assert.match(creator, /request\.httpMethod = "POST"/)
  assert.match(creator, /guard http\.statusCode == 201/)
  assert.match(creator, /saved\.parent_id == parentID/)
  assert.match(creator, /completionHandler\(nil\)/)
  assert.match(go, /func \(s \*Server\) createDirectory\(c \*gin\.Context\)/)
  assert.match(go, /c\.JSON\(http\.StatusCreated, toNodeDTO\(n\)\)/)
  assert.match(policy, /name\.utf8\.count <= 255/)
  assert.doesNotMatch(creator, /WKWebView\s*\(|document\.cookie/)
})
