const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('only bounded, category-level integrity evidence reaches the administrator Task Center', () => {
  const go = read('internal/api/storage_verify_evidence.go')
  const dto = read('internal/api/background_tasks.go')
  const projection = read('internal/api/system_maintenance_status.go')
  assert.match(go, /storageVerifyEvidenceProtocol = "xdrive-storage-integrity-evidence-v1"/)
  assert.match(go, /DisallowUnknownFields\(\)/)
  assert.match(go, /status = \?"/)
  assert.doesNotMatch(go, /json:"storage_key"/)
  assert.doesNotMatch(go, /json:"node_id"/)
  assert.doesNotMatch(go, /json:"sha256"/)
  assert.match(dto, /json:"storage_integrity,omitempty"/)
  assert.match(projection, /parseStorageVerifyEvidence\(run.ReportJSON\)/)
  assert.match(projection, /StatusSuccess|SystemMaintenanceStatusSuccess/)
  assert.match(read('internal/api/background_tasks.go'), /if admin \{/)
})

test('Web/Desktop/DSM shared Task Center displays accurate mode and counts', () => {
  const view = read('ui/shared/src/mui/StorageIntegrityReceipt.tsx')
  const panel = read('ui/shared/src/mui/BackgroundTaskCenter.tsx')
  const model = read('ui/shared/src/background-tasks.ts')
  assert.match(model, /export type XDriveStorageIntegrityEvidence/)
  assert.match(model, /storage_integrity\?: XDriveStorageIntegrityEvidence/)
  assert.match(panel, /XDriveStorageIntegrityReceipt report=\{task.storage_integrity\}/)
  assert.match(view, /data-xdrive-admin-storage-integrity-receipt/)
  assert.match(view, /fast 不检测同大小内容篡改/)
  assert.match(view, /不代表备份仓库验证/)
  assert.match(view, /缺失对象/)
  assert.match(view, /哈希不匹配/)
})
