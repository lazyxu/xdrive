const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..', '..')
const read = (filename) => fs.readFileSync(path.join(root, filename), 'utf8')

test('G11 cleanup group pages are reachable past 48 cards on Web and Desktop', () => {
  const server = read('internal/api/media_cleanup.go')
  const client = read('internal/client/media.go')
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  const goAgent = read('cmd/xdrive-agent/cloud_files.go')
  const desktopMain = read('desktop/src/main/index.cts')
  const desktopClient = read('desktop/src/main/agent_client.cts')
  const preload = read('desktop/src/preload/index.cts')
  const globals = read('desktop/src/renderer/global.d.ts')
  const desktopAdapter = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const webAPI = read('web/src/api.ts')
  const webAdapter = read('web/src/mediaGalleryAdapter.ts')
  const sharedAdapter = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const models = read('ui/shared/src/models.ts')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const cleanup = read('ui/shared/src/mui/MediaGalleryCleanup.tsx')

  assert.match(server, /func mediaCleanupOffset\(/)
  assert.match(server, /\.\s*Offset\(offset\)/)
  assert.match(server, /func mediaBurstReviewPage\(/)
  assert.match(server, /out\.HasMore/)
  assert.match(client, /values\.Set\("offset", strconv\.Itoa\(offsets\[0\]\)\)/)
  assert.match(ipc, /media_cleanup_paging_unavailable/)
  assert.match(ipc, /CloudMediaDuplicateGroupsPage/)
  assert.match(ipc, /CloudMediaBurstReviewsPage/)
  assert.match(goAgent, /CloudMediaDuplicateGroupsPage/)
  assert.match(goAgent, /CloudMediaBurstReviewsPage/)
  assert.match(desktopMain, /normalizeMediaCleanupOffset\(offset\)/)
  assert.match(desktopClient, /mediaDuplicateGroups\(limit = 24, offset = 0\)/)
  assert.match(desktopClient, /mediaBurstReviews\(limit = 24, offset = 0\)/)
  assert.match(preload, /getMediaDuplicateGroups: \(limit = 24, offset = 0\)/)
  assert.match(globals, /getMediaDuplicateGroups:[\s\S]{0,100}offset\?: number/)
  assert.match(desktopAdapter, /getMediaDuplicateGroups\(limit, offset\)/)
  assert.match(webAPI, /mediaDuplicateGroups\(limit = 24, offset = 0\)/)
  assert.match(webAdapter, /mediaDuplicateGroups\(limit, offset\)/)
  assert.match(sharedAdapter, /port\.listDuplicateGroups!\(limit, offset\)/)
  assert.match(sharedAdapter, /port\.listBurstReviews!\(limit, offset\)/)
  assert.match(models, /offset\?: number/)
  assert.match(models, /has_more\?: boolean/)
  assert.match(gallery, /loadMoreCleanupGroups/)
  assert.ok(gallery.includes("onLoadMoreDuplicate={() => void loadMoreCleanupGroups('duplicate')}"))
  assert.ok(gallery.includes('onLoadMoreDuplicate={onLoadMoreDuplicate}'))
  assert.match(gallery, /next\.offset !== offset/)
  assert.match(gallery, /next\.total_groups !== current\.total_groups/)
  assert.match(cleanup, /加载更多重复组/)
  assert.match(cleanup, /加载更多连拍组/)
  assert.match(cleanup, /当前已索引素材暂时没有清理建议/)
  assert.match(cleanup, /后台删除任务完成后可刷新检查最新组数/)
})
