const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('three clients share a strictly redacted owner/device folder keyset transport', () => {
  const view = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')
  const web = read('web', 'src', 'App.tsx')
  const desktop = read('desktop', 'src', 'renderer', 'App.tsx')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const globals = read('desktop', 'src', 'renderer', 'global.d.ts')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  assert.ok(dto.includes('foldersPage?(deviceID: string, limit: number, afterSourceID: number)'))
  assert.ok(web.includes('api.deviceBackupFoldersPage(deviceID, limit, afterSourceID)'))
  assert.ok(desktop.includes('window.xdriveDesktop.agent.getDeviceBackupFoldersPage(deviceID, limit, afterSourceID)'))
  assert.ok(preload.includes("ipcRenderer.invoke('agent:get-device-backup-folders-page', deviceID, limit, afterSourceID)"))
  assert.ok(globals.includes('getDeviceBackupFoldersPage: (deviceID: string, limit?: number, afterSourceID?: number)'))
  const start = main.indexOf("ipcMain.handle('agent:get-device-backup-folders-page'")
  const end = main.indexOf("ipcMain.handle('agent:get-device-backup-runs'", start)
  assert.ok(start > 0 && end > start, 'folder read must use a separate IPC boundary')
  const bounded = main.slice(start, end)
  assert.ok(bounded.includes("requireAgentCapability(hello, 'device-backup-read')"))
  assert.ok(bounded.includes('Number.isSafeInteger(requestedLimit)'))
  assert.ok(bounded.includes('Number.isSafeInteger(requestedCursor)'))
  assert.ok(bounded.includes('deviceBackupFoldersPage(deviceID, requestedLimit, requestedCursor)'))
  for (const forbidden of ['CloudSources', 'RootFingerprint', 'createSource', 'cancelSourceRun', 'localRoot']) {
    assert.equal(bounded.includes(forbidden), false, 'read IPC accepted an unsafe mutable route: ' + forbidden)
  }
  assert.ok(client.includes('/v1/device-backups/folders?'))
  assert.ok(view.includes('source.foldersPage(deviceID, 100, cursor)'))
  assert.equal(view.includes('sourceOverview('), false)
  assert.equal(view.includes('sourceItems('), false)
})

test('folder continuation cannot claim completeness or publish stale account data', () => {
  const view = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  assert.ok(view.includes('folderScopeRef.current.source !== source'))
  assert.ok(view.includes('folderScopeRef.current.refreshID !== refreshID'))
  assert.ok(view.includes('folderScopeRef.current.epoch !== scope'))
  assert.ok(view.includes('folderRequestIDs.current[deviceID] !== requestID'))
  assert.ok(view.includes('prev.scope !== scope'))
  assert.ok(view.includes('const ids = new Set(items.map((item) => item.source_id))'))
  assert.ok(view.includes('lastID <= cursor'))
  assert.ok(view.includes('page.next_after_source_id !== lastID'))
  assert.ok(view.includes('folderPages[device.id]?.complete'))
  assert.ok(view.includes('overview.devices.every((device) => folderPages[device.id]?.complete)'))
  assert.ok(view.includes('未读完前不能将当前列表视作完整'))
  assert.ok(view.includes('文件夹读取失败，已保留当前内容；可重试'))
  assert.ok(view.includes('当前 Server 或 Agent 不支持文件夹连续分页'))
  assert.ok(view.includes('localOwnsFolder(renameTarget.id)'))
  assert.ok(view.includes('localOwnsFolder(removeTarget.id)'))
  assert.ok(view.includes('verifiedLocalDeviceID && overview?.devices.some'))
  assert.ok(view.includes('device.id === verifiedLocalDeviceID && !device.revoked'))
  assert.ok(view.includes('visibleFolders(device).some((folder) => folder.source_id === sourceID)'))
  assert.ok(view.includes('NAS 备份 · 待支持'))
  assert.ok(view.includes('连接状态未知'))
  const gated = (view.match(/localOwnsFolder\([a-zA-Z]+\.id\)/g) ?? [])
  assert.equal(gated.length, 12, 'all twelve own-Desktop local dialogs remain scope-gated')
})
