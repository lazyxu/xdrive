const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')
const text = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('Caddy readonly local evidence remains explicitly unsigned in shared Web/Desktop UI', () => {
  const shared = text('ui/shared/src/mui/CaddyDetailV1.tsx')
  const type = text('ui/shared/src/service-dependencies.ts')
  const client = text('internal/client/admin_caddy_configuration.go')
  assert.match(type, /local_runtime_state\?: 'matching-local' \| 'changed-local' \| 'unverified'/)
  assert.match(client, /LocalRuntimeState string.*local_runtime_state/)
  assert.match(shared, /data-xdrive-caddy-local-runtime-state/)
  assert.match(shared, /未独立签名，不代表持续生效/)
  assert.match(shared, /不能视为此次部署仍然生效/)
  assert.match(shared, /当前运行代际与应用生效状态未验证/)
  assert.doesNotMatch(shared, /已签名应用成功/)
})

test('Caddy same-tab operation resumes only after authenticated ID and SHA match', () => {
  const shared = text('ui/shared/src/mui/CaddyDetailV1.tsx')
  assert.match(shared, /window\.sessionStorage\.getItem\(storageKey\)/)
  assert.match(shared, /window\.sessionStorage\.setItem\(storageKey/)
  assert.match(shared, /receipt\?\.request_id !== saved\.request_id/)
  assert.match(shared, /receipt\.sha256 !== saved\.sha256/)
  assert.match(shared, /if \(!alive/)
  assert.match(shared, /getCaddyDeployStatus\(saved\.request_id\)/)
  assert.match(text('web/src/App.tsx'), /operationScope: profile\?\.id/)
  assert.match(text('desktop/src/renderer/App.tsx'), /operationScope: status\?\.server/)
})

test('Caddy recent Host archive is admin-only, bounded and Web/Desktop parity', () => {
  const router = text('internal/api/router.go')
  const shared = text('ui/shared/src/mui/CaddyDetailV1.tsx')
  const api = text('internal/api/admin_caddy_host_deploy_history.go')
  const web = text('web/src/App.tsx')
  const desktop = text('desktop/src/renderer/App.tsx')
  assert.match(router, /admin\.GET\("\/services\/caddy\/config\/deploy\/history"/)
  assert.match(api, /len\(candidates\) > 20/)
  assert.match(api, /readCaddyEnvDeployStatus\(item\.id\)/)
  assert.match(shared, /data-xdrive-caddy-host-terminal-history/)
  assert.match(shared, /不能推断没有执行过部署/)
  assert.match(shared, /未独立签名/)
  assert.match(shared, /caddyHostDeployFailureMessage\(item\)/)
  assert.doesNotMatch(shared, /历史部署失败，物理回退未确认/)
  assert.match(web, /loadCaddyDeployHistory/)
  assert.match(desktop, /loadCaddyDeployHistory/)
})

test('Caddy redeploy is permitted only for a NEW saved Host fingerprint', () => {
  const shared = text('ui/shared/src/mui/CaddyDetailV1.tsx')
  assert.match(shared, /config\.host_env_pending_redeploy === true/)
  assert.match(shared, /\/\^\[0-9a-f\]\{64\}\$\/\.test\(config\.host_env_sha256 \?\? ''\)/)
  assert.match(shared, /deployReceipt\.sha256 === config\?\.host_env_sha256/)
  assert.match(shared, /validPendingTarget && !alreadyCompletedThisTarget/)
  const deployGate = shared.split('const canDeploy =')[1]?.split('const startDeploy =')[0] ?? ''
  assert.ok(deployGate, 'must find the actual redeploy guard')
  assert.doesNotMatch(deployGate, /deployReceipt\?\.state !== 'deployed'/)
  assert.match(shared, /activeTab === 'history' \? 'caddy-v1-history'/)
  assert.match(shared, /id="caddy-v1-history"/)
})
