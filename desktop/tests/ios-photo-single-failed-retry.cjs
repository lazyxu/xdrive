'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const queue = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
const controller = read('ios/XDriveIOS/NativePhotoBackupController.swift')
const ui = read('ios/XDriveIOS/PhotoPriorityBackupSection.swift')
const start = controller.slice(controller.indexOf('private func start('))
const single = start.slice(start.indexOf('if kind == .single {'), start.indexOf('} else if kind == .focused {'))
const method = queue.slice(queue.indexOf('func retryFailedSingle('),
  queue.indexOf('/// Read the explicitly selected PhotoKit revision'))
assert.ok(method.length > 100, 'single-item retry must be isolated')

test('retry only one explicitly selected revision, never the oldest 64 failures', () => {
  assert.match(method, /try verifyOwner\(owner\)/)
  assert.match(method, /XDriveIOSPhotoKitLibraryEpoch\.matches\(/)
  assert.match(method, /row\.state == \.failed/)
  assert.match(method, /store\.status\(for: localIdentifier\)/)
  assert.match(method, /PHAsset\.fetchAssets\(/)
  assert.match(method, /store\.retryFailed\(/)
  assert.match(method, /expectedBaselineToken: baseline\.token/)
  assert.match(method, /verifyAuthorization\(stillMatches: epoch\)/)
  assert.match(method, /epoch\.serialized, as: after\.token/)
  assert.doesNotMatch(method, /failed\(limit:|retryFailedCandidates\(|installNewOnlyBaseline|uploadPrepared|finalize\(/)
})

test('explicit selected retry is after global unknown-ACK and target fences, before same writer', () => {
  const preflight = start.indexOf('pendingCount(owner: selected)')
  const managed = start.indexOf('readExistingForUpload(owner: selected')
  const retry = start.indexOf('queue.retryFailedSingle(')
  const captured = start.indexOf('queue.pendingForSingle(')
  const writer = start.indexOf(').runSingle(')
  assert.ok(preflight >= 0 && managed > preflight && retry > managed &&
    captured > retry && writer > captured)
  assert.match(single, /plan\.enabled, plan\.backupStartRule == \.onlyNew/)
  assert.match(single, /!plan\.pausedForReview/)
  assert.match(single, /!plan\.requiresFullLibraryReconciliation/)
  assert.match(single, /_ = try await queue\.retryFailedSingle\(/)
  assert.match(single, /selectedRevision = try await queue\.pendingForSingle\(/)
  assert.match(single, /queueRevisionSettled = try await selectedQueue\.settle\(/)
  const startRun = single.indexOf(').runSingle(')
  const endQueue = single.indexOf('selectedRevision = try await queue.pendingForSingle(')
  const reporter = single.indexOf('await reporter.begin()')
  assert.ok(endQueue >= 0 && reporter > endQueue && startRun > reporter)
  const between = single.slice(endQueue, startRun)
  assert.match(between, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, selected\)/)
  assert.match(between, /XDriveIOSNativePhotoOwnerScope\.matches\(self\.runningOwner, selected\)/)
  assert.match(between, /UIApplication\.shared\.applicationState == \.active/)
  assert.match(between, /throw XDriveIOSNativeSessionError\.staleSession/)

  assert.match(ui, /确认上传所选原件/)
  assert.match(ui, /仅重新排队这一版本/)
})

test('retry atomically removes stale reason; next failed attempt cannot inherit it', () => {
  const retry = store.slice(store.indexOf('func retryFailed('), store.indexOf('/// Bounded iCloud wait queue'))
  const assertion = read('ios/tests/PhotoBackupChangeQueueStoreChecks.swift')
  assert.match(retry, /BEGIN IMMEDIATE/)
  assert.match(retry, /WHERE asset_id=\? AND revision=\? AND state='failed'/)
  assert.match(retry, /if changed \{[\s\S]*?DELETE FROM failure_reasons WHERE asset_id=\? AND revision=\?/)
  assert.match(retry, /try execute\("COMMIT"\)/)
  assert.match(assertion, /A second item-local failure of the same queued revision/)
  assert.match(assertion, /70 failed revisions must include a non-head item/)
  assert.match(assertion, /selected-beyond-64.sqlite3/)
  assert.match(assertion, /reopened\.status\(for: "reason-video"\)\?\.failureReasonCode == nil/)
  assert.doesNotMatch(method, /URLSession|NodeReceipt|ServerResponse|pendingCount/)
})
