const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const repo = path.resolve(__dirname, '../..')
const read = (...parts) => fs.readFileSync(path.join(repo, ...parts), 'utf8')
const main = read('desktop', 'src', 'main', 'index.cts')
const app = read('desktop', 'src', 'renderer', 'App.tsx')
const sourceManager = read('ui', 'shared', 'src', 'mui', 'SourceManager.tsx')
const sourceDetails = read('ui', 'shared', 'src', 'mui', 'SourceManagerDetailsDialog.tsx')

test('Mount terminal status opens a full task page with a truthful scope notice', () => {
  assert.match(main, /mountSyncCompletionPresentation\(\)/)
  assert.match(main, /'sync-activity'\)/)
  assert.match(app, /target === 'sync-activity'/)
  assert.match(app, /setSyncActivityFromNotification\(true\)/)
  assert.match(app, /setView\('transfers'\)/)
  assert.match(app, /逐项同步历史尚未接入/)
  assert.doesNotMatch(main, /'同步已完成。', 'transfers'/)
})

test('Source-run notification is account scoped and routes into its actual run', () => {
  assert.match(main, /agentState\.status\?\.server !== view\.server/)
  assert.match(main, /agentState\.status\?\.username !== view\.username/)
  assert.match(main, /sourceRunNotificationTarget\(/)
  assert.match(app, /target\?\.kind === 'source-run'/)
  assert.match(app, /sourceRunFocus\.server === status\?\.server/)
  assert.match(app, /sourceRunFocus\.username === status\?\.username/)
  assert.match(sourceManager, /focusedRequestOpenedRef\.current === focusedRun\.requestID/)
  assert.match(sourceManager, /openDetails\(row, focusedRun\.runID\)/)
  assert.match(sourceDetails, /defaultExpanded=\{run\.id === focusedRunID\}/)
  assert.match(sourceManager, /loadRunFailures\(focusedRun\.sourceID, run\.id, 1\)/)
  assert.match(sourceManager, /loadRunSkips\(focusedRun\.sourceID, run\.id, 1\)/)
})
