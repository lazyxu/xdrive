const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('upgrade adopts authenticated Caddy before committing the old deployment', () => {
  const installer = read('deploy/install-server.sh')
  const imported = installer.indexOf('compose_with_stdin exec -T server xdrive-server caddy-host adopt-stdin')
  const caddyReady = installer.indexOf('wait_lan_https "$(env_value XD_LAN_HTTPS_IP)"')
  const commit = installer.lastIndexOf('commit_upgrade_transaction\n')
  assert.ok(imported > caddyReady && imported < commit,
    'must adopt only after verified HTTPS while upgrade rollback remains armed')
  assert.match(installer, /printf '%s\\0' "\$caddy_import_key_secret"/)
  assert.match(installer, /unset caddy_import_key_id caddy_import_key_secret/)
  assert.match(installer, /legacy-caddy\/original.Caddyfile/)
  assert.doesNotMatch(installer.slice(imported - 750, commit),
    /--password=|--access-key-secret=|ALIYUN_ACCESS_KEY_SECRET=\$|docker exec -e/)
  const cli = read('cmd/server/caddy_host_adopt.go')
  assert.match(cli, /io.LimitReader\(os.Stdin, caddyHostAdoptMaxBytes\+1\)/)
  assert.match(cli, /defer clear\(raw\)/)
  assert.match(cli, /ImportCaddyHostDeployment/)
  assert.doesNotMatch(cli, /fmt\.Printf\([^\n]*AccessSecret|fmt\.Println\([^\n]*input/)
})

test('imported HTTPS and AliDNS are source-labeled and keep Host Apply blocked', () => {
  const https = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  const alidns = read('ui/shared/src/mui/CaddyAliDNSPanel.tsx')
  const host = read('internal/api/admin_caddy_host_import.go')
  const model = read('internal/meta/admin_caddy_https_setting.go')
  assert.match(https, /旧宿主配置已导入/)
  assert.match(alidns, /原 Caddy 凭据已加密导入/)
  assert.match(host, /caddyImportedHostOrigin/)
  assert.match(host, /host_applied": false/)
  assert.match(host, /OnConflict\{DoNothing: true\}/)
  assert.match(model, /Origin/)
  assert.doesNotMatch(host, /Docker|exec\.Command|StopCaddy|restartCaddy/)
})
