const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Agent acknowledges the manual Source quickly and keeps one durable worker', () => {
  const worker = read('cmd', 'xdrive-agent', 'device_backup_local_common_batch_v2.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_common_batch_v2.go')
  assert.ok(worker.includes('CloudStartLocalBoundBackupCommonBatch('))
  assert.ok(worker.includes('beginLocalCommonBatchJob('))
  assert.ok(worker.includes('c.localBoundBackupConfig(ctx, sourceID)'))
  assert.ok(worker.includes('go func()'))
  assert.ok(worker.includes('c.runLocalCommonBackupBatchPrivate('))
  assert.ok(worker.includes('c.ctx, key.sourceID, job.setProgress'))
  assert.ok(worker.includes('return job.currentProgress(), nil'))
  assert.ok(!worker.includes('context.WithTimeout(ctx, 30*time.Minute)'))
  assert.ok(handler.includes('runner.CloudStartLocalBoundBackupCommonBatch(r.Context(), sourceID)'))
  assert.ok(handler.includes('http.StatusAccepted'))
  assert.ok(handler.includes('result.Running != (result.State == "running")'))
  assert.ok(!handler.includes('runner.CloudRunLocalBoundBackupCommonBatch(r.Context(), sourceID)'))
  for (const proof of ['result.BackupComplete', 'result.RetirementSafe', 'result.CurrentCASVerified']) {
    assert.ok(handler.includes(proof), proof + ' must never be asserted by a start ACK')
  }
})

test('Desktop POST has bounded request time; UI keeps polling and offers safe original receipt replay', () => {
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalCommonBatchDialog.tsx')
  const start = client.indexOf('localBoundBackupCommonBatch(sourceID: number)')
  const end = client.indexOf('localBoundBackupCommonBatchStatus(sourceID: number)', start)
  assert.ok(start >= 0 && end > start)
  const post = client.slice(start, end)
  assert.ok(post.includes('30_000'))
  assert.ok(!post.includes('1_860_000'))
  assert.ok(dialog.includes('window.setInterval(() => { void refresh() }, 2000)'))
  assert.ok(dialog.includes('window.clearInterval(timer)'))
  assert.ok(dialog.includes('inspectGeneration.current !== generation'))
  assert.ok(dialog.includes('if (pending || inspecting || hasAttempted || status?.running) return'))
  assert.ok(dialog.includes('核对并恢复原始任务'))
  assert.ok(dialog.includes('Agent 核对并恢复原始 Operation'))
  assert.ok(!dialog.includes("status?.state === 'uncertain' || (status?.uncertain_files ?? 0) > 0) return"))
  assert.ok(dialog.includes('setHasAttempted(false)'))
  assert.ok(dialog.includes('value.backup_complete !== false'))
  assert.ok(dialog.includes('value.retirement_safe !== false'))
  assert.ok(dialog.includes('value.current_cas_verified !== false'))
  assert.ok(dialog.includes('关闭此窗口不会取消 Agent 已开始的上传'))
  assert.ok(dialog.includes('含嵌套目录'))
})
