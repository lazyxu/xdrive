const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Agent acknowledges the manual Source quickly and keeps one durable worker', () => {
  const worker = read('cmd', 'xdrive-agent', 'device_backup_local_common_batch_v2.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_common_batch_v2.go')
  assert.ok(worker.includes('CloudStartLocalBoundBackupCommonBatch('))
  assert.ok(worker.includes('beginLocalCommonBatchJob('))
  assert.ok(worker.includes('c.localBoundBackupConfig(ctx, sourceID)'))
  assert.ok(worker.includes('go func()'))
  assert.ok(worker.includes('c.runLocalCommonBackupBatchPrivate('))
  assert.ok(worker.includes('c.ctx, key.sourceID, job.setProgress'))
  assert.ok(worker.includes('return job.currentProgress(), nil'))
  assert.ok(!worker.includes('context.WithTimeout(ctx, 30*time.Minute)'))
  assert.ok(handler.includes('runner.CloudStartLocalBoundBackupCommonBatch(r.Context(), sourceID)'))
  assert.ok(handler.includes('http.StatusAccepted'))
  assert.ok(handler.includes('result.Running != (result.State == "running")'))
  assert.ok(!handler.includes('runner.CloudRunLocalBoundBackupCommonBatch(r.Context(), sourceID)'))
  for (const proof of ['result.BackupComplete', 'result.RetirementSafe', 'result.CurrentCASVerified']) {
    assert.ok(handler.includes(proof), proof + ' must never be asserted by a start ACK')
  }
})

