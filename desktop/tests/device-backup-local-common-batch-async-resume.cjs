test('pause and cancel are owning-Desktop-only scheduling requests, never physical remote cancellation', () => {
  const ipc = read('cmd','xdrive-agent','desktop_ipc_device_backup_common_batch_v2.go')
  const worker = read('cmd','xdrive-agent','device_backup_local_common_batch_v2.go')
  const checkpoint = read('internal','localpush','common_upload_run_checkpoint.go')
  const preload = read('desktop','src','preload','index.cts')
  const client = read('desktop','src','main','agent_client.cts')
  const index = read('desktop','src','main','index.cts')
  const renderer = read('desktop','src','renderer','App.tsx')
  const dialog = read('ui','shared','src','mui','DeviceBackupLocalCommonBatchDialog.tsx')
  const dto = read('ui','shared','src','device-backups.ts')
  assert.ok(ipc.includes('validLocalCommonBatchControlRequest('))
  assert.ok(ipc.includes('result.StopRequested'))
  assert.ok(ipc.includes('runner.CloudControlLocalBoundBackupCommonBatch('))
  assert.ok(worker.includes('stopAtBoundary()'))
  assert.ok(worker.includes('source.SyncMode != meta.SourceSyncModeBackup'))
  assert.ok(worker.includes('job.requestStop(action)'))
  assert.ok(worker.includes('job.stopClosed = true'))
  assert.ok(worker.includes('job.stopClosed'))
  assert.ok(worker.includes('c.localCommonBatchJobMu.Lock()'))
  assert.ok(checkpoint.includes('p.State != "paused" && p.State != "cancelled"'))
  assert.ok(preload.includes('agent:control-device-backup-local-common-batch'))
  assert.ok(index.includes("requireAgentCapability(hello, 'device-backup-local-common-batch')"))
  assert.ok(index.includes("action !== 'pause' && action !== 'cancel'"))
  assert.ok(client.includes('/v1/device-backups/local-common-batch/control?'))
  assert.ok(renderer.includes('controlDeviceBackupLocalCommonBatch(sourceID, action)'))
  assert.ok(dialog.includes('暂停后续文件'))
  assert.ok(dialog.includes('结束本轮'))
  assert.ok(dialog.includes("actions.control(sourceID, action)"))
  assert.ok(dialog.includes('不代表远端物理取消'))
  assert.ok(dto.includes("stop_requested?: 'pause' | 'cancel'"))
  for (const flag of ['backup_complete: false', 'retirement_safe: false', 'current_cas_verified: false']) {
    assert.ok(dto.includes(flag), 'control cannot assert ' + flag)
  }
})

