'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
const source = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')

test('PhotoKit persistent changes use exact Owner and Apple asset change history', () => {
  assert.match(source, /actor XDriveIOSPhotoKitPersistentBackupQueue/)
  assert.match(source, /Self\.ownerScope\(owner\) == scope/)
  assert.match(source, /PHPhotoLibrary\.shared\(\)\.fetchPersistentChanges\(since: token\)/)
  assert.match(source, /change\.changeDetails\(for: \.asset\)/)
  assert.match(source, /details\.insertedLocalIdentifiers/)
  assert.match(source, /details\.updatedLocalIdentifiers/)
  assert.match(source, /details\.deletedLocalIdentifiers/)
  assert.match(source, /XDriveIOSPhotoKitLibraryEpoch\.capture\(\)/)
  assert.match(source, /requiresExplicitBaseline/)
  assert.doesNotMatch(source, /\.uploadPrepared\(|\.finalize\(|\.deleteNode\(/)
})

test('SQLite change token and queued asset IDs commit atomically without inventing uploaded receipts', () => {
  assert.match(store, /CREATE TABLE IF NOT EXISTS entries/)
  assert.match(store, /BEGIN IMMEDIATE/)
  assert.match(store, /UPDATE baseline SET token=\?/)
  assert.match(store, /COMMIT/)
  assert.match(store, /ROLLBACK/)
  assert.match(store, /expectedToken: Data, nextToken: Data/)
  assert.match(store, /previous\.token == expectedToken/)
  assert.match(store, /ORDER BY priority DESC,queue_order DESC LIMIT \?/)
  assert.match(store, /guard \(1\.\.\.64\)\.contains\(limit\)/)
  assert.match(store, /state='missingLocal'/)
  assert.doesNotMatch(store, /markConfirmed\(|\.upload\(|\.deleteNode\(/)
})
