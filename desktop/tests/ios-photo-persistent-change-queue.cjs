'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
const source = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')

test('PhotoKit persistent changes use exact Owner and Apple asset change history', () => {
  assert.match(source, /actor XDriveIOSPhotoKitPersistentBackupQueue/)
  assert.match(source, /Self\.ownerScope\(owner\) == scope/)
  assert.match(source, /PHPhotoLibrary\.shared\(\)\.fetchPersistentChanges\(since: token\)/)
  assert.match(source, /change\.changeDetails\(for: \.asset\)/)
  assert.match(source, /details\.insertedLocalIdentifiers/)
  assert.match(source, /details\.updatedLocalIdentifiers/)
  assert.match(source, /details\.deletedLocalIdentifiers/)
  assert.match(source, /XDriveIOSPhotoKitLibraryEpoch\.capture\(\)/)
  assert.match(source, /requiresExplicitBaseline/)
  assert.doesNotMatch(source, /\.uploadPrepared\(|\.finalize\(|\.deleteNode\(/)
})

test('SQLite change token and queued asset IDs commit atomically without inventing uploaded receipts', () => {
  assert.match(store, /CREATE TABLE IF NOT EXISTS entries/)
  assert.match(store, /BEGIN IMMEDIATE/)
  assert.match(store, /UPDATE baseline SET token=\?/)
  assert.match(store, /COMMIT/)
  assert.match(store, /ROLLBACK/)
  assert.match(store, /expectedToken: Data, nextToken: Data/)
  assert.match(store, /previous\.token == expectedToken/)
  assert.match(store, /ORDER BY priority DESC,queue_order DESC LIMIT \?/)
  assert.match(store, /guard \(1\.\.\.64\)\.contains\(limit\)/)
  assert.match(store, /state='missingLocal'/)
  assert.doesNotMatch(store, /markConfirmed\(|\.upload\(|\.deleteNode\(/)
})

test('a receipt or item-local failure settles only the currently queued revision', () => {
  assert.match(store, /enum Settled: String/)
  assert.match(store, /enum ItemState: String/)
  assert.match(store, /func status\(for localIdentifier: String\) throws -> ItemStatus\?/)
  assert.match(store, /SELECT revision,state FROM entries WHERE asset_id=\?/)
  assert.match(store, /case confirmed/)
  assert.match(store, /case failed/)
  assert.match(store, /func settle\(_ candidate: Pending, result: Settled\)/)
  assert.match(store, /WHERE asset_id=\? AND revision=\? AND state='pending'/)
  assert.match(store, /return sqlite3_changes\(database\) == 1/)
  assert.match(store, /func retryFailed\(_ candidate: Pending\)/)
  assert.match(store, /WHERE asset_id=\? AND revision=\? AND state='failed'/)
  assert.match(store, /ON CONFLICT\(asset_id\) DO UPDATE SET revision=entries.revision\+1/)
  assert.match(store, /state='missingLocal'/)
  assert.doesNotMatch(store, /\.uploadPrepared\(|\.finalize\(|\.deleteNode\(/)
})

test('native queue summary is Owner-fenced, bounded by local SQLite aggregation and never fakes remote coverage', () => {
  const model = read('ios/XDriveIOS/NativePhotoQueueSummaryModel.swift')
  const screen = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')
  assert.match(store, /struct Counts: Equatable/)
  assert.match(store, /SELECT state,COUNT\(\*\) FROM entries GROUP BY state/)
  assert.match(store, /case \.pending: totals\.pending = count/)
  assert.match(store, /case \.failed: totals\.failed = count/)
  assert.match(store, /case \.confirmed: totals\.confirmed = count/)
  assert.match(store, /case \.missingLocal: totals\.missingLocal = count/)
  assert.match(source, /func summary\(owner: XDriveNativeOwnerRoot\)/)
  assert.match(source, /try verifyOwner\(owner\)/)
  assert.match(source, /guard let baseline = try store\.baseline\(\) else \{ return nil \}/)
  assert.match(source, /let totals = try store\.counts\(\)/)
  assert.match(model, /XDriveIOSNativePhotoOwnerScope\.matches\(verified\.owner, selected\)/)
  assert.match(model, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, selected\)/)
  assert.match(model, /queue\.summary\(owner: selected\)/)
  assert.match(model, /generation == ticket/)
  assert.match(screen, /Section\("本机新增照片变更队列"\)/)
  assert.match(screen, /queueSummary\.refresh\(login: login\)/)
  assert.match(screen, /counts\.pending/)
  assert.match(screen, /counts\.failed/)
  assert.match(screen, /不能当作服务器备份覆盖率/)
  assert.doesNotMatch(model, /UploadSession|uploadPrepared|finalize\(|\.deleteNode\(/)
});
