'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname,'../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')
const crypto = read('ios/XDriveIOS/NativeClipboardDeviceCrypto.swift')
const screen = read('ios/XDriveIOS/NativeClipboardScreen.swift')
const client = read('ios/XDriveIOS/NativeClipboardClient.swift')
const enroll = read('ios/XDriveIOS/IOSDeviceEnrollment.swift')
test('device key is stored only after a user-controlled action in a device-only Keychain',()=>{
  assert.match(crypto,/Curve25519\.KeyAgreement\.PrivateKey/)
  assert.match(crypto,/kSecAttrAccessibleWhenUnlockedThisDeviceOnly/)
  assert.match(crypto,/SecItemAdd/)
  assert.match(screen,/Button\("启用本机设备定向加密接收"\)/)
  assert.match(screen,/enableDeviceReceipt\(\)/)
  assert.match(enroll,/func clipboardDeviceProof\(/)
  assert.match(client,/func enrollClipboardDevice\(publicKey:/)
})
test('target decrypt binds recipient, Owner/event, MIME kind and Node ID',()=>{
  assert.match(crypto,/item\.target_device_id == deviceID/)
  assert.match(crypto,/xdrive-clipboard-target-v1/)
  assert.match(crypto,/context \+ "\\|salt"/)
  assert.match(crypto,/context \+ "\\|wrap"/)
  assert.match(crypto,/AES\.GCM\.open/)
  assert.match(crypto,/item\.kind/)
  assert.match(crypto,/nodeID/)
})
test('Owner Lock clears sensitive in-memory recipient state and bearer is device-scoped',()=>{
  assert.match(screen,/recipientPrivateKey = nil/)
  assert.match(screen,/recipientProof = nil/)
  assert.match(client,/X-XDrive-Device-ID/)
  assert.match(client,/X-XDrive-Device-Token/)
  assert.match(screen,/sessionGeneration == generation/)
  assert.doesNotMatch(crypto,/UserDefaults|iCloud|SourceRun|write\(to:/)
})
