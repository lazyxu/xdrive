const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('local reveal records are owned by trusted direct Agent tasks', () => {
  const model = read('internal/transfer/model.go')
  const cloud = read('cmd/xdrive-agent/cloud_files.go')
  const controller = read('cmd/xdrive-agent/controller.go')
  assert.match(model, /LocalRevealable\s+bool\s+`json:"local_revealable,omitempty"`/)
  assert.match(model, /func \(h \*Handle\) AllowLocalReveal\(\)/)
  assert.match(model, /func \(m \*Manager\) LocalRevealTask\(id string\)/)
  assert.match(cloud, /handle\.AllowLocalReveal\(\)/)
  assert.match(controller, /func \(c \*agentController\) OpenTransferLocal\(id string\)/)
  assert.match(controller, /c\.transfers\.LocalRevealTask\(id\)/)
  assert.match(controller, /selectFilePlatform\(localPath\)/)
  assert.match(controller, /openFolderPlatform\(parent\)/)
})

test('Desktop menu passes only a transfer ID through capability-gated IPC', () => {
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  const client = read('desktop/src/main/agent_client.cts')
  const preload = read('desktop/src/preload/index.cts')
  const types = read('desktop/src/renderer/global.d.ts')
  const renderer = read('desktop/src/renderer/App.tsx')
  const shared = read('ui/shared/src/mui/TransferPopover.tsx')
  assert.match(ipc, /"transfer-open-local"/)
  assert.match(ipc, /POST \/v1\/transfers\/open-local/)
  assert.match(client, /openTransferLocal\(id: string\)/)
  assert.match(preload, /openTransferLocal: \(id: string\)/)
  assert.match(types, /openTransferLocal: \(id: string\)/)
  assert.match(renderer, /capabilities\.includes\('transfer-open-local'\)/)
  assert.match(renderer, /openTransferLocal\(task\.id\)/)
  assert.match(shared, /在本地文件管理器中显示/)
  assert.match(shared, /task\.local_revealable === true/)
  assert.doesNotMatch(renderer, /openTransferLocal\(task\.path\)/)
})
