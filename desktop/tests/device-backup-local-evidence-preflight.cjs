const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('private preflight cannot grant local Push execution or leak its evidence to Web', () => {
  const handler = read('internal', 'api', 'local_source_item_evidence_preflight.go')
  const router = read('internal', 'api', 'router.go')
  const coverage = read('internal', 'api', 'router_contract_test.go')
  const client = read('internal', 'client', 'local_source_item_evidence_preflight.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_preflight.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const ipcProjection = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_preflight.go')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(router, /local-identity\/evidence-preflight", s\.requireLocalSourceExecutor\(\), s\.preflightLocalSourceItemEvidence/)
  assert.match(coverage, /POST", path: "\/api\/v1\/sources\/:id\/local-identity\/evidence-preflight"/)
  assert.match(handler, /s\.requireLocalSourceProofTx\(tx, c, sourceID, "", false\)/)
  assert.match(handler, /source\.Status != meta\.SourceStatusPaused/)
  assert.match(handler, /item\.NodeRevision == 0 \|\| item\.ExternalID != row\.PreviousPathKey/)
  assert.match(handler, /node\.Revision != item\.NodeRevision/)
  assert.match(handler, /index\.resolve\(row\.CurrentPathKey, nil\)/)
  assert.match(handler, /ContentVerified: false, CommitSupported: false/)
  assert.match(handler, /Authoritative: false, MissingInferenceSafe: false/)
  assert.doesNotMatch(handler, /tx\.(Create|Delete|Updates)\(|BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  assert.match(client, /PreflightLocalSourceItemEvidence\(/)
  assert.match(client, /decoder\.DisallowUnknownFields\(\)/)
  assert.match(client, /got\.ContentVerified \|\| got\.CommitSupported/)
  assert.match(agent, /localFolderGrantMu\.TryLock\(\)/)
  assert.match(agent, /localpush\.LoadLocalReconcileEvidence/)
  assert.match(agent, /cli\.ReadLocalSourceItemEvidencePage\(/)
  assert.match(agent, /cli\.PreflightLocalSourceItemEvidence\(/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  // The new Desktop entry is ONLY a manually requested count-only projection.
  // Server evidence IDs/hashes and the private internal endpoint remain
  // Agent-internal; this contract still forbids upload or alias promotion.
  assert.match(ipc, /GET \/v1\/device-backups\/local-evidence-preflight/)
  assert.match(ipcProjection, /desktopLocalEvidencePreflightProjection\(/)
  assert.match(ipcProjection, /CommitSupported: false/)
  assert.match(ipcProjection, /MissingInferenceSafe: false/)
  assert.doesNotMatch(ipcProjection, /json:"(source_item_id|root_id|root_fingerprint|device_token|sha256|storage_key|previous_path_key|current_path_key)"/)
  assert.doesNotMatch(preload, /preflightLocalBoundBackupEvidencePage|PreflightLocalSourceItemEvidence|evidence-cloud-bytes/)
  assert.doesNotMatch(web, /evidence-preflight|preflightLocalBoundBackupEvidencePage/)
})
