const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Source Manager exposes archived Sources and restores them as paused', () => {
  const manager = read('ui', 'shared', 'src', 'mui', 'SourceManager.tsx')
  const list = read('ui', 'shared', 'src', 'mui', 'SourceManagerListPage.tsx')
  const states = read('ui', 'shared', 'src', 'external-sources.ts')
  const api = read('web', 'src', 'api.ts')
  assert.match(manager, /sourceOverview\(controller\.signal, showArchived\)/)
  assert.match(manager, /已恢复为暂停状态/)
  assert.match(list, /显示已归档/)
  assert.match(list, /恢复（保持暂停）/)
  assert.match(states, /source\.status === 'archived'/)
  assert.match(api, /include_archived=true/)
  assert.match(api, /sources\/\$\{sourceID\}\/restore/)
  assert.match(api, /If-Match/)
})

test('Generic Source Manager does not bypass owning-device authorization for Local Push', () => {
  const adapter = read('ui', 'shared', 'src', 'mui', 'SourceManagerAdapter.ts')
  const settings = read('ui', 'shared', 'src', 'mui', 'SourceManagerSettingsDialog.tsx')
  const agent = read('cmd', 'xdrive-agent', 'cloud_files.go')
  assert.match(adapter, /row\.source\.kind !== 'local_folder'/)
  assert.match(settings, /本机 Push 的归档与恢复需要拥有设备身份/)
  assert.match(agent, /local Push archive\/restore requires the owning-device backup flow/)
})

test('Desktop Agent uses a bounded private IPC route for server-managed Source restore', () => {
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  assert.match(client, /restoreSource\(sourceID: number, revision: number\)/)
  assert.match(preload, /agent:restore-source/)
  assert.match(ipc, /POST \/v1\/sources\/restore/)
  assert.match(ipc, /CloudRestoreSource\(context\.Context, uint64, uint64\)/)
})
