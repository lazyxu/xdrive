'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=file=>fs.readFileSync(path.join(root,file),'utf8')

test('retained Agent session restores Desktop map without remembering a password',()=>{
  const main=read('desktop/src/main/index.cts')
  const native=read('desktop/src/main/agent_client.cts')
  assert.match(native,/desktopMapGuestGrant\(signal\?: AbortSignal\)/)
  assert.match(native,/POST', '\/v1\/cloud\/desktop-map-grant', undefined, 15_000/)
  assert.match(main,/function seedDesktopPlacesWebAuthFromAgent\(identity: DesktopPlacesWebIdentity\)/)
  assert.match(main,/requireAgentClient\(\)\.desktopMapGuestGrant\(\)/)
  assert.match(main,/places\.fetch\(identity\.origin \+ '\/api\/v1\/auth\/desktop-map\/redeem'/)
  assert.match(main,/method: 'POST', credentials: 'include', redirect: 'error'/)
  assert.match(main,/body: JSON\.stringify\(\{ticket:grant\.ticket\}\)/)
  assert.match(main,/grant\.username !== identity\.owner/)
  assert.match(main,/desktopPlacesWebOwnerStillCurrent\(identity\)/)
  assert.match(main,/generation !== desktopPlacesWebGeneration/)
  assert.match(main,/name: '__Host-xdrive_refresh'/)
  assert.match(main,/if \(await seedDesktopPlacesWebAuthFromAgent\(identity\)\) return true/)
  const ensure=main.slice(main.indexOf('async function ensureDesktopPlacesWebAuth('),
    main.indexOf('function closeDesktopPlacesGuests()'))
  assert.ok(ensure.indexOf('seedDesktopPlacesWebAuthFromAgent') <
    ensure.indexOf('securePasswordStorageAvailable'),
    'native Agent proof must be tried BEFORE saved-password fallback')
  assert.match(ensure,/if \(!profile\?\.remember_password \|\| !profile\.encrypted_password\) return false/)
})

test('transient native grant stays in Main, never Desktop renderer, WebView preload or Baidu JS',()=>{
  const main=read('desktop/src/main/index.cts')
  const preload=read('desktop/src/preload/places_embed.cts')
  const renderer=read('desktop/src/renderer/App.tsx')
  const web=read('web/src/App.tsx')
  const guestSource=main.slice(main.indexOf('function seedDesktopPlacesWebAuthFromAgent('),
    main.indexOf('async function ensureDesktopPlacesWebAuth('))
  assert.doesNotMatch(guestSource,/send\('agent:|xdrivePlacesEmbedBridge|postMessage|localStorage|sessionStorage|searchParams\.set/)
  assert.match(guestSource,/\/api\/v1\/auth\/desktop-map\/redeem/)
  assert.doesNotMatch(preload,/desktop-map-grant|native_refresh_token|agent:desktopMap|accessToken|refreshToken/)
  assert.doesNotMatch(renderer,/desktopMapGuestGrant|desktop-map-grant|native_refresh_token/)
  assert.doesNotMatch(web,/desktop-map-grant|native_refresh_token/)
  assert.match(main,/session\.fromPartition\(desktopPlacesWebPartition,\s*\{cache:false\}\)/)
  assert.match(main,/clearStorageData\(\{\s*storages: \['cookies', 'localstorage'\]/)
  assert.match(main,/ipcMain\.handle\('agent:logout',[\s\S]*?closeDesktopPlacesGuests\(\)/)
})

test('Server enforces native RefreshToken proof, hashed single-use DB grant and Same-Origin browser Cookie',()=>{
  const server=read('internal/api/auth_desktop_map_guest.go')
  const router=read('internal/api/router.go')
  const migrate=read('cmd/server/main.go')
  const meta=read('internal/meta/desktop_map_guest_grant.go')
  const agent=read('cmd/xdrive-agent/controller_desktop_map_guest_grant.go')
  const native=read('internal/client/desktop_map_guest_grant.go')
  assert.match(router,/authed\.POST\("\/auth\/desktop-map\/issue", s\.issueDesktopMapGuestGrant\)/)
  assert.match(router,/v1\.POST\("\/auth\/desktop-map\/redeem", s\.redeemDesktopMapGuestGrant\)/)
  assert.match(migrate,/&meta\.DesktopMapGuestGrant\{\}/)
  assert.match(server,/const desktopMapGuestGrantTTL = 30 \* time\.Second/)
  assert.match(server,/token_hash = \? AND user_id = \? AND revoked_at IS NULL AND expires_at > \?/)
  assert.match(server,/NativeRefreshID: native\.ID/)
  assert.match(server,/redeemed_at IS NULL AND expires_at > \?/)
  assert.match(server,/native\.UserID|grant\.NativeRefreshID|grant\.OwnerID/)
  assert.match(server,/requireBrowserAuthOrigin\(c\)/)
  assert.match(server,/s\.replyBrowserAuthSession\(c, issued\)/)
  assert.match(meta,/xd_desktop_map_guest_grants/)
  assert.match(meta,/Hash\s+string\s+`gorm:"size:64;primaryKey"`/)
  assert.match(agent,/userconfig\.NewClient\(cfg\)/)
  assert.match(agent,/before\.Username|after\.Username/)
  assert.match(native,/c\.doAuth\(req\)/,
    'native refresh credential MUST reject cross-site 307/308 redirects')
  assert.doesNotMatch(native,/c\.json\(ctx, http\.MethodPost, "\/api\/v1\/auth\/desktop-map\/issue"/)
})
