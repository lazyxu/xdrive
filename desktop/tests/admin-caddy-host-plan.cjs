const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const repo = path.resolve(__dirname, '../..')
const read = (name) => fs.readFileSync(path.join(repo, name), 'utf8')

test('NET-M5-B2 host plan is admin-only GET and cannot mutate Caddy, DNS, Docker or restart ingress', () => {
  const router = read('internal/api/router.go')
  const server = read('internal/api/admin_caddy_host_plan.go')
  const host = read('scripts/caddy-https-host-plan.py')
  const plan = read('internal/api/admin_caddy_preflight_snapshot.go')
  assert.ok(router.includes('admin.Use(s.requireAdmin())'))
  assert.ok(router.includes('admin.GET("/services/caddy/https/host-plan", s.adminCaddyHTTPSHostPlan)'))
  assert.equal(router.includes('admin.POST("/services/caddy/https/host-plan"'), false)
  assert.equal(router.includes('admin.POST("/services/caddy/https/apply"'), false)
  assert.match(server, /json.Marshal\(map\[string\]any\{/)
  assert.match(server, /sameCaddyPreflightSnapshot\(snapshot, current\)/)
  assert.match(server, /c.Header\("Cache-Control", "no-store"\)/)
  assert.doesNotMatch(server, /docker\.sock|exec\.Command|docker compose|stopCaddy|restartCaddy|Credential\.Ciphertext\s*[,}]/)
  assert.match(host, /independent-rescue-not-proven/)
  assert.match(host, /timed-rollback-not-armed/)
  assert.match(host, /os\.O_NOFOLLOW/)
  assert.match(host, /os\.O_NONBLOCK/)
  assert.match(host, /"apply_supported": False/)
  assert.doesNotMatch(host, /import subprocess|requests\.|socket\.|os\.replace|--insecure/)
  assert.match(plan, /result\.Desired\.LANIP == last\.Desired\.LANIP|first\.Desired\.LANIP == last\.Desired\.LANIP/)
})
