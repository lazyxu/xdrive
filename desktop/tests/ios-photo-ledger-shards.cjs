'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const {createHmac} = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const ledger = fs.readFileSync(path.join(root, 'ios/XDriveIOS/PhotoSyncEncryptedLedger.swift'), 'utf8')
const policy = fs.readFileSync(path.join(root, 'ios/XDriveIOS/PhotoLedgerShardPolicy.swift'), 'utf8')

test('100k independent HMAC-scoped photo intents have bounded 4096-way shard load', () => {
  const counts = new Uint32Array(4096)
  for (let i=0; i<100_000; i++) {
    const fingerprint = createHmac('sha256', 'fixed-synthetic-test-secret')
      .update('owner-17/root-31/asset-'+i).digest('hex')
    const prefix = Number.parseInt(fingerprint.slice(0, 3), 16)
    counts[prefix]++
  }
  assert.equal(counts.reduce((a,b)=>a+b,0), 100_000)
  assert.ok(Math.max(...counts) < 1024, 'fixed synthetic HMAC fixture overflowed a single shard')
  assert.match(policy, /static let prefixLength = 3/)
  assert.match(policy, /static let maximumShardOperations = 1024/)
  assert.match(policy, /UUID\(uuidString: id\)/)
})

test('V1 ledger remains immutable on new V2 prepare and its prior receipts win', () => {
  const prepare = ledger.slice(ledger.indexOf('func prepare(scope:'),ledger.indexOf('func beginCreate(scope:'))
  assert.match(prepare,/let legacy = try read\(scope: scope, key: key\)/)
  assert.match(prepare,/if let prior = legacy\.operations\.first/)
  assert.match(prepare,/var shard = try readShard\(scope: scope, key: key, prefix: prefix\)/)
  assert.ok(prepare.indexOf('let legacy =') < prepare.indexOf('var shard ='))
  assert.doesNotMatch(prepare,/try write\(legacy/)
  assert.match(prepare,/try writeShard\(shard, scope: scope, key: key, prefix: prefix\)/)
  assert.match(ledger,/private let maxOperations = 1024/)
  assert.match(ledger,/guard envelope\.version == 1, envelope\.scope == scope/)
})

test('all V2 writes are bound to exact Owner scope and shard, atomic and protected', () => {
  assert.match(ledger,/private func shardAAD\(scope: XDrivePhotoSyncScope, prefix: String\)/)
  assert.match(ledger,/canonicalData\(scope\) \+ Data\(/)
  assert.match(ledger,/photo-ledger-shard-v2:/)
  assert.match(ledger,/authenticating: shardAAD\(scope: scope, prefix: prefix\)/)
  assert.match(ledger,/envelope\.version == 2, envelope\.scope == scope/)
  assert.match(ledger,/FileProtectionType\.complete/)
  assert.match(ledger,/ciphertext\.write\(to: url, options: \[\.atomic, \.completeFileProtection\]\)/)
  assert.match(ledger,/file\.synchronize\(\)/)
  assert.match(ledger,/throw XDrivePhotoSyncLedgerError\.corruptOrInaccessible/)
  assert.doesNotMatch(policy,/localIdentifier|accessToken|deviceToken|refreshToken/)
})

test('V1 and V2 updates retain unknown ACK fence and never silently drop operations', () => {
  const change = ledger.slice(ledger.indexOf('private func change(scope:'),ledger.indexOf('private func canonicalData('))
  assert.match(change,/if let index = legacy\.operations\.firstIndex/)
  assert.match(change,/let prefix = XDrivePhotoLedgerShardPolicy\.prefix\(/)
  assert.match(change,/try writeShard\(shard, scope: scope, key: key, prefix: prefix\)/)
  assert.match(ledger,/entry\.state = \.needsReconciliation/)
  assert.match(ledger,/guard \(entry\.state == \.finalizing \|\| entry\.state == \.needsReconciliation\)/)
  assert.match(ledger,/for prefix in try availableShardPrefixes\(scope: scope\)/)
  assert.match(ledger,/fingerprints\.insert\(entry\.assetFingerprint\)\.inserted/)
  assert.doesNotMatch(change,/removeItem|clearLocalRecords/)
})

test('single original upload and unknown-ACK checks read only their authenticated V2 shard', () => {
  const journal = fs.readFileSync(path.join(root, 'ios/XDriveIOS/IOSJournaledOriginalUpload.swift'), 'utf8')
  const runner = fs.readFileSync(path.join(root, 'ios/XDriveIOS/ForegroundPhotoBackupMVP.swift'), 'utf8')
  const start = ledger.indexOf('func operation(scope: XDrivePhotoSyncScope, id: String)')
  const end = ledger.indexOf('/// Explicit destructive LOCAL reset;', start)
  assert.ok(start > 0 && end > start, 'missing bounded operation reader')
  const readOne = ledger.slice(start, end)
  assert.match(readOne, /let legacy = try read\(scope: scope, key: key\)/)
  assert.match(readOne, /XDrivePhotoLedgerShardPolicy\.prefix\(/)
  assert.match(readOne, /try readShard\(scope: scope, key: key, prefix: prefix\)/)
  assert.doesNotMatch(readOne, /availableShardPrefixes\(|func operations\(/)
  assert.match(journal, /ledger\.operation\(/)
  assert.doesNotMatch(journal, /ledger\.operations\(scope: scope\)/)
  assert.match(runner, /journal\.operation\(/)
  assert.doesNotMatch(runner, /journal\.operations\(scope: binding\.scope\)/)
  assert.match(journal, /last\.state != \.prepared, last\.state != \.confirmed/)
  assert.match(runner, /current\.state != \.prepared/)
})
