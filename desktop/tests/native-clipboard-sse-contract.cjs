'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

const swiftClient = read('ios/XDriveIOS/NativeClipboardClient.swift')
const swiftPage = read('ios/XDriveIOS/NativeClipboardScreen.swift')
const swiftParser = read('ios/XDriveIOS/NativeClipboardSSECursor.swift')
const androidAPI = read('android/core/src/main/kotlin/com/tfluid/xdrive/core/XDriveApi.kt')
const androidPage = read('android/app/src/main/java/com/tfluid/xdrive/NativeClipboardScreens.kt')
const androidController = read('android/app/src/main/java/com/tfluid/xdrive/DriveController.kt')
const androidParser = read('android/core/src/main/kotlin/com/tfluid/xdrive/core/XDriveClipboardSSECursor.kt')

test('iOS SSE uses verified Owner HTTPS bearer and cancellable ephemeral URLSession', () => {
  assert.match(swiftClient, /func watchChanges\(after: UInt64, onChange: \(\) async -> Void\)/)
  assert.match(swiftClient, /url\.path = "\/api\/v1\/clipboard\/events"/)
  assert.match(swiftClient, /url\.queryItems = \[URLQueryItem\(name: "after"/)
  assert.match(swiftClient, /endpoint\.scheme == "https"/)
  assert.ok(swiftClient.includes('request.setValue("Bearer \\(token)"'))
  assert.match(swiftClient, /URLSessionConfiguration\.ephemeral/)
  assert.match(swiftClient, /XDriveIOSClipboardRejectRedirects\(\)/)
  assert.match(swiftClient, /session\.bytes\(for: request\)/)
  assert.match(swiftClient, /defer \{ session\.invalidateAndCancel\(\) \}/)
  assert.match(swiftClient, /line\.count < 4096/)
  assert.match(swiftClient, /try decoder\.acceptLine\(text\)/)
  assert.doesNotMatch(swiftClient.slice(swiftClient.indexOf('func watchChanges('),swiftClient.indexOf('func vault()',swiftClient.indexOf('func watchChanges('))), /UIPasteboard|UserDefaults|Keychain|http:\/\//)
})

test('iOS subscription only runs while unlocked, has 15s GET fallback and reconnect GET', () => {
  assert.match(swiftPage, /\.task\(id: unlocked && scenePhase == \.active\)/)
  assert.match(swiftPage, /@Environment\(\\\.scenePhase\) private var scenePhase/)
  assert.match(swiftPage, /sessionGeneration == generation/)
  assert.match(swiftPage, /client\.watchChanges\(after: after\)/)
  assert.match(swiftPage, /await refresh\(\) \/\/ Full GET after disconnect/)
  assert.match(swiftPage, /15_000_000_000/)
  assert.match(swiftPage, /3_000_000_000/)
  assert.match(swiftPage, /\.onDisappear \{ lock\(\) \}/)
  assert.match(swiftParser, /value == "\{\}"/)
})

test('Android SSE stays on the same pinned Owner transport with cancellable frames', () => {
  assert.match(androidAPI, /\.pinConnection\(address, connectionIp\)/)
  assert.match(androidAPI, /override suspend fun clipboardWatch\(/)
  assert.match(androidAPI, /\.addPathSegments\("api\/v1\/clipboard\/events"\)/)
  assert.match(androidAPI, /\.header\("Authorization", "Bearer \$accessToken"\)/)
  assert.match(androidAPI, /\.header\("Accept", "text\/event-stream"\)/)
  assert.match(androidAPI, /currentCoroutineContext\(\)\[Job\]\?\.invokeOnCompletion \{ call\.cancel\(\) \}/)
  assert.match(androidAPI, /source\.readUtf8LineStrict\(4096\)/)
  assert.match(androidAPI, /cursor\.acceptLine\(line\)/)
  assert.match(androidController, /withNotesOwner \{ service, token -> service\.clipboardWatch\(token, after, onChange\) \}/)
  assert.match(androidParser, /require\(value == "\{\}"\)/)
  assert.doesNotMatch(androidAPI.slice(androidAPI.indexOf('override suspend fun clipboardWatch('),
    androidAPI.indexOf('override suspend fun notesInitialize(',androidAPI.indexOf('override suspend fun clipboardWatch('))),
    /X-XDrive-Device-Token|SourceRun|clipboard\.setPrimaryClip/)
})

test('Android SSE locks with Owner and never replaces polling / authoritative GET', () => {
  assert.match(androidPage, /controller\.clipboardWatch\(after\)/)
  assert.match(androidPage, /lifecycleOwner\.lifecycle\.repeatOnLifecycle\(Lifecycle\.State\.STARTED\)/)
  assert.match(androidPage, /while \(stillSession\(snapshot\) && key != null\)/)
  assert.match(androidPage, /if \(stillSession\(snapshot\) && key != null\) refresh\(\)/)
  assert.match(androidPage, /refresh\(\) \/\/ Disconnect\/cursor eviction/)
  assert.match(androidPage, /delay\(15_000\)/)
  assert.match(androidPage, /delay\(3_000\)/)
  assert.match(androidPage, /onDispose \{ lock\(\) \}/)
})
