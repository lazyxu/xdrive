const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Desktop stages only advisory identity evidence through real authenticated Agent', () => {
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_evidence.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const globals = read('desktop', 'src', 'renderer', 'global.d.ts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalEvidenceDialog.tsx')
  const web = read('web', 'src', 'App.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')

  assert.match(agent, /CloudStageLocalBoundBackupEvidence\(/)
  assert.match(agent, /localFolderGrantMu.TryLock\(\)/)
  assert.match(agent, /localBoundBackupConfig\(stageCtx, sourceID\)/)
  assert.match(agent, /cli.LocalBoundRules\(stageCtx, sourceID, proof\)/)
  assert.match(agent, /localpush.LoadRootGrant\(/)
  assert.match(agent, /localpush.PublishLocalReconcileEvidence\(/)
  assert.match(agent, /localpushstage.StageVerifiedLocalRenameEvidence\(/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /Authoritative: false, MissingInferenceSafe: false/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem\(|MirrorMissingFullScans/)
  assert.match(ipc, /"device-backup-local-evidence"/)
  assert.match(ipc, /POST \/v1\/device-backups\/local-evidence/)
  assert.match(handler, /CloudStageLocalBoundBackupEvidence\(r.Context\(\), sourceID\)/)
  assert.match(handler, /"private, no-store"/)
  assert.doesNotMatch(handler, /root_id|fingerprint|local_path|file_path/)
  assert.match(client, /localBoundBackupEvidence\(sourceID: number, signal\?: AbortSignal\)/)
  assert.match(client, /315_000, signal/)
  assert.match(main, /localEvidenceRequests.set\(key, controller\)/)
  assert.match(main, /localEvidenceRequests.get\(key\)\?\.abort\(\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-evidence'\)/)
  assert.match(preload, /stageDeviceBackupLocalEvidence:/)
  assert.match(preload, /cancelDeviceBackupLocalEvidence:/)
  assert.match(globals, /XDriveLocalBackupEvidence/)
  assert.match(app, /localEvidence=\{localBackupEvidence\}/)
  assert.match(page, /localEvidence && verifiedLocalDeviceID === device.id && !device.revoked/)
  assert.match(page, /evidenceTarget.source === source/)
  assert.match(dialog, /crypto.randomUUID\(\)/)
  assert.match(dialog, /actions.cancel\(currentRequest.current\)/)
  assert.match(dialog, /result|setResult/)
  assert.match(dialog, /value.hints !== value.matched \+ value.unmatched/)
  assert.match(dialog, /value.matched !== value.stored \+ value.replayed/)
  assert.match(dialog, /暂存不证明重命名已成立/)
  assert.doesNotMatch(dialog, /startUpload\(|triggerSource\(|cancelSourceRun\(|deleteSource\(|SourceItemAlias\(/)
  assert.doesNotMatch(web, /stageDeviceBackupLocalEvidence|localEvidence=/)
  const remoteProjection = dto.slice(0, dto.indexOf('// Separate private Agent-only draft projection.'))
  assert.doesNotMatch(remoteProjection, /native_identity|root_id|source_item_id|replayed|matched/)
})
