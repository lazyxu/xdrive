const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')

test('bounded private native restart recovery has no IPC or execution authority', () => {
  const code = read('cmd/xdrive-agent/device_backup_local_stage_restart_recovery.go')
  const tests = read('cmd/xdrive-agent/device_backup_local_stage_restart_recovery_test.go')
  const hints = read('internal/localpushstage/private_recovery_hint.go')
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  const electron = read('desktop/src/main/index.cts')
  const web = read('web/src/App.tsx')
  const router = read('internal/api/router.go')
  assert.match(code, /func \(c \*agentController\) inspectLocalBoundBackupStageRestartPage\(/)
  assert.match(code, /localpushstage\.ListLocalOriginalRecoveryHints\(/)
  assert.match(code, /c\.readLocalBoundBackupHistoricalPhysicalReceipt\(/)
  assert.match(code, /localBoundBackupConfig\(readCtx, sourceID\)/)
  assert.match(code, /localBackupRuleSessionUnchanged\(account\)/)
  assert.match(code, /localStageRestartInspectLimit = 8/)
  assert.match(code, /BackupComplete: false, Authoritative: false/)
  assert.match(code, /localStageRestartUnresolved/)
  assert.match(hints, /localStageRecoveryMaxFiles\s+= 128/)
  assert.match(tests, /TestPrivateStageRestartPageIsBoundedSortedAndRequiresExactCursor/)
  assert.match(tests, /TestPrivateStageRestartOnlyHistoricalPhysicalReceiptCountsAsObserved/)
  assert.match(tests, /TestPrivateStageRestartPropagatesCancellationAndCannotBeUsedAsCommitToken/)
  assert.match(code, /@private@|json:"-"/)
  assert.doesNotMatch(code, /(?:BeginSourceRun|TriggerSource|commitBoundLocalPushFirstLeaf|CancelSourceRun|SaveLocalOriginalRecoveryHint|os\.Remove)\(/)
  for (const surface of [ipc, electron, web, router]) {
    assert.equal(surface.includes('inspectLocalBoundBackupStageRestartPage'), false,
      'private restart observation was exported into Renderer/IPC/Web/REST')
    assert.equal(surface.includes('localStageRestartInspectionPage'), false)
  }
})
