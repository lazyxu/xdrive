const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')
const shared = read('ui', 'shared', 'src', 'mui', 'AdminAuditPage.tsx')
const web = read('web', 'src', 'AdminAudit.tsx')
const desktop = read('desktop', 'src', 'renderer', 'App.tsx')
const main = read('desktop', 'src', 'main', 'index.cts')
const preload = read('desktop', 'src', 'preload', 'index.cts')
const globals = read('desktop', 'src', 'renderer', 'global.d.ts')
const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_admin_audit.go')
const controller = read('cmd', 'xdrive-agent', 'cloud_admin_audit.go')
const client = read('internal', 'client', 'admin_audit.go')
const server = read('internal', 'api', 'audit.go')
const port = read('ui', 'shared', 'src', 'admin-management.ts')

test('Web and Desktop use the identical snapshot-bound virtualized audit page', () => {
  assert.ok(web.includes("export { XDriveAdminAuditPage as default } from '@xdrive/ui/mui'"))
  assert.ok(desktop.includes('<XDriveAdminAuditPage api={adminAuditPort} />'))
  for (const token of ['useXDriveVirtualCollection<AuditEvent>', 'virtualCollection.ensureViewport(',
    'snapshotMaxIDRef', 'api.adminAuditRange({', 'data-xdrive-admin-audit-mobile-list']) {
    assert.ok(shared.includes(token), 'missing shared audit contract: ' + token)
  }
  assert.ok(port.includes('export type XDriveAdminAuditPort'))
})

test('Desktop audit path is admin-only, bounded and cancellable to Go', () => {
  assert.ok(desktop.includes("key: 'admin-audit', label: '审计日志'"))
  assert.ok(desktop.includes("view === 'admin-audit' && status?.role === 'admin'"))
  assert.ok(desktop.includes("capabilities.includes('admin-audit')"))
  assert.ok(desktop.includes('xDriveDesktopViewportRequest(signal'))
  assert.ok(main.includes("requireAgentCapability(hello, 'admin-audit')"))
  assert.ok(main.includes("viewportRequests.run(event.sender, requestID"))
  assert.ok(main.includes("'agent:cloud-admin-audit-range'"))
  assert.ok(preload.includes('cloudAdminAuditRange:'))
  assert.ok(globals.includes('cloudAdminAuditRange:'))
  assert.ok(ipc.includes('POST /v1/cloud/admin-audit/range'))
  assert.ok(ipc.includes('"admin-audit"'))
  assert.ok(handler.includes('snapshot.Role != "admin"'))
  assert.ok(handler.includes('validDesktopAdminAuditRange(query)'))
  assert.ok(handler.includes('provider.CloudAdminAuditRange(r.Context(), query)'))
  assert.ok(controller.includes('cli.AdminAuditRange(ctx, query)'))
  assert.ok(client.includes('query.Set("range", "true")'))
  assert.ok(client.includes('query.Set("snapshot_max_id"'))
  assert.ok(client.includes('c.json(ctx, http.MethodGet, "/api/v1/admin/audit?"'))
  assert.ok(server.includes('s.DB.WithContext(c.Request.Context())'))
})
