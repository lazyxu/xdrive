'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')
const native = read('ios/XDriveIOS/NativeUploadSessionTransport.swift')
const policy = read('ios/XDriveIOS/BackgroundOriginalRoutePolicy.swift')
const server = read('internal/api/ios_photo_background_uploads.go')
const router = read('internal/api/router.go')
const managedPolicy = read('ios/XDriveIOS/ManagedPhotoUploadRoutePolicy.swift')
const managed = read('internal/api/ios_photo_managed_uploads.go')

test('foreground bearer and approved iOS background grant reuse EXACTLY one native upload engine', () => {
  assert.match(native, /case foregroundBearer\(String\)/)
  assert.match(native, /case scopedIOSBackground\(XDriveIOSApprovedPhotoBGCredential\)/)
  assert.match(native, /approvedBackgroundGrant: XDriveIOSApprovedPhotoBGCredential/)
  assert.match(native, /func uploadPreparedOriginal\(/)
  assert.match(native, /private func uploadInternally\(/)
  assert.match(native, /if case \.scopedIOSBackground\(let credential\) = authorization/)
  assert.match(native, /XDriveIOSBackgroundOriginalNamePolicy\.valid\(name\)/)
  assert.match(native, /parentID == credential\.targetNodeID/)
  assert.match(native, /guard case \.foregroundBearer = authorization else/)
  assert.match(native, /XDriveIOSManagedPhotoBackgroundUploadRoutePolicy\.translatedPath\(path\)/)
  assert.match(native, /credential\.grantSecret/)
  assert.match(native, /X-XDrive-Device-Token/)
  assert.match(native, /X-XDrive-IOS-Photo-Grant/)
  assert.match(native, /URLSessionConfiguration\.ephemeral/)
  assert.match(native, /completionHandler\(nil\)/)
  assert.equal((native.match(/private func uploadInternally\(/g) || []).length, 1,
    'no second native chunk/finalize state machine')
})

test('BG-specific URL policy matches only the protected Go aliases', () => {
  assert.match(policy, /private static let scopedPrefix = "\/api\/v1\/ios\/photos\/background\/uploads"/)
  assert.match(policy, /UUID\(uuidString: String\(parts\[0\]\)\)/)
  assert.match(policy, /String\(index\) == String\(parts\[2\]\)/)
  assert.match(router, /iosPhotoBackground\.Use\(s\.requireIOSPhotoBackgroundGrant\(\)\)/)
  assert.match(router, /iosPhotoBackground\.POST\("\/uploads", s\.iosBackgroundCreateUpload\)/)
  assert.match(router, /iosPhotoBackground\.PUT\("\/uploads\/:id\/chunks\/:index", s\.iosBackgroundPutChunk\)/)
  assert.match(router, /iosPhotoBackground\.POST\("\/uploads\/:id\/finalize", s\.iosBackgroundFinalizeUpload\)/)
  assert.match(server, /iosBackgroundOriginalNameValid\(req\.Name\)/)
  assert.match(server, /req\.ParentID != nil && \*req\.ParentID == grant\.RootNodeID/)
  assert.match(native, /XDriveIOSManagedPhotoBackgroundUploadRoutePolicy\.translatedPath\(path\)/)
  assert.match(managedPolicy, /private static let managed = "\/api\/v1\/ios\/photos\/background-managed\/uploads"/)
  assert.match(router, /iosPhotoManagedBG\.POST\("\/uploads", s\.iosPhotoManagedCreateUpload\)/)
  assert.match(managed, /iosPhotoManagedAuthorizedScope\(c\)/)
  assert.match(managed, /iosPhotoGrantHasManagedTarget\(grant\)/)
  assert.doesNotMatch(native, /URLSessionConfiguration\.background\(/,
    'long-lived tokens must not travel in OS-replayed background URLSession')
})

test('staged file read failure stops the original scan without bypassing the sealed ACK journal', () => {
  const writer = read('ios/XDriveIOS/IOSJournaledOriginalUpload.swift')
  const runner = read('ios/XDriveIOS/ForegroundPhotoBackupMVP.swift')
  const transport = native.slice(native.indexOf('private func uploadInternally('),
    native.indexOf('private func statusFor('))
  const hash = native.slice(native.indexOf('private func localSize('),
    native.indexOf('private func sha('))
  const readFailures = [transport, hash].join('\n')
  assert.match(native, /case localStorageUnavailable/)
  assert.equal((readFailures.match(/throw XDriveNativeUploadError\.localStorageUnavailable/g) || []).length,
    5, 'the five local size/open/read/seek filesystem error paths must stop work')
  assert.match(transport, /let fileSize = try localSize\(stagedFileURL\)[\s\S]*?let hashes = try fileHashes\(stagedFileURL, expectedSize: fileSize\)[\s\S]*?hooks\.beforeCreate\(\)/)
  assert.match(transport, /do \{\s*try file\.seek\(toOffset: UInt64\(start\)\)\s*chunk = try file\.read\(upToCount: bytes\)\s*\} catch \{\s*throw XDriveNativeUploadError\.localStorageUnavailable/)
  assert.match(hash, /do \{\s*attributes = try FileManager\.default\.attributesOfItem\(atPath: url\.path\)\s*\} catch \{\s*throw XDriveNativeUploadError\.localStorageUnavailable/)
  assert.match(hash, /do \{\s*chunk = try file\.read\(upToCount: Self\.chunkBytes\)\s*\} catch \{\s*throw XDriveNativeUploadError\.localStorageUnavailable/)
  const catchWriter = writer.slice(writer.indexOf('        } catch {', writer.indexOf('let hooks = XDriveNativeUploadCheckpointHooks(')))
  const mark = catchWriter.indexOf('ledger.markUnknown(')
  const typed = catchWriter.indexOf('case .localStorageUnavailable = storage')
  assert.ok(mark >= 0 && typed > mark, 'uncertain remote write is journaled before translating storage failure')
  assert.match(catchWriter, /throw XDrivePhotoKitExportFailure\.storageUnavailable/)
  assert.match(runner, /case \.storageUnavailable = source \{\s*return true/)
  assert.match(runner, /if Self\.isTransientConfirmedReadbackFailure\(error\) \|\|\s*Self\.mustAbortRun\(after: error\) \{ throw error \}/)
  assert.doesNotMatch(writer, /retryUpload|retryFinalize|clearLedger|removePersistentDomain/)
});
