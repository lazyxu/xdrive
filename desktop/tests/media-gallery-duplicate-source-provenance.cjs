const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')
const read = (filename) => fs.readFileSync(path.join(root, filename), 'utf8')

test('G11 source provenance is scoped to the owner and all persisted Node resources', () => {
  const plan = read('internal/api/media_duplicate_organize_plan.go')
  const integration = read('internal/api/media_duplicate_organize_plan_integration_test.go')
  assert.match(plan, /JOIN xd_source_items AS si ON si.node_id = pr.node_id/)
  assert.match(plan, /pr\.asset_id IN \? AND pr\.resource_kind = \? AND src\.owner_id = \?/)
  assert.match(plan, /mediaDuplicateOrganizeMaxSourceLinks = 1024/)
  assert.match(plan, /link\.Direction == meta\.SourceDirectionPull/)
  assert.match(plan, /link\.ItemState != meta\.SourceItemStateMissing/)
  assert.match(plan, /link\.ItemState != meta\.SourceItemStateIgnored/)
  assert.match(plan, /ResourceNodeID: link\.ResourceNodeID/)
  assert.match(plan, /sourceLinksByAsset\[row\.AssetID\]/)
  assert.match(plan, /snapshot, err := json\.Marshal\(out\)/)
  assert.match(plan, /out\.PlanRevision = hex\.EncodeToString\(digest\[:\]\)/)
  assert.match(integration, /TestMediaDuplicateOrganizePlanFindsLiveMotionSourceLinks/)
  assert.match(integration, /changed sync-folder provenance must reject stale review/)
  assert.match(integration, /cross-owner plan must not reveal assets/)
  assert.match(integration, /annotation union mutated sync-folder identity/)
})

test('G11 read-only source provenance reaches Web/Desktop shared confirmation without unsafe deletion', () => {
  const types = read('ui/shared/src/models.ts')
  const goClient = read('internal/client/media.go')
  const ui = read('ui/shared/src/mui/MediaGalleryDuplicateOrganizePreview.tsx')
  const apply = read('internal/api/media_duplicate_organize_apply.go')
  assert.match(types, /export interface MediaDuplicateOrganizeSourceLink/)
  assert.match(types, /source_links\?: MediaDuplicateOrganizeSourceLink\[\]/)
  assert.match(types, /potential_reimport_assets\?: number/)
  assert.match(goClient, /type MediaDuplicateOrganizeSourceLink struct/)
  assert.match(goClient, /SourceLinks\s+\[\]MediaDuplicateOrganizeSourceLink/)
  assert.match(ui, /data-xdrive-gallery-organize-source-coverage/)
  assert.match(ui, /data-xdrive-gallery-organize-source-links/)
  assert.match(ui, /远端仍存在时再次同步可能重新导入/)
  assert.match(ui, /未发现已关联来源记录；不能据此判定远端不存在副本/)
  assert.doesNotMatch(ui, /media-duplicate-organize\/trash|permanentlyDelete|onDeleteNode/)
  assert.match(apply, /OriginalFilesRetained = true/)
  assert.match(apply, /SourceLinksUnchanged = true/)
  assert.match(apply, /PhysicalBytesReclaimed = 0/)
})
