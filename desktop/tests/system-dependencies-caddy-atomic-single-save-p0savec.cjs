test('P0-SAVE-C: in-flight atomic Save freezes both editors and secondary requests', () => {
  const page = read('ui/shared/src/mui/CaddyDetailV1.tsx')
  const https = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  const alidns = read('ui/shared/src/mui/CaddyAliDNSPanel.tsx')
  assert.equal((page.match(/atomicSaving=\{savingAtomic\}/g) || []).length, 2)
  assert.match(page, /data-xdrive-caddy-v11-atomic-save aria-busy=\{savingAtomic \|\| undefined\}/)
  assert.match(https, /atomicSaving\?: boolean/)
  assert.match(https, /const canEdit = !!config\?\.editable && !busy && !loading && !atomicSaving/)
  assert.match(https, /if \(!source\.loadCaddyHTTPSConfig \|\| busy \|\| atomicSaving \|\| changed\) return/)
  assert.match(https, /disabled=\{busy \|\| loading \|\| atomicSaving \|\| changed/)
  assert.match(alidns, /atomicSaving\?: boolean/)
  assert.match(alidns, /const canEdit = !!config\?\.editable && !busy && !loading && !revealing && !atomicSaving/)
  assert.match(alidns, /if \(!config\?\.configured \|\| !source\.revealCaddyAliDNS \|\| revealing \|\| busy \|\| atomicSaving\) return/)
  assert.match(alidns, /revealDisabled=\{!config\.configured \|\| !source\.revealCaddyAliDNS/)
  assert.match(alidns, /disabled=\{busy \|\| atomicSaving\}/)
})

