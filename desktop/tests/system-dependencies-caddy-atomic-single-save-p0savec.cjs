'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')

test('P0-SAVE-C: Caddy one-page Save is one revision-fenced API call, never two legacy writes', () => {
  const page = read('ui/shared/src/mui/CaddyDetailV1.tsx')
  const https = read('ui/shared/src/mui/CaddyHTTPSDesiredPanel.tsx')
  const alidns = read('ui/shared/src/mui/CaddyAliDNSPanel.tsx')
  assert.match(page, /data-xdrive-caddy-v11-atomic-save/)
  assert.match(page, /data-xdrive-caddy-v11-save-only/)
  assert.match(page, /source\.saveCaddyConfiguration\(input\)/)
  assert.match(page, /https_revision: https\.revision, alidns_revision: ali\.revision/)
  assert.match(page, /https\.changed \? \{ https: \{/)
  assert.match(page, /ali\.action === 'keep'/)
  assert.match(page, /action: 'clear' as const/)
  assert.match(page, /action: 'replace' as const/)
  assert.match(page, /lan_enabled: https\.lan_enabled, lan_ip: https\.lan_ip/)
  assert.match(page, /if \(!canSaveAtomic/)
  assert.match(page, /savePendingRef\.current/)
  assert.doesNotMatch(page, /source\.saveCaddyHTTPSConfig\(|source\.saveCaddyAliDNS\(/)
  assert.match(https, /atomicMode\?: boolean/)
  assert.match(https, /\{!atomicMode && <Button/)
  assert.match(https, /\{!atomicMode && <XDriveConfirmDialog open=\{confirmSave\}/)
  assert.match(alidns, /atomicMode\?: boolean/)
  assert.match(alidns, /\{!atomicMode && <Button/)
  assert.match(alidns, /\{!atomicMode && <XDriveConfirmDialog open=\{confirmSave\}/)
})

test('P0-SAVE-C: refuse stale, missing, invalid or cross-instance drafts and forged apply proof', () => {
  const page = read('ui/shared/src/mui/CaddyDetailV1.tsx')
  assert.match(page, /httpsDraft\?\.source === source/)
  assert.match(page, /aliDraft\?\.source === source/)
  assert.match(page, /Number\.isSafeInteger\(v\) && v >= 0/)
  assert.match(page, /readyRevisions/)
  assert.match(page, /!\(https\?\.host_pending \|\| ali\?\.host_pending\)/)
  assert.match(page, /!https\?\.changed \|\| !!https\.valid/)
  assert.match(page, /ali\?\.action === 'keep' \|\| !!ali\?\.valid/)
  assert.match(page, /if \(!canSaveAtomic/)
  assert.match(page, /result\.saved !== true \|\| result\.host_applied !== false/)
  assert.match(page, /result\.apply_supported !== false/)
  assert.match(page, /result\.https_revision !== input\.https_revision \+ \(input\.https \? 1 : 0\)/)
  assert.match(page, /result\.alidns_revision !== input\.alidns_revision \+ \(input\.alidns \? 1 : 0\)/)
  assert.match(page, /\+\+saveEpoch\.current/)
  assert.match(page, /epoch !== saveEpoch\.current/)
  assert.match(page, /需要兼容联合保存的 Server\/Agent/)
  assert.match(page, /放弃未保存的修改/)
  assert.match(page, /setAtomicRefreshID/)
  assert.doesNotMatch(page, /applyCaddy|restartCaddy|docker restart|source\.deploy/)
})

