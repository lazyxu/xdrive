'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')

test('known Node revision reaches Web and Desktop authenticated thumbnail API', () => {
  const shared = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const scheduler = read('ui/shared/src/mui/MediaGalleryThumbnailScheduler.ts')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const thumbnail = read('ui/shared/src/mui/MediaGalleryPreviewMedia.tsx')
  const filmstrip = read('ui/shared/src/mui/MediaGalleryFilmstrip.tsx')
  const poster = read('ui/shared/src/mui/MediaGalleryVideoPoster.ts')
  const web = read('web/src/mediaGalleryAdapter.ts')
  const api = read('web/src/api.ts')
  const desktop = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const agent = read('desktop/src/main/agent_client.cts')
  const dts = read('desktop/src/renderer/global.d.ts')

  assert.match(shared, /port\.loadThumbnail\(nodeID,\s*signal,\s*revision\)/)
  assert.match(scheduler, /this\.loader\(task\.nodeID,\s*task\.controller\.signal,\s*task\.revision \|\| undefined\)/)
  assert.match(gallery, /thumbnailScheduler\.load\(nodeID,\s*thumbnailPriority,\s*item\.node\.revision\)/)
  assert.match(thumbnail, /loadThumbnail\(nodeID,\s*controller\.signal,\s*revision\)/)
  assert.match(filmstrip, /revision=\{item\.node\.revision\}/)
  assert.match(poster, /loadCached\(nodeID,\s*signal,\s*revision\)/)
  assert.match(web, /api\.mediaThumbnail\(nodeID,\s*signal,\s*revision\)/)
  assert.match(api, /cache: sourceRevision \? 'default' : 'no-cache'/)
  assert.match(api, /thumbnail\?v=3\$\{revisionQuery\}/)
  assert.match(desktop, /agent\.getMediaThumbnail\(nodeID,\s*requestID,\s*revision\)/)
  assert.match(preload, /'agent:get-media-thumbnail', nodeID, requestID, revision/)
  assert.match(main, /mediaThumbnail\(nodeID,\s*signal,\s*[\s\S]*?revision : undefined\)/)
  assert.match(agent, /query\.set\('revision', String\(revision\)\)/)
  assert.match(dts, /getMediaThumbnail: \(nodeID: number, requestID\?: string, revision\?: number\)/)
})

test('unknown-revision Agent covers require ETag revalidation and source scope', () => {
  const agent = read('cmd/xdrive-agent/cloud_files.go')
  const cache = read('cmd/xdrive-agent/media_thumbnail_cache.go')
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  assert.match(agent, /if sourceRevision == 0 \{\s*maxAge = 0/)
  assert.match(agent, /agentMediaThumbnailCacheKey\(cfg, nodeID, sourceRevision\)/)
  assert.match(cache, /agentMediaThumbnailCacheVersion/)
  assert.match(cache, /revision\[0\] > 0/)
  assert.match(ipc, /CloudMediaThumbnail\(r\.Context\(\), nodeID, revision\)/)
  assert.match(ipc, /invalid_revision/)
})
