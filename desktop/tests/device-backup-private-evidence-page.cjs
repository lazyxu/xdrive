const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Agent evidence readback is private and remains non-authoritative', () => {
  const api = read('internal', 'api', 'local_source_item_evidence_page.go')
  const manifest = read('internal', 'api', 'router_contract_test.go')
  const router = read('internal', 'api', 'router.go')
  const client = read('internal', 'client', 'local_source_item_evidence_page.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_page.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(router, /local-identity\/evidence-page", s\.requireLocalSourceExecutor\(\), s\.readLocalSourceItemEvidencePage/)
  assert.match(manifest, /POST", path: "\/api\/v1\/sources\/:id\/local-identity\/evidence-page"/)
  assert.match(api, /s\.requireLocalSourceProofTx\(tx, c, sourceID, "", false\)/)
  assert.match(api, /Order\("id ASC"\)\.Limit\(input\.Limit \+ 1\)/)
  assert.match(api, /input\.PreviousSnapshotSHA256, input\.CurrentSnapshotSHA256/)
  assert.match(api, /proof\.DeviceID, proof\.RootID/)
  assert.match(api, /SourceStatusPaused/)
  assert.match(api, /Authoritative: false, MissingInferenceSafe: false/)
  assert.match(api, /private, no-store/)
  assert.doesNotMatch(api, /BeginSourceRun|UploadChunk|CommitSourceItem|SourceItemAlias\{|MirrorDeletion/)
  assert.match(client, /ReadLocalSourceItemEvidencePage\(/)
  assert.match(client, /DisallowUnknownFields/)
  assert.match(client, /localSourceEvidencePageMaxResponseBytes/)
  assert.match(agent, /localFolderGrantMu\.TryLock\(\)/)
  assert.match(agent, /localBoundBackupConfig\(readCtx, sourceID\)/)
  assert.match(agent, /localpush\.LoadRootGrant/)
  assert.match(agent, /localpush\.LoadLocalReconcileEvidence/)
  assert.match(agent, /cli\.LocalBoundRules/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  assert.doesNotMatch(ipc, /local-identity\/evidence-page|CloudReadLocalBoundBackupEvidencePage/)
  assert.doesNotMatch(preload, /getDeviceBackupLocalEvidencePage|readLocalBoundBackupEvidencePage/)
  assert.doesNotMatch(web, /local-identity\/evidence-page|readLocalBoundBackupEvidencePage/)
})
