const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = (p) => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')

test('one Baidu photo consent DTO and one Owner Server path across Web, Mobile and Desktop', () => {
  const ui = read('ui/shared/src/mui/MediaGalleryViewerLocationDialog.tsx')
  const adapter = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const web = read('web/src/mediaGalleryAdapter.ts')
  const desktop = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const api = read('web/src/api.ts')
  const agent = read('cmd/xdrive-agent/desktop_ipc.go')
  const bridge = read('cmd/xdrive-agent/desktop_ipc_media_baidu_consent.go')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const goClient = read('internal/client/media.go')
  for (const method of ['getBaiduMapConsent', 'saveBaiduMapConsent', 'revokeBaiduMapConsent']) {
    assert.ok(adapter.includes(method))
    assert.ok(web.includes(method))
    assert.ok(desktop.includes(method))
    assert.ok(ui.includes(method))
  }
  assert.match(api, /baidu-map-consent/)
  assert.match(goClient, /baidu-map-consent/)
  assert.match(agent, /"GET \/v1\/media\/baidu-consent"/)
  assert.match(agent, /"PUT \/v1\/media\/baidu-consent"/)
  assert.match(agent, /"DELETE \/v1\/media\/baidu-consent"/)
  assert.match(bridge, /CloudRevokeMediaBaiduConsent/)
  assert.match(main, /validConsentNode/)
  assert.match(preload, /agent:revoke-media-baidu-consent/)
  assert.match(ui, /consent_to_baidu_conversion:\s*true/)
  assert.match(ui, /consent_to_derived_index:\s*true/)
  assert.match(ui, /source_changed:\s*/)
  assert.match(ui, /动态地图/)
  assert.match(ui, /generation\.current/)
  assert.doesNotMatch(bridge, /BaiduMapAK|BrowserAK|Getenv\(/)
})
