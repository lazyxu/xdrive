'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const browser = fs.readFileSync(path.join(__dirname, '../../ios/XDriveIOS/NativeCloudFilesBrowser.swift'), 'utf8')
const section = (start, end) => browser.slice(browser.indexOf(start), browser.indexOf(end, browser.indexOf(start)))
const row = section('@ViewBuilder private func fileEntryRow(', 'private var filesContinuousStatus:')
const grid = section('private func gridTile(', 'private func gridLabel(')
const chrome = section('private var filesChrome:', 'private var filesModals:')

test('Browse uses large native title; directory and search use inline title', () => {
  assert.match(browser, /\.navigationTitle\(isHome \? "浏览" : \(folder\?\.name \?\? "搜索结果"\)\)/)
  assert.match(browser, /\.navigationBarTitleDisplayMode\(isHome \? \.large : \.inline\)/)
  assert.match(browser, /private var isHome: Bool \{ folder == nil && !isGlobalSearch \}/)
})
test('native Files list tap targets do not show permanent trailing More/Locate buttons', () => {
  assert.doesNotMatch(row, /Image\(systemName: "ellipsis\.circle"\)/)
  assert.match(row, /NavigationLink\(value: XDriveIOSNativeFilesFolder/)
  assert.match(row, /Button \{ openViewer\(entry\) \}/)
  assert.match(row, /\.contextMenu \{[\s\S]*?nativeQuickActions\(for: entry\)/)
  assert.match(row, /Label\("属性", systemImage: "info\.circle"\)/)
  assert.match(row, /Label\("显示位置", systemImage: "folder\.badge\.questionmark"\)/)
  assert.match(row, /native-ios-files-locate-/)
  assert.match(browser, /\.swipeActions\(edge: \.trailing, allowsFullSwipe: false\)/)
})
test('icon grid is unboxed while long-press still supports actions and location', () => {
  assert.doesNotMatch(grid, /Image\(systemName: "ellipsis\.circle"\)|\.background\(Color\(uiColor: \.secondarySystemGroupedBackground\)/)
  assert.match(grid, /toggleSelection\(entry\)/)
  assert.match(grid, /NavigationLink\(value: XDriveIOSNativeFilesFolder/)
  assert.match(grid, /Button \{ openViewer\(entry\) \}/)
  assert.match(grid, /\.contextMenu \{[\s\S]*?nativeQuickActions\(for: entry\)/)
  assert.match(grid, /openManagement\(for: entry\.node\)/)
  assert.match(grid, /requestLocation\(for: entry\)/)
})
test('native selection starts in More menu, ends with Done, keeps guards and sorting', () => {
  assert.match(chrome, /if selecting \{\s*Button\("完成"\)/)
  assert.match(chrome, /if !selecting \{\s*Menu \{\s*Button \{/)
  assert.match(chrome, /Label\("选择", systemImage: "checkmark\.circle"\)/)
  assert.match(chrome, /native-ios-files-multi-select|native-ios-files-selection-done/)
  assert.match(chrome, /Picker\("显示方式", selection: Binding\(/)
  assert.match(chrome, /Picker\("排序", selection: \$sort\)/)
  assert.match(chrome, /Picker\("顺序", selection: \$order\)/)
  assert.match(browser, /private var canSelectPage: Bool \{[\s\S]*?model\.verifiedPage/)
})
