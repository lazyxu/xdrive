const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')

test('B1-D hierarchy uses bounded server facets and existing Owner Range + Viewer', () => {
  const view = read('ui/shared/src/mui/MediaGalleryPlacesHierarchy.tsx')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const adapter = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const web = read('web/src/mediaGalleryAdapter.ts')
  assert.match(view, /PAGE_LIMIT = 48/)
  assert.match(view, /AbortController/)
  assert.match(view, /return \(\) => controller\.abort\(\)/)
  assert.match(view, /data-xdrive-places-hierarchy-breadcrumb/)
  assert.match(view, /data-xdrive-places-hierarchy-item/)
  assert.match(view, /onOpenPhotoRange\(item\)/)
  assert.match(gallery, /place_hierarchy: place\.id/)
  assert.match(gallery, /listPlacesHierarchy=\{source\.listPlacesHierarchy\}/)
  assert.match(gallery, /XDriveMediaGalleryPlacesHierarchy/)
  assert.match(adapter, /listPlacesHierarchy: port\.listPlacesHierarchy/)
  assert.match(web, /api\.mediaPlaceHierarchy\(request, filters, signal\)/)
  assert.ok(view.indexOf('fetch(') === -1, 'the component must not bypass the authenticated port')
})
