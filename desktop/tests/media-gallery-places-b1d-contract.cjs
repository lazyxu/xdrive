test('B1-D Desktop Agent-to-Renderer bridge validates inputs and uses the same Owner contract', () => {
  const client = read('internal/client/media.go')
  const ctrl = read('cmd/xdrive-agent/cloud_files.go')
  const router = read('cmd/xdrive-agent/desktop_ipc.go')
  const handler = read('cmd/xdrive-agent/desktop_ipc_media_places_hierarchy.go')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const renderer = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  assert.match(client, /MediaPlaceHierarchy\(ctx context\.Context/)
  assert.match(ctrl, /CloudMediaPlaceHierarchy\(ctx context\.Context/)
  assert.match(router, /GET \/v1\/media\/places\/hierarchy/)
  assert.match(handler, /parseDesktopIPCMediaPlacesHierarchy/)
  assert.match(handler, /CloudMediaPlaceHierarchy\(context\.Context, url\.Values/)
  assert.match(main, /agent:get-media-place-hierarchy/)
  assert.match(main, /requireAgentCapability\(hello, 'media-gallery'\)/)
  assert.match(preload, /agent:get-media-place-hierarchy/)
  assert.match(renderer, /agent\.getMediaPlaceHierarchy\(request, filters, requestID\)/)
  assert.ok(!renderer.includes('https://api.map.baidu.com'))
})

