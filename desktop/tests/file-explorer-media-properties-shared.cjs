const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')

const repo = path.join(__dirname, '..', '..')
const read = (...names) => fs.readFileSync(path.join(repo, ...names), 'utf8')
const explorer = read('ui', 'shared', 'src', 'mui', 'FileExplorer.tsx')
const details = read('ui', 'shared', 'src', 'mui', 'MediaGalleryDetails.tsx')
const inspector = read('ui', 'shared', 'src', 'mui', 'MediaGalleryInspector.tsx')
const webExplorer = read('web', 'src', 'WebFileExplorer.tsx')
const webApi = read('web', 'src', 'api.ts')
const desktop = read('desktop', 'src', 'renderer', 'DesktopFileExplorer.tsx')
const agentGo = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
const cloudGo = read('cmd', 'xdrive-agent', 'cloud_files.go')
const agentClient = read('desktop', 'src', 'main', 'agent_client.cts')
const main = read('desktop', 'src', 'main', 'index.cts')
const preload = read('desktop', 'src', 'preload', 'index.cts')
const globals = read('desktop', 'src', 'renderer', 'global.d.ts')

test('single image/video/LIVP media Properties reuses the shared Inspector', () => {
  assert.match(explorer, /mediaFileKind === 'image' \|\| mediaFileKind === 'video'/)
  assert.match(explorer, /endsWith\('\.livp'\)/)
  assert.match(explorer, /propertiesItems\.length === 1/)
  assert.match(explorer, /<XDriveMediaDetailsInspector/)
  assert.match(explorer, /loadThumbnail=\{async \(\) => null\}/)
  assert.match(explorer, /showPreview=\{false\}/)
  assert.match(inspector, /<XDriveMediaDetailsContent item=\{item\}/)
  assert.match(details, /extraFileRows\?: Array/)
  assert.match(details, /<MediaDetailsRows rows=\{extraFileRows\}/)
})

test('normal files, directories, batches and unsupported media retain the existing Properties dialog', () => {
  assert.match(explorer, /<XDriveFilePropertiesDialog/)
  assert.match(explorer, /open=\{propertiesItems\.length > 0 && !showMediaProperties\}/)
  assert.match(explorer, /mediaPropertiesEnabled && !mediaPropertiesError/)
  assert.match(explorer, /label: '媒体属性', value: mediaPropertiesError/)
  assert.match(explorer, /propertiesDialogHasFolder/)
  assert.match(explorer, /useXDriveFileExplorerPropertiesController/)
})

test('media request is lazy, cancellable and rejects stale Node/revision responses', () => {
  assert.match(explorer, /mediaPropertiesRequestRef/)
  assert.match(explorer, /new AbortController\(\)/)
  assert.match(explorer, /return \(\) => controller\.abort\(\)/)
  assert.match(explorer, /value\.node\.id !== Number\(currentItem\.id\)/)
  assert.match(explorer, /value\.node\.revision !== expectedRevision/)
  assert.match(explorer, /\[interactionScopeKey, propertiesDialogItem\.id, propertiesDialogItem\.revision/)
  assert.match(explorer, /loadMediaItem\(currentItem, controller\.signal\)/)
  assert.match(inspector, /正在加载媒体属性/)
})

test('Web and Desktop fetch the canonical single MediaItem without traversing the media wall', () => {
  assert.match(webApi, /mediaItem\(nodeID: number, signal\?: AbortSignal\)/)
  assert.match(webExplorer, /api\.mediaItem\(Number\(item\.id\), signal\)/)
  assert.match(webExplorer, /loadMediaItem=\{trashActive \? undefined : loadMediaItem\}/)
  assert.match(desktop, /getMediaItem\(Number\(item\.id\), requestID\)/)
  assert.match(desktop, /loadMediaItem=\{!trashActive && mediaPropertiesSupported \? loadMediaItem : undefined\}/)
  assert.match(cloudGo, /return cli\.MediaItem\(ctx, nodeID\)/)
  assert.match(agentGo, /GET \/v1\/media\/item/)
  assert.match(agentGo, /CloudMediaItem\(r\.Context\(\), nodeID\)/)
})

test('Desktop media cancellation propagates to the authenticated Agent HTTP request', () => {
  assert.match(desktop, /signal\.addEventListener\('abort', cancel, \{ once: true \}\)/)
  assert.match(desktop, /cancelMediaItem\(requestID\)/)
  assert.match(globals, /getMediaItem: \(nodeID: number, requestID: string\)/)
  assert.match(preload, /ipcRenderer\.invoke\('agent:get-media-item', nodeID, requestID\)/)
  assert.match(preload, /ipcRenderer\.invoke\('agent:cancel-media-item', requestID\)/)
  assert.match(main, /cancelledMediaItemRequests\.delete\(requestID\)/)
  assert.match(main, /controller\.abort\(\)/)
  assert.match(main, /mediaItem\(nodeID, controller\.signal\)/)
  assert.match(agentClient, /mediaItem\(nodeID: number, signal\?: AbortSignal\)/)
  assert.match(agentClient, /\/v1\/media\/item\?node_id=/)
  assert.match(agentClient, /10_000,\s*signal,/)
})

test('media presentation uses the canonical field builder and resource membership without double-counting', () => {
  assert.match(details, /export function xDriveMediaInspectorFields\(item: MediaItem\)/)
  assert.match(details, /\['大小', formatMediaBytes\(item\.node\.size\)\]/)
  assert.match(details, /item\.resources && item\.resources\.length > 1/)
  assert.match(details, /asset_kind === 'live_photo'/)
  assert.match(explorer, /mediaFileRows: Array<\[string, string\]>/)
  assert.match(explorer, /\['位置', propertiesDialogItem\.path/)
  assert.match(explorer, /\['Revision', String\(propertiesDialogItem\.revision/)
  assert.doesNotMatch(explorer.slice(explorer.indexOf('const mediaPropertiesEnabled'), explorer.indexOf('const mediaPropertiesKey')), /fetch\(|listItems\(/)
})

test('old Desktop Agents fall back to ordinary properties without requesting an unsupported route', () => {
  const desktopApp = read('desktop', 'src', 'renderer', 'App.tsx')
  assert.match(agentGo, /"media-item-properties"/)
  assert.match(desktopApp, /capabilities\.includes\('media-item-properties'\)/)
  assert.match(main, /requireAgentCapability\(hello, 'media-item-properties'\)/)
})
