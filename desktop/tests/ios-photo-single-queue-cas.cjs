'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const controller = read('ios/XDriveIOS/NativePhotoBackupController.swift')
const queue = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
const runner = read('ios/XDriveIOS/ForegroundPhotoBackupMVP.swift')
const begin = controller.indexOf('if kind == .single {')
const end = controller.indexOf('} else if kind == .focused {', begin)
assert.ok(begin > 0 && end > begin, 'single-run branch exists')
const single = controller.slice(begin, end)
const helperBegin = queue.indexOf('func pendingForSingle(')
const helperEnd = queue.indexOf('/// Settle one exact queued revision', helperBegin)
assert.ok(helperBegin > 0 && helperEnd > helperBegin)
const lookup = queue.slice(helperBegin, helperEnd)

test('selected item beyond first 64 uses indexed exact ID and a caught-up token', () => {
  assert.match(lookup, /try verifyOwner\(owner\)/)
  assert.match(lookup, /XDriveIOSPhotoKitLibraryEpoch\.matches\(/)
  assert.match(lookup, /baseline\.authorization == epoch\.authorization/)
  assert.match(lookup, /let status = try store\.status\(for: localIdentifier\)/)
  assert.match(lookup, /status\.state == \.pending/)
  assert.match(lookup, /PHAsset\.fetchAssets\(/)
  assert.match(lookup, /verifyAuthorization\(stillMatches: epoch\)/)
  assert.match(store, /func status\(for localIdentifier: String\)/)
  assert.doesNotMatch(lookup, /pending\(limit:|installNewOnlyBaseline|retryFailed/)
})

test('only live consented new-only scope captures the exact pending revision before upload', () => {
  assert.match(single, /plan\.enabled, plan\.backupStartRule == \.onlyNew/)
  assert.match(single, /!plan\.pausedForReview/)
  assert.match(single, /!plan\.requiresFullLibraryReconciliation/)
  assert.match(single, /queue\.pendingForSingle\(/)
  assert.ok(single.indexOf('pendingForSingle(') < single.indexOf(').runSingle('))
  assert.match(single, /onPotentialWrite: \{ beganOriginalWrite = true \}/)
  assert.match(runner, /func runSingle\(/)
  assert.doesNotMatch(single, /installNewOnlyBaseline|retryFailedCandidates/)
})

test('settle exact pre-write revision only after verified Server Node receipt', () => {
  assert.ok(single.indexOf(').runSingle(') < single.indexOf('selectedQueue.settle('))
  assert.match(single, /result\.uploaded == 1 \|\| result\.verifiedAlready == 1/)
  assert.match(single, /!result\.stoppedForReview, result\.needsReview == 0/)
  assert.match(single, /selectedRevision, result: \.confirmed, owner: selected/)
  assert.match(single, /queueNeedsRecheck = !queueRevisionSettled/)
  assert.match(single, /pauseForPendingReceipts\(owner: selected\)/)
  assert.match(single, /if queueNeedsRecheck \{/)
  assert.match(queue, /func settle\(_ candidate:[\s\S]*?expectedBaselineToken: baseline\.token/)
  assert.match(store, /WHERE asset_id=\? AND revision=\? AND state='pending'/)
  assert.doesNotMatch(single, /retryWaitingICloudCandidates|installNewOnlyBaseline/)
})

test('verified preexisting receipt updates display only at terminal Owner-fenced boundary', () => {
  const terminalStart = controller.indexOf('// A successful original may be followed')
  const terminal = controller.slice(terminalStart)
  assert.ok(terminalStart > 0)
  assert.match(single, /if queueRevisionSettled && result\.verifiedAlready > 0/)
  assert.match(single, /didSettleVerifiedExistingSingle = true/)
  assert.doesNotMatch(single, /self\.confirmedOriginalUpdate = ConfirmedOriginalUpdate\(/)
  assert.match(terminal, /didSettleVerifiedExistingSingle && current\.verifiedAlready > 0/)
  assert.match(terminal, /self\.displayEpoch == uiEpoch/)
  assert.match(terminal, /XDriveIOSNativePhotoOwnerScope\.matches\(self\.runningOwner, selected\)/)
  assert.match(terminal, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, selected\)/)
  assert.match(terminal, /self\.confirmedOriginalUpdate = ConfirmedOriginalUpdate\(/)
  assert.match(terminal, /owner: selected, id: UUID\(\)/)
})

test('single-item PhotoKit queue accesses correctly await the isolated actor', () => {
  assert.match(single, /selectedRevision = try await queue\.pendingForSingle\(/)
  assert.match(single, /queueRevisionSettled = try await selectedQueue\.settle\(/)
  assert.doesNotMatch(single, /selectedRevision = try queue\.pendingForSingle\(/)
  assert.doesNotMatch(single, /queueRevisionSettled = try selectedQueue\.settle\(/)
})
