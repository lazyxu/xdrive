'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const upload = read('ios/XDriveIOS/NativeFilesManualUpload.swift')
const transport = read('ios/XDriveIOS/NativeUploadSessionTransport.swift')
const stage = read('ios/XDriveIOS/NativeManualDocumentStage.swift')
const policy = read('ios/XDriveIOS/NativeFilesUploadBatchPolicy.swift')
const go = read('internal/api/router.go')

test('native Files picker uses the sole existing Go UploadSession writer and private one-shot staging', () => {
  assert.match(panel, /\.fileImporter\(/)
  assert.match(panel, /allowedContentTypes: \[\.item\]/)
  assert.match(panel, /uploader\.start\(/)
  assert.match(upload, /XDriveManualDocumentStager\.stage\(fileURL\)/)
  assert.match(upload, /defer \{ staged\.delete\(\) \}/)
  assert.match(stage, /static let maxFirstFileBytes: Int64 = XDriveIOSNativeFilesUploadBatchPolicy\.maximumStagedFileBytes/)
  assert.match(upload, /XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(upload, /XDriveIOSOriginalRunGate\.shared\.release\(gate\)/)
  assert.match(upload, /XDriveNativeUploadSessionTransport\(/)
  assert.match(upload, /\.uploadOnce\(\s*from: staged\.fileURL, name: staged\.originalName, parentID: parentID/)
  assert.match(transport, /path: "\/api\/v1\/uploads"/)
  assert.match(go, /authed\.POST\("\/uploads", s\.createUploadSession\)/)
})
test('native Files upload verifies exact Owner, folder and durable Node SHA before confirmed success', () => {
  assert.match(upload, /login\.verifiedAuthorization\(\)/)
  assert.match(upload, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.match(upload, /requireDestination\(parentID, expectedName: expectedFolderName\)/)
  assert.match(upload, /requireCommitted\(receipt, parentID: parentID,/)
  assert.match(upload, /XDriveIOSNativeFilesUploadConfirmationPolicy\.matches\(/)
  assert.match(upload, /请刷新目录核对，不要盲目重复提交/)
  assert.match(panel, /uploader\.invalidate\(\)/)
  assert.doesNotMatch(upload, /WKWebView\s*\(|document\.cookie|localStorage/)
})

test('1 GiB foreground staging uses bounded disk preflight before the original private copy', () => {
  assert.match(policy, /maximumStagedFileBytes: Int64 = 1_073_741_824/)
  assert.match(policy, /freeDiskReserveBytes: Int64 = 128 \* 1_048_576/)
  assert.match(policy, /bytes <= freeDiskBytes - freeDiskReserveBytes/)
  assert.match(stage, /attributesOfFileSystem\(/)
  assert.match(stage, /XDriveIOSNativeFilesUploadBatchPolicy\.mayStage\(/)
  assert.match(stage, /throw XDriveManualDocumentStageError\.insufficientDiskSpace/)
  assert.match(stage, /try fm\.copyItem\(at: pickedURL, to: target\)/)
  assert.match(stage, /copiedSize\.int64Value == originalSize\.int64Value/)
  assert.match(upload, /catch XDriveManualDocumentStageError\.insufficientDiskSpace/)
  assert.match(upload, /手机可用暂存空间不足/)
  assert.match(panel, /单文件最大 1 GiB/)
  assert.doesNotMatch(stage, /URLSession|WKWebView|\/api\/v1\/uploads/)
})


test('native Files folder picker scans the full subtree before any remote POST, then reuses verified writers', () => {
  assert.match(panel, /allowedContentTypes: \[\.folder\]/)
  assert.match(panel, /native-ios-files-folder-upload/)
  assert.match(panel, /uploader\.start\(\s*folderURL: pickedFolder/)
  assert.match(panel, /showingFolderImporter = false/)
  assert.match(upload, /private struct XDriveIOSNativeFilesFolderUploadPlan/)
  assert.match(upload, /FileManager\.default/)
  assert.match(upload, /fm\.enumerator\(/)
  assert.match(upload, /isSymbolicLink != true/)
  assert.match(upload, /isPackage != true/)
  assert.match(upload, /unreadable == nil/)
  assert.match(upload, /duplicateName/)
  assert.match(upload, /let steps = try await withTaskCancellationHandler/)
  assert.match(upload, /var directoryIDs: \[String: UInt64\] = \["": parentID\]/)
  assert.match(upload, /XDriveIOSNativeFilesDirectoryCreator\(/)
  assert.match(upload, /requireDestination\(targetParent, expectedName: parentName\)/)
  assert.match(upload, /try await uploadOne\(\s*fileURL: pickedFile/)
  assert.match(upload, /XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(upload, /XDriveIOSOriginalRunGate\.shared\.release\(gate\)/)
  assert.match(upload, /possiblySubmitted = true/)
  assert.match(upload, /不要自动重传/)
  assert.match(policy, /enum XDriveIOSNativeFilesFolderUploadPolicy/)
  assert.match(policy, /static let maximumFiles = 128/)
  assert.match(policy, /static let maximumDirectories = 64/)
  assert.match(policy, /maximumTotalBytes: Int64 = 512 \* 1_048_576/)
});
