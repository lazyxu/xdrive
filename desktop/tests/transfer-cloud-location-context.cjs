const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const repo = path.resolve(__dirname, '../..')
const read = (file) => fs.readFileSync(path.join(repo, file), 'utf8')

test('shared transfer context menu only navigates using stored cloud IDs, not local paths', () => {
  const pop = read('ui/shared/src/mui/TransferPopover.tsx')
  const model = read('ui/shared/src/transfers.ts')
  assert.match(model, /cloud_parent_id\?: number/)
  assert.match(model, /cloud_node_id\?: number/)
  assert.match(pop, /onContextMenu=\{\(event\) =>/)
  assert.match(pop, /event\.preventDefault\(\)/)
  assert.match(pop, /Number\.isSafeInteger\(task\.cloud_parent_id\)/)
  assert.match(pop, /Number\.isSafeInteger\(task\.cloud_node_id\)/)
  assert.match(pop, /在云端文件管理器中显示/)
  assert.doesNotMatch(pop, /onShowInCloud\?\.\(\s*contextMenu\.task\.path/)
})

test('Web upload and single downloads use authoritative Node identity and shared Files app navigation', () => {
  const api = read('web/src/api.ts')
  const store = read('web/src/transfers.ts')
  const web = read('web/src/App.tsx')
  assert.match(api, /cloudParentID: parentID/)
  assert.match(api, /cloudParentID,\s+cloudNodeID,\s+kind: 'download'/)
  assert.match(api, /node\.parent_id,\s+node\.id/)
  assert.match(store, /cloud_parent_id: input\.cloudParentID/)
  assert.match(store, /cloud_node_id: input\.cloudNodeID/)
  assert.match(web, /onShowInCloud=\{\(task\) =>/)
  assert.match(web, /launchWebApp\(\{ app: 'files', params: \{ dir: parentID \} \}\)/)
})

test('Desktop Agent records cloud location IDs and Desktop resolves via authenticated getNodeLocation', () => {
  const model = read('internal/transfer/model.go')
  const agent = read('cmd/xdrive-agent/cloud_files.go')
  const desktop = read('desktop/src/renderer/App.tsx')
  assert.match(model, /CloudParentID\s+uint64\s+`json:"cloud_parent_id,omitempty"`/)
  assert.match(model, /CloudNodeID\s+uint64\s+`json:"cloud_node_id,omitempty"`/)
  assert.match(agent, /agentCloudTransferLocation\{ParentID: parentID\}/)
  assert.match(agent, /agentCloudTransferLocation\{NodeID: id\}/)
  assert.match(desktop, /window\.xdriveDesktop\.agent\.getNodeLocation\(locatorID\)/)
  assert.match(desktop, /loadCloudDirectory\(dir, ancestry\)/)
})
