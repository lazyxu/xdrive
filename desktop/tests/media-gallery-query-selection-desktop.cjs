const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')

test('G07 Desktop Snapshot uses Agent Client, authenticated Go client, not direct Electron server fetch', () => {
  const go = read('internal/client/media.go')
  const controller = read('cmd/xdrive-agent/cloud_files.go')
  const agent = read('cmd/xdrive-agent/desktop_ipc.go')
  const main = read('desktop/src/main/index.cts')
  const client = read('desktop/src/main/agent_client.cts')
  const preload = read('desktop/src/preload/index.cts')
  const renderer = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  for (const op of ['Create', 'Get', 'SetSelectionExcluded', 'Delete']) {
    assert.match(go, new RegExp('Media' + op + 'SelectionSnapshot|MediaSetSelectionExcluded'))
  }
  assert.match(controller, /CloudMediaCreateSelectionSnapshot/)
  assert.match(controller, /CloudMediaSetSelectionExcluded/)
  assert.match(agent, /"media-selection-snapshot"/)
  assert.match(agent, /POST \/v1\/media\/selection-snapshot/)
  assert.match(agent, /PATCH \/v1\/media\/selection-snapshot\/exclusion/)
  assert.match(main, /requireAgentCapability\(hello, 'media-selection-snapshot'\)/)
  assert.match(client, /appendAgentMediaQuery\(query, filters\)/)
  assert.match(preload, /agent:create-media-selection-snapshot/)
  assert.match(renderer, /createSelectionSnapshot: \(query, albumID, day\)/)
  assert.doesNotMatch(renderer, /fetch\(|new WebSocket|serverURL/)
})

test('G07 Desktop Snapshot rejects invalid tokens, days, limits and unsafe mutations', () => {
  const agent = read('cmd/xdrive-agent/desktop_ipc.go')
  const main = read('desktop/src/main/index.cts')
  const renderer = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  assert.match(agent, /uuid\.Parse\(token\)/)
  assert.match(agent, /day must be YYYY-MM-DD/)
  assert.match(agent, /limit must be 1\.\.200/)
  assert.match(agent, /input\.Version == 0/)
  assert.match(main, /normalized\.fold_duplicates/)
  assert.match(main, /normalized\.fold_member_ids/)
  assert.match(main, /Number\.isSafeInteger\(nodeID\)/)
  assert.match(main, /Number\.isSafeInteger\(version\)/)
  assert.match(renderer, /deleteSelectionSnapshot: \(token\)/)
  assert.doesNotMatch(renderer, /onDeleteItems.*snapshot|onDownloadItems.*snapshot/)
})
