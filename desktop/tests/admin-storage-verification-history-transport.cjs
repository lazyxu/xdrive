const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

test('read-only history is a fixed admin API, never an arbitrary filesystem/Host path', () => {
  const router = read('internal/api/router.go')
  const handler = read('internal/api/storage_verification_runs.go')
  assert.match(router, /admin\.Use\(s\.requireAdmin\(\)\)/)
  assert.match(router, /admin\.GET\("\/storage\/verification-runs", s\.adminStorageVerificationRuns\)/)
  assert.match(handler, /Select\("id", "kind", "status", "started_at", "finished_at"\)/)
  assert.match(handler, /Where\("id < \?", beforeID\)/)
  assert.match(handler, /Limit\(limit \+ 1\)/)
  assert.match(handler, /strconv\.FormatUint\(item\.ID, 10\)/)
  assert.doesNotMatch(handler, /item\.(Summary|Error|ReportJSON)/)
  assert.match(read('internal/api/router_contract_test.go'), /storage\/verification-runs/)
})

test('Web and Desktop Agent have independent bounded read-only allowlists', () => {
  const go = read('cmd/xdrive-agent/desktop_ipc_admin_storage.go')
  const client = read('internal/client/admin_storage.go')
  const main = read('desktop/src/main/index.cts')
  const shared = read('ui/shared/src/admin-management.ts')
  const web = read('web/src/api.ts')
  const desktop = read('desktop/src/renderer/App.tsx')
  assert.match(go, /case "verification-runs":/)
  assert.match(go, /validVerificationHistoryCursor\(input\.Cursor\)/)
  assert.match(client, /case "verification-runs":/)
  assert.match(client, /invalid bounded storage verification history request/)
  assert.match(main, /p\.operation === 'verification-runs'/)
  assert.match(shared, /export type XDriveStorageVerificationRunPage/)
  assert.match(shared, /adminStorageVerificationRuns/)
  assert.match(web, /adminStorageVerificationRuns\(/)
  assert.match(desktop, /adminStorageVerificationRuns:/)
})
