'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('dynamic Baidu map is the sole renderer; legacy static WGS84 viewport is retired', () => {
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  assert.match(map, /XDriveMediaGalleryBaiduIsolatedPhotoSurface/)
  assert.match(map, /xDriveValidBaiduNativeCameraSnapshot/)
  assert.match(map, /onNativeCameraChange/)
  assert.match(gallery, /initialNativeCamera=\{baiduNativeCameraSnapshot\}/)
  assert.doesNotMatch(map, /onCameraViewport|onStaticCameraChange|listPlacesViewport\(/)
  assert.doesNotMatch(map, /StaticMap|onViewportChange|static fallback/i)
  assert.equal(fs.existsSync(path.join(root, 'ui/shared/src/media-gallery-baidu-camera.ts')), false)
})

test('removed static image route cannot be reached through Server, Agent or Electron', () => {
  const router = read('internal/api/router.go')
  const agent = read('cmd/xdrive-agent/desktop_ipc.go')
  const preload = read('desktop/src/preload/index.cts')
  const desktop = read('desktop/src/main/index.cts')
  const client = read('internal/client/media.go')
  assert.doesNotMatch(router, /media\/places\/baidu-static|media\/places\/map-provider/)
  assert.doesNotMatch(agent, /v1\/media\/baidu-static|v1\/media\/map-provider|baidu-static-map/)
  assert.doesNotMatch(preload, /get-baidu-static-map|getBaiduStaticMap/)
  assert.doesNotMatch(desktop, /get-baidu-static-map|getBaiduStaticMap/)
  assert.doesNotMatch(client, /MediaBaiduStaticMap|MediaBaiduMapProvider/)
  assert.match(router, /media\/places\/baidu-jsapi\/status/)
  assert.match(router, /media\/places\/baidu-jsapi\/cells/)
})
