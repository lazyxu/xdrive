  assert.match(source, /Button\("收藏选中"\) \{ updateFavorites\(true\) \}/)
  assert.match(source, /Button\("取消收藏"\) \{ updateFavorites\(false\) \}/)
  assert.match(source, /Button\("删除选中", role: \.destructive\)/)
