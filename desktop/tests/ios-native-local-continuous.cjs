'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const source = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
const shell = read('ios/XDriveIOS/NativePhotoTimelineBrowser.swift')
const policy = read('ios/XDriveIOS/NativePhotoTimelinePolicy.swift')

test('local PhotoKit Gallery defaults to continuous lazy virtual pages with legacy pagination fallback', () => {
  assert.match(shell, /@State private var useContinuousWall = true/)
  assert.match(shell, /XDriveIOSNativeLocalContinuousGalleryScreen\(savedOffset: \$savedOffset\)/)
  assert.match(shell, /content\.id\(wallRevision\)/)
  assert.match(shell, /Button\("连续滚动"\) \{ useContinuousWall = true \}/)
  assert.match(source, /LazyVStack\(alignment: \.leading/)
  assert.match(source, /ForEach\(0\.\.<XDriveIOSNativePhotoVirtualPagePolicy\.pageCount\(total: total\)/)
  assert.match(source, /ForEach\(page\.items\.filter \{ \$0\.kind != "unsupported" \}\)/)
  assert.match(source, /XDrivePhotoKitBoundedSnapshotScanner\(\)/)
  assert.match(source, /let count = try await reader\.start\(atOffset: offset\)/)
  assert.match(source, /loaded\.startOffset == offset/)
  assert.match(source, /count == expectedTotal/)
  assert.match(source, /\.onDisappear \{\s*page = nil/)
  assert.doesNotMatch(source, /\[PHAsset\]|\[String: PHAsset\]|fetchAssets\(withLocalIdentifiers: \w+\.map/)
  assert.match(policy, /static let pageSize = 64/)
})

test('continuous Gallery verifies Viewer identity and restores authorized tile', () => {
  assert.match(source, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(source, /private final class XDriveIOSNativeVirtualWallChangeMonitor/)
  assert.match(source, /photoLibraryDidChange\(_ change: PHChange\)/)
  assert.match(source, /asset\.creationDate == candidate\.capturedAt/)
  assert.match(source, /asset\.modificationDate == candidate\.modifiedAt/)
  assert.match(source, /candidate\.isLive == asset\.mediaSubtypes\.contains\(\.photoLive\)/)
  assert.match(source, /XDriveIOSNativeLocalPhotoDetail\(\s*candidate: current\.candidate,\s*loadedItems: current\.page\.items\.filter/)
  assert.match(source, /\$0\.id == expected && \$0\.capturedAt == returnDate/)
  assert.match(source, /\$0\.modifiedAt == returnModified/)
  assert.match(source, /scroll\.scrollTo\("photo:/)
  assert.match(source, /\.onChange\(of: phase\)/)
  assert.match(source, /\.fullScreenCover\(item: \$selected, onDismiss: restoreAfterViewer\)/)
  const route = read('ios/XDriveIOS/NativeNavigationRouteStore.swift')
  assert.doesNotMatch(route, /returnID|returnDate|returnModified|PHAsset/)
})
