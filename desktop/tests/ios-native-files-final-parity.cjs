const section = (start, end) => {
  const from = browser.indexOf(start)
  const to = browser.indexOf(end, from + start.length)
  assert.ok(from >= 0 && to > from, 'source section: ' + start)
  return browser.slice(from, to)
}

test('same verified Owner, folder and search preserve committed list during resort/regroup', () => {
  const model = section('@MainActor\nprivate final class XDriveIOSNativeFilesPageModel',
    '@MainActor\nprivate final class XDriveIOSNativeFilesSearchOptionsModel')
  const load = model.slice(model.indexOf('    func load(login:'), model.indexOf('    func loadAdjacent('))
  assert.match(load, /sameBrowseScope = expectedOwner\.map/)
  assert.match(load, /verifiedPage &&[\s\S]*?verifiedOwner\.map/)
  assert.match(load, /XDriveIOSNativePhotoOwnerScope\.matches\(\$0, current\)/)
  assert.match(load, /verifiedFolderID == folderID && verifiedQuery == query &&\s*verifiedFilters == filters/)
  assert.match(load, /if sameBrowseScope \{[\s\S]*?job\?\.cancel\(\)[\s\S]*?cancelAdjacent\(\)[\s\S]*?\} else \{\s*invalidate\(\)/)
  assert.match(load, /self\?\.entries = found/)
  assert.match(load, /self\?\.verifiedPage = true/)
  assert.match(load, /self\?\.epoch == ticket/)
  assert.match(load, /case \.server\(401\), \.server\(403\), \.server\(404\), \.invalidScope:/)
  assert.doesNotMatch(load, /if sameBrowseScope \{\s*invalidate\(\)/)
})

test('retained-range loading feedback is delayed, cancellable, and never hides real errors', () => {
  const model = section('@MainActor\nprivate final class XDriveIOSNativeFilesPageModel',
    '@MainActor\nprivate final class XDriveIOSNativeFilesSearchOptionsModel')
  assert.match(model, /@Published private\(set\) var slowLoading = false/)
  assert.match(model, /private var feedbackJob: Task<Void, Never>\?/)
  assert.match(model, /Task\.sleep\(nanoseconds: 300_000_000\)/)
  assert.match(model, /guard !Task\.isCancelled, let self,[\s\S]*?self\.epoch == ticket && self\.loading/)
  assert.match(model, /func suspendForNavigation\(\)[\s\S]*?feedbackJob\?\.cancel\(\)/)
  assert.match(model, /func invalidate\(\)[\s\S]*?feedbackJob\?\.cancel\(\)/)
  assert.match(browser, /if model\.loading && model\.entries\.isEmpty/)
  assert.match(browser, /else if model\.slowLoading && !model\.entries\.isEmpty/)
  assert.match(browser, /native-ios-files-retained-range-loading/)
  assert.match(browser, /else if let error = model\.errorMessage/)
})

test('Viewer and read-only sheets return to verified list without forced first-range refetch', () => {
  const modals = section('    private var filesModals: some View', '    private func rememberedPosition()')
  assert.match(modals, /\.sheet\(item: \$locateIntent\) \{ intent in/)
  assert.match(modals, /\.sheet\(item: \$managementIntent, onDismiss: \{\s*if managementWriteConfirmed \{[\s\S]*?reload\(\)/)
  assert.match(modals, /managementWriteConfirmed = true\s*managementIntent = nil/)
  assert.match(modals, /\.sheet\(item: \$versionHistoryIntent, onDismiss: \{\s*if versionRestoreConfirmed \{[\s\S]*?reload\(\)/)
  assert.match(modals, /versionRestoreConfirmed = true\s*versionHistoryIntent = nil/)
  assert.match(modals, /\.fullScreenCover\(item: \$selectedFile, onDismiss: \{[\s\S]*?model\.canResume\(/)
  assert.match(modals, /lastViewedFile = nil\s*returnOwner = nil/)
  const manager = modals.slice(modals.indexOf('.sheet(item: $managementIntent'), modals.indexOf('.sheet(item: $versionHistoryIntent'))
  assert.doesNotMatch(manager, /onDismiss: \{\s*reload\(\)/)
})

