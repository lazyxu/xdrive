  assert.match(browser, /func beginInternalDrag\(/)
  assert.match(browser, /visibility: \.ownProcess/)
  assert.match(browser, /completion\(Data\(nonce\.uuidString\.utf8\), nil\)/)
  assert.match(browser, /loadDataRepresentation\(forTypeIdentifier: Self\.internalDragType\)/)
  assert.match(browser, /received == nonce\.uuidString, dragNonce == nonce/)
  assert.match(browser, /draggedNode == original/)
  assert.match(browser, /XDriveIOSNativePhotoOwnerScope\.matches\(current, startedOwner\)/)
  assert.match(browser, /containsVerifiedNode\(original\), containsVerifiedNode\(destination\)/)
  assert.match(browser, /pendingDrop = \.init\(owner: startedOwner, original: original,/)
  assert.match(browser, /private func confirmInternalDrop\(\)/)
