  assert.match(serverRouter, /POST\("\/media\/duplicate-organize\/apply"/)
  assert.match(backend, /sql\.LevelSerializable/)
  assert.match(backend, /ExpectedPlanRevision/)
  assert.match(backend, /mediaDuplicateOrganizeResourcesCurrent/)
  assert.match(backend, /mediaDuplicateOrganizeMaxManualAlbums/)
  assert.match(backend, /mediaDuplicateOrganizeMaxDurablePeople/)
  assert.match(backend, /OriginalFilesRetained = true/)
  assert.match(backend, /PhysicalBytesReclaimed = 0/)
  assert.match(models, /export interface MediaDuplicateOrganizeApplyInput/)
  assert.match(models, /confirm: true/)
  assert.match(models, /export interface MediaDuplicateOrganizeApplyResult/)
  assert.match(gallery, /applyPlan=\{source\.applyDuplicateOrganize\}/)
  assert.match(gallery, /onRefresh=\{onRefresh\}/)
  assert.match(preview, /const requestConfirmedApply = \(\) => \{/)
  assert.match(preview, /data-xdrive-gallery-organize-confirm/)
  assert.match(preview, /data-xdrive-gallery-organize-apply/)
  assert.match(preview, /data-xdrive-gallery-organize-applied/)
  assert.match(preview, /plan\.ready_for_manual_review/)
  assert.match(preview, /plan\.asset_comparison !== 'identical'/)
  assert.match(preview, /plan\.distinct_descriptions\.length > 1/)
  assert.match(preview, /expected_plan_revision: plan\.plan_revision/)
