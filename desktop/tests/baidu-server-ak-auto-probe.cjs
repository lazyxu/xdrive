'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

test('Server AK automatic live check is fixed-public-coordinate, cross-replica quota-admitted and secret-free', () => {
  const probe = read('internal/api/baidu_server_ak_auto_probe.go')
  const model = read('internal/meta/baidu_server_ak_probe.go')
  const migrations = read('cmd/server/main.go')
  const provider = read('internal/baidumapjsapi/geoconv_forward.go')
  const router = read('internal/api/router.go')
  assert.match(probe, /baiduServerAKProbeInterval[ \t]+=[ \t]*time\.Hour\b/)
  assert.match(probe, /baiduServerAKProbeLongitude = 116\.404/)
  assert.match(probe, /baiduServerAKProbeLatitude\s+= 39\.915/)
  assert.match(probe, /NewBaiduGeoconvForwardRequest\(ctx, ak/)
  assert.match(probe, /baidumapjsapi\.SafeHTTPClient\(\)/)
  assert.match(probe, /reserveBaiduServerProbeFleetQuota\(ctx, tx, now\)/)
  assert.match(probe, /ON CONFLICT \(scope_id\) DO UPDATE SET/)
  assert.match(probe, /window_second|day_requests|window_minute/)
  assert.match(probe, /clause\.Locking\{Strength: "UPDATE"\}/)
  assert.match(probe, /s\.DB\.WithContext\(ctx\)\.Transaction/)
  assert.match(probe, /StartBaiduServerAKAutoProbe\(ctx context\.Context\)/)
  assert.match(probe, /baiduServerAKProbeTag\(salt, latest\.AK\) != tag/)
  assert.match(model, /TableName\(\) string \{ return "xd_baidu_server_ak_probes" \}/)
  assert.match(migrations, /&meta\.BaiduServerAKProbe\{\}/)
  assert.match(migrations, /srv\.StartBaiduServerAKAutoProbe\(serverCtx\)/)
  assert.match(provider, /https:\/\/api\.map\.baidu\.com\/geoconv\/v2\//)
  assert.match(router, /admin\.GET\("\/services", s\.adminServiceDependencies\)/)
  assert.doesNotMatch(router, /admin\.(?:GET|POST)\("\/services\/baidu-map\/(?:auto-verify|probe)/)
  assert.doesNotMatch(probe, /gps_.*user|PhotoAsset|SourceItem|http\.ListenAndServe|gin\.Context|c\.Query\(/)
})

test('Admin status and Web Desktop only expose bounded current-AK provider evidence, never an AK', () => {
  const backend = read('internal/api/admin_service_dependencies.go')
  const ui = read('ui/shared/src/mui/BaiduServerAPIDetail.tsx')
  const parent = read('ui/shared/src/mui/ServiceDependenciesPage.tsx')
  const dto = read('ui/shared/src/service-dependencies.ts')
  const tests = read('internal/api/baidu_server_ak_auto_probe_test.go')
  assert.match(backend, /BaiduServerProbeState\s+string/)
  assert.match(backend, /BaiduServerProbeCheckedAt\s+string/)
  assert.match(backend, /applyBaiduServerProbeEvidence\(&services\[7\], s\.observeBaiduServerAKProbe\(ctx, cfg\)\)/)
  assert.match(ui, /probe === 'checking' \? '自动在线检测中'/)
  assert.match(ui, /data-xdrive-baidu-server-upstream-check-time/)
  assert.match(ui, /固定公开坐标检测百度 Geoconv v2/)
  assert.match(ui, /不代表实际照片索引或动态地图 JSAPI4 成功/)
  assert.match(parent, /baiduProbePolls\.current >= 3/)
  assert.match(parent, /document\.visibilityState !== 'visible'/)
  assert.match(dto, /baidu_server_probe_state\?/)
  assert.match(tests, /TestBaiduServerAKProbePinnedPublicCoordinateAndResponse/)
  assert.doesNotMatch(ui, /\{(?:config|service)\.ak\}|HTTP.*api\.map\.baidu\.com/)
})
