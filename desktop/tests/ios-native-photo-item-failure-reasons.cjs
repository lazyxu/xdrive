'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const queue = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')
const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
const policy = read('ios/XDriveIOS/NativeVisiblePhotoQueueBadgePolicy.swift')
const issues = read('ios/XDriveIOS/PhotoBackupIssueSummary.swift')
const from = queue.indexOf('func visibleStatusDetails(')
const to = queue.indexOf('/// Whether every persisted PhotoKit change event', from)
assert.ok(from > 0 && to > from)
const lookup = queue.slice(from, to)

test('each failure reason comes from one indexed exact-version Owner-local row', () => {
  assert.match(lookup, /guard localIdentifiers\.count <= 64/)
  assert.match(lookup, /try verifyOwner\(owner\)/)
  assert.match(lookup, /baseline\.authorization == epoch\.authorization/)
  assert.match(lookup, /XDriveIOSPhotoKitLibraryEpoch\.matches\(baseline\.token, as: epoch\.token\)/)
  assert.match(lookup, /let row = try store\.status\(for: id\)/)
  assert.match(store, /LEFT JOIN failure_reasons r ON r\.asset_id=e\.asset_id AND r\.revision=e\.revision/)
  assert.match(lookup, /row\.state == \.failed/)
  assert.match(lookup, /XDriveIOSPhotoBackupIssueReason\(rawValue: code\) != nil/)
  assert.match(lookup, /let after = try XDriveIOSPhotoKitLibraryEpoch\.capture\(\)/)
  assert.match(lookup, /epoch\.serialized, as: after\.token/)
  assert.match(lookup, /try verifyAuthorization\(stillMatches: epoch\)/)
  assert.doesNotMatch(lookup, /uploadPrepared|confirmReceipt|finalize\(|URLSession\(/)
})

test('visible failure reasons never display a raw Server response or a current cloud success claim', () => {
  assert.match(policy, /case "failed":/)
  assert.match(policy, /XDriveIOSPhotoBackupIssueReason\(rawValue: \$0\)/)
  assert.match(policy, /let explanation = known\.map/)
  assert.match(policy, /当前版本尚未备份，核验后重试/)
  assert.match(policy, /case "confirmed":/)
  assert.match(policy, /当前云端原件仍需重新核验/)
  assert.match(issues, /enum XDriveIOSPhotoBackupIssueReason: String/)
  assert.doesNotMatch(policy, /title: "已备份"|HTTPError|ServerResponse|URLSession/)
})

test('only visible mounted 64 ID page receives reason detail and invalidates on Owner/scene/page change', () => {
  assert.match(wall, /visibleBackupQueueStates: \[String: XDriveIOSPhotoKitPersistentBackupQueue\.VisibleItemStatus\]/)
  assert.match(wall, /queue\.visibleStatusDetails\(/)
  assert.match(wall, /page\?\.startOffset == current\.startOffset/)
  assert.match(wall, /page\?\.items\.map\(\\\.id\) == identifiers/)
  assert.match(wall, /XDriveIOSNativePhotoOwnerScope\.matches\(backupBadgeOwner, owner\)/)
  assert.match(wall, /photoQueueScenePhase == \.active/)
  assert.match(wall, /visibleBackupQueueStates = \[:\]/)
  assert.match(wall, /failureReasonCode: visibleBackupQueueStates\[candidate\.id\]\?\.failureReasonCode/)
  // Both a refresh and the initial page-load await must fence results to
  // the same mounted IDs; a reused page offset cannot show old item reasons.
  const initial = wall.slice(wall.indexOf('let initialBadgeEpoch = UUID()'))
  assert.match(initial, /page\?\.startOffset == loaded\.startOffset/)
  assert.match(initial, /page\?\.items\.map\(\\\.id\) == loaded\.items\.map\(\\\.id\)/)
  assert.doesNotMatch(wall, /uploadPreparedOriginal|createUploadSession|stageOriginal\(/)
})
