'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const screen = read('ios/XDriveIOS/NativeFilesCollections.swift')
const policy = read('ios/XDriveIOS/NativeFilesCollectionsPolicy.swift')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const viewer = read('ios/XDriveIOS/NativeFilesViewer.swift')
const serverRecent = read('internal/api/file_recent.go')
const serverFavorites = read('internal/api/file_favorites.go')
const router = read('internal/api/router.go')

test('native Files owns recent and favorites subroutes, including Server directory navigation', () => {
  assert.match(browser, /XDriveIOSNativeFilesCollectionScreen\(login: login, kind: \.recent\)/)
  assert.match(browser, /XDriveIOSNativeFilesCollectionScreen\(login: login, kind: \.favorites\)/)
  assert.match(browser, /native-ios-files-open-recent/)
  assert.match(browser, /native-ios-files-open-favorites/)
  assert.match(browser, /init\(login: XDriveIOSNativeOwnerLoginModel, folderID: UInt64,/)
  assert.match(screen, /XDriveIOSNativeFilesBrowser\([\s\S]*?folderID: item\.node\.id, folderName: item\.node\.name/)
  assert.doesNotMatch(screen, /import WebKit|WKWebView|URLSession\.shared|document\.cookie/)
})

test('real Owner projections respect both server caps and do not use local guessed search', () => {
  assert.match(serverRecent, /const \([\s\S]*?fileRecentMaxLimit\s*=\s*50/)
  assert.match(serverFavorites, /const fileFavoriteLimit = 256/)
  assert.match(router, /authed\.GET\("\/file-recent", s\.listFileRecent\)/)
  assert.match(router, /authed\.GET\("\/file-favorites", s\.listFileFavorites\)/)
  assert.match(policy, /self == \.recent \? 50 : 256/)
  assert.match(policy, /Set\(items\.map\(\\\.id\)\)\.count == items\.count/)
  assert.match(screen, /URLSessionConfiguration\.ephemeral/)
  assert.match(screen, /completionHandler\(nil\)/)
  assert.match(screen, /URLQueryItem\(name: "limit", value: String\(kind\.maximumItems\)\)/)
  assert.match(screen, /XDriveIOSNativeFilesCollectionsPolicy\.validItems/)
  assert.match(screen, /login\.verifiedAuthorization\(\)/)
  assert.match(screen, /XDriveIOSNativePhotoOwnerScope\.matches/)
})

test('favorite create/remove endpoints verify real Server response and no blind replay', () => {
  assert.match(router, /authed\.PUT\("\/file-favorites\/:id", s\.favoriteFile\)/)
  assert.match(router, /authed\.DELETE\("\/file-favorites\/:id", s\.unfavoriteFile\)/)
  assert.match(screen, /func addFavorite\(_ node:/)
  assert.match(screen, /try await requireCurrent\(node, client: client\)/)
  assert.match(screen, /method: "PUT"/)
  assert.match(screen, /accepted: \[200, 201\]/)
  assert.match(screen, /favorite\.node == node/)
  assert.match(screen, /func removeFavorite\(_ selected:/)
  assert.match(screen, /before\.contains\(selected\)/)
  assert.match(screen, /method: "DELETE"/)
  assert.match(screen, /accepted: \[204\], maximumBytes: 0/)
  assert.match(screen, /!after\.contains\(where: \{ \$0\.id == selected\.id \}\)/)
  assert.match(panel, /favoriteMutation\.add\(file, login: login\)/)
  assert.match(panel, /favoriteMutation\.invalidate\(\)/)
  assert.match(screen, /favoriteMutation|favorites\.remove\(item, login: login\)/)
})

test('Viewer triggers recent only after successful real preview and reuses same full-screen native Viewer', () => {
  assert.match(viewer, /display = result[\s\S]*?XDriveIOSNativeFilesRecentRecorder\.recordLoadedPreview\(/)
  assert.match(screen, /func touchViewed\(_ node:/)
  assert.match(screen, /method: "POST"/)
  assert.match(router, /authed\.POST\("\/file-recent\/:id", s\.touchFileRecent\)/)
  assert.match(screen, /\.fullScreenCover\(item: \$selectedFile/)
  assert.match(screen, /XDriveIOSNativeFilesViewer\(/)
  assert.match(screen, /XDriveIOSNativeFilesViewerPolicy\.maximumLoadedRows/)
  assert.match(screen, /\$0\.node\.parent_id == selected\.node\.parent_id/)
  assert.match(screen, /returnScroll\.scrollTo\(target\.id, anchor: \.center\)/)
  assert.match(screen, /\.onChange\(of: login\.owner\)/)
  assert.match(screen, /busy = false\s*running = nil\s*onConfirmed\(\)/)
  assert.doesNotMatch(screen, /POST.*\/api\/v1\/uploads|OriginalRunGate|downloadFileVersion/)
})
