test('native Recent clear is Owner scoped, confirmed and checks empty server readback', () => {
  assert.match(router, /authed\.DELETE\("\/file-recent", s\.clearFileRecent\)/)
  assert.match(serverRecent, /func \(s \*Server\) clearFileRecent[\s\S]*?Where\("owner_id = \?", userID\(c\)\)[\s\S]*?Status\(http\.StatusNoContent\)/)
  const transport = screen.slice(screen.indexOf('func clearRecent() async throws'), screen.indexOf('private func requireCurrent('))
  assert.match(transport, /request\("\/api\/v1\/file-recent", method: "DELETE"\)/)
  assert.match(transport, /accepted: \[204\], maximumBytes: 0/)
  assert.match(transport, /let remaining = try await list\(\.recent, in: client\)/)
  assert.match(transport, /guard remaining\.isEmpty/)
  assert.doesNotMatch(transport, /file-favorites/)
  const mutation = screen.slice(screen.indexOf('final class XDriveIOSNativeFilesRecentClearModel'), screen.indexOf('private struct XDriveIOSNativeFilesCollectionManageIntent'))
  assert.match(mutation, /login\.verifiedAuthorization\(\)/)
  assert.match(mutation, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(mutation, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expected\)/)
  assert.match(mutation, /try await XDriveIOSNativeFilesCollectionsTransport\([\s\S]*?\)\.clearRecent\(\)/)
  assert.match(mutation, /status = "清空结果未确认，请刷新最近使用；不要自动重试。"/)
  assert.match(screen, /if kind == \.recent \{[\s\S]*?Label\("清空最近使用记录", systemImage: "trash"\)/)
  assert.match(screen, /showingClearRecentConfirmation = true/)
  assert.match(screen, /isPresented: \$showingClearRecentConfirmation/)
  assert.match(screen, /Button\("清空最近使用记录", role: \.destructive\)/)
  assert.match(screen, /recentClear\.clear\(login: login\) \{ reload\(\) \}/)
  assert.match(screen, /只清除当前账号的最近访问记录，不会删除文件、文件夹或收藏。/)
  assert.match(screen, /recentClear\.invalidate\(\)/)
  assert.match(screen, /guard !favorites\.busy, !recentClear\.busy else \{ return \}/)
});
