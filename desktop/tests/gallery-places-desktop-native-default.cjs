'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=file=>fs.readFileSync(path.join(root,file),'utf8')

test('Desktop defaults to the shared non-isolated Baidu map, not GPS overview',()=>{
  const renderer=read('desktop/src/renderer/App.tsx')
  const map=read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  const mode=read('ui/shared/src/media-gallery-places-map-mode.ts')
  assert.match(renderer,/desktopEmbeddedPlacesURL:\s*xDriveDesktopEmbeddedPlacesURL\(status\?\.server\)/)
  assert.match(renderer,/onPrepareDesktopPlaces:\s*async scope =>/)
  assert.match(renderer,/desktop_places_embed=1#\/app\/gallery\?section=places/)
  assert.match(map,/desktopOnly && desktopEmbeddedPlacesURL && onPrepareDesktopPlaces/)
  assert.match(map,/component=\{'webview' as 'div'\}/)
  assert.doesNotMatch(map,/GPS 备用地图|OwnerGPSOverview|setDesktopFallback/)
  assert.match(mode,/if \(selections\.length === 0\) return 'prototype'/)
  assert.match(map,/mapMode = desktopOnly \? 'isolated' : xDrivePlacesMapModeFromHref/)
  // The HTTPS guest is a Web host, so its default is determined from href
  // and remains prototype (non-isolated), not Desktop file:// mapMode.
  assert.match(renderer,/return url\.origin\+'\/\?desktop_places_embed=1#\/app\/gallery\?section=places'/)
})

test('Main establishes an ephemeral HTTPS Cookie session before attaching map guest',()=>{
  const main=read('desktop/src/main/index.cts')
  const web=read('web/src/App.tsx')
  const preload=read('desktop/src/preload/places_embed.cts')
  assert.match(main,/const desktopPlacesWebPartition = 'xdrive-places-web'/)
  assert.match(main,/session\.fromPartition\(desktopPlacesWebPartition,\s*\{cache:false\}\)/)
  assert.match(main,/places\.fetch\(identity\.origin \+ '\/api\/v1\/auth\/browser\/login'/)
  assert.match(main,/credentials: 'include'/)
  assert.match(main,/name: '__Host-xdrive_refresh'/)
  assert.match(main,/const ready=await ensureDesktopPlacesWebAuth/)
  assert.match(main,/if \(!ready[\s\S]*?map_browser_session_unavailable/)
  assert.match(web,/function xDriveTrustedDesktopPlacesBridge/)
  assert.match(web,/desktopBridge\.expectedOwner\(\)/)
  assert.match(web,/new XDriveApi\(\{browserSession:true,username:owner\}\)/)
  assert.match(web,/\.restoreBrowserSession\(\)/)
  assert.match(web,/persistSession\(sessionFromAuth\(result\), false\)/)
  assert.match(web,/if \(!session\.accessToken && xDriveTrustedDesktopPlacesBridge\(\)\)/)
  assert.match(preload,/expectedOwner:/)
  assert.match(preload,/consume:/)
  assert.doesNotMatch(preload,/ipcRenderer\.invoke\('agent:|window\.xdriveDesktop|\.password\b|refreshToken|accessToken|cookies\.get/)
})

test('Guest sessions are revoked on Desktop Owner/server change and never persisted',()=>{
  const main=read('desktop/src/main/index.cts')
  assert.match(main,/function closeDesktopPlacesGuests\(\) \{\s*resetDesktopPlacesWebAuth\(\)/)
  assert.match(main,/desktopPlacesWebGeneration/)
  assert.match(main,/desktopPlacesWebQueue/)
  assert.match(main,/clearStorageData\(\{\s*storages: \['cookies', 'localstorage'\]/)
  assert.match(main,/if \(\(desktopPlacesGuests\.size \|\| desktopPlacesPending \|\|[\s\S]*?desktopPlacesWebReady/)
  assert.match(main,/closeDesktopPlacesGuests\(\)/)
  assert.match(main,/ipcMain\.handle\('agent:logout',[\s\S]*?closeDesktopPlacesGuests\(\)/)
  assert.match(main,/params\.partition!==desktopPlacesWebPartition/)
  assert.match(main,/preferences\.contextIsolation=true/)
  assert.match(main,/preferences\.nodeIntegration=false/)
  assert.match(main,/preferences\.sandbox=true/)
})
