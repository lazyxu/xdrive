const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning-Agent CAS metadata check is private, read-only and never a commit token', () => {
  const router = read('internal', 'api', 'router.go')
  const coverage = read('internal', 'api', 'router_contract_test.go')
  const server = read('internal', 'api', 'local_source_item_evidence_cloud_metadata.go')
  const apiTest = read('internal', 'api', 'local_source_item_evidence_cloud_metadata_integration_test.go')
  const client = read('internal', 'client', 'local_source_item_evidence_cloud_metadata.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_preflight.go')
  const agentIPC = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const web = read('web', 'src', 'App.tsx')
  const sourceRun = read('internal', 'api', 'source_runs.go')

  assert.match(router, /evidence-cloud-metadata", s\.requireLocalSourceExecutor\(\), s\.readLocalSourceEvidenceCloudMetadata/)
  assert.match(coverage, /POST", path: "\/api\/v1\/sources\/:id\/local-identity\/evidence-cloud-metadata"/)
  assert.match(server, /s\.requireLocalSourceProofTx\(tx, c, sourceID, "", false\)/)
  assert.match(server, /input\.PreviousSnapshotSHA256, input\.CurrentSnapshotSHA256/)
  assert.match(server, /loadSourceIdentityIndex\(tx, sourceID, keys\)/)
  assert.match(server, /JOIN xd_files AS f/)
  assert.match(server, /JOIN xd_file_versions AS v/)
  assert.match(server, /JOIN xd_content_blobs AS b/)
  assert.match(server, /meta\.ContentBlobStateReady/)
  assert.match(server, /storage\.ContentAddressedKey\(claim\.SHA256\)/)
  assert.match(server, /CloudMetadataMatched: true, CloudBytesVerified: false/)
  assert.match(server, /ContentVerified: false, CommitSupported: false/)
  assert.match(server, /Authoritative: false, MissingInferenceSafe: false/)
  assert.doesNotMatch(server, /tx\.(Create|Delete|Updates|Update)\(|BeginSourceRun|UploadChunk|CommitSourceItem|MirrorDeletion/)
  assert.match(client, /CheckLocalSourceItemCloudMetadata\(/)
  assert.match(client, /decoder\.DisallowUnknownFields\(\)/)
  assert.match(client, /got\.CloudBytesVerified \|\| got\.ContentVerified/)
  assert.match(apiTest, /TestLocalEvidenceCloudMetadataMatchesOnlyCurrentReadyCASRecords/)
  assert.match(agent, /localpush\.HashCurrentLocalEvidenceBatch\(/)
  assert.match(agent, /cli\.CheckLocalSourceItemCloudMetadata\(/)
  assert.match(agent, /cli\.PreflightLocalSourceItemEvidence\(/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.doesNotMatch(agent, /UploadChunk|BeginSourceRun|CommitSourceItem|MirrorDeletion/)
  assert.doesNotMatch(agentIPC, /evidence-cloud-metadata|CheckLocalSourceItemCloudMetadata/)
  assert.doesNotMatch(preload, /evidence-cloud-metadata|CheckLocalSourceItemCloudMetadata/)
  assert.doesNotMatch(web, /evidence-cloud-metadata|CheckLocalSourceItemCloudMetadata/)
  assert.match(sourceRun, /source\.Kind == meta\.SourceKindLocalFolder[\s\S]*?errLocalFolderNotReady/)
})
