const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('physical CAS preflight is owning-Desktop-only and aggregate-redacted through all layers', () => {
  const go = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_preflight.go')
  const goTest = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_preflight_test.go')
  const router = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const preflight = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_preflight.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const types = read('desktop', 'src', 'renderer', 'global.d.ts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalEvidencePreflightDialog.tsx')
  const web = read('web', 'src', 'App.tsx')

  assert.match(router, /device-backup-local-evidence-preflight/)
  assert.match(router, /GET \/v1\/device-backups\/local-evidence-preflight/)
  assert.match(go, /preflightLocalBoundBackupEvidencePage\(r\.Context\(\), sourceID, afterID\)/)
  assert.match(go, /desktopLocalEvidencePreflightProjection\(/)
  assert.match(go, /Cache-Control", "private, no-store"/)
  assert.match(go, /PhysicalCASUnobservedFiles/)
  assert.match(go, /CommitSupported: false/)
  assert.match(go, /MissingInferenceSafe: false/)
  assert.doesNotMatch(go, /json:"(path|sha256|storage_key|source_item_id|device_id|root_id|root_fingerprint|native_identity_key)"/)
  assert.match(goTest, /TestDesktopIPCLocalContentPreflightCancellationPropagatesToGoContext/)
  assert.match(goTest, /TestDesktopIPCLocalContentPreflightNoGenericSourceFallback/)
  assert.match(goTest, /TestDesktopIPCLocalContentPreflightRejectsUnsafeResults/)
  assert.match(preflight, /localpush\.HashCurrentLocalEvidenceBatch\(/)
  assert.match(preflight, /observeLocalEvidencePhysicalBatches\(/)
  assert.match(preflight, /metadataAgain, err := cli\.CheckLocalSourceItemCloudMetadata\(/)
  assert.match(preflight, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(client, /localBoundBackupEvidencePreflight\(/)
  assert.match(main, /const localEvidencePreflightRequests = new Map<string, AbortController>\(\)/)
  assert.match(main, /localEvidencePreflightRequests\.get\(key\)\?\.abort\(\)/)
  assert.match(main, /event\.sender\.once\('destroyed', onSenderDestroyed\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-evidence-preflight'\)/)
  assert.match(preload, /getDeviceBackupLocalEvidencePreflight/)
  assert.match(preload, /cancelDeviceBackupLocalEvidencePreflight/)
  assert.match(types, /XDriveLocalBackupEvidencePreflight/)
  assert.match(app, /localEvidencePreflight=\{localBackupEvidencePreflight\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(page, /evidencePreflightTarget\.source === source/)
  assert.match(dialog, /physical_unobserved_files/)
  assert.match(dialog, /value\.content_verified === false && value\.commit_supported === false/)
  assert.match(dialog, /actions\.cancel\(requestID\)/)
  assert.match(dialog, /本机内容一致性|内容一致性预检/)
  assert.doesNotMatch(web, /localEvidencePreflight=|getDeviceBackupLocalEvidencePreflight/)
  assert.doesNotMatch(preload, /evidence-cloud-bytes|CheckLocalSourceItemCloudBytes/)
  assert.doesNotMatch(main, /evidence-cloud-bytes|CheckLocalSourceItemCloudBytes/)
})
