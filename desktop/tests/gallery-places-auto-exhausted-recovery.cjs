'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname,'../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')
test('permanent failed map jobs cool down and recover without consent or cancellation replay',()=>{
 const plan=read('internal/api/baidu_photo_map_auto_plan.go')
 const intent=read('internal/api/baidu_photo_map_index_intent.go')
 const fixture=read('internal/api/baidu_photo_map_auto_plan_integration_test.go')
 const router=read('internal/api/router.go')
 assert.match(plan,/baiduPhotoMapAutoFailedRetryCooldown\s*=\s*24 \* time\.Hour/)
 assert.match(plan,/i\.updated_at \+ INTERVAL '24 hours' > clock_timestamp\(\)/)
 assert.match(plan,/i\.status <> \? OR/)
 assert.match(plan,/i\.status = \? AND i\.consent_revision <> 0/)
 assert.match(intent,/baiduPhotoMapFailedRetryDue\(now, old\.UpdatedAt, old\.RetryAfter\)/)
 assert.match(intent,/old\.Status == baiduMapIndexFailed/)
 assert.match(intent,/old\.Status != baiduMapIndexCompleted/)
 assert.match(intent,/baiduMapIndexSameOwnerSourceGeneration\(old, source\)/)
 assert.match(fixture,/exhausted work remained permanently hidden/)
 assert.match(fixture,/cancelled photo was re-admitted/)
 assert.match(fixture,/migration-era cancellation was silently restored/)
 assert.match(fixture,/legacy failure bypassed cooldown/)
 assert.match(fixture,/new GPS generation remained permanently cancelled/)
 assert.doesNotMatch(router,/authed\.POST\("\/media\/items\/:id\/baidu-map-index-job"/)
})
