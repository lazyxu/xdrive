'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const screen = read('ios/XDriveIOS/NativeFilesVersionHistory.swift')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const router = read('internal/api/router.go')
const server = read('internal/api/history_trash.go')

test('native Files version history uses existing Owner-scoped Server API and real DTO', () => {
  assert.match(router, /authed\.GET\("\/files\/:id\/versions", s\.fileVersions\)/)
  assert.match(router, /authed\.POST\("\/files\/:id\/versions\/:versionID\/restore", s\.restoreFileVersion\)/)
  assert.match(server, /type fileVersionDTO struct \{/)
  for (const prop of ['id', 'node_id', 'revision', 'size', 'sha256', 'created_at']) {
    assert.match(server, new RegExp('json:"' + prop + '(?:,omitempty)?"'))
    assert.match(screen, new RegExp('let ' + prop + ':'))
  }
  assert.match(server, /func \(s \*Server\) fileVersions\(c \*gin\.Context\)/)
  assert.match(server, /func \(s \*Server\) restoreFileVersion\(c \*gin\.Context\)/)
  assert.match(screen, /\/api\/v1\/nodes\/\\\(nodeID\)/)
  assert.match(screen, /\/api\/v1\/files\/\\\(node\.id\)\/versions/)
  assert.match(screen, /\/api\/v1\/files\/\\\(node\.id\)\/versions\/\\\(version\.id\)\/restore/)
  assert.doesNotMatch(screen, /WKWebView|import WebKit|URLSession\.shared|\/api\/v1\/uploads/)
})

test('Files list/grid expose current verified file versions without a second tab', () => {
  assert.match(browser, /@State private var versionHistoryIntent: XDriveIOSNativeFilesVersionIntent\?/)
  assert.match(browser, /Button\("版本历史"\) \{ openVersionHistory\(for: entry\.node\) \}/)
  assert.match(browser, /node\.type == "file", let owner = login\.owner/)
  assert.match(browser, /model\.entries\.contains\(where: \{ \$0\.node == node \}\)/)
  assert.match(browser, /versionHistoryIntent = XDriveIOSNativeFilesVersionIntent\(/)
  assert.match(browser, /\.sheet\(item: \$versionHistoryIntent, onDismiss: \{/)
  assert.match(browser, /XDriveIOSNativeFilesVersionHistoryScreen\(/)
  assert.match(browser, /versionHistoryIntent = nil/)
  assert.match(browser, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, intent\.owner\)/)
  assert.match(browser, /if !entry\.node\.isDirectory \{/)
})

test('version list rejects malformed, stale, oversized or mismatched Owner records', () => {
  assert.match(screen, /static let maximumRows = 2048/)
  assert.match(screen, /Set\(rows\.map\(\\\.id\)\)\.count == rows\.count/)
  assert.match(screen, /version\.node_id == node\.id/)
  assert.match(screen, /version\.revision > 0 && version\.revision < node\.revision/)
  assert.match(screen, /version\.size >= 0/)
  assert.match(screen, /XDriveIOSNativeFilesVersionHistoryPolicy\.valid\(versions, for: node\)/)
  assert.match(screen, /guard try await current\(node\.id, session: client\) == node/)
  assert.match(screen, /maximum: 2_097_152/)
  assert.match(screen, /URLSessionConfiguration\.ephemeral/)
  assert.match(screen, /completionHandler\(nil\)/)
  assert.match(screen, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(screen, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(screen, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, openedOwner\)/)
})

test('restore is a single revision-locked POST with exact readback and no blind retry', () => {
  assert.match(server, /expected, ok := expectedRevision\(c\)/)
  assert.match(server, /current\.Revision != expected/)
  assert.match(server, /"revision": gorm\.Expr\("revision \+ 1"\)/)
  assert.match(server, /tx\.Delete\(&meta\.FileVersion\{\}, selected\.ID\)/)
  assert.match(screen, /available\.contains\(version\)/)
  assert.match(screen, /request\.setValue\("\\"\\\(ifMatch\)\\"", forHTTPHeaderField: "If-Match"\)/)
  assert.match(screen, /method: "POST", ifMatch: node\.revision/)
  assert.match(screen, /validRestored\(\s*restored, original: node, version: version/)
  assert.match(screen, /next\.size == version\.size/)
  assert.match(screen, /next\.revision == original\.revision \+ 1/)
  assert.match(screen, /current\(node\.id, session: client\) == restored/)
  assert.match(screen, /!latest\.contains\(where: \{ \$0\.id == version\.id \}\)/)
  assert.match(screen, /恢复结果无法确认；请刷新当前目录核对，不要再次提交。/)
  assert.doesNotMatch(screen, /retry.*POST|Task\.sleep|DispatchQueue\.main\.asyncAfter/)
})

test('iOS screen confirms user intent and tears down stale Owner/session state', () => {
  assert.match(screen, /@State private var pendingVersion: XDriveIOSNativeFilesVersionRecord\?/)
  assert.match(screen, /\.confirmationDialog\("恢复到选中的历史版本？"/)
  assert.match(screen, /Button\("确认恢复", role: \.destructive\)/)
  assert.match(screen, /model\.verified, model\.items\.contains\(version\)/)
  assert.match(screen, /Button\("刷新版本历史"\)/)
  assert.match(screen, /native-ios-files-versions-refresh/)
  assert.match(screen, /native-ios-files-restore-/)
  assert.match(screen, /\.onDisappear \{/)
  assert.match(screen, /model\.invalidate\(\)/)
  assert.match(screen, /\.onChange\(of: login\.owner\)/)
  assert.match(screen, /\.onChange\(of: phase\)/)
  assert.match(screen, /onConfirmed\(\)/)
})
