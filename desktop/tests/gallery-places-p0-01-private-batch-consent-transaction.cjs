'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')

test('P0-01 batch authorization private selector reuses Owner WGS84 provenance and never accepts client-supplied IDs', () => {
  const code = read('internal/api/baidu_photo_map_batch_candidates.go')
  assert.match(code, /mediaPlacesBaseQuery\(readCtx, db, ownerID\)/)
  assert.match(code, /n\.owner_id = \? AND n\.type = \? AND n\.revision > 0/)
  assert.match(code, /xd_media_metadata\.node_revision = n\.revision/)
  assert.match(code, /c\.source_media_updated_at IS DISTINCT FROM xd_media_metadata\.updated_at/)
  assert.match(code, /c\.source_latitude IS DISTINCT FROM xd_media_metadata\.latitude/)
  assert.match(code, /c\.source_longitude IS DISTINCT FROM xd_media_metadata\.longitude/)
  assert.match(code, /Order\("pa.id ASC"\)\.Limit\(limit\)/)
  assert.match(code, /baiduPhotoMapGrantBatchMaxItems = 32/)
  assert.match(code, /func \(baiduPhotoMapGrantBatchCandidate\) MarshalJSON\(\)/)
  assert.doesNotMatch(code, /gin\.Context|http\.Request|http\.Client|BaiduGeoconv|BrowserAK|window\.location/)
})

test('P0-01 private Owner decision atomically grants, purges, queues, audits or rolls back', () => {
  const code = read('internal/api/baidu_photo_map_batch_grant_queue.go')
  const a = code.indexOf('db.WithContext(ctx).Transaction(')
  const grant = code.indexOf('grantBaiduPhotoMapConsent(', a)
  const queue = code.indexOf('enqueueBaiduPhotoMapIndexIntent(', grant)
  const audit = code.indexOf('auditpkg.Record(', queue)
  const commit = code.indexOf('committed = grant.Revision', audit)
  assert.ok(a >= 0 && a < grant && grant < queue && queue < audit && audit < commit)
  assert.match(code, /verifyDecision == nil/)
  assert.match(code, /actualOwner == ownerID/)
  assert.match(code, /assetID == candidate.AssetID/)
  assert.match(code, /grant.Revision == 0/)
  assert.match(code, /"media.photo_map.index.enqueue"/)
  assert.match(code, /"explicit-batch-consent"/)
  assert.doesNotMatch(code, /BaiduGeoconv|exec\.Command|http\.Client|http\.Post|fetch\(/)
  const consent = read('internal/api/baidu_photo_map_consent_grant.go')
  assert.match(consent, /clause.Locking\{Strength: "UPDATE"\}/)
  assert.match(consent, /media\.UpdatedAt\.Equal\(candidate\.MediaUpdatedAt\)/)
  assert.match(consent, /revoked_at/)
  assert.match(consent, /Delete\(&meta.BaiduPhotoMapPosition\{\}\)/)
  const intent = read('internal/api/baidu_photo_map_index_intent.go')
  assert.match(intent, /func enqueueBaiduPhotoMapIndexIntent/)
  assert.match(intent, /lockBaiduMapIndexSourceTx/)
  assert.match(intent, /old.Status == baiduMapIndexQueued \|\| old.Status == baiduMapIndexLeased/)
  assert.doesNotMatch(code, /JSON\(http.StatusAccepted|server\.ServeHTTP/)
})

