test('unified gallery defaults to all sources and keeps unknown evidence distinct', () => {
  const ui = read('NativeUnifiedPhotoGallery')
  const dashboard = read('NativePhotosDashboard')
  const timeline = read('NativeUnifiedPhotoTimeline')
  const wall = read('NativeUnifiedPhotoWall')
  const viewer = read('NativeUnifiedPhotoViewer')
  assert.match(dashboard, /gallerySource: XDriveIOSNativeGallerySource = \.unified/)
  assert.match(dashboard, /case \.unified:\s*XDriveIOSNativeUnifiedPhotoGallery\(login: login\)/)
  assert.match(ui, /filterButton\(nil, title: "全部"\)/)
  assert.match(timeline, /checkedLocal\?\.provesAbsence\(for: probe\.kind\) == true && ids\.isEmpty/)
  assert.match(timeline, /localIDs\[key\] == \[candidate\.id\]/)
  assert.match(timeline, /matches\[key\]\?\.matches\(photo\) == true/)
  assert.match(timeline, /cloudAnchorRevision[\s\S]*?slice\.items\.first\?\.node\.revision == cursor\.cloudAnchorRevision/)
  assert.match(viewer, /row\.local == nil \? row\.cloud : nil/)
  assert.match(ui, /local\.load\(asset\.id,[^\n]*allowICloud: false\)/)
  assert.match(ui, /displayActive: selected == nil && phase == \.active/)
  assert.match(ui, /local\.cancel\(\)[\s\S]*?fallback\?\.cancel\(\)[\s\S]*?guard displayActive else \{ return \}/)
  assert.doesNotMatch(ui, /UploadSession|WKWebView|requestImageDataAndOrientation/)
})

