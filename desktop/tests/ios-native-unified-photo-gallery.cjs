'use strict'

const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname, '../../ios/XDriveIOS', name + '.swift'), 'utf8')

test('unified gallery defaults to all sources and keeps unknown evidence distinct', () => {
  const ui = read('NativeUnifiedPhotoGallery')
  const dashboard = read('NativePhotosDashboard')
  const timeline = read('NativeUnifiedPhotoTimeline')
  assert.match(dashboard, /gallerySource: XDriveIOSNativeGallerySource = \.unified/)
  assert.match(dashboard, /case \.unified:\s*XDriveIOSNativeUnifiedPhotoGallery\(login: login\)/)
  assert.match(ui, /filterButton\(nil, title: "全部"\)/)
  assert.match(timeline, /coverage\(lease: lease\)\?\.provesAbsence == true/)
  assert.match(timeline, /checkedAllLocal && ids\.isEmpty/)
  assert.match(timeline, /localIDs\[key\] == \[candidate\.id\]/)
  assert.match(timeline, /matches\[key\]\?\.matches\(photo\) == true/)
  assert.match(timeline, /cloudAnchorRevision[\s\S]*?slice\.items\.first\?\.node\.revision == cursor\.cloudAnchorRevision/)
  assert.match(ui, /if let local = row\.local \{ selected = \.local\(local, row, owner\) \}/)
  assert.match(ui, /local\.load\(asset\.id,[^\n]*allowICloud: false\)/)
  assert.match(ui, /displayActive: selected == nil && phase == \.active/)
  assert.match(ui, /local\.cancel\(\)[\s\S]*?fallback\?\.cancel\(\)[\s\S]*?guard displayActive else \{ return \}/)
  assert.doesNotMatch(ui, /UploadSession|WKWebView|requestImageDataAndOrientation/)
})

test('cross-source matching streams original chunks and verifies both Live parts', () => {
  const proof = read('NativeGalleryExactPhoto')
  const transport = read('NativeServerMediaGalleryTransport')
  assert.match(proof, /options\.isNetworkAccessAllowed = false/)
  assert.match(proof, /case "live_photo": roles = \["still", "motion"\]/)
  assert.match(proof, /originalResources\(for: asset\)/)
  assert.match(proof, /var digest = SHA256\(\)/)
  assert.match(proof, /manager\.cancelDataRequest\(id\)/)
  assert.doesNotMatch(proof, /maximumBytesPerResource|Data\(contentsOf:|\.stage\(/)
  assert.match(proof, /XDriveIOSNativePhotoProofStamp\.current\(candidate\.id\) == stamp/)
  assert.match(transport, /endpoint\("\/api\/v1\/media\/exact-match"\)/)
  assert.match(transport, /reply\.matches\.count == probes\.count, reply\.matches\.allSatisfy\(\\\.isValid\)/)
})

test('unified Gallery searches source cursors and persists a generation-bound full-library index', () => {
  const timeline = read('NativeUnifiedPhotoTimeline')
  const ui = read('NativeUnifiedPhotoGallery')
  const index = read('NativePhotoMatchMemo')
  const store = read('NativePhotoFingerprintStore')
  assert.match(ui, /load\(from: cursor, filter: sourceFilter/)
  assert.doesNotMatch(ui, /timeline\.rows\.filter/)
  assert.match(timeline, /while visible\.count < Self\.pageSize && visited < Self\.searchLimit/)
  assert.match(timeline, /localIDs\(for: probe, lease: lease\)/)
  assert.match(index, /fetchPersistentChanges\(since: token\)/)
  assert.match(index, /details\.deletedLocalIdentifiers/)
  assert.match(index, /expected == lease, let store, Self\.isCurrent\(expected\.library\)/)
  assert.match(index, /finished && checked == total && unavailable == 0/)
  assert.match(store, /CREATE INDEX IF NOT EXISTS fingerprints_by_content/)
  assert.match(store, /LIMIT 2/)
  assert.doesNotMatch(index + store, /proofLimit|limit = 512|removeFirst\(\)/)
})

test('thumbnail cache isolates Owner and revision and fences in-flight writes after deletion', () => {
  const cache = read('NativePhotoThumbnailCache')
  const ui = read('NativePhotoThumbnailCacheScreen')
  const transport = read('NativeServerMediaGalleryTransport')
  assert.match(cache, /owner\.origin\.absoluteString[\s\S]*?owner\.instanceID[\s\S]*?owner\.ownerID[\s\S]*?owner\.rootNodeID/)
  assert.match(cache, /guard revision == expectedRevision/)
  assert.match(cache, /func remove\(scope:[\s\S]*?revision = UUID\(\)/)
  assert.match(cache, /\.cachesDirectory/)
  assert.match(cache, /maximumBytes = 512 \* 1_048_576/)
  assert.match(cache, /\.completeFileProtection/)
  assert.match(transport, /func thumbnail[\s\S]*?metadata\.thumbnail_version[\s\S]*?cache\.load[\s\S]*?downloadThumbnail/)
  assert.match(ui, /let expected = clearOwner/)
  assert.match(ui, /guard XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, owner\) else \{ return \}/)
  assert.doesNotMatch(ui + cache, /URLSession|PHPhotoLibrary\.shared\(\)\.performChanges|deleteOriginal/)
})
