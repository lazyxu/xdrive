  assert.match(index, /catch XDriveIOSNativePhotoFingerprintStore\.Failure\.invalidRecord[\s\S]*?begin\(library: library, invalidate: changed\)/)
  assert.match(index, /prepareUnavailableRetry\(\)/)
  assert.match(index, /if try database\(expected\)\.incrementalWork\(\) != nil[\s\S]*?finishPending/)
  assert.match(index, /Self\.isCurrent\(expected\.library\)/)
