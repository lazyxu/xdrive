  assert.match(webReader, /listItemRange: \(limit, offset, query, signal\) => api\.mediaItemRange\(/)
  assert.match(desktopReader, /listItems: \(limit, offset, query\) => agent\.getMediaItems\(/)
  assert.doesNotMatch(webReader + desktopReader, /PHPhotoLibrary|MediaStore|getGeneration\(/)
