'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '../..', file), 'utf8')
const policy = read('ios/XDriveIOS/NativePhotoCoveragePolicy.swift')
const model = read('ios/XDriveIOS/NativePhotoCoverageModel.swift')
const ledger = read('ios/XDriveIOS/PhotoSyncEncryptedLedger.swift')
const screen = read('ios/XDriveIOS/NativePhotoBackupScreen.swift')

test('read-only Owner receipt summary never declares entire iPhone library backed up', () => {
  assert.match(policy, /var wholeLibraryCompletionVerified: Bool \{ false \}/)
  assert.match(policy, /case "confirmed":\s*if hasVerifiedReceipt/)
  assert.match(policy, /case "creating", "uploading", "finalizing", "needsReconciliation":/)
  assert.match(model, /login\.verifiedAuthorization\(\)/)
  assert.match(model, /\.existingLocalScope\(owner: expectedOwner\)/)
  assert.match(model, /\.historicalReceiptTally\(scope: existingScope\)/)
  assert.match(model, /PHAsset\.fetchAssets\(with: \.image, options: nil\)\.count/)
  assert.match(model, /PHAsset\.fetchAssets\(with: \.video, options: nil\)\.count/)
  assert.doesNotMatch(model, /localScopeAndTag|uploadPrepared|prepare\(|resumeDue|performChanges/)
  assert.match(screen, /Section\("当前图库与历史原件收据"\)/)
  assert.match(screen, /Button\("只读统计当前图库和既有收据"\)/)
  assert.match(screen, /整库是否已经备份：尚未逐张核验/)
  assert.doesNotMatch(screen, /historicallyConfirmed \/\s*snapshot\.currentAuthorizedMedia/)
})

test('counts authenticated V1 and V2 receipt records without treating an unknown ACK as confirmed', () => {
  assert.match(ledger, /func historicalReceiptTally\(scope: XDrivePhotoSyncScope\)/)
  assert.match(ledger, /for prefix in try availableShardPrefixes\(scope: scope\)/)
  assert.match(ledger, /try readShard\(scope: scope, key: key, prefix: prefix\)/)
  assert.match(ledger, /legacyIDs\.contains\(entry\.id\)/)
  assert.match(ledger, /legacyFingerprints\.contains\(entry\.assetFingerprint\)/)
  assert.match(ledger, /entry\.verifiedNodeID != nil/)
  assert.match(ledger, /entry\.verifiedNodeRevision != nil/)
  assert.match(ledger, /entry\.sessionID != nil/)
  assert.match(ledger, /counts\.include\(state: entry\.state\.rawValue, hasVerifiedReceipt: hasReceipt\)/)
  assert.doesNotMatch(model, /XDrivePhotoSyncLedger\.shared\.prepare|clearLocalRecords/)
})
