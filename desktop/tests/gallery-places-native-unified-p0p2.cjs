'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root,file),'utf8')

const ownerMap = read('ios/XDriveIOS/NativeOwnerMapClusterAlbum.swift')
const unifiedGallery = read('ios/XDriveIOS/NativeUnifiedPhotoGallery.swift')
const unifiedWall = read('ios/XDriveIOS/NativeUnifiedPhotoWall.swift')
const sharedComponents = read('ios/XDriveIOS/NativePhotoWallComponents.swift')
const sharedPolicy = read('ios/XDriveIOS/NativePhotoWallDensityPolicy.swift')
const webGallery = read('ui/shared/src/mui/MediaGallery.tsx')
const webPlaces = read('ui/shared/src/mui/MediaGalleryPlacesPhotoDrawer.tsx')
const switches = read('ui/shared/src/mui/MediaGalleryTimeScaleControls.tsx')

test('iOS MapKit and Gallery use the same SwiftUI framing, density and date-scale controls',()=>{
  assert.match(sharedPolicy,/enum XDriveIOSNativePhotoWallFraming/)
  assert.match(sharedPolicy,/enum XDriveIOSNativePhotoWallTimeScale/)
  assert.match(sharedComponents,/struct XDriveIOSNativePhotoWallTimeScaleControls/)
  assert.match(sharedComponents,/func xdrivePhotoWallFramingButtons/)
  assert.match(ownerMap,/XDriveIOSNativePhotoWallTimeScaleControls\(scale: \$wallTimeScale\)/)
  assert.match(unifiedGallery,/XDriveIOSNativePhotoWallTimeScaleControls\(scale: \$wallTimeScale\)/)
  assert.match(ownerMap,/xdrivePhotoWallFramingButtons\(\$wallFraming\)/)
  assert.match(unifiedGallery,/xdrivePhotoWallFramingButtons\(\$wallFraming\)/)
  assert.match(ownerMap,/wallFraming == \.complete \? \.fit : \.fill/)
  assert.match(unifiedGallery,/framing == \.complete \? \.fit : \.fill/)
  assert.match(unifiedWall,/framing: framing/)
  assert.match(ownerMap,/xdrivePhotoWallPinch\(/)
  assert.match(unifiedGallery,/xdrivePhotoWallPinch\(/)
})

test('Owner MapKit shows no previous Owner count, image or tiles during synchronous render transition',()=>{
  assert.match(ownerMap,/if activeOwner \{\s+Text\(/)
  assert.match(ownerMap,/if activeOwner \{\s+if wallTimeScale == \.all/)
  assert.match(ownerMap,/if activeOwner, let next/)
  assert.match(ownerMap,/if activeOwner, let error/)
  assert.match(ownerMap,/XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, selection\.owner\)/)
  assert.match(ownerMap,/XDriveIOSNativePhotoWallWindowPolicy\.canRestore/)
  assert.match(ownerMap,/sameVisibleSnapshot\(as: departingPage\)/)
  assert.match(ownerMap,/reader\.page\(/)
  assert.match(ownerMap,/if case \.response\(let code\) = failure, code == 401 \|\| code == 403/)
})

test('native dates are presentation-only on at most two signed pages, never invented full-place index',()=>{
  assert.match(ownerMap,/private var visibleSections/)
  assert.match(ownerMap,/priorWindow\.map/)
  assert.match(ownerMap,/page\.map/)
  assert.match(ownerMap,/仅对当前已授权、已加载的照片分组/)
  assert.match(sharedPolicy,/key\(forISO8601 value: String\?\)/)
  assert.doesNotMatch(ownerMap,/fetchAllOwner|loadAllPhotos|while.*hasNext/)
  assert.match(unifiedWall,/Dictionary\(grouping: model\.rows\)/)
})

test('Web/PWA routes share date switches while Places never gains an unrestricted bulk action',()=>{
  assert.match(webGallery,/XDriveMediaGalleryTimeScaleControls/)
  assert.match(webPlaces,/XDriveMediaGalleryTimeScaleControls/)
  assert.match(switches,/data-xdrive-gallery-time-scale/)
  assert.match(switches,/data-xdrive-places-photo-time-scale/)
  assert.match(webPlaces,/onSetFavorite/)
  assert.match(webPlaces,/onOpenAll/)
  assert.doesNotMatch(webPlaces,/onDeleteSelection|deleteItems\(|removeSelectedNodes\(/)
})
