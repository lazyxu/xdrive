'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const ios=read('ios/XDriveIOS/NativeClipboardScreen.swift')
const android=read('android/app/src/main/java/com/tfluid/xdrive/NativeClipboardScreens.kt')
const fence=read('android/core/src/main/kotlin/com/tfluid/xdrive/core/XDriveClipboardSessionFence.kt')

test('iOS Owner switch, screen exit and foreground SSE invalidate stale content',()=>{
 assert.match(ios,/@State private var sessionGeneration: UInt64 = 0/)
 assert.match(ios,/\.onChange\(of: login\.owner\) \{ _ in reset\(\) \}/)
 assert.match(ios,/\.onDisappear \{ reset\(\) \}/)
 assert.match(ios,/private func reset\(\) \{[\s\S]*?sessionGeneration &\+= 1/)
 assert.match(ios,/let proof = try await login\.verifiedAuthorization\(\)/)
 assert.match(ios,/ownerAtOpen == client\.owner/)
 assert.match(ios,/\.task\(id: scenePhase == \.active\)/)
 assert.match(ios,/try await Task\.sleep\(nanoseconds: 15_000_000_000\)/)
 assert.match(ios,/recipientProof = nil/)
})
test('iOS clipboard has no independent unlock/password or crypto key lifecycle',()=>{
 assert.doesNotMatch(ios,/SecureField|Button\("解锁"\)|SymmetricKey|recipientPrivateKey|AES\.GCM/)
 assert.match(ios,/let wire: XDriveIOSClipboardWrite/)
 assert.match(ios,/previous\.wire/)
})
test('Android Owner epoch and route disposal invalidate late callbacks',()=>{
 assert.match(android,/remember\(epoch\) \{ XDriveClipboardSessionFence\(\) \}/)
 assert.match(android,/fun stillSession\(snapshot: Long\) = stillOwner\(\) && actionFence\.accepts\(snapshot\)/)
 assert.match(android,/onDispose \{ lock\(\) \}/)
 assert.match(android,/fun lock\(\) \{\s*actionFence\.invalidate\(\)/)
 assert.match(android,/if \(draft == textAtStart\) draft = ""/)
 assert.match(android,/lifecycleOwner\.lifecycle\.repeatOnLifecycle\(Lifecycle\.State\.STARTED\)/)
 assert.match(android,/delay\(15_000\)/)
 assert.doesNotMatch(android,/PasswordVisualTransformation|XDriveClipboardCrypto|XDriveClipboardTargetCrypto/)
})
test('Android session fence supports explicit invalidation',()=>{
 assert.match(fence,/fun invalidate\(\) \{\s*generation \+= 1L/)
 assert.match(fence,/fun accepts\(snapshot: Long\): Boolean = generation == snapshot/)
})
