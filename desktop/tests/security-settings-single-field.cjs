'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..', '..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')

test('single sensitive input is shared, editable, eye-revealed and bounded', () => {
  const field = read('ui/shared/src/mui/SensitiveField.tsx')
  assert.match(field, /VisibilityOutlinedIcon/)
  assert.match(field, /VisibilityOffOutlinedIcon/)
  assert.match(field, /revealedValue/)
  assert.match(field, /onReveal\?\.\(\)/)
  assert.match(field, /onHide\?\.\(\)/)
  assert.match(field, /30_000/)
  assert.match(field, /visibilitychange/)
  assert.match(field, /window\.addEventListener\('blur'/)
  assert.doesNotMatch(field, /localStorage|sessionStorage|console\.log|dangerouslySetInnerHTML/)
})
test('one AliDNS field per value; no shadow current-value inputs', () => {
  const caddy = read('ui/shared/src/mui/CaddyAliDNSPanel.tsx')
  assert.equal((caddy.match(/<XDriveSensitiveField /g) || []).length, 2)
  assert.doesNotMatch(caddy, /已保存 AccessKey|AccessKey ID（新值）|AccessKey Secret（新值）/)
  assert.match(caddy, /access_key_id: action === 'replace'/)
  assert.match(caddy, /Math\.min\(30, shown\.expires_in_seconds\)/)
})
test('static-map and external source settings reuse one password-style editor', () => {
  const map = read('ui/shared/src/mui/ServiceDependenciesPage.tsx')
  const source = read('ui/shared/src/mui/SourceManagerSettingsDialog.tsx')
  const dsm = read('ui/shared/src/mui/SourceCredentialFields.tsx')
  assert.match(map, /XDriveSensitiveField label="Server AK"/)
  assert.doesNotMatch(map, /<XDriveStoredCredentialField/)
  assert.match(source, /XDriveSensitiveField label="一刻相册 Cookie"/)
  assert.doesNotMatch(source, /<XDriveStoredCredentialField/)
  assert.match(dsm, /XDriveSensitiveField label="DSM 密码"/)
})

test('all temporary admin/share passwords use one typed editor without a Server reveal', () => {
  const field = read('ui/shared/src/mui/SensitiveField.tsx')
  const admin = read('ui/shared/src/mui/AdminUsersPage.tsx')
  const share = read('ui/shared/src/mui/ShareFields.tsx')
  const publicShare = read('web/src/PublicShare.tsx')
  const index = read('ui/shared/src/mui/index.tsx')
  const oldSource = read('ui/shared/src/mui/SourceCredentialFields.tsx')
  assert.match(field, /!configured \|\| !!value \|\| !!onReveal/)
  assert.match(field, /startAdornment/)
  assert.match(index, /export \* from '\.\/SensitiveField'/)
  assert.match(admin, /XDriveSensitiveField[\s\S]*label="临时密码"/)
  assert.match(admin, /XDriveSensitiveField[\s\S]*label="新临时密码"/)
  assert.equal((admin.match(/type="password"/g) || []).length, 0)
  assert.match(share, /<XDriveSensitiveField[\s\S]*label="密码（可选）"/)
  assert.match(publicShare, /<XDriveSensitiveField[\s\S]*label="分享密码"/)
  assert.doesNotMatch(oldSource, /XDriveStoredCredentialField/)
  // Authentication passwords are irreversible and require create/change/reset.
  // Transient editors must never invent a backend old-password reveal route.
  assert.doesNotMatch(share + publicShare + admin, /onReveal=|revealPassword|readCurrentPassword/)
})
