'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const policy = read('ios/XDriveIOS/NativeVisiblePhotoQueueBadgePolicy.swift')
const queue = read('ios/XDriveIOS/PhotoKitPersistentBackupQueue.swift')
const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
const dashboard = read('ios/XDriveIOS/NativePhotosDashboard.swift')
const store = read('ios/XDriveIOS/PhotoBackupChangeQueueStore.swift')

test('native Timeline shows bounded Owner-local status in enabled full and only-new plans', () => {
  assert.match(dashboard, /backup\.schedule\?\.enabled == true \? login\.owner : nil/)
  assert.match(dashboard, /xdriveNativePhotoOnlyNewSince/)
  assert.match(wall, /queue\.isCaughtUp\(owner: owner\)/)
  assert.match(wall, /@Environment\(\\\.xdriveNativePhotoQueueBadgeOwner\) private var backupBadgeOwner/)
  assert.match(wall, /XDriveIOSNativePhotoOwnerScope\.matches\(backupBadgeOwner, owner\)/)
  assert.match(wall, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\) == \.authorized/)
})

test('only mounted 64-item PhotoKit page IDs are read and queue never uploads media', () => {
  assert.match(wall, /visibleStatusDetails\(\s*owner: owner, localIdentifiers: loaded\.items\.map\(\\\.id\)/)
  assert.match(wall, /visibleBackupQueueStates = \[:\]/)
  assert.match(wall, /\.task\(id: "\\\(generation\)-\\\(offset\)-\\\(mediaFilter\.rawValue\)"\)/)
  assert.match(wall, /\.onChange\(of: backupBadgeOwner\) \{ _ in[\s\S]*?visibleBackupQueueStates = \[:\]/)
  assert.match(wall, /let states = try await queue\.visibleStatusDetails\(/)
  assert.match(queue, /guard localIdentifiers\.count <= 64 else/)
  assert.match(queue, /let baseline = try store\.baseline\(\)/)
  assert.match(queue, /baseline\.authorization == epoch\.authorization/)
  assert.match(queue, /XDriveIOSPhotoKitLibraryEpoch\.matches\(baseline\.token, as: epoch\.token\)/)
  assert.match(queue, /store\.status\(for: id\)/)
  assert.match(queue, /try verifyAuthorization\(stillMatches: epoch\)/)
  assert.match(store, /SELECT e\.revision,e\.state,r\.reason FROM entries e LEFT JOIN failure_reasons r ON r\.asset_id=e\.asset_id AND r\.revision=e\.revision WHERE e\.asset_id=\?/)
  const method = queue.slice(queue.indexOf('    func visibleStatusDetails('), queue.indexOf('    /// Whether every persisted PhotoKit change event'))
  assert.ok(method.length > 0)
  assert.doesNotMatch(method, /UploadSession|uploadPrepared|finalize|deleteNode|URLSession/)
})

test('queue badges never portray historical ACK as present-day cloud backup completion', () => {
  assert.match(policy, /case "pending":/)
  assert.match(policy, /case "waitingICloud":/)
  assert.match(policy, /case "failed":/)
  assert.match(policy, /case "confirmed":/)
  assert.match(policy, /当前云端原件仍需重新核验/)
  assert.doesNotMatch(policy, /title: "已备份"/)
  assert.doesNotMatch(policy, /case "missingLocal":\s*return \.init/)
  assert.match(wall, /当前云端备份状态未核验/)
  assert.match(wall, /visibleBackupQueueStates = \[:\]/)
})
