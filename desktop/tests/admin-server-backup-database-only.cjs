const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const read = name => fs.readFileSync(path.resolve(__dirname, '../..', name), 'utf8')

test('DB-only recovery is a distinct, exact-confirmed Admin operation on every Host', () => {
  const panel = read('ui/shared/src/mui/ServerBackupManagementPanel.tsx')
  const shared = read('ui/shared/src/server-backup-admin.ts')
  const api = read('internal/api/admin_backup_management.go')
  const host = read('scripts/server-control.sh')
  const desktop = read('desktop/src/main/index.cts')
  const agent = read('cmd/xdrive-agent/desktop_ipc_admin_backups.go')
  const client = read('desktop/src/main/agent_client.cts')

  assert.match(panel, /selectedDatabaseOnly/)
  assert.match(panel, /DATABASE ONLY RESTORE /)
  assert.match(panel, /仅恢复 v1 数据库（保留文件）/)
  assert.match(panel, /数据库与当前文件可能产生引用不一致/)
  assert.match(shared, /action: 'restore_database_only'/)
  assert.match(api, /case "restore_database_only":/)
  assert.match(api, /backup_snapshot_not_database_only/)
  assert.match(agent, /case "restore_database_only":/)
  assert.match(desktop, /case 'restore_database_only':/)
  assert.match(desktop, /value\.confirmation === 'DATABASE ONLY RESTORE '/)
  assert.match(client, /'restore_database_only'/)
  assert.match(host, /restore_database_only\)/)
  assert.match(host, /--yes --database-only/)
  assert.match(host, /backup verify "\$target"/)
  assert.doesNotMatch(panel, /--database-only|--no-safety-backup/)
})
