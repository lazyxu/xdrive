const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('only owning Desktop can read bounded, redacted local backup history', () => {
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_common_batch_v2.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_common_batch_history_v2.go')
  const router = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const globals = read('desktop', 'src', 'renderer', 'global.d.ts')
  const renderer = read('desktop', 'src', 'renderer', 'App.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalCommonBatchDialog.tsx')
  const types = read('ui', 'shared', 'src', 'device-backups.ts')
  const web = read('web', 'src', 'App.tsx')
  assert.ok(router.includes('GET /v1/device-backups/local-common-batch/history'))
  assert.ok(ipc.includes('validLocalCommonBatchRequest(r)'))
  assert.ok(ipc.includes('len(result.Items) > 20'))
  assert.ok(agent.includes('c.localBoundBackupConfig(ctx, sourceID)'))
  assert.ok(agent.includes('localpush.LoadRootGrant('))
  assert.ok(agent.includes('localpush.ListVerifiedCommonBatchHistory('))
  assert.ok(agent.includes('localBackupRuleSessionUnchanged(account)'))
  assert.ok(main.includes("requireAgentCapability(hello, 'device-backup-local-common-batch')"))
  assert.ok(preload.includes('agent:get-device-backup-local-common-batch-history'))
  assert.ok(globals.includes('getDeviceBackupLocalCommonBatchHistory: (sourceID: number)'))
  assert.ok(client.includes('/v1/device-backups/local-common-batch/history?'))
  assert.ok(renderer.includes('window.xdriveDesktop.agent.getDeviceBackupLocalCommonBatchHistory(sourceID)'))
  assert.ok(dialog.includes('最近本机备份记录'))
  assert.ok(dialog.includes('actions.history(sourceID)'))
  assert.ok(!web.includes('getDeviceBackupLocalCommonBatchHistory'))
  const project = types.slice(types.indexOf('export interface XDriveLocalBackupCommonBatchHistoryItem'),
    types.indexOf('export interface XDriveLocalBackupSnapshot'))
  for (const forbidden of [
    'root_id', 'root_fingerprint', 'session_digest', 'absolute_path',
    'operation_id', 'device_token', 'content_sha256', 'target_node_id', 'backup_complete',
  ]) {
    assert.equal(project.includes(forbidden), false, 'private history exposed forbidden field: ' + forbidden)
  }
})

test('history only observes terminal local attempts, never grants backup_complete or CAS proof', () => {
  const history = read('internal','localpush','common_upload_run_history.go')
  const checkpoint = read('internal','localpush','common_upload_run_checkpoint.go')
  const worker = read('cmd','xdrive-agent','device_backup_local_common_batch_v2.go')
  assert.ok(history.includes('commonBatchHistoryLimit = 64'))
  assert.ok(history.includes('commonBatchHistoryReadLimit = 20'))
  assert.ok(history.includes('record.State == "running"'))
  assert.ok(history.includes('os.Link(temp.Name(), target)'))
  assert.ok(history.includes('ReconcileVerifiedCommonBatchHistoryBeforeRun'))
  assert.ok(history.includes('checkpoint.State = "uncertain"'))
  assert.ok(history.includes('ReadVerifiedCommonBatchCheckpoint('))
  assert.ok(checkpoint.includes('StartedAt'))
  assert.ok(checkpoint.includes('p.BackupComplete || p.RetirementSafe || p.CurrentCASVerified'))
  assert.ok(worker.includes('ReconcileVerifiedCommonBatchHistoryBeforeRun('))
  assert.ok(worker.includes('AppendVerifiedCommonBatchHistory('))
  assert.ok(worker.includes('_, _ = saveRun(syncCtx, "uncertain")'))
  assert.ok(worker.includes('BackupComplete: false'))
})
