'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const ui=read('ui/shared/src/mui/MediaGalleryBaiduIsolatedPhotoSurface.tsx')
const inline=read('ui/shared/src/media-gallery-baidu-inline-map-host.ts')
const isolated=read('ui/shared/src/media-gallery-baidu-isolated-frame-host.ts')
const child=read('deploy/baidu-isolated-child/child.js')
const runner=read('desktop/scripts/gallery-places-dual-host-chromium.cjs')

test('direct five-photo image opens its own bounded Cell instead of full map',()=>{
  assert.match(ui,/onClick=\{currentCoverActive\s*\? \(\) => openVerifiedCell\(pin.selection\)/)
  assert.match(ui,/selectCellRef\.current\(selection\)/)
  assert.match(ui,/data-xdrive-places-full-camera-wall/)
  assert.match(runner,/async function testDirectFivePhotoCoverClick/)
  assert.match(runner,/name:'查看该区域 5 张照片'/)
  assert.match(runner,/await five\.click\(\)/)
  assert.match(runner,/photoPreviewRanges\.at\(-1\)/)
})

test('a stale cover never directly reuses revoked Owner Cell permission',()=>{
  assert.match(ui,/disabled=\{!currentCoverActive\}/)
  assert.match(ui,/data-xdrive-places-gesture-photo-cover=/)
  assert.match(ui,/data-xdrive-places-photo-cover-revalidate=/)
  assert.match(ui,/pendingCoverClick\.current=/)
  assert.match(ui,/requestCurrentViewport\(\)/)
  assert.match(ui,/liveCamera && pendingCoverClick\.current/)
  assert.match(ui,/item\.selection\.asset_id===intent\.assetID/)
  assert.match(ui,/item\.selection\.node_revision===intent\.revision/)
  assert.match(ui,/selectCellRef\.current\(fresh\.selection\)/)
  assert.match(ui,/data-xdrive-places-cover-click-status/)
})

test('SDK retry requests only anonymous current viewport, not private media',()=>{
  assert.match(inline,/requestCurrentViewport\(\): boolean/)
  assert.match(inline,/scheduleViewport\(\)/)
  assert.match(isolated,/kind:'request-viewport'/)
  assert.match(isolated,/boundary\.childOrigin/)
  assert.match(child,/data\.kind==='request-viewport'/)
  assert.match(child,/exact\(data,\['version','generation','nonce','kind'\]\)/)
  assert.match(child,/scheduleViewport\(\)/)
  assert.doesNotMatch(isolated,/kind:'request-viewport'[\s\S]{0,100}node_id/)
})
