'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')

test('A4 real WGS84 filtering reuses one Owner Media Range on Web/Mobile/Desktop', () => {
  const backend = read('internal/api/media_nearby.go')
  const filters = read('internal/api/media_filters.go')
  const goClient = read('internal/client/media.go')
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  const agent = read('desktop/src/main/agent_client.cts')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const web = read('web/src/api.ts')
  const shared = read('ui/shared/src/models.ts')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  assert.match(backend, /applyMediaGeoSelection/)
  assert.match(backend, /mediaPlaceValidGPSPredicate/)
  assert.match(backend, /ASIN\(LEAST\(1\.0/)
  assert.match(filters, /out\.Geo, err = geoquery\.Parse/)
  assert.match(filters, /query = applyMediaGeoSelection\(query, options\.Geo\)/)
  for (const text of [goClient, ipc, agent, web, shared]) {
    assert.match(text, /nearby/)
    assert.match(text, /bbox/i)
  }
  assert.match(ipc, /geoquery\.Parse\(out\.Nearby, out\.BBox\)/)
  // Reject both modes even when one is an empty query parameter.
  assert.match(ipc, /hasNear && hasBBox/)
  assert.match(main, /function normalizeMediaGalleryQuery\(value: unknown\)/)
  assert.match(main, /const hasNearby = Object\.prototype\.hasOwnProperty\.call\(input, 'nearby'\)/)
  assert.match(main, /if \(hasNearby && hasBBox\)/)
  assert.match(main, /out\[mode\] = raw/)
  const sourcePattern = main.match(/const numberPattern = (\/.*\/)/)
  assert.ok(sourcePattern, 'Desktop numeric validator must exist')
  const numeric = new RegExp(sourcePattern[1].slice(1, -1))
  assert.equal(numeric.test('1.3521'), true)
  assert.equal(numeric.test('-179.99'), true)
  assert.equal(numeric.test('NaN'), false)
  assert.equal(numeric.test('0xFF'), false)
  assert.match(preload, /nearby\?: string/)
  assert.match(preload, /bbox\?: string/)
  assert.match(filters, /hasNear && hasBBox/)
  assert.match(gallery, /openNearbyGeoRange/)
  assert.match(gallery, /loadFirstPage\(null, nextQuery/)
  assert.match(map, /data-xdrive-gallery-nearby-a4/)
  // Live JSAPI4 uses BD-09: never query the last static WGS84 viewport.
  assert.match(map, /const boundedWGS84Viewport = Boolean\(!showingNative && viewportBounds/)
  // The user-selected date/search/favorite criteria still intersect with Nearby;
  // only the previous exact Place cell is removed.
  assert.match(gallery, /\.\.\.draftFilters, place: '', location: 'with'/)
  assert.match(map, /data-xdrive-gallery-bbox-photos/)
  assert.match(gallery, /activePlaceID=\{(?:query\.place_hierarchy \|\| )?query\.place \|\|/)
  assert.doesNotMatch(backend, /http\.Get|baidu|_BMapService/)
})
