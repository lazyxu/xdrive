'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const store = read('ios/XDriveIOS/NativeFilesInlineFolders.swift')
const policy = read('ios/XDriveIOS/NativeFilesInlinePolicy.swift')
const window = read('ios/XDriveIOS/NativeFilesContinuousWindowPolicy.swift')

test('chevron is an independent 44pt sibling and row remains real NavigationLink', () => {
  const row = browser.slice(browser.indexOf('@ViewBuilder private func fileEntryRow('),
    browser.indexOf('private var filesContinuousStatus:'))
  assert.match(row, /HStack\(spacing: 0\) \{[\s\S]*?Button \{[\s\S]*?toggleInline\(entry\)/)
  assert.match(row, /frame\(width: 44, height: 44\)/)
  assert.match(row, /buttonStyle\(\.borderless\)/)
  assert.match(row, /native-ios-files-disclose-/)
  assert.match(row, /NavigationLink\(value: XDriveIOSNativeFilesFolder\(/)
  assert.match(row, /native-ios-files-folder-/)
  assert.match(row, /if !isGlobalSearch && viewMode == "list"/)
  assert.doesNotMatch(row, /NavigationLink\(value:[\s\S]*?\{\s*Button \{\s*toggleInline\(entry\)/)
})

