'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const page = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const picker = read('ios/XDriveIOS/NativeFilesDestinationPicker.swift')
const policy = read('ios/XDriveIOS/NativeFilesBatchTargetPolicy.swift')
const writer = read('ios/XDriveIOS/NativeFilesBatchTarget.swift')
const sourcePolicy = read('ios/XDriveIOS/NativeFilesBatchTrashPolicy.swift')
const server = read('internal/api/batch_nodes.go')
const router = read('internal/api/router.go')

test('one real Owner-verified native Files page supports bounded multi-copy and multi-move', () => {
  assert.match(page, /@StateObject private var batchTarget = XDriveIOSNativeFilesBatchTargetModel\(\)/)
  assert.match(page, /private var canSelectPage: Bool \{[\s\S]*?model\.verifiedPage && activeQuery\.isEmpty/)
  assert.match(page, /Button\("已选项复制到…"\)/)
  assert.match(page, /Button\("已选项移动到…"\)/)
  assert.match(page, /private func openBatchDestination\(/)
  assert.match(page, /XDriveIOSNativeFilesBatchTrashPolicy\.validSelection\(\s*chosenItems, parentID: sourceParentID/)
  assert.match(page, /selectedIDs == Set\(chosenItems\.map\(\\\.id\)\)/)
  assert.match(page, /model\.entries\.contains\(where: \{ \$0\.node == selected \}\)/)
  assert.match(page, /selected: intent\.items\[0\], selectedItems: intent\.items/)
  assert.match(page, /batchTarget\.perform\(/)
  assert.match(page, /batchTarget\.invalidate\(\)/)
  assert.match(page, /batchTarget\.cancelCurrent\(\)/)
  assert.match(page, /native-ios-files-batch-target-status/)
  assert.match(page, /native-ios-files-batch-target-cancel/)
  assert.match(sourcePolicy, /static let maxSelected = XDriveIOSNativeFilesPagePolicy\.pageSize/)
})

test('existing native destination chooser validates every selected folder and retains single-item support', () => {
  assert.match(picker, /var selectedItems: \[XDriveIOSNativeFilesNode\] = \[\]/)
  assert.match(picker, /selectedItems\.isEmpty \? \[selected\] : selectedItems/)
  assert.match(picker, /selected: selected, selectedItems: selectedItems/)
  assert.match(picker, /allSelected\.contains\(where: \{ \$0\.isDirectory && \$0\.id == folder\.id \}\)/)
  assert.match(picker, /allSelected\.contains\(where: \{ \$0\.parent_id == folder\.id \}\)/)
  assert.match(picker, /reader\.children\(/)
  assert.match(picker, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, originalOwner\)/)
  assert.match(policy, /enum XDriveIOSNativeFilesDestinationKind: String, Equatable/)
})

test('Server performs one atomic batch POST, revision-locking every selected Node', () => {
  assert.match(router, /authed\.POST\("\/nodes\/batch\/copy", s\.batchCopyNodes\)/)
  assert.match(router, /authed\.POST\("\/nodes\/batch\/move", s\.batchMoveNodes\)/)
  assert.match(server, /const maxNodeBatchItems = 200/)
  assert.match(server, /func \(s \*Server\) batchCopyNodes\(c \*gin\.Context\)/)
  assert.match(server, /func \(s \*Server\) batchMoveNodes\(c \*gin\.Context\)/)
  assert.match(server, /validateBatchNodeRefs\(req\.Items\)/)
  assert.match(server, /batchSelectionHasAncestor\(tx, uid, req\.Items\)/)
  assert.match(server, /batchTargetInsideNode\(tx, uid, req\.ParentID, source\.ID\)/)
  assert.match(server, /batchTargetInsideNode\(tx, uid, req\.ParentID, node\.ID\)/)
  assert.match(writer, /\/api\/v1\/nodes\/batch\/copy/)
  assert.match(writer, /\/api\/v1\/nodes\/batch\/move/)
  assert.match(writer, /request\.httpMethod = "POST"/)
  assert.match(writer, /items\.map \{\s*XDriveIOSNativeBatchNodeRef\(id: \$0\.id, revision: \$0\.revision\)/)
  assert.match(writer, /let expectedStatus = kind == \.copy \? 201 : 200/)
  assert.match(writer, /validReceipt\(/)
  assert.match(policy, /UUID\(uuidString: receipt\.operation_id\) != nil/)
  assert.match(policy, /Set\(receipt\.items\.map\(\\\.id\)\)\.count == original\.count/)
  assert.match(policy, /result\.revision > selected\.revision/)
  assert.match(policy, /!sourceIDs\.contains\(result\.id\)/)
})

test('native batch action does not retry a lost commit and cancels on Owner or page changes', () => {
  assert.match(writer, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(writer, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(writer, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expectedOwner\)/)
  assert.match(writer, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, expectedOwner\)/)
  assert.match(writer, /completionHandler\(nil\)/)
  assert.match(writer, /guard busy, let running else \{ return \}[\s\S]*?running\.cancel\(\)/)
  assert.match(writer, /批量复制\/移动结果未确认，请先核对云端，不要自动重试/)
  assert.match(page, /\.onChange\(of: login\.owner\) \{ _ in[\s\S]*?batchTarget\.invalidate\(\)/)
  // Reload first retires the single-page selection, then cancels its batch
  // operation before any replacement Owner directory request is launched.
  // Reload must retire the page selection and staged downloads before
  // invalidating the independent copy/move mutation task.
  assert.match(page, /private func reload\(resetOffset: Bool = false\) \{\s*selecting = false\s*selectedIDs\.removeAll\(\)\s*batchExport\.invalidate\(\)\s*batchTarget\.invalidate\(\)/)
  assert.doesNotMatch(writer, /WKWebView|localStorage|URLSession\.shared|\/api\/v1\/uploads/)
})
