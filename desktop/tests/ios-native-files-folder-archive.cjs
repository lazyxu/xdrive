'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const transport = read('ios/XDriveIOS/NativeFilesFolderArchiveExport.swift')
const policy = read('ios/XDriveIOS/NativeFilesFolderArchivePolicy.swift')
const router = read('internal/api/router.go')
const prepare = read('internal/api/archive_prepare.go')
const stream = read('internal/api/download_ticket.go')
const zip = read('internal/api/archive_download.go')

test('native Files folder ZIP reuses Server prepared archive snapshots, not local recursion', () => {
  assert.match(router, /authed\.POST\("\/download\/archive\/prepare", s\.prepareArchiveDownload\)/)
  assert.match(router, /authed\.GET\("\/download\/archive\/prepare\/:id", s\.getArchiveDownloadPrepare\)/)
  assert.match(router, /authed\.POST\("\/download\/archive\/prepare\/:id\/download-ticket", s\.archiveDownloadTicket\)/)
  assert.match(router, /v1\.GET\("\/archive-download\/:id", s\.archiveDownloadTicketStream\)/)
  assert.match(prepare, /func \(s \*Server\) prepareArchiveDownload\(c \*gin\.Context\)/)
  assert.match(prepare, /func \(s \*Server\) getArchiveDownloadPrepare\(c \*gin\.Context\)/)
  assert.match(stream, /func \(s \*Server\) archiveDownloadTicket\(c \*gin\.Context\)/)
  assert.match(zip, /c\.Header\("Content-Type", "application\/zip"\)/)
  assert.match(transport, /"\/api\/v1\/download\/archive\/prepare"/)
  assert.match(transport, /"\/api\/v1\/download\/archive\/prepare\/\\\(runID\)"/)
  assert.match(transport, /"\/api\/v1\/download\/archive\/prepare\/\\\(runID\)\/download-ticket"/)
  assert.match(transport, /"\/api\/v1\/archive-download\/\\\(runID\)"/)
  assert.match(transport, /session\.download\(for: get\)/)
  assert.doesNotMatch(transport, /WKWebView|Data\(contentsOf:|\/api\/v1\/uploads|\/api\/v1\/download\/archive"[,)]/)
})

test('native folder archive fails closed on oversized/expired/unknown snapshots and unverified Owner changes', () => {
  assert.match(policy, /maximumOriginalBytes: Int64 = 512 \* 1_048_576/)
  assert.match(policy, /maximumArchiveBytes: Int64 = 640 \* 1_048_576/)
  assert.match(policy, /freeDiskReserveBytes: Int64 = 128 \* 1_048_576/)
  assert.match(policy, /maximumFileEntries = 2048/)
  assert.match(policy, /validRunID\(_ value: String\)/)
  assert.match(policy, /item\.path\.split\(separator: "\/", omittingEmptySubsequences: false\)/)
  assert.match(policy, /item\.size <= maximumOriginalBytes - sum/)
  assert.match(policy, /snapshot\.total_bytes \?\? 0/)
  assert.match(transport, /XDriveIOSNativeFilesFolderArchivePolicy\.validReady\(ready, runID: runID\)/)
  assert.match(transport, /let freeBytes = \(try\? FileManager\.default\.attributesOfFileSystem/)
  assert.match(transport, /hasCapacity\(\s*freeDiskBytes: freeBytes\?\.int64Value/)
  assert.match(transport, /guard try await current\(folder\.id, session: session\) == folder/)
  assert.match(transport, /settings\.timeoutIntervalForResource = 1800/)
  assert.match(transport, /completionHandler\(nil\)/)
  assert.match(transport, /http\.value\(forHTTPHeaderField: "Content-Type"\)\?\.hasPrefix\("application\/zip"\)/)
  assert.match(transport, /try verifyZIP\(temporary, bytes: bytes\)/)
  assert.match(transport, /tail\.range\(of: Data\(\[0x50, 0x4b, 0x05, 0x06\]\)\) != nil/)
  assert.match(transport, /let after = try await login\.verifiedAuthorization\(\)/)
  assert.match(transport, /XDriveIOSNativePhotoOwnerScope\.matches\(after\.owner, expectedOwner\)/)
  assert.doesNotMatch(transport, /URLSession\.shared|document\.cookie|UserDefaults|@AppStorage/)
})

test('one current native Files folder can explicitly share Server ZIP after complete download', () => {
  assert.match(panel, /@StateObject private var folderArchive = XDriveIOSNativeFilesFolderArchiveModel\(\)/)
  assert.match(panel, /Section\("下载文件夹 ZIP"\)/)
  assert.match(panel, /folderArchive\.prepare\(directory, login: login,/)
  assert.match(panel, /ShareLink\(item: archive\.fileURL\)/)
  assert.match(panel, /native-ios-files-folder-zip-download/)
  assert.match(panel, /native-ios-files-folder-zip-share/)
  assert.match(panel, /native-ios-files-folder-zip-cancel/)
  assert.match(panel, /folderArchive\.invalidate\(\)/)
  assert.match(panel, /createBusy \|\| exporter\.busy \|\| folderArchive\.busy \|\| uploader\.busy/)
  assert.match(transport, /URLSessionConfiguration\.ephemeral/)
  assert.match(transport, /FileProtectionType\.complete/)
  assert.match(transport, /prepared\?\.discard\(\)/)
  assert.match(transport, /archive\.discard\(\)/)
  assert.match(transport, /尚未自动保存/)
  assert.match(transport, /取消文件夹 ZIP 下载/)
  assert.match(transport, /for _ in 0\.\.<90/)
  assert.doesNotMatch(transport, /status = "已保存到|\.uploadOnce\(|\.fileImporter\(/)
})
