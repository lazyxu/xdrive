const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')
const page = read('ui', 'shared', 'src', 'mui', 'TaskCenterPage.tsx')
const bg = read('ui', 'shared', 'src', 'mui', 'BackgroundTaskCenter.tsx')
const controller = read('ui', 'shared', 'src', 'mui', 'TaskCenterController.ts')
test('personal and global Server background tasks default to the same reusable card', () => {
  assert.ok(page.includes("useState<'cards' | 'table'>('cards')"))
  assert.ok(page.includes("globalTaskView === 'cards'"))
  assert.ok(page.includes('<XDriveBackgroundTaskList'))
  assert.ok(page.includes('showOwners'))
  assert.ok(page.includes('<XDriveBackgroundTaskTable'))
  assert.ok(page.includes('aria-label="全局后台任务显示方式"'))
  assert.ok(bg.includes('function BackgroundTaskItem('))
  assert.ok(bg.includes('showOwners?: boolean'))
  assert.ok(bg.includes("task.scope === 'system' ? '系统'"))
  assert.ok(bg.includes('<BackgroundTaskControls'))
  assert.ok(bg.includes('<LinearProgress'))
})
test('tasks remain separate owner scope with existing controls and pagination', () => {
  assert.ok(page.includes("scope === 'global' ? '全局后台任务' : '任务'"))
  assert.ok(page.includes('<XDriveTaskHistorySentinel'))
  assert.ok(page.includes('<XDriveFileOperationCenter'))
  assert.ok(page.includes('<XDriveTransferCenter'))
  assert.ok(page.includes('onBackgroundTaskControl'))
  assert.ok(controller.includes("effectiveScope === 'global'"))
  assert.ok(controller.includes('port.loadGlobalPage'))
})
