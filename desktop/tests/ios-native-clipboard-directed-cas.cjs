'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const screen=read('ios/XDriveIOS/NativeClipboardScreen.swift')
const client=read('ios/XDriveIOS/NativeClipboardClient.swift')
const files=read('ios/XDriveIOS/NativeFilesManualUpload.swift')

test('iOS directed Clipboard sends plaintext message, never a public-key envelope',()=>{
  assert.match(client,/struct XDriveIOSClipboardWrite: Encodable/)
  assert.match(client,/let target_device_id: String\?/)
  assert.match(client,/let content: String/)
  assert.match(client,/func send\(_ wire: XDriveIOSClipboardWrite\)/)
  assert.match(client,/wire\.content == "asset:/)
  assert.doesNotMatch(client,/AES\.GCM|X25519|wrapped_key|ephemeral_key|public_key/)
  assert.match(screen,/client\.send\(wire\)/)
})
test('iOS CAS references still use existing Files uploader and verified receipt',()=>{
  assert.match(screen,/\.fileImporter\(isPresented: \$filePickerOpen/)
  assert.match(screen,/XDriveManualDocumentStager\.stage\(selectedURL\)/)
  assert.match(screen,/XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(screen,/XDriveNativeUploadSessionTransport\(/)
  assert.match(screen,/writer\.uploadOnce\(/)
  assert.match(screen,/verifier\.requireCommitted\(/)
  assert.match(files,/^struct XDriveIOSNativeFilesUploadReadback/m)
  assert.match(screen,/referenceNodeID = String\(receipt\.nodeID\)/)
  assert.match(screen,/uploadTask\?\.cancel\(\)/)
})
test('iOS unknown ACK preserves EventID, target, node and Owner fence',()=>{
  assert.match(screen,/previous\.sourceText == payload, previous\.targetID == selected/)
  assert.match(screen,/previous\.kind == kind, previous\.nodeID == nodeID/)
  assert.match(screen,/previous\.wire/)
  assert.match(screen,/elapsed >= 0 && elapsed < 300/)
  assert.match(screen,/XDriveIOSClipboardWrite\(payload, kind: kind/)
  assert.match(screen,/ownerAtOpen == client\.owner/)
  assert.match(screen,/\.onChange\(of: targetID\)/)
})