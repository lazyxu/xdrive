'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = name => fs.readFileSync(path.join(root,name),'utf8')
const crypto = read('ios/XDriveIOS/NativeClipboardDeviceCrypto.swift')
const client = read('ios/XDriveIOS/NativeClipboardClient.swift')
const screen = read('ios/XDriveIOS/NativeClipboardScreen.swift')
const files = read('ios/XDriveIOS/NativeFilesManualUpload.swift')

test('iOS native directed sender uses X25519 HKDF, AES-GCM and exact Owner/target/Node AAD',()=>{
  assert.match(crypto,/static func encryptForDevice\(/)
  assert.match(crypto,/Curve25519\.KeyAgreement\.PrivateKey\(\)/)
  assert.match(crypto,/hkdfDerivedSymmetricKey/)
  assert.match(crypto,/AES\.GCM\.seal/)
  assert.match(crypto,/ephemeral\.publicKey\.rawRepresentation/)
  assert.match(crypto,/context \+ "\|key\|/)
  assert.match(crypto,/context \+ "\|content\|/)
  assert.match(crypto,/node_id: nodeID > 0 \? nodeID : nil/)
  assert.doesNotMatch(crypto,/Server.*(privateKey|rawRepresentation).*POST/)
})
test('iOS public-key directory and targeted sender never use device token as a send grant',()=>{
  assert.match(client,/func devices\(\) async throws/)
  assert.match(client,/func sendDirected\(/)
  assert.match(client,/XDriveIOSNativeClipboardClient\(owner: owner, accessToken: token\)/)
  assert.match(client,/value\.target_device_id == wire\.target_device_id/)
  assert.match(client,/value\.wrapped_key == wire\.wrapped_key/)
  assert.match(client,/value\.node_id == wire\.node_id/)
  assert.doesNotMatch(client,/sendDirected[\s\S]*?deviceProof: deviceProof/)
})
test('iOS manual document enters the existing CAS writer and exact Node/SHA verifier',()=>{
  assert.match(screen,/\.fileImporter\(isPresented: \$localFilePicker/)
  assert.match(screen,/XDriveManualDocumentStager\.stage\(selectedURL\)/)
  assert.match(screen,/XDriveIOSOriginalRunGate\.shared\.acquire\(\)/)
  assert.match(screen,/XDriveNativeUploadSessionTransport\(/)
  assert.match(screen,/writer\.uploadOnce\(/)
  assert.match(screen,/verifier\.requireCommitted\(/)
  assert.match(files,/^struct XDriveIOSNativeFilesUploadReadback/m)
  assert.match(screen,/referenceNodeID = String\(receipt\.nodeID\)/)
  assert.match(screen,/再次点击定向加密发送/)
  assert.match(screen,/uploadTask\?\.cancel\(\)/)
  // No stale CAS Node may cross the image/file authenticated-kind boundary.
  assert.match(screen,/\.onChange\(of: referenceKind\) \{ _ in referenceNodeID = "" \}/)
})
test('iOS original v1 send cannot fall back from directed or replay changed unknown ACK',()=>{
  assert.match(screen,/draft\.isEmpty \|\| !targetID\.isEmpty/)
  assert.match(screen,/targetID\.isEmpty,[\s\S]*?pendingDirected == nil else \{ return \}/)
  assert.match(screen,/prior\.targetID == selected/)
  assert.match(screen,/prior\.kind == kind, prior\.nodeID == nodeID/)
  assert.match(screen,/elapsed >= 0, elapsed < 300/)
  assert.match(screen,/pendingDirected = PendingDirected/)
  assert.match(screen,/client\.sendDirected\(wire\)/)
  assert.match(screen,/pendingDirected = nil/)
  assert.match(screen,/sessionGeneration &\+= 1/)
  assert.match(screen,/\.onChange\(of: login\.owner\) \{ _ in lock\(\) \}/)
})
