'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.resolve(__dirname, '../..', name), 'utf8')
const browser = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const window = read('ios/XDriveIOS/NativeFilesContinuousWindowPolicy.swift')
const range = read('ios/XDriveIOS/NativeCloudFilesPolicy.swift')

test('Files uses one lazy continuous list/grid instead of explicit 64-item page controls', () => {
  assert.doesNotMatch(browser, /private var filesPager|Button\("上一页"\)|Button\("下一页"\)/)
  assert.match(browser, /private var filesContinuousStatus: some View/)
  assert.match(browser, /ForEach\(model\.entries\) \{ entry in[\s\S]*?fileEntryRow\(entry\)[\s\S]*?onAppear \{ requestContinuousNeighbor\(for: entry\.id\) \}/)
  assert.match(browser, /gridTile\(entry\)[\s\S]*?onAppear \{ requestContinuousNeighbor\(for: entry\.id\) \}/)
  assert.match(browser, /if viewMode == "grid" \{[\s\S]*?LazyVGrid\(/)
  assert.match(browser, /func loadAdjacent\(_ direction: XDriveIOSNativeFilesContinuousWindowPolicy\.Direction/)
  assert.match(browser, /model\.loadAdjacent\(\s*\.next/)
  assert.match(browser, /model\.loadAdjacent\(\s*\.previous/)
  assert.match(range, /static let pageSize = 64/)
  assert.match(window, /static let maximumVisibleItems = 4 \* pageSize/)
})

test('each adjacent range is reauthenticated and cannot append stale or overlapped rows', () => {
  assert.match(browser, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(browser, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(browser, /let page = try await reader\.children\(/)
  assert.match(browser, /let page = try await reader\.search\(/)
  assert.match(browser, /self\.adjacentTicket == ticket/)
  assert.match(browser, /self\.entries\.map\(\\\.id\) == oldIDs/)
  assert.match(browser, /self\.total == oldTotal/)
  assert.match(browser, /XDriveIOSNativeFilesContinuousWindowPolicy\.mergePlan\(/)
  assert.match(window, /Set\(currentIDs\)\.isDisjoint\(with: Set\(incomingIDs\)\)/)
  assert.match(window, /total == returnedTotal/)
  assert.match(browser, /self\.adjacentError = "文件列表在滚动期间发生变化，请刷新后继续。"/)
})

test('sliding range preserves Viewer return and bounded selection, and owner/navigation cancellation', () => {
  assert.match(browser, /offset = model\.startOffset \+[\s\S]*?XDriveIOSNativeFilesPagePolicy\.pageSize/)
  assert.match(browser, /model\.cancelAdjacent\(\)\s*selectedOwner = owner/)
  assert.match(browser, /selectedIDs\.count < XDriveIOSNativeFilesBatchTrashPolicy\.maxSelected/)
  assert.match(browser, /selectedIDs\.formUnion\(model\.entries\.filter/)
  assert.match(browser, /\.onChange\(of: login\.owner\) \{ _ in/)
  assert.match(browser, /func invalidate\(\) \{[\s\S]*?cancelAdjacent\(\)/)
  assert.match(browser, /self\.entries = \[\]\s*self\.total = 0\s*self\.verifiedPage = false/)
  assert.match(browser, /\.onDisappear \{ suspendVisibleRange\(\) \}/)
  assert.match(browser, /private func suspendVisibleRange\(\) \{[\s\S]*?guard selectedFile == nil else \{ return \}[\s\S]*?model\.invalidate\(\)/)
})


test('bounded Files window never retains unloaded selected IDs and batch cap matches existing Server', () => {
  assert.match(browser, /\.onChange\(of: model\.entries\.map\(\\\.id\)\) \{ visibleIDs in/)
  assert.match(browser, /selectedIDs\.formIntersection\(visibleIDs\)/)
  assert.match(browser, /XDriveIOSNativeFilesBatchTrashPolicy\.maxSelected -\s*selectedIDs\.count/)
  assert.match(browser, /selectedIDs\.count < XDriveIOSNativeFilesBatchTrashPolicy\.maxSelected/)
  assert.match(window, /static let maximumVisibleItems = 4 \* pageSize/)
  // 4*64 loaded rows, but only 200 selectable for one Server operation.
  assert.doesNotMatch(browser, /XDriveIOSNativeFilesPagePolicy\.pageSize - selectedIDs\.count/)
})

test('Files restores a bounded, verified Node anchor across child navigation and global search', () => {
  assert.match(window, /struct RestoreAnchor: Equatable/)
  assert.match(window, /static func restoreAnchor\(lastAppearedNodeID: UInt64\?, startOffset: Int,/)
  assert.match(window, /startOffset \+ \(index \/ pageSize\) \* pageSize/)
  assert.match(browser, /@State private var lastAppearedNodeID: UInt64\?/)
  assert.match(browser, /@State private var pendingNavigationReturnNodeID: UInt64\?/)
  assert.match(browser, /lastAppearedNodeID = visibleID\s*guard !model\.loadingAdjacent/)
  assert.match(browser, /private func rememberedPosition\([\s\S]*?model\.verifiedPage, !model\.loading/)
  assert.match(browser, /XDriveIOSNativeFilesContinuousWindowPolicy\.restoreAnchor\(/)
  assert.match(browser, /private func suspendVisibleRange\([\s\S]*?offset = saved\.pageOffset\s*pendingNavigationReturnNodeID = saved\.nodeID/)
  assert.match(browser, /model\.entries\.contains\(where: \{ \$0\.id == returnID \}\)/)
  assert.match(browser, /returnScroll\.scrollTo\(returnID, anchor: \.center\)/)
  assert.match(browser, /let saved = rememberedPosition\(\)\s*searchReturnOffset = saved\?\.pageOffset \?\? offset\s*searchReturnNodeID = saved\?\.nodeID/)
  assert.match(browser, /pendingNavigationReturnNodeID = restoreNodeID\s*reload\(\)/)
  assert.match(browser, /searchReturnNodeID = nil\s*lastAppearedNodeID = nil\s*pendingNavigationReturnNodeID = nil/)
  assert.doesNotMatch(browser, /\.onDisappear \{ if selectedFile == nil \{ model\.invalidate\(\) \} \}/)
})
