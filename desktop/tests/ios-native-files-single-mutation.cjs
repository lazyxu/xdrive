'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const s = read('ios/XDriveIOS/NativeFilesSingleMutation.swift')
const view = read('ios/XDriveIOS/NativeCloudFilesBrowser.swift')
const go = read('internal/api/handlers.go')

test('single File rename and trash use only genuine current-Owner Node REST with If-Match revision', () => {
  assert.match(s, /login\.verifiedAuthorization\(\)/)
  assert.match(s, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, expected\)/)
  assert.match(s, /XDriveIOSNativePhotoOwnerScope\.matches\(verified\.owner, expected\)/)
  assert.match(s, /URLSessionConfiguration\.ephemeral/)
  assert.match(s, /completionHandler\(nil\)/)
  assert.match(s, /request\.setValue\("\\"\\\(revision\)\\"", forHTTPHeaderField: "If-Match"\)/)
  assert.match(s, /current == node/)
  assert.match(s, /request\.httpMethod = method/)
  assert.match(s, /method: "PATCH", revision: node\.revision, name: name/)
  assert.match(s, /method: "DELETE", revision: node\.revision/)
  assert.match(s, /checkedResponse\(response, accepted: 200\)/)
  assert.match(s, /checkedResponse\(response, accepted: 204\)/)
  assert.match(go, /func \(s \*Server\) updateNode\(c \*gin\.Context\)/)
  assert.match(go, /func \(s \*Server\) deleteNode\(c \*gin\.Context\)/)
  assert.match(go, /revisionConflict\(c, expected/)
})
test('real file detail actions guard stale writes and report uncertainty on cancellation', () => {
  assert.match(view, /Label\("原生只读预览", systemImage: "eye"\)/)
  assert.match(view, /Button\("重命名文件"\)/)
  assert.match(view, /Button\("移入回收站", role: \.destructive\)/)
  assert.match(view, /\.confirmationDialog\("将“/)
  assert.match(view, /mutator\.perform\(node: entry\.node, kind: \.trash,/)
  assert.match(view, /mutator\.perform\(node: entry\.node, kind: \.rename\(renameDraft\),/)
  assert.match(view, /mutator\.invalidate\(\)/)
  assert.match(s, /status = "文件操作结果未确认，请刷新核对后再操作。"/)
  assert.doesNotMatch(s, /localStorage|WKWebView\s*\(|\/api\/v1\/file-operations/)
})
