'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '../..', p), 'utf8')
const panel = read('ios/XDriveIOS/NativeFilesManagementPanel.swift')
const native = read('ios/XDriveIOS/NativeFilesSingleMutation.swift')
const go = read('internal/api/handlers.go')

test('native Files rename/trash require current exact Node, If-Match and real Server ACK', () => {
  assert.match(panel, /Button\("重命名文件"\)/)
  assert.match(panel, /Button\("移入回收站", role: \.destructive\)/)
  assert.match(panel, /\.confirmationDialog\(/)
  assert.match(panel, /mutator\.perform\(node: file, kind: \.rename\(renameDraft\)/)
  assert.match(panel, /mutator\.perform\(node: file, kind: \.trash/)
  assert.match(native, /let auth = try await login\.verifiedAuthorization\(\)/)
  assert.match(native, /guard epoch == ticket/)
  assert.match(native, /guard body\.count <= 65_536,[\s\S]*?current == node/)
  assert.match(native, /forHTTPHeaderField: "If-Match"/)
  assert.match(native, /method: "PATCH", revision: node\.revision, name: name/)
  assert.match(native, /method: "DELETE", revision: node\.revision/)
  assert.match(native, /checkedResponse\(response, accepted: 200\)/)
  assert.match(native, /checkedResponse\(response, accepted: 204\)/)
  assert.match(native, /status = "文件操作结果未确认，请刷新核对后再操作。"/)
  assert.match(go, /func \(s \*Server\) updateNode\(c \*gin\.Context\)/)
  assert.match(go, /func \(s \*Server\) deleteNode\(c \*gin\.Context\)/)
})
