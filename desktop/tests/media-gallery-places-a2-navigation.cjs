const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')

test('P0-Places-A2 Gallery has a shared map entry on Web/Mobile/Desktop', () => {
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  assert.match(gallery, /data-xdrive-gallery-show-map/)
  assert.match(gallery, /onShowMap=\{onShowMap && \(mobileCollectionsOverview/)
  const mobile = read('ui/shared/src/mui/MobileGalleryChrome.tsx')
  assert.match(mobile, /data-xdrive-mobile-gallery-show-map/)
  assert.match(mobile, /onShowMap\(\)/)
  assert.match(gallery, /selectSection\('places'\)/)
  assert.match(gallery, /onShowMap=\{\(\) => \{/)
  assert.match(gallery, /<XDriveMediaGalleryPlacesMap/)
  assert.match(gallery, /onOpenPlace=\{onOpenPlace\}/)
  assert.match(gallery, /useXDriveVirtualCollection<MediaItem>/)
})
test('P0-Places-A2 place return keeps a bounded page and real place selection', () => {
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const map = read('ui/shared/src/mui/MediaGalleryPlacesMap.tsx')
  assert.match(gallery, /placesReturnPageRef/)
  assert.match(gallery, /retainedPlacePage \? Promise.resolve/)
  assert.match(gallery, /setPlacesPageOffset\(retainedPlacePage\?\.offset \?\? 0\)/)
  assert.match(gallery, /setLastOpenedPlaceID\(place.id\)/)
  assert.match(map, /focusPlaceID/)
  assert.match(gallery, /data-xdrive-places-return-anchor/)
  assert.match(gallery, /scrollIntoView/)
  assert.match(gallery, /placeOpenedFromCollectionsRef/)
  assert.match(gallery, /\[preferenceScope\]/)
})
test('P0-Places-A2 Viewer map is one Server-backed dialog in desktop and routed Web', () => {
  const dialog = read('ui/shared/src/mui/MediaGalleryViewerLocationDialog.tsx')
  const desktop = read('ui/shared/src/mui/MediaGalleryViewer.tsx')
  const web = read('web/src/WebFileViewerApps.tsx')
  const staticMap = read('ui/shared/src/mui/MediaGalleryBaiduStaticMap.tsx')
  assert.match(desktop, /<XDriveMediaGalleryViewerLocationDialog/)
  assert.match(web, /<XDriveMediaGalleryViewerLocationDialog/)
  assert.match(web, /MenuItem aria-label="在地图上查看照片"/)
  assert.match(dialog, /loadStaticMap=\{loadBaiduStaticMap\}/)
  assert.match(dialog, /Number\.isFinite\(latitude\)/)
  assert.match(staticMap, /location\?\.latitude \?\?/)
  assert.doesNotMatch(dialog, /(?:api\.map\.baidu\.com|[?&]ak=|<iframe)/)
})
