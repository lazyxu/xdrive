'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.resolve(__dirname, '../..', name), 'utf8')

test('all React browser Hosts use exactly one canonical route main surface', () => {
  const component = read('ui/shared/src/mui/WorkspaceRouteSurface.tsx')
  const desktopDsm = read('ui/shared/src/mui/XDriveAppRouteContent.tsx')
  const web = read('web/src/App.tsx')
  const registry = read('ui/shared/src/mui/WorkspaceRoute.ts')
  const barrel = read('ui/shared/src/mui/index.tsx')

  assert.match(component, /export function XDriveWorkspaceRouteSurface/)
  assert.match(component, /view: XDriveWorkspaceAppRoute/)
  assert.match(component, /<XDriveWorkspaceContent\s+responsive\s+presentation=\{xDriveWorkspacePresentation\(view\)\}/)
  assert.match(registry, /return view === 'files' \? 'files' : 'page'/)
  assert.match(barrel, /export \* from '\.\/WorkspaceRouteSurface'/)
  assert.match(desktopDsm, /<XDriveWorkspaceRouteSurface\s+view=\{view\}/)
  assert.match(web, /<XDriveWorkspaceRouteSurface\s+view=\{appView\}/)
  assert.doesNotMatch(desktopDsm, /<XDriveWorkspaceContent\b/)
  assert.equal((web.match(/<XDriveWorkspaceRouteSurface\b/g) || []).length, 1)
  assert.match(web, /overflowAnchor: appView === 'gallery' \? 'none' : undefined/)
  assert.match(desktopDsm, /sx=\{view === 'files' \? undefined : pageSx\}/)
})

test('Web keeps immersive Viewer, PWA and Owner runtime outside the canonical main', () => {
  const web = read('web/src/App.tsx')
  const frame = read('ui/shared/src/mui/WorkspaceShell.tsx')
  const component = read('ui/shared/src/mui/WorkspaceRouteSurface.tsx')
  assert.match(web, /<XDriveWorkspaceFrame\b/)
  assert.match(web, /<XDriveCommittedWorkspaceRoute view=\{appView\}/)
  assert.match(web, /xDriveWebAppViewer\(route\.app\)/)
  assert.match(web, /data-xdrive-pwa-upload-resume-picker/)
  assert.match(web, /xDriveAcquireViewerForeground/)
  assert.match(frame, /<XDriveWorkspaceShell responsive/)
  assert.doesNotMatch(component, /window\.|localStorage|fetch\s*\(|xdriveDesktop|navigator\./)
})
