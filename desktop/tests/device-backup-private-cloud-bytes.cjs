const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('owning Agent real CAS sample stays bounded, private and non-authoritative', () => {
  const router = read('internal', 'api', 'router.go')
  const contract = read('internal', 'api', 'router_contract_test.go')
  const observer = read('internal', 'api', 'local_source_item_evidence_cloud_bytes.go')
  const metadata = read('internal', 'api', 'local_source_item_evidence_cloud_metadata.go')
  const apiTests = read('internal', 'api', 'local_source_item_evidence_cloud_metadata_integration_test.go')
  const client = read('internal', 'client', 'local_source_item_evidence_cloud_bytes.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_preflight.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(router, /evidence-cloud-bytes", s\.requireLocalSourceExecutor\(\), s\.readLocalSourceEvidenceCloudBytes/)
  assert.match(contract, /POST", path: "\/api\/v1\/sources\/:id\/local-identity\/evidence-cloud-bytes"/)
  assert.match(observer, /validLocalEvidencePhysicalCASBatch\(input\.Items\)/)
  assert.match(observer, /localEvidencePhysicalCASLimitItems = 4/)
  assert.match(observer, /localEvidencePhysicalCASLimitBytes = int64\(64 << 20\)/)
  assert.match(observer, /localEvidencePhysicalCASDeadline\s+= 90 \* time\.Second/)
  assert.match(observer, /io\.CopyBuffer\(hash,/)
  assert.match(observer, /make\(\[\]byte, 256<<10\)/)
  assert.match(observer, /for _, object := range objects/)
  assert.match(observer, /verifyPhysicalEvidenceCAS\(readCtx, s\.Store, object\)/)
  assert.equal((observer.match(/s\.checkLocalEvidenceCloudMetadata\(/g) || []).length, 2)
  assert.match(observer, /CloudBytesVerified: false, ContentVerified: false/)
  assert.match(observer, /CommitSupported: false, Authoritative: false, MissingInferenceSafe: false/)
  assert.doesNotMatch(observer, /\btx\.\w+\(|UploadChunk|BeginSourceRun|CommitSourceItem|MirrorDeletion/)
  assert.match(metadata, /s\.requireLocalSourceProofTx\(tx, c, sourceID, "", false\)/)
  assert.match(metadata, /JOIN xd_file_versions AS v/)
  assert.match(metadata, /JOIN xd_content_blobs AS b/)
  assert.match(apiTests, /sendPhysical\(ownerJWT, clone\(\), sample, http\.StatusConflict\)/)
  assert.match(apiTests, /sendPhysical\(ownerJWT, clone\(\), original, http\.StatusConflict\)/)
  assert.match(client, /CheckLocalSourceItemCloudBytes\(/)
  assert.match(client, /CheckLocalSourceItemCloudBytesBatch\(/)
  assert.match(client, /decoder\.DisallowUnknownFields\(\)/)
  assert.match(client, /got\.CloudBytesVerified \|\| got\.ContentVerified/)
  assert.match(agent, /cli\.CheckLocalSourceItemCloudBytesBatch\(/)
  assert.match(agent, /result\.PhysicalCASObservedFiles = len\(samples\)/)
  assert.match(agent, /total \+= claim\.Size/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.doesNotMatch(ipc, /evidence-cloud-bytes|CheckLocalSourceItemCloudBytes/)
  assert.doesNotMatch(preload, /evidence-cloud-bytes|CheckLocalSourceItemCloudBytes/)
  assert.doesNotMatch(web, /evidence-cloud-bytes|CheckLocalSourceItemCloudBytes/)
})
