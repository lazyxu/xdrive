'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')
const read = (rel) => readFileSync(path.join(root, rel), 'utf8')

test('OBS-P002 is off the HTTP request hot path and reuses the existing sampler', () => {
  const perRequest = read('internal/api/observability.go')
  const sampler = read('internal/api/storage_history.go')
  const route = read('internal/api/router.go')
  const window = read('internal/api/storage_performance_window.go')
  assert.doesNotMatch(perRequest, /recordStoragePerformanceSample|snapshotRecentStoragePerformance|storagePerformanceWindow/)
  assert.match(sampler, /func \(s \*Server\) StartStorageSampler\(ctx context\.Context\)/)
  assert.match(sampler, /time\.NewTicker\(storagePerformancePeriod\)/)
  assert.match(sampler, /case <-ctx\.Done\(\)/)
  assert.match(sampler, /s\.recordStoragePerformanceSample\(now\.UTC\(\)\)/)
  assert.match(route, /storagePerformanceSamples\s+storagePerformanceSampleRing/)
  assert.match(window, /storagePerformanceSampleSlot = 7/)
  assert.match(window, /storagePerformanceWindow\s+= 5 \* time\.Minute/)
  assert.match(window, /s\.obs\.httpRequests/)
  assert.doesNotMatch(window, /\.WalkDir\(|\.Create\(|\.Exec\(|\.Find\(|http\.Get\(|setInterval\(/)
})

test('OBS-P002 recent rates and actual coverage are admin-only and shared on Web and Desktop', () => {
  const api = read('internal/api/storage_intelligence.go')
  const router = read('internal/api/router.go')
  const ui = read('ui/shared/src/mui/GlobalStorageStatsPage.tsx')
  const ts = read('ui/shared/src/models.ts')
  const web = read('web/src/StorageStatsPanel.tsx')
  const desktop = read('desktop/src/renderer/App.tsx')
  assert.match(router, /admin := authed\.Group\("\/admin"\)[\s\S]*?admin\.Use\(s\.requireAdmin\(\)\)/)
  assert.match(router, /admin\.GET\("\/storage", s\.adminStorageStats\)/)
  assert.match(api, /stats\.RecentPerformance = s\.snapshotRecentStoragePerformance\(time\.Now\(\)\.UTC\(\)\)/)
  assert.match(api, /json:"recent_performance,omitempty"/)
  assert.match(ts, /recent_performance\?: StorageRecentPerformance/)
  assert.match(ui, /stats\.recent_performance\?\.available/)
  assert.match(ui, /window_seconds\.toLocaleString\(\)/)
  assert.match(ui, /requests_per_second\.toFixed\(2\)/)
  assert.match(ui, /尚在积累/)
  assert.match(web, /@xdrive\/ui\/mui/)
  assert.match(desktop, /XDriveGlobalStorageStatsPage/)
  assert.doesNotMatch(ui, /setInterval\(|new Worker\(/)
})
