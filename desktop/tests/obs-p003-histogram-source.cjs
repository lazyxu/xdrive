'use strict'
const {test}=require('node:test')
const assert=require('node:assert/strict')
const {readFileSync}=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=name=>readFileSync(path.join(root,name),'utf8')

test('OBS-P003 always-on histogram uses EXISTING request mutex with fixed anonymous routes and no I/O',()=>{
  const obs=read('internal/api/observability.go')
  const hist=read('internal/api/storage_performance_histogram.go')
  const sample=read('internal/api/storage_performance_window.go')
  const boundary=read('internal/api/storage_performance_observation.go')
  assert.match(obs,/o\.mu\.Lock\(\)/)
  assert.match(obs,/storagePerformanceCategory\(method, route\)/)
  assert.match(obs,/storageP003BucketForDuration\(duration\)/)
  assert.match(obs,/o\.p003Histogram\.bins\[category\]\[bucket\]\+\+/)
  assert.doesNotMatch(hist,/sync\.Mutex|new\(sync|\.Exec\(|\.Find\(|\.WalkDir\(|http\.Get\(|\buserID\(|\bclientIP/)
  assert.match(hist,/storageP003BucketCount = 25/)
  assert.match(boundary,/storagePerformanceKeys = \[\.\.\.\]string/)
  assert.match(sample,/histogram \[len\(storagePerformanceKeys\)\]\[storageP003BucketCount\]uint64/)
  assert.match(sample,/storageP003QuantileUpperMS\(delta, total, 95\)/)
  assert.match(sample,/storageP003QuantileUpperMS\(delta, total, 99\)/)
})

test('OBS-P003 only authorized shared MUI Global Storage displays honest upper bucket endpoints',()=>{
  const ui=read('ui/shared/src/mui/GlobalStorageStatsPage.tsx')
  const ts=read('ui/shared/src/models.ts')
  const router=read('internal/api/router.go')
  assert.match(ui,/scope === 'global' && stats\.performance/)
  assert.match(ui,/recent\?\.p95_upper_ms/)
  assert.match(ui,/recent\?\.p99_upper_ms/)
  assert.match(ui,/≤ \$\{recent\.p95_upper_ms/)
  assert.match(ui,/超过最大桶界限/)
  assert.match(ts,/p95_upper_ms\?: number/)
  assert.match(ts,/p99_upper_ms\?: number/)
  assert.match(router,/admin := authed\.Group\("\/admin"\)[\s\S]*?admin\.Use\(s\.requireAdmin\(\)\)/)
  assert.doesNotMatch(ui,/setInterval\(|new Worker\(/)
  assert.match(read('docs/performance-test-registry.md'),/OBS-P003/)
  assert.match(read('docs/performance-platform-coverage.md'),/OBS-P003/)
})
