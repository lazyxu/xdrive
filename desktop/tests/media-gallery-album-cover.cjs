const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (filename) => fs.readFileSync(path.join(root, filename), 'utf8')

test('G04 manual cover is an owner-scoped, revision-fenced Server album setting', () => {
  const meta = read('internal/meta/photo.go')
  const handler = read('internal/api/media_album_cover.go')
  const router = read('internal/api/router.go')
  const api = read('internal/api/media.go')
  const readOne = read('internal/api/media_manual_albums.go')
  assert.match(meta, /PreferredCoverNodeID \*uint64/)
  assert.match(router, /PUT\("\/media\/albums\/:albumID\/cover"/)
  assert.match(read('internal/api/router_contract_test.go'),
    /method: "PUT", path: "\/api\/v1\/media\/albums\/:albumID\/cover"/)
  assert.match(handler, /expectedRevision\(c\)/)
  assert.match(handler, /meta\.PhotoCollectionKindManual/)
  assert.match(handler, /pa\.owner_id = \?/)
  assert.match(handler, /n\.deleted_at IS NULL/)
  assert.match(handler, /pca\.collection_id = \? AND pa\.primary_node_id = \?/)
  assert.match(handler, /errRevisionConflict/)
  assert.match(handler, /preferred_cover_node_id/)
  assert.match(api, /pc\.preferred_cover_node_id/)
  assert.match(readOne, /pc\.preferred_cover_node_id/)
  const integration = read('internal/api/media_manual_albums_integration_test.go')
  assert.match(integration, /custom album cover/)
  assert.match(integration, /automatic album cover/)
  assert.match(integration, /http\.StatusConflict/)
})

test('G04 album cover uses existing Web/Desktop media membership and Viewer surfaces', () => {
  const client = read('internal/client/media.go')
  const cloud = read('cmd/xdrive-agent/cloud_files.go')
  const ipc = read('cmd/xdrive-agent/desktop_ipc.go')
  const agent = read('desktop/src/main/agent_client.cts')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const renderer = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const sharedAdapter = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const web = read('web/src/api.ts')
  const webAdapter = read('web/src/mediaGalleryAdapter.ts')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  assert.match(client, /SetMediaAlbumCover/)
  assert.match(cloud, /CloudSetMediaAlbumCover/)
  assert.match(ipc, /setMediaAlbumCover/)
  assert.match(agent, /setMediaAlbumCover/)
  assert.match(main, /agent:set-media-album-cover/)
  assert.match(preload, /agent:set-media-album-cover/)
  assert.match(renderer, /setAlbumCover/)
  assert.match(sharedAdapter, /setAlbumCover\?:/)
  assert.match(sharedAdapter, /port\.setAlbumCover!\(albumID, revision, nodeID\)/)
  assert.match(web, /setMediaAlbumCover/)
  assert.match(webAdapter, /setAlbumCover/)
  assert.match(gallery, /onChooseCollectionCover/)
  assert.match(gallery, /恢复自动封面/)
  assert.match(gallery, /replaceAlbum\(updated\)/)
  assert.doesNotMatch(gallery, /new Array\(virtualCollection\.itemCount\)/)
})
