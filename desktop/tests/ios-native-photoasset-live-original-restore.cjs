'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const viewer = read('ios/XDriveIOS/NativeServerMediaGallery.swift')
const transport = read('ios/XDriveIOS/NativeServerMediaGalleryTransport.swift')
const filePreview = read('internal/api/file_preview.go')
const mediaAPI = read('internal/api/media.go')
const detail = viewer.slice(
  viewer.indexOf('struct XDriveIOSNativeServerMediaPreview: View'),
  viewer.indexOf('/// Root and album-specific media wall')
)
const live = transport.slice(transport.indexOf('/// Read-only native PhotoAsset Live playback.'))
const importBody = detail.slice(detail.indexOf('private func restorePhotoAssetOriginal()'),
  detail.indexOf('@MainActor\n    private func playbackLoadFailed'))

test('one explicit add-only action imports BOTH verified Live Photo originals', () => {
  assert.match(detail, /native-ios-photoasset-original-save-to-photos/)
  assert.match(detail, /PHPhotoLibrary\.requestAuthorization\(for: \.addOnly\)/)
  assert.match(detail, /guard !photosRestoreBusy, ownerAuthorized,\s*viewed\.supportsPreview/)
  assert.match(importBody, /if selected\.isLive \{[\s\S]*?reader\.livePreview\(selected\)/)
  assert.match(importBody, /asset\.addResource\(\s*with: \.photo, fileURL: verified\.files\.stillURL, options: nil/)
  assert.match(importBody, /asset\.addResource\(\s*with: \.pairedVideo, fileURL: verified\.files\.motionURL, options: nil/)
  assert.match(importBody, /defer \{ verified\.files\.discard\(\) \}/)
  assert.match(importBody, /let originalURL = try await reader\.downloadOriginalForPhotos\(selected\)/)
  assert.match(importBody, /selected\.isVideo \? \.video : \.photo/)
  assert.doesNotMatch(importBody, /thumbnail\(|saveToCameraRoll|onlyStill/)
})

test('native Live original reader authenticates before and after paired downloads', () => {
  assert.match(live, /let before = try await currentLiveItem\(selected\.id\)/)
  assert.match(live, /guard sameLiveSource\(before, selected\)/)
  assert.match(live, /let after = try await currentLiveItem\(selected\.id\)/)
  assert.match(live, /guard sameLiveSource\(before, after\)/)
  assert.match(live, /let mode = try liveMode\(before\)/)
  assert.match(live, /func downloadLiveResource\(/)
  assert.match(live, /let stillURL = directory\.appendingPathComponent\("still\." \+ stillExt\)/)
  assert.match(live, /let motionURL = directory\.appendingPathComponent\("motion\." \+ motionExt\)/)
  assert.match(live, /try await downloadLiveResource\(stillKind, destination: stillURL/)
  assert.match(live, /try await downloadLiveResource\(motionKind, destination: motionURL/)
  assert.match(live, /try\? manager\.removeItem\(at: directory\)/)
  assert.match(live, /signedLiveURL\(ticket, path: streamPath, kind: kind\)/)
})

test('Server streams original file bytes for paired still and exact LIVP byte ranges', () => {
  const stream = filePreview.slice(filePreview.indexOf('func (s *Server) filePreviewTicketStream('))
  assert.match(stream, /node\.Revision != claims\.NodeRevision/)
  assert.match(stream, /s\.serveFilePreview\(c, node, descriptor\)/)
  assert.match(stream, /s\.Store\.Open\(c\.Request\.Context\(\), node\.File\.StorageKey\)/)
  assert.match(stream, /http\.ServeContent\(c\.Writer, c\.Request, node\.Name, node\.File\.UpdatedAt, file\)/)
  assert.match(mediaAPI, /func \(s \*Server\) mediaLivePhotoStillTicketStream\(/)
  assert.match(mediaAPI, /mediaLivePhotoStillPreviewKind/)
  assert.match(mediaAPI, /func \(s \*Server\) serveMediaLivePhotoMotion\(/)
  assert.match(mediaAPI, /descriptor\.Resource\.ByteOffset/)
  assert.match(mediaAPI, /descriptor\.Resource\.ByteSize/)
  assert.match(mediaAPI, /descriptor\.MotionNode\.File\.StorageKey/)
  assert.match(mediaAPI, /io\.NewSectionReader\(/)
})

test('Viewer Owner, exact media revision and scene cancellation fence Live import', () => {
  assert.match(detail, /viewed\.isLive == selected\.isLive/)
  assert.match(detail, /viewed\.sameVisibleRevision\(as: selected\)/)
  assert.match(detail, /XDriveIOSNativePhotoOwnerScope\.matches\(auth\.owner, owner\)/)
  assert.match(detail, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, owner\)/)
  assert.match(importBody, /guard canCommitPhotosRestore\(selected, owner: owner, epoch: epoch\)/)
  assert.match(detail, /photosRestoreTask\?\.cancel\(\)/)
  assert.match(detail, /\.onDisappear \{ cancelPhotosRestore\(\) \}/)
  assert.match(detail, /if phase != \.active &&[\s\S]*?phase == \.background \|\| !photosPermissionPrompt/)
  assert.doesNotMatch(importBody, /uploadSession|ledger\.write|markConfirmed|deleteCloud/)
})
