'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.resolve(__dirname, '../..', p), 'utf8')
const album = read('ios/XDriveIOS/NativeOwnerMapClusterAlbum.swift')
const policy = read('ios/XDriveIOS/NativePhotoAssetRangeCursorPolicy.swift')
const transport = read('ios/XDriveIOS/NativeServerMediaGalleryTransport.swift')
const viewer = read('ios/XDriveIOS/NativeServerMediaGallery.swift')

test('Owner cloud map cluster Viewer crosses the exact adjacent 48-photo Range only within the selected real place', () => {
  assert.match(album, /onCrossRange: \{ previous, anchor, direction in/)
  assert.match(album, /current\.sameVisibleSnapshot\(as: previous\)/)
  assert.match(album, /previous\.offset == cursor\.offset/)
  assert.match(album, /selection\.places\.indices\.contains\(cursor\.placeIndex\)/)
  assert.match(album, /previous\.items\.firstIndex\(where: \{[\s\S]*?sameVisibleRevision\(as: anchor\)/)
  assert.match(album, /XDriveIOSNativePhotoAssetRangeCursorPolicy\.adjacentOffset\(/)
  assert.match(album, /targetCursor = XDriveIOSOwnerClusterCursor\(\s*placeIndex: currentCursor\.placeIndex, offset: targetOffset\)/)
  assert.match(album, /XDriveIOSNativeOwnerMapSelectionPolicy\.canOpenPhotoRange\(facet\)/)
  assert.match(album, /previous\.total_count == facet\.item_count/)
  assert.match(album, /login\.verifiedAuthorization\(\)/)
  assert.match(album, /XDriveIOSNativePhotoOwnerScope\.matches\(\s*authorized\.owner, selection\.owner/)
  assert.match(album, /reader\.page\(\s*offset: currentCursor\.offset, placeID: facet\.id\)/)
  assert.match(album, /previous\.sameVisibleSnapshot\(as: reread\)/)
  assert.match(album, /reader\.page\(\s*offset: targetOffset, placeID: facet\.id\)/)
  assert.match(album, /following\.total_count == facet\.item_count/)
  assert.match(album, /XDriveIOSNativePhotoAssetRangeCursorPolicy\.validPage\(/)
  assert.match(album, /Set\(following\.items\.map\(\\\.id\)\)\.count == following\.items\.count/)
  assert.match(album, /pendingViewerCross = targetCursor/)
  assert.match(policy, /guard selectedIndex == count - 1, current < total - count/)
  assert.match(policy, /guard selectedIndex == 0, current >= pageSize/)
  assert.doesNotMatch(album, /map-region:q:|URLSession\(|UploadSession|isNetworkAccessAllowed = true/)
})

test('Owner cloud map Viewer accepts returned page only for pending cursor under same Owner and restores album page after dismissal', () => {
  assert.match(album, /onCrossedRange: \{ opened, verifiedRange in/)
  assert.match(album, /let oldPage = page, let admitted = pendingViewerCross/)
  assert.match(album, /admitted\.placeIndex == cursor\.placeIndex/)
  assert.match(album, /admitted\.offset == verifiedRange\.offset/)
  assert.match(album, /abs\(verifiedRange\.offset - oldPage\.offset\) ==\s*XDriveIOSNativePhotoAssetRangeCursorPolicy\.pageSize/)
  assert.match(album, /verifiedRange\.items\.contains\(where: \{[\s\S]*?sameVisibleRevision\(as: opened\)/)
  assert.match(album, /if admitted\.offset > cursor\.offset \{\s*earlier\.append\(cursor\)/)
  assert.match(album, /else if earlier\.last == admitted \{\s*earlier\.removeLast\(\)/)
  assert.match(album, /cursor = admitted\s*page = verifiedRange/)
  assert.match(album, /coverTask\?\.cancel\(\)\s*coverImages = \[:\]/)
  assert.match(album, /onDismiss: \{\s*pendingViewerCross = nil[\s\S]*?load\(cursor, history: earlier\)/)
  assert.match(album, /private func invalidate\(\) \{[\s\S]*?pendingViewerCross = nil/)
  assert.match(transport, /func sameVisibleSnapshot\(as rhs: Self\)/)
  assert.match(viewer, /onCrossRange: \(\([\s\S]*?onCrossedRange:/)
  assert.doesNotMatch(album, /cacheAllPhotos|UserDefaults|localStorage|POST/)
})
