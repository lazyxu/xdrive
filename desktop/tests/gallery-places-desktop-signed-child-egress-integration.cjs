'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root,p),'utf8')

test('real secure BrowserWindow consumes Agent verified signed-release Child Origin, never Renderer URL',()=>{
  const main = read('desktop/src/main/index.cts')
  const policy = read('desktop/src/main/baidu_map_child_resource_policy.cts')
  const agent = read('desktop/src/main/agent_client.cts')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  assert.match(agent,/mediaBaiduJSAPI4Release\(signal\?: AbortSignal\)/)
  assert.match(main,/const released = await requireAgentClient\(\)\.mediaBaiduJSAPI4Release\(\)/)
  assert.match(main,/xDriveReleasedBaiduChildOrigin\(released, target\.origin\)/)
  assert.match(main,/if \(!releasedOrigin \|\| !sameOwner\(\)\)/)
  assert.match(main,/secureBaiduMapChildOrigin === childOrigin/)
  assert.match(main,/const childOrigin = releasedOrigin/)
  assert.match(main,/xDriveBaiduReleasedChildResourceAllowed\(details\.url, childOrigin\)/)
  assert.match(main,/details\.resourceType !== 'subFrame'/)
  assert.match(main,/Date\.now\(\) - releaseVerifiedAt < 3000/)
  assert.match(main,/inflightReleaseCheck = verifyChildRelease\(\)/)
  assert.match(main,/releaseRevoked = true/)
  assert.match(main,/secureBaiduMapChildOrigin = null/)
  assert.match(main,/secureBaiduMapWindowOwner === ownerName/)
  assert.match(main,/!secureBaiduMapWindowDenied && sameOwner\(\)/)
  assert.match(main,/secureBaiduMapOpenGeneration\+\+/)
  assert.match(main,/openGeneration !== secureBaiduMapOpenGeneration/)
  assert.match(main,/const revokeWindow = \(\): false =>/)
  assert.match(main,/secureBaiduMapWindowDenied = true/)
  assert.match(main,/windowID = win\.webContents\.id/)
  assert.match(main,/secureBaiduMapWindow !== win \|\| !sameOwner\(\)/)
  assert.match(policy,/Object\.keys\(serverRelease\)\.length !== releaseFields\.size/)
  assert.match(gallery,/onOpenSecureDesktopMap\(entry.scope\)/)
  // Map-only Child cannot use any arbitrary third-party URL or a false
  // "insecure content" override. Parent remains independently authenticated.
  assert.doesNotMatch(main,/allowRunningInsecureContent: true|BaiduBrowserAK|unsafeChildHost/)
  assert.doesNotMatch(read('desktop/src/preload/baidu_map_secure.cts'),
    /mediaBaiduJSAPI4Release|xDriveReleasedBaiduChildOrigin/)
})
