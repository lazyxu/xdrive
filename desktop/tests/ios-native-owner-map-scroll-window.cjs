'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const album = fs.readFileSync(path.resolve(__dirname, '../../ios/XDriveIOS/NativeOwnerMapClusterAlbum.swift'), 'utf8')

test('native Owner map cluster only auto-pages at a visible LazyVGrid foot after a user drag', () => {
  assert.match(album, /LazyVGrid\(columns: columns, spacing: 2\) \{[\s\S]*?if let next \{\s*Color\.clear/)
  assert.match(album, /\.onAppear \{ scrollFootVisible = true \}/)
  assert.match(album, /\.onDisappear \{ scrollFootVisible = false \}/)
  assert.match(album, /\.simultaneousGesture\(\s*DragGesture\(minimumDistance: 12\)\.onEnded/)
  assert.match(album, /guard gesture\.translation\.height <= -12,[\s\S]*?scrollFootVisible, activeOwner, !busy,\s*viewing == nil, page != nil, let next else \{ return \}/)
  assert.match(album, /load\(next, history: earlier \+ \[cursor\],\s*autoAdvance: true\)/)
  assert.match(album, /private func load\(_ target: XDriveIOSOwnerClusterCursor,[\s\S]*?autoAdvance: Bool = false/)
  assert.doesNotMatch(album, /onAppear \{\s*load\(next|Timer\.scheduledTimer|URLSession\(|cacheAllPhotos/)
})

test('auto-scrolling keeps exactly one previous and one current signed 48-photo window', () => {
  assert.match(album, /@State private var priorWindow: XDriveIOSNativeMediaRange\?/)
  assert.match(album, /@State private var priorWindowCursor: XDriveIOSOwnerClusterCursor\?/)
  assert.match(album, /ForEach\(priorWindow\.items\) \{ item in\s*photoTile\(item, from: priorWindow\)/)
  assert.match(album, /ForEach\(page\.items\) \{ item in\s*photoTile\(item, from: page\)/)
  assert.match(album, /let departingPage = page\s*let departingCursor = cursor/)
  assert.match(album, /if autoAdvance, let departingPage,\s*history\.last == departingCursor,\s*target != departingCursor/)
  assert.match(album, /priorWindow = departingPage\s*priorWindowCursor = departingCursor/)
  assert.match(album, /let admitted = Set\(\s*departingPage\.items\.map\(\\\.id\) \+ fetched\.items\.map\(\\\.id\)/)
  assert.match(album, /coverImages = coverImages\.filter \{\s*admitted\.contains\(\$0\.key\)/)
  assert.match(album, /priorWindow = nil\s*priorWindowCursor = nil\s*coverImages = \[:\]/)
  assert.match(album, /private func invalidate\(\) \{[\s\S]*?scrollFootVisible = false/)
  assert.doesNotMatch(album, /UserDefaults\.|UploadSession|isNetworkAccessAllowed = true/)
})

