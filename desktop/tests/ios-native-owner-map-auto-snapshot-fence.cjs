'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8')
const album = read('ios/XDriveIOS/NativeOwnerMapClusterAlbum.swift')
const transport = read('ios/XDriveIOS/NativeServerMediaGalleryTransport.swift')
const load = album.slice(album.indexOf('    private func load('))

test('map cluster auto-append re-verifies its previous exact Owner place Range before reading the next', () => {
  assert.match(load, /if autoAdvance \{\s*\/\/ A stable item count/)
  assert.match(load, /guard let departingPage,\s*history\.last == departingCursor,\s*target != departingCursor/)
  assert.match(load, /selection\.places\.indices\.contains\(departingCursor\.placeIndex\)/)
  assert.match(load, /departingPage\.offset == departingCursor\.offset/)
  assert.match(load, /XDriveIOSNativePhotoAssetRangeCursorPolicy\.validPage\(\s*offset: departingPage\.offset,[\s\S]*?total: departingPage\.total_count/)
  assert.match(load, /departingPage\.total_count ==\s*selection\.places\[departingCursor\.placeIndex\]\.item_count/)
  assert.match(load, /let priorFacet = selection\.places\[departingCursor\.placeIndex\]/)
  assert.match(load, /XDriveIOSNativeOwnerMapSelectionPolicy\.canOpenPhotoRange\(priorFacet\)/)
  assert.match(load, /let currentOldPage = try await reader\.page\(\s*offset: departingCursor\.offset, placeID: priorFacet\.id, captureRange: selection\.captureRange\)/)
  assert.match(load, /currentOldPage\.sameVisibleSnapshot\(as: departingPage\)/)
  assert.match(load, /page\?\.sameVisibleSnapshot\(as: departingPage\) == true/)
  assert.match(load, /XDriveIOSNativePhotoOwnerScope\.matches\(\s*login\.owner, selection\.owner/)
  const oldRead = load.indexOf('let currentOldPage = try await reader.page(')
  const newRead = load.indexOf('let fetched = try await reader.page(')
  const publish = load.indexOf('cursor = target')
  assert.ok(oldRead > 0 && newRead > oldRead && publish > newRead,
    'old snapshot must be proven before new place reads and cursor publication')
})

test('map cluster rejects changed revisions even when the indexed place count is unchanged', () => {
  assert.match(transport, /func sameVisibleRevision\(as rhs: Self\) -> Bool/)
  assert.match(transport, /node\.revision == rhs\.node\.revision/)
  assert.match(transport, /node\.size == rhs\.node\.size/)
  assert.match(transport, /func sameVisibleSnapshot\(as rhs: Self\) -> Bool/)
  assert.match(transport, /zip\(items, rhs\.items\)\.allSatisfy \{ \$0\.sameVisibleRevision\(as: \$1\) \}/)
  assert.match(load, /currentOldPage\.sameVisibleSnapshot\(as: departingPage\)[\s\S]*?throw XDriveIOSNativeMediaReadFailure\.invalidPage/)
  assert.match(load, /Set\(fetched\.items\.map\(\\\.id\)\)\.count == fetched\.items\.count/)
  assert.match(load, /!Set\(departingPage\.items\.map\(\\\.id\)\)\s*\.isDisjoint\(with: fetched\.items\.map\(\\\.id\)\)/)
  assert.match(load, /if autoAdvance, let departingPage,[\s\S]*?priorWindow = departingPage/)
  assert.doesNotMatch(load, /UserDefaults\.|POST\b|UploadSession|map-region:q:/)
})
