test('owning Desktop can only inspect generation-scoped advisory evidence count', () => {
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_evidence_summary.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_evidence_summary.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const client = read('desktop', 'src', 'main', 'agent_client.cts')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const types = read('desktop', 'src', 'renderer', 'global.d.ts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalEvidenceSummaryDialog.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(agent, /CloudReadLocalBoundBackupEvidenceSummary\(/)
  assert.match(agent, /localFolderGrantMu.TryLock\(\)/)
  assert.match(agent, /localBoundBackupConfig\(readCtx, sourceID\)/)
  assert.match(agent, /cli.LocalBoundRules\(readCtx, sourceID, proof\)/)
  assert.match(agent, /localpush.LoadRootGrant\(/)
  assert.match(agent, /localpush.LoadLocalReconcileEvidence\(/)
  assert.match(agent, /cli.ReadLocalSourceItemEvidenceSummary\(/)
  assert.match(agent, /localBackupRuleSessionUnchanged\(cfg\)/)
  assert.match(agent, /StagedRecords: saved.StagedRecords, Authoritative: false, MissingInferenceSafe: false/)
  assert.doesNotMatch(agent, /BeginSourceRun|UploadChunk|CommitSourceItem\(|MirrorMissingFullScans/)
  assert.match(ipc, /"device-backup-local-evidence-summary"/)
  assert.match(ipc, /GET \/v1\/device-backups\/local-evidence-summary/)
  assert.match(handler, /len\(r.URL.Query\(\)\) != 1 \|\| len\(ids\) != 1/)
  assert.match(handler, /CloudReadLocalBoundBackupEvidenceSummary\(r.Context\(\), sourceID\)/)
  assert.match(handler, /"private, no-store"/)
  assert.doesNotMatch(handler, /root_id|fingerprint|local_path|file_path|native_identity/)
  assert.match(client, /localBoundBackupEvidenceSummary\(sourceID: number, signal\?: AbortSignal\)/)
  assert.match(client, /195_000, signal/)
  assert.match(main, /localEvidenceSummaryRequests.set\(key, controller\)/)
  assert.match(main, /localEvidenceSummaryRequests.get\(key\)\?\.abort\(\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-evidence-summary'\)/)
  assert.match(preload, /getDeviceBackupLocalEvidenceSummary:/)
  assert.match(preload, /cancelDeviceBackupLocalEvidenceSummary:/)
  assert.match(types, /XDriveLocalBackupEvidenceSummary/)
  assert.match(app, /localEvidenceSummary=\{localBackupEvidenceSummary\}/)
  assert.match(page, /localEvidenceSummary && verifiedLocalDeviceID === device.id && !device.revoked/)
  assert.match(page, /evidenceSummaryTarget.source === source/)
  assert.match(page, /device.folders.some\(\(folder\) => folder.source_id === evidenceSummaryTarget.id\)/)
  assert.match(dialog, /actions.load\(sourceID, requestID\)/)
  assert.match(dialog, /actions.cancel\(requestID\)/)
  assert.match(dialog, /Number.isSafeInteger\(value.staged_records\)/)
  assert.match(dialog, /value.authoritative !== false \|\| value.missing_inference_safe !== false/)
  assert.match(dialog, /这不代表本机文件为空/)
  assert.doesNotMatch(dialog, /startUpload\(|triggerSource\(|cancelSourceRun\(|deleteSource\(|SourceItemAlias\(/)
  assert.doesNotMatch(web, /getDeviceBackupLocalEvidenceSummary|localEvidenceSummary=/)
  const remoteProjection = dto.slice(0, dto.indexOf('// Separate private Agent-only draft projection.'))
  assert.doesNotMatch(remoteProjection, /staged_records|local_root|native_identity|source_item_id/)
  assert.match(dto, /export interface XDriveLocalBackupEvidenceSummary/)
})

test('local persisted evidence recovery is a narrow private count, not an alias promotion', () => {
  const api = read('internal', 'api', 'local_source_item_evidence_summary.go')
  const router = read('internal', 'api', 'router.go')
  const client = read('internal', 'client', 'local_source_item_evidence_summary.go')
  assert.match(router, /local-identity\/evidence-summary", s.requireLocalSourceExecutor\(\), s.readLocalSourceItemEvidenceSummary/)
  assert.match(api, /s.requireLocalSourceProofTx\(tx, c, sourceID, "", false\)/)
  assert.match(api, /tx.Model\(&meta.LocalSourceItemEvidence\{\}\)/)
  assert.match(api, /Count\(&count\).Error/)
  assert.match(api, /src.Status != meta.SourceStatusPaused/)
  assert.match(client, /localRulesProofHeaders\(req, proof\)/)
  assert.match(client, /req.Header.Set\("If-Match"/)
  assert.doesNotMatch(api, /tx.Create\(|SourceItemAlias\{|Update\("external_id"|BeginRun|MirrorDeletion/)
})
