'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const browser = read('ios/XDriveIOS/NativePhotoTimelineBrowser.swift')
const policy = read('ios/XDriveIOS/NativePhotoTimelinePolicy.swift')
const dashboard = read('ios/XDriveIOS/NativePhotosDashboard.swift')

test('local Gallery mounts a full-authorized-library date navigator without replacing its native wall', () => {
  assert.match(dashboard, /case \.local:\s*XDriveIOSNativeLocalPhotoTimelineContainer\(\s*savedOffset: \$localGalleryPageOffset\s*\)/)
  assert.doesNotMatch(dashboard, /XDriveIOSNativeLocalGalleryScreen\(/)
  assert.match(browser, /Label\("按年／月／日定位", systemImage: "calendar"\)/)
  assert.match(browser, /ForEach\(XDriveIOSNativePhotoTimelineScale\.allCases\)/)
  assert.match(browser, /ForEach\(index\.groups\(for: scale\)\)/)
  assert.match(browser, /savedOffset = requestedOffset\s*wallRevision &\+= 1/)
  assert.match(browser, /\.id\(wallRevision\)/)
  assert.doesNotMatch(browser, /useContinuousWall|content\.id\(wallRevision\)/)
})

test('calendar counts use original PhotoKit slots and invalidate on any library/permission change', () => {
  assert.match(browser, /PHPhotoLibrary\.authorizationStatus\(for: \.readWrite\)/)
  assert.match(browser, /PHPhotoLibrary\.shared\(\)\.register\(observer\)/)
  assert.match(browser, /defer \{ PHPhotoLibrary\.shared\(\)\.unregisterChangeObserver\(observer\) \}/)
  assert.match(browser, /NSSortDescriptor\(key: "creationDate", ascending: false\)/)
  assert.match(browser, /NSSortDescriptor\(key: "modificationDate", ascending: false\)/)
  assert.match(browser, /for slot in 0\.\.<snapshot\.count/)
  assert.match(browser, /if asset\.mediaType == \.image \|\| asset\.mediaType == \.video/)
  assert.match(browser, /index\.append\(capturedAt: asset\.creationDate, slot: slot\)/)
  assert.match(browser, /try verify\(status: status, observer: observer, revision: revision\)/)
  assert.match(browser, /\.onChange\(of: changes\.revision\) \{ _ in model\.invalidate\(\) \}/)
  assert.match(browser, /\.onChange\(of: phase\)/)
  assert.match(policy, /var firstPageOffset: Int \{ \(firstSlot \/ 64\) \* 64 \}/)
  assert.doesNotMatch(policy, /import Photos|PHAsset\.fetchAssets|localIdentifier:|accessToken|uploadSession/)
})
test('date jump reuses the real PhotoKit media filter instead of all-photo offsets', () => {
  const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
  assert.match(browser, /@State private var mediaFilter: XDriveIOSNativePhotoMediaFilter = \.all/)
  assert.match(browser, /XDriveIOSNativeLocalContinuousGalleryScreen\(\s*savedOffset: \$savedOffset, mediaFilter: \$mediaFilter/)
  assert.match(wall, /@Binding var mediaFilter: XDriveIOSNativePhotoMediaFilter/)
  assert.doesNotMatch(wall, /@State private var mediaFilter/)
  assert.match(browser, /func read\(mediaFilter: XDriveIOSNativePhotoMediaFilter\)/)
  assert.match(browser, /case \.all:\s*snapshot = PHAsset\.fetchAssets\(with: options\)/)
  assert.match(browser, /case \.photos:\s*snapshot = PHAsset\.fetchAssets\(with: \.image, options: options\)/)
  assert.match(browser, /case \.videos:\s*snapshot = PHAsset\.fetchAssets\(with: \.video, options: options\)/)
  assert.match(browser, /mediaFilter\.includes\(kind: kind\)/)
  assert.match(browser, /result\.indexedMediaCount == result\.totalSlots/)
  assert.match(browser, /\.read\(mediaFilter: mediaFilter\)/)
  assert.match(browser, /model\.indexFilter == mediaFilter/)
  assert.match(browser, /\.onChange\(of: mediaFilter\) \{ _ in[\s\S]*?model\.invalidate\(\)/)
  assert.match(browser, /let index = model\.index, model\.indexFilter == mediaFilter/)
  assert.match(browser, /requestedOffset % 64 == 0/)
  assert.doesNotMatch(browser, /Button\("按页查看"\)|Button\("连续滚动"\)/)
  assert.match(browser, /model\.load\(mediaFilter: mediaFilter\)/)
});


test('favorite day jump uses the same scoped PhotoKit predicate as favorite wall', () => {
  const wall = read('ios/XDriveIOS/NativeLocalContinuousGallery.swift')
  const filter = read('ios/XDriveIOS/NativePhotoMediaFilterPolicy.swift')
  assert.match(browser, /case \.favorites:\s*snapshot = PHAsset\.fetchAssets\(with: options\)/)
  assert.match(browser, /options\.predicate = NSPredicate\(format: "favorite == YES"\)/)
  assert.match(browser, /model\.indexFilter == mediaFilter/)
  assert.match(wall, /Picker\("媒体类型", selection: \$mediaFilter\)/)
  assert.match(filter, /case all, photos, videos, favorites/)
})

test('year/month navigator shows verified PhotoKit covers and drills to the continuous wall', () => {
  assert.match(browser, /private struct XDriveIOSNativeTimelineCoverTile: View/)
  assert.match(browser, /XDriveIOSNativeSquarePhotoTile\(candidate: representative\)/)
  assert.match(browser, /atOffset: group\.firstPageOffset, mediaFilter: mediaFilter/)
  assert.match(browser, /count == totalSlots, batch\.totalAccessibleAssets == totalSlots/)
  assert.match(browser, /batch\.startOffset == group\.firstPageOffset/)
  assert.match(browser, /matchesGroup\(candidate\)/)
  assert.match(browser, /case \.year where group\.key != "unknown":/)
  assert.match(browser, /case \.month where group\.key != "unknown":/)
  assert.match(browser, /scale = \.day/)
  assert.match(browser, /LazyVGrid\(columns:/)
  assert.match(browser, /ForEach\(index\.groups\(for: scale\)\)/)
  assert.match(browser, /jump\(to: group\.firstPageOffset\)/)
  assert.doesNotMatch(browser, /Button\("上一页"\)|Button\("下一页"\)/)
})
