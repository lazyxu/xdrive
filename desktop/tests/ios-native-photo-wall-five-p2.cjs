'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const shared = read('ios/XDriveIOS/NativePhotoWallComponents.swift')
const policy = read('ios/XDriveIOS/NativePhotoWallDensityPolicy.swift')
const album = read('ios/XDriveIOS/NativePhotoAlbumBrowser.swift')
const map = read('ios/XDriveIOS/NativeLocalPhotoMap.swift')
const cloud = read('ios/XDriveIOS/NativeServerMediaGallery.swift')
const anchorPolicy = read('ios/XDriveIOS/NativePhotoViewerReturnAnchorPolicy.swift')

test('P2-1: a single SwiftUI Section List renders authorized headers, grid and tile callbacks', () => {
  assert.match(shared, /struct XDriveIOSNativePhotoWallSectionList<Section: Identifiable, Item: Identifiable, Tile: View>/)
  assert.match(shared, /LazyVStack\(alignment: \.leading, spacing: spacing\)/)
  assert.match(shared, /ForEach\(sections\) \{ section in/)
  assert.match(shared, /XDriveIOSNativePhotoWallDayHeader\(title: heading\)/)
  assert.match(shared, /XDriveIOSNativePhotoWallGrid\(density: density\)/)
  assert.match(shared, /ForEach\(items\(section\)\) \{ item in tile\(item\) \}/)
  assert.match(album, /XDriveIOSNativePhotoWallSectionList\(/)
  assert.equal((map.match(/XDriveIOSNativePhotoWallSectionList\(/g) || []).length, 2)
  assert.match(cloud, /XDriveIOSNativePhotoWallSectionList\(/)
  assert.doesNotMatch(shared, /PHPhotoLibrary|PHAsset\.fetchAssets|URLSession|accessToken|Keychain|verifiedAuthorization|loadNext\(/)
})

test('P2-2: cloud hides repeated date heading only across adjacent verified 48-item ranges', () => {
  assert.match(policy, /struct XDriveIOSNativePhotoWallVerifiedPageDateBoundary: Equatable/)
  assert.match(policy, /count == 48, total > 0/)
  assert.match(policy, /offset \+ count == nextOffset, nextOffset < total/)
  assert.match(policy, /nextTotal == total/)
  assert.match(policy, /previous != "unknown" && previous == next/)
  assert.match(cloud, /precedingBoundary\?\.continues\(/)
  assert.match(cloud, /range\.limit == XDriveIOSNativeMediaGalleryReader\.pageSize/)
  assert.match(cloud, /datePageBoundaries\[range\.offset\] = \.init\(/)
  assert.match(cloud, /datePageBoundaries\.removeValue\(forKey: farthest\)/)
  assert.match(cloud, /XDriveIOSNativePhotoOwnerScope\.matches\(login\.owner, \$0\)/)
  assert.match(cloud, /\.onChange\(of: login\.owner\)/)
  assert.match(cloud, /\.onChange\(of: captureRange\)/)
  assert.match(cloud, /private func applySearch\(\) \{[\s\S]*?datePageBoundaries\.removeAll\(\)/)
  assert.match(cloud, /recentRangeIDs\.removeAll\(\)\s*datePageBoundaries\.removeAll\(\)\s*dateBoundaryOwner = nil/)
  // Date summaries alone cannot authorize a new Owner/Node request.
  assert.doesNotMatch(policy, /URLSession|PHAsset|OwnerRoot|accessToken|UserDefaults/)
})

test('P2-3: two local GPS walls share rows while keeping distinct bounded membership', () => {
  const preview = map.slice(map.indexOf('private struct XDriveIOSMapPhotoAlbum: View'), map.indexOf('enum XDriveIOSNativeLocalMapScope'))
  const spatial = map.slice(map.indexOf('private struct XDriveIOSMapSpatialAlbum: View'), map.indexOf('private func readWindow(', map.indexOf('private struct XDriveIOSMapSpatialAlbum: View')))
  for (const source of [preview, spatial]) {
    assert.match(source, /XDriveIOSNativePhotoWallSectionList\(/)
    assert.match(source, /XDriveIOSNativePhotoWallTimeScaleControls\(scale: \$wallTimeScale\)/)
    assert.match(source, /XDriveIOSNativePhotoWallDisplayMenu\(/)
    assert.match(source, /XDriveIOSNativeMapViewerAdmission\.allows\(/)
    assert.match(source, /XDriveIOSMapCurrentPhotoKitAdmission\.allows\(/)
    assert.match(source, /XDriveIOSNativePhotoViewerReturnAnchorPolicy\.target\(/)
    assert.match(source, /xdrivePhotoWallFocusVerifiedTile\(/)
  }
  assert.match(preview, /items\.prefix\(XDriveIOSNativePhotoMapPolicy\.pageSize\)/)
  assert.match(spatial, /priorWindow \+ items/)
  assert.match(map, /rows\.reserveCapacity\(48\)/)
  assert.match(spatial, /if hasNext \{[\s\S]*?advanceIfVisible\(\)/)
  assert.doesNotMatch(map, /PHAssetChangeRequest|UploadSession/)
})

