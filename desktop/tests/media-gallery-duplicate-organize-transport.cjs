const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('G11 read-only duplicate organizing plan crosses Web and Desktop with validated keeper IDs', () => {
  const server = read('internal/api/media_duplicate_organize_plan.go')
  const router = read('internal/api/router.go')
  const goClient = read('internal/client/media.go')
  const agent = read('cmd/xdrive-agent/cloud_files.go')
  const agentIPC = read('cmd/xdrive-agent/desktop_ipc.go')
  const mainClient = read('desktop/src/main/agent_client.cts')
  const main = read('desktop/src/main/index.cts')
  const preload = read('desktop/src/preload/index.cts')
  const declarations = read('desktop/src/renderer/global.d.ts')
  const web = read('web/src/api.ts')
  const webAdapter = read('web/src/mediaGalleryAdapter.ts')
  const desktopAdapter = read('desktop/src/renderer/mediaGalleryAdapter.ts')
  const sharedAdapter = read('ui/shared/src/mui/MediaGalleryAdapter.ts')
  const gallery = read('ui/shared/src/mui/MediaGallery.tsx')
  const preview = read('ui/shared/src/mui/MediaGalleryDuplicateOrganizePreview.tsx')
  const models = read('ui/shared/src/models.ts')

  assert.match(server, /func \(s \*Server\) queryMediaDuplicateOrganizePlan/)
  assert.match(router, /GET\("\/media\/duplicate-organize\/plan"/)
  assert.match(goClient, /func \(c \*Client\) MediaDuplicateOrganizePlan/)
  assert.match(goClient, /query.Add\("node_id"/)
  assert.match(agent, /CloudMediaDuplicateOrganizePlan/)
  assert.match(agentIPC, /GET \/v1\/media\/duplicate-organize\/plan/)
  assert.match(agentIPC, /media-duplicate-organize-plan/)
  assert.match(mainClient, /mediaDuplicateOrganizePlan\(keeperNodeID: number, nodeIDs: number\[\]\)/)
  assert.match(main, /'agent:get-media-duplicate-organize-plan'/)
  assert.match(main, /requireAgentCapability\(hello, 'media-duplicate-organize-plan'\)/)
  assert.match(preload, /getMediaDuplicateOrganizePlan:/)
  assert.match(declarations, /getMediaDuplicateOrganizePlan:/)
  assert.match(web, /mediaDuplicateOrganizePlan\(keeperNodeID: number, nodeIDs: number\[\]\)/)
  assert.match(webAdapter, /getDuplicateOrganizePlan:/)
  assert.match(desktopAdapter, /getDuplicateOrganizePlan:/)
  assert.match(sharedAdapter, /getDuplicateOrganizePlan: port\.getDuplicateOrganizePlan/)
  assert.match(models, /export interface MediaDuplicateOrganizePlan/)
  assert.match(gallery, /requestPlan=\{source\.getDuplicateOrganizePlan\}/)
  assert.match(preview, /data-xdrive-gallery-organize-preview/)
  assert.match(preview, /data-xdrive-gallery-organize-plan/)
  assert.match(preview, /nodeIDs\.length > 32/)
  assert.match(preview, /distinct_descriptions\.length > 1/)
  assert.match(preview, /durable_people/)
  assert.match(preview, /original_resources/)
  assert.match(preview, /no_mutation/)
  assert.match(preview, /不会移动、删除文件或释放共享 Blob/)
  assert.doesNotMatch(preview, /fetch\(|setInterval\(|useEffect\(\(\) => requestPlan/)
  assert.doesNotMatch(preview, /permanentlyDelete|deleteMedia|mergeMedia|moveMedia/)
})
