'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

// P0-01 source-only proof: it does not enumerate actual Baidu network resources.
test('isolated Baidu provider resources stay on Child host and Go-owned routes', () => {
  const child = read('deploy/baidu-isolated-child/child.js')
  const caddy = read('deploy/baidu-isolated-child/Caddyfile.example')
  const parent = read('deploy/baidu-isolated-child/Caddyfile.parent.example')
  assert.match(child, /window\.location\.origin \+ '\/_BMapService\/'/)
  assert.match(child, /script\.src = '\/_BMapService\/api\?v=4\.0'/)
  assert.doesNotMatch(child, /https?:\/\/api\.map\.baidu\.com|document\.cookie|parent\.document/)
  assert.match(caddy, /handle \/_BMapService\/\* \{\s*reverse_proxy server:8080\s*\}/)
  assert.match(caddy, /handle \{\s*respond 404\s*\}/)
  assert.match(caddy, /script-src 'self'; connect-src 'self'/)
  assert.match(caddy, /frame-ancestors \{\$XD_BAIDU_GALLERY_ORIGIN\}/)
  assert.doesNotMatch(caddy, /reverse_proxy\s+https?:\/\//)
  assert.match(parent, /frame-src \{\$XD_BAIDU_ISOLATED_CHILD_ORIGIN\}/)
  assert.match(parent, /frame-ancestors 'self'/)
})

test('Baidu serviceHost family retains source approval, signed session and fail-closed policy', () => {
  const policy = read('internal/baidumapjsapi/resource_policy.go')
  const family = read('internal/baidumapjsapi/provider_family.go')
  const ticket = read('internal/api/baidu_jsapi4_isolated_ticket.go')
  const handlers = read('internal/api/baidu_jsapi4_http.go')
  const routes = read('internal/api/router.go')
  assert.match(policy, /reviewedJSAPI4ChildInventoryRevision/)
  assert.match(policy, /reviewedJSAPI4ChildResourceCount = 1/)
  assert.match(policy, /ReviewJSAPI4ResourceRequest/)
  assert.match(policy, /JSAPI4ApprovedPolicySHA256/)
  assert.match(family, /case "ak", "key", "token", "secret"/)
  assert.match(family, /ErrUnreviewedResource/)
  assert.match(ticket, /publicsuffix\.EffectiveTLDPlusOne/)
  assert.match(ticket, /cookie\.Partitioned = true/)
  assert.match(handlers, /currentBaiduJSAPI4OperatorRelease/)
  assert.match(handlers, /isolated_map_required/)
  assert.match(handlers, /map resource unavailable/)
  assert.match(routes, /ApprovedJSAPI4ChildPaths\(\)/)
})
