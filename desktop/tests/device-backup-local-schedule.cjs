const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8')

test('Only the owning native Agent may view/edit a saved local schedule; no automatic execution', () => {
  const router = read('internal', 'api', 'router.go')
  const source = read('internal', 'api', 'sources.go')
  const privateRead = read('internal', 'api', 'local_source_schedule.go')
  const client = read('internal', 'client', 'local_bound_schedule.go')
  const agent = read('cmd', 'xdrive-agent', 'device_backup_local_schedule.go')
  const ipc = read('cmd', 'xdrive-agent', 'desktop_ipc.go')
  const handler = read('cmd', 'xdrive-agent', 'desktop_ipc_device_backup_schedule.go')
  const main = read('desktop', 'src', 'main', 'index.cts')
  const preload = read('desktop', 'src', 'preload', 'index.cts')
  const app = read('desktop', 'src', 'renderer', 'App.tsx')
  const page = read('ui', 'shared', 'src', 'mui', 'DeviceBackupPage.tsx')
  const dialog = read('ui', 'shared', 'src', 'mui', 'DeviceBackupLocalScheduleDialog.tsx')
  const dto = read('ui', 'shared', 'src', 'device-backups.ts')
  const web = read('web', 'src', 'App.tsx')

  assert.match(router, /GET\("\/sources\/:id\/local-schedule", s\.requireLocalSourceExecutor\(\), s\.getLocalSourceSchedule\)/)
  assert.match(privateRead, /requireLocalSourceProofTx\(tx, c, id, "", false\)/)
  assert.match(privateRead, /localSourceExecutorContextKey/)
  assert.match(privateRead, /"private, no-store"/)
  for (const field of ['ScheduleType', 'ScheduleExpression', 'ScheduleTimezone']) {
    assert.ok(source.includes('dto.' + field + ' = ""'), 'generic local Source leaked ' + field)
  }
  assert.match(source, /isLocalFolderPush\(current\) && current\.Status != meta\.SourceStatusPaused/)
  assert.match(source, /sourceschedule\.Normalize\(scheduleType, expression, timezone\)/)
  assert.match(client, /UpdateSourceInput\{\s*ScheduleType:\s*&normalized\.Type,/)
  for (const header of ['X-XDrive-Device-ID', 'X-XDrive-Device-Token',
    'X-XDrive-Local-Root-ID', 'X-XDrive-Local-Root-Fingerprint']) {
    const proof = read('internal', 'client', 'local_bound_rules.go')
    assert.ok(proof.includes(header), 'private schedule transport missing native proof ' + header)
  }
  assert.match(agent, /localBoundBackupConfig\(ctx, sourceID\)/)
  assert.match(agent, /cli\.LocalBoundSchedule\(ctx, sourceID, proof\)/)
  assert.match(agent, /cli\.SetLocalBoundSchedule\(ctx, sourceID, revision, normalized, proof\)/)
  assert.doesNotMatch(agent, /localpush\.EnsureDevice\(/)
  assert.match(ipc, /"device-backup-local-schedule"/)
  assert.match(handler, /sourceschedule\.Normalize\(input\.ScheduleType, input\.ScheduleExpression, input\.ScheduleTimezone\)/)
  assert.match(main, /requireAgentCapability\(hello, 'device-backup-local-schedule'\)/)
  assert.match(preload, /getDeviceBackupLocalSchedule:/)
  assert.match(preload, /setDeviceBackupLocalSchedule:/)
  assert.match(app, /localSchedule=\{localBackupSchedule\}/)
  assert.match(page, /verifiedLocalDeviceID === device\.id && !device\.revoked/)
  assert.match(page, /source === source/)
  assert.match(dialog, /actions\.save\(sourceID, loaded\.revision, proposal\)/)
  assert.match(dialog, /不会自动运行/)
  assert.doesNotMatch(web, /localSchedule=/)
  assert.doesNotMatch(web, /getDeviceBackupLocalSchedule/)
  assert.ok(dto.includes('export interface XDriveLocalBoundBackupSchedule'))
  const remoteModel = dto.slice(0, dto.indexOf('// Separate private Agent-only draft projection.'))
  assert.doesNotMatch(remoteModel, /schedule_expression|schedule_timezone/)
  assert.doesNotMatch(dialog, /(?:triggerSource|startUpload|cancelSourceRun|deleteSource)\(/)
})
