const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..', '..')
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8')

test('Each service lifecycle axis is carried across Go Client and shared Web/Desktop MUI', () => {
  const backend = read('internal', 'api', 'admin_service_dependencies.go')
  const lifecycle = read('internal', 'api', 'admin_service_lifecycle.go')
  const goClient = read('internal', 'client', 'client.go')
  const agent = read('desktop', 'src', 'main', 'agent_client.cts')
  const types = read('ui', 'shared', 'src', 'service-dependencies.ts')
  const page = read('ui', 'shared', 'src', 'mui', 'ServiceDependenciesPage.tsx')

  for (const field of ['configuration_state', 'installation_state', 'health_state', 'activation_state']) {
    assert.ok(backend.includes('json:"' + field + '"'), 'missing Server '+field)
    assert.ok(goClient.includes('json:"' + field + ',omitempty"'), 'missing Go Client '+field)
    assert.ok(types.includes(field + '?:'), 'missing shared TypeScript '+field)
    assert.ok(agent.includes(field + '?:'), 'missing Desktop Agent '+field)
    assert.ok(page.includes('service.' + field + " ?? 'unknown'"), 'missing safe UI fallback '+field)
  }
  assert.ok(backend.includes('s.setServiceLifecycleStates('))
  assert.ok(page.includes('data-xdrive-service-lifecycle'))
  assert.ok(lifecycle.includes('baidu.Enabled && baidu.Configured'))
  assert.ok(lifecycle.includes('item.ActivationState = "local-effective"'))
  assert.ok(lifecycle.includes('item.ActivationState = "deployment-only"'))
  assert.ok(lifecycle.includes('item.ActivationState = "verified"'))
  assert.equal(lifecycle.includes('docker.sock'), false)
  assert.equal(lifecycle.includes('openSyncFolders'), false)
})

test('Caddy HTTPS and local TLS observations retain explicit false via Go Client / Desktop', () => {
  const backend = read('internal', 'api', 'admin_service_dependencies.go')
  const goClient = read('internal', 'client', 'client.go')
  const agent = read('desktop', 'src', 'main', 'agent_client.cts')
  const shared = read('ui', 'shared', 'src', 'service-dependencies.ts')
  assert.ok(backend.includes('json:"https_configured,omitempty"'))
  assert.ok(backend.includes('json:"local_tls_state,omitempty"'))
  assert.match(goClient, /HTTPSConfigured\s+\*bool\s+`json:"https_configured,omitempty"`/)
  assert.match(goClient, /LocalTLSState\s+string\s+`json:"local_tls_state,omitempty"`/)
  assert.ok(agent.includes('https_configured?: boolean'))
  assert.ok(agent.includes('local_tls_state?:'))
  assert.ok(shared.includes('https_configured?: boolean'))
  assert.equal(shared.includes("'connectors'"), false)
})
