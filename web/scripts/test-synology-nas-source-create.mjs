#!/usr/bin/env node
// Source-exact DSM GUI setup: no browser pathname, no independent Runner,
// no unverified Owner target or claiming Source creation as a CAS receipt.
import assert from 'node:assert/strict'
import fs from 'node:fs'
const base = new URL('../../', import.meta.url)
const read = p => fs.readFileSync(new URL(p, base), 'utf8')
const gateway = read('internal/synologyui/gateway.go')
const routing = read('internal/synologyui/cgi.go')
const create = read('internal/synologyui/nas_share_create.go')
const native = read('internal/localbackupipc/bootstrap.go')
const adapter = read('ui/shared/src/synology-backup-adapter.ts')
const share = read('ui/shared/src/mui/SynologyNASShareInventory.tsx')
const picker = read('ui/shared/src/mui/SynologyBackupTargetBrowser.tsx')
const form = read('ui/shared/src/mui/SynologyBackupSourceSetup.tsx')
const panel = read('ui/shared/src/mui/SynologyBackupLocalPanel.tsx')
const workflow = read('.github/workflows/synology-ui.yml')

assert.match(panel, /<XDriveSynologyBackupSourceSetup client=\{client\} onCreated=\{refresh\}/)
assert.match(form, /<XDriveSynologyNASShareInventory client=\{client\} onVerifiedShare=\{onVerifiedShare\}/)
assert.match(form, /<XDriveSynologyBackupTargetBrowser client=\{client\} onSelectTarget=\{onSelectTarget\}/)
assert.match(share, /client\.preflightNASShare\(share\.selection_id, controller\.signal\)/)
assert.match(share, /onVerifiedShare\?\.\(share\)/)
assert.match(picker, /currentScopeVerified && isCurrentOwner\(\)/)
assert.match(picker, /onSelectTarget\?\.\(/)
assert.match(form, /selectedShare\.selection_id, ownerScope, selectedTarget\.id, name/)
assert.match(form, /status !== 'idle'/)
assert.match(form, /setStatus\('uncertain'\)/)
assert.match(form, /Source \{createdID\} 已创建，但原生 Root 绑定结果尚未确认/)
assert.match(form, /尚未验证任何上传收据/)
assert.doesNotMatch(form + picker + share, /exec\.Command|localStorage\.setItem|sessionStorage\.setItem|\.\s*CreateLocalBackupSource\(|\.\s*AuthorizeLocalRoot\(/)

assert.match(adapter, /'\/v1\/nas-share-create', 'POST'/)
assert.match(adapter, /selection_id: selectionID, owner_scope: ownerScope, target_id: targetID, name, confirmed: true/)
assert.match(adapter, /Object\.keys\(payload\)\.length !== 2/)
assert.match(adapter, /state: payload\.state/)
assert.match(routing, /"nas-share-create"/)
assert.match(gateway, /parseNASShareCreate\(r\)/)
assert.match(gateway, /resolveNASSharePreflight\(ctx, root, key, username/)
assert.match(gateway, /subtle\.ConstantTimeCompare/)
assert.match(gateway, /bootstrapper\.PreflightLocalRoot\(ctx, path\)/)
assert.match(gateway, /bootstrapper\.CreateLocalBackupSource\(ctx, input\.Name, input\.TargetID\)/)
assert.match(gateway, /bootstrapper\.AuthorizeLocalRoot\(ctx, created\.ID, path\)/)
assert.match(gateway, /"state": "needs_inspection"/)
assert.match(gateway, /"state": "authorized"/)
assert.match(gateway, /quotaReader\.OwnerQuota\(ctx\)/)
assert.match(create, /dsmOwnerScope\(/)
assert.match(create, /value\.Confirmed/)
assert.match(create, /duplicate or invalid DSM Source setup field/)
assert.match(native, /"\/v1\/sources"/)
assert.match(native, /"\/v1\/local-folder\/authorize"/)
assert.match(workflow, /node web\/scripts\/test-synology-nas-source-create\.mjs/)
console.log('DSM GUI Source setup is Owner-pinned, native-Agent-backed and never reports a backup receipt')
